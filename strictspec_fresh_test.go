package rlsbl

import (
	"io/fs"
	"os"
	"os/exec"
	"path/filepath"
	"strings"
	"testing"

	"github.com/stricttools/testisolation/go/hygiene"
)

// The strictspec-generated validators are fresh: strictspec's own freshness
// check (`strictspec check`, which re-renders every target of strictspec.toml
// and compares it with the committed file) passes, run from a strictspec
// built from the module the build resolves (the workspace's checkout), so the
// generator is the one rlsbl compiles against and nothing is fetched from a
// network. Every committed file carrying strictspec's generated header is a
// target of the manifest, so a validator the manifest dropped is not passed
// over.
func TestTheStrictspecValidatorsAreFresh(t *testing.T) {
	hygiene.Isolate(t, hygiene.Preserve(hygiene.GoCache, hygiene.GoModCache))
	goTool, err := exec.LookPath("go")
	if err != nil {
		t.Skip("no Go toolchain on PATH: the freshness of the strictspec validators cannot be checked here")
	}
	root, err := os.Getwd()
	if err != nil {
		t.Fatal(err)
	}
	bin := filepath.Join(t.TempDir(), "strictspec")
	build := exec.Command(goTool, "build", "-o", bin, "github.com/stricttools/strictspec/go/cmd/strictspec")
	build.Dir = root
	build.Env = append(os.Environ(), "GOPROXY=off", "GOFLAGS=-mod=readonly")
	if out, err := build.CombinedOutput(); err != nil {
		t.Fatalf("building strictspec: %v\n%s", err, out)
	}
	check := exec.Command(bin, "check", "--manifest", "strictspec.toml")
	check.Dir = root
	out, err := check.CombinedOutput()
	if err != nil {
		t.Fatalf("strictspec check refuses the generated validators; run `strictspec gen --manifest strictspec.toml` with the strictspec this module builds against, and commit the result: %v\n%s", err, out)
	}
	var generated []string
	err = filepath.WalkDir(root, func(path string, d fs.DirEntry, err error) error {
		if err != nil {
			return err
		}
		rel, _ := filepath.Rel(root, path)
		if d.IsDir() {
			switch rel {
			case ".git", "experiments", "screenshots", "node_modules":
				return filepath.SkipDir
			}
			return nil
		}
		if !strings.HasSuffix(path, ".go") {
			return nil
		}
		data, err := os.ReadFile(path)
		if err != nil {
			return err
		}
		if strings.HasPrefix(string(data), "// Code generated by strictspec. DO NOT EDIT.") {
			generated = append(generated, filepath.ToSlash(rel))
		}
		return nil
	})
	if err != nil {
		t.Fatal(err)
	}
	if len(generated) == 0 {
		t.Fatal("no strictspec-generated Go file was found")
	}
	for _, rel := range generated {
		if !strings.Contains(string(out), "-> "+rel+": fresh") {
			t.Errorf("%s carries strictspec's generated header, and strictspec check did not report it fresh: declare it as a target in strictspec.toml or delete it\n%s", rel, out)
		}
	}
}
