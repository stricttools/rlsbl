package main

import (
	"os"
	"path/filepath"
	"testing"

	"github.com/stricttools/testisolation/go/hygiene"

	"github.com/stricttools/rlsbl"
	"github.com/stricttools/rlsbl/internal/cli"
	"github.com/stricttools/rlsbl/internal/targets"
)

// The committed help document is the application's own help --json at the
// version VERSION holds, which is what a release writes there (the dump
// sets its version to the version released, and the release writes VERSION
// in the same commit).
func TestTheCommittedHelpDocumentIsTheApplicationsHelp(t *testing.T) {
	hygiene.Isolate(t)
	committed, err := os.ReadFile(filepath.Join("..", "..", filepath.FromSlash(targets.SchemaDumpPath)))
	if err != nil {
		t.Fatal(err)
	}
	app, err := cli.New(cli.Dependencies{Version: rlsbl.Version, HTTPClient: cli.NewHTTPClient()})
	if err != nil {
		t.Fatal(err)
	}
	r := app.Test([]string{"help", "--json"})
	if r.ExitCode != 0 {
		t.Fatalf("rlsbl help --json exited %d: %s", r.ExitCode, r.Stderr)
	}
	if r.Stdout != string(committed) {
		t.Fatalf("%s differs from rlsbl help --json; run scripts/gen-schema.sh from the repository root and commit the result with the Autogenerated trailer", targets.SchemaDumpPath)
	}
}
