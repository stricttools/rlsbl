package main

import (
	"encoding/json"
	"fmt"
	"os"
	"path/filepath"
	"testing"

	"github.com/stricttools/testisolation/go/hygiene"

	"github.com/stricttools/rlsbl/internal/cli"
	"github.com/stricttools/rlsbl/internal/targets"
)

// helpAt is the application's help --json at version.
func helpAt(t *testing.T, version string) string {
	t.Helper()
	app, err := cli.New(cli.Dependencies{Version: version, HTTPClient: cli.NewHTTPClient()})
	if err != nil {
		t.Fatal(err)
	}
	r := app.Test([]string{"help", "--json"})
	if r.ExitCode != 0 {
		t.Fatalf("rlsbl help --json exited %d: %s", r.ExitCode, r.Stderr)
	}
	return r.Stdout
}

// checkHelpDocument reports whether document is the application's help
// --json at the version the document records: a release dumps it at the
// version it releases before the tests run, and writes VERSION afterwards.
func checkHelpDocument(t *testing.T, document string) error {
	t.Helper()
	var recorded struct {
		Version string `json:"version"`
	}
	if err := json.Unmarshal([]byte(document), &recorded); err != nil {
		return fmt.Errorf("%s is not a help document: %v", targets.SchemaDumpPath, err)
	}
	if helpAt(t, recorded.Version) != document {
		return fmt.Errorf("%s differs from rlsbl help --json; run scripts/gen-schema.sh from the repository root and commit the result with the Autogenerated trailer", targets.SchemaDumpPath)
	}
	return nil
}

func TestTheCommittedHelpDocumentIsTheApplicationsHelp(t *testing.T) {
	hygiene.Isolate(t)
	committed, err := os.ReadFile(filepath.Join("..", "..", filepath.FromSlash(targets.SchemaDumpPath)))
	if err != nil {
		t.Fatal(err)
	}
	if err := checkHelpDocument(t, string(committed)); err != nil {
		t.Fatal(err)
	}
}

// A release dumps the help document at the version it releases before it
// runs the tests, and writes VERSION only afterwards, in the version bump.
func TestAHelpDocumentDumpedAtTheReleasedVersionIsTheApplicationsHelp(t *testing.T) {
	hygiene.Isolate(t)
	if err := checkHelpDocument(t, helpAt(t, "0.999.0")); err != nil {
		t.Fatal(err)
	}
}
