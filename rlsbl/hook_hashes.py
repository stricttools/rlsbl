# Version 3: two-line dispatcher that incorrectly forwards "$@" to rlsbl
# (strictcli rejects extra positional args). Inlined in init_cmd.py only --
# never lived as a standalone template file. Reconstructed from
# todo/fix-pre-push-hook-args.md.
_PRE_PUSH_HOOK_V3 = '#!/usr/bin/env bash\nexec rlsbl pre-push-check "$@"\n'

# Version 4: two-line dispatcher without "$@".
_PRE_PUSH_HOOK_V4 = '#!/usr/bin/env bash\nexec rlsbl pre-push-check\n'

# Version 5 (current): captures git's push stdin and delegates to the check system.
_PRE_PUSH_HOOK_V5 = CURRENT_PRE_PUSH_HOOK


def compute_hook_hash(content):
    """Return the SHA-256 hex digest of `content`, with trailing whitespace stripped.

    Trailing whitespace (including newlines) is stripped before hashing so that
    a hook re-saved by an editor with a tweaked trailing newline still matches.
    """
    if isinstance(content, bytes):
        content = content.decode("utf-8", errors="replace")
    normalized = content.rstrip()
    return hashlib.sha256(normalized.encode("utf-8")).hexdigest()


# Every pre-push hook content rlsbl has ever shipped. If we find one of these
# on disk we know it's an unmodified rlsbl-installed hook and we can replace
# it. Anything not in this set is treated as user-customized.
PRE_PUSH_HOOK_HASHES = frozenset({
    compute_hook_hash(_PRE_PUSH_HOOK_V1),
    compute_hook_hash(_PRE_PUSH_HOOK_V2),
    compute_hook_hash(_PRE_PUSH_HOOK_V3),
    compute_hook_hash(_PRE_PUSH_HOOK_V4),
    compute_hook_hash(_PRE_PUSH_HOOK_V5),
})


CURRENT_PRE_PUSH_HOOK_HASH = compute_hook_hash(CURRENT_PRE_PUSH_HOOK)
