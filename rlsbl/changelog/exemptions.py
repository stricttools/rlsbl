"""Centralized changelog exemption registry for commit filtering rules, managing path-based and message-based exclusions from coverage checks."""

from __future__ import annotations

import subprocess
from dataclasses import dataclass
from typing import Callable

from ..git_util import get_commit_files
from ..ownership import is_tool_owned_path
from .. import effects


@dataclass
class ExemptionRule:
    name: str
    predicate: Callable[[str], bool]  # takes SHA, returns bool
    reason: str


@dataclass
class ExemptionStats:
    """Counts of commits filtered by each exemption predicate."""

    autogenerated: int = 0
    changelog_only: int = 0


def is_autogenerated(sha: str) -> bool:
    """Check if a commit has the ``Autogenerated: true`` trailer.

    Returns True when the trailer is present with value ``true``,
    False otherwise.  Subprocess errors are treated as non-autogenerated.
    """
    try:
        result = effects.run(
            ["git", "log", "-1", "--format=%(trailers:key=Autogenerated,valueonly)", sha],
            capture_output=True,
            text=True,
            timeout=10,
        )
        if result.returncode != 0:
            return False
        return result.stdout.strip() == "true"
    except (subprocess.TimeoutExpired, FileNotFoundError, OSError):
        return False


# A changelog/release infrastructure path is exactly a tool-owned path: the
# rules are enumerated once, in rlsbl.ownership, and used both to exempt a
# commit from coverage and to keep the path out of member attribution.
is_changelog_path = is_tool_owned_path


def is_changelog_only_commit(sha: str) -> bool:
    """Check if a commit only touches changelog/release infrastructure files.

    Returns True when every file changed by the commit matches one of:
    - ``.rlsbl/changes/`` (any depth)
    - ``.rlsbl/releases/`` (any depth)
    - ``.rlsbl/version``
    - ``CHANGELOG.md``

    For monorepo support, paths prefixed with a subdirectory are also
    accepted (e.g. ``python/.rlsbl/changes/unreleased.jsonl``).

    Subprocess errors or empty file lists are treated conservatively
    (returns False).
    """
    files = get_commit_files(sha)
    if not files:
        return False

    for f in files:
        # Strip optional leading subdirectory (monorepo prefix).
        # We check both the raw path and the basename-after-first-slash.
        if is_changelog_path(f):
            continue
        return False
    return True


class ExemptionRegistry:
    """Ordered registry of exemption rules for changelog commit filtering."""

    def __init__(self) -> None:
        self._rules: list[ExemptionRule] = []

    def register(self, name: str, predicate: Callable[[str], bool], reason: str) -> None:
        """Add a rule. Order matters -- first match wins for stats."""
        self._rules.append(ExemptionRule(name=name, predicate=predicate, reason=reason))

    @property
    def rules(self) -> list[ExemptionRule]:
        """Return a copy of the rules list."""
        return list(self._rules)

    def check(self, sha: str) -> tuple[bool, str | None]:
        """Evaluate rules in order. Returns (exempt, reason) on first match."""
        for rule in self._rules:
            if rule.predicate(sha):
                return True, rule.reason
        return False, None

    def filter_commits(self, commits: list[str]) -> tuple[list[str], ExemptionStats]:
        """Batch filter. Returns (non_exempt_commits, stats).

        Stats tracks per-rule counts. First matching rule wins for stats counting.
        """
        stats = ExemptionStats()
        remaining: list[str] = []
        for commit in commits:
            matched = False
            for rule in self._rules:
                if rule.predicate(commit):
                    # Increment the matching stat field
                    if rule.name == "autogenerated":
                        stats.autogenerated += 1
                    elif rule.name == "changelog_only":
                        stats.changelog_only += 1
                    matched = True
                    break
            if not matched:
                remaining.append(commit)
        return remaining, stats


def create_default_registry() -> ExemptionRegistry:
    """Create the default registry with autogenerated and changelog_only rules.

    Order matters: autogenerated is checked first, then changelog_only.
    A commit matching both is counted as autogenerated only.
    """
    registry = ExemptionRegistry()
    registry.register(
        "autogenerated",
        is_autogenerated,
        "commit has Autogenerated: true trailer",
    )
    registry.register(
        "changelog_only",
        is_changelog_only_commit,
        "commit only touches changelog/release infrastructure files",
    )
    return registry
