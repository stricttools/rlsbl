"""Generate a Markdown CHANGELOG.md from structured JSONL changelog entries, grouping them by version with configurable formatting."""

from __future__ import annotations

import os
import sys

import tomlkit

from .files import get_changes_dir, list_versioned_files, read_unreleased
from .schema import ChangelogEntry, parse_jsonl

_HEADER_COMMENT = "<!-- Generated by rlsbl from .rlsbl/changes/ — do not edit -->"


def _base_version(version: str) -> str:
    """Strip the pre-release suffix from a version string.

    ``"0.43.0-alpha.0"`` -> ``"0.43.0"``
    ``"1.0.0"`` -> ``"1.0.0"``
    """
    return version.split("-", 1)[0]


def _is_prerelease(version: str) -> bool:
    """Return True if the version has a pre-release suffix."""
    return "-" in version


# Type name -> display header, in canonical order.
_TYPE_ORDER: list[tuple[str, str]] = [
    ("breaking", "Breaking"),
    ("feature", "Features"),
    ("fix", "Fixes"),
]


def _read_release_metadata(project_path: str, version: str, *,
                           releases_dir: str | None = None) -> tuple[str, str]:
    """Read description and context from an archived release toml file.

    Looks for v{version}.toml in ``releases_dir`` (default:
    ``<project_path>/.rlsbl/releases/``; releasable releases archive under
    the releasable's own releases dir) and extracts the description and
    context fields. Returns ("", "") if the file doesn't exist or can't
    be parsed.
    """
    desc, ctx, _bump = _read_release_metadata_full(
        project_path, version, releases_dir=releases_dir,
    )
    return (desc, ctx)


def _read_release_metadata_full(project_path: str, version: str, *,
                                releases_dir: str | None = None) -> tuple[str, str, str]:
    """Read description, context, and bump type from an archived release toml file.

    Looks for v{version}.toml in ``releases_dir`` (default:
    ``<project_path>/.rlsbl/releases/``; releasable releases archive under
    the releasable's own releases dir) and extracts the description,
    context, and bump fields. Returns ("", "", "") if the file doesn't exist
    or can't be parsed.
    """
    if releases_dir is None:
        releases_dir = os.path.join(project_path, ".rlsbl", "releases")
    toml_path = os.path.join(releases_dir, f"v{version}.toml")
    try:
        with open(toml_path, "r", encoding="utf-8") as f:
            data = tomlkit.load(f)
    except (OSError, tomlkit.exceptions.ParseError):
        return ("", "", "")

    description = data.get("description", "")
    context = data.get("context", "")
    bump = data.get("bump", "")
    if not isinstance(description, str):
        description = ""
    if not isinstance(context, str):
        context = ""
    if not isinstance(bump, str):
        bump = ""
    return (description.strip(), context.strip(), bump.strip())


def generate_version_section(
    version: str,
    entries: list[ChangelogEntry],
    *,
    description: str = "",
    context: str = "",
    bump_type: str | None = None,
) -> str:
    """Generate markdown for one version section.

    Only includes entries where user_facing=True. Groups by type under
    sub-headers (Breaking, Features, Fixes, Other). Empty groups are omitted.
    If no user-facing entries exist, emits a single "No user-facing changes." bullet.

    If all entries share a release_type (e.g., "ota" or "build"), a marker
    is appended to the version heading.

    When ``description`` is provided, it is added as a paragraph after the
    version heading and before the first type group. When ``context`` is
    provided, it is rendered as a collapsible ``<details>`` block after the
    description.
    """
    # Determine release type marker from entries
    release_types = {e.release_type for e in entries if e.release_type}
    release_marker = ""
    if len(release_types) == 1:
        rt = release_types.pop()
        release_marker = f" ({rt.upper()})"

    user_facing = [e for e in entries if e.user_facing]

    if not user_facing:
        section = f"## {version}{release_marker}\n\n"
        if description:
            section += f"{description}\n\n"
        if context:
            section += (
                "<details>\n<summary>Context</summary>\n\n"
                f"{context}\n\n</details>\n\n"
            )
        if bump_type == "hotfix" and description:
            section += f"### Hotfix\n\n- {description}\n"
        else:
            section += "- No user-facing changes.\n"
        return section

    # Bucket entries by type.
    buckets: dict[str, list[str]] = {}
    for entry in user_facing:
        key = entry.type if entry.type in ("breaking", "feature", "fix") else "_other"
        buckets.setdefault(key, []).append(entry.description or "")

    parts: list[str] = [f"## {version}{release_marker}"]

    if description:
        parts.append("")
        parts.append(description)

    if context:
        parts.append("")
        parts.append("<details>")
        parts.append("<summary>Context</summary>")
        parts.append("")
        parts.append(context)
        parts.append("")
        parts.append("</details>")

    for type_key, header in _TYPE_ORDER:
        descs = buckets.get(type_key)
        if not descs:
            continue
        parts.append("")
        parts.append(f"### {header}")
        parts.append("")
        for desc in descs:
            parts.append(f"- {desc}")

    other = buckets.get("_other")
    if other:
        parts.append("")
        parts.append("### Other")
        parts.append("")
        for desc in other:
            parts.append(f"- {desc}")

    parts.append("")  # trailing newline
    return "\n".join(parts)


def generate_version_file(
    changes_dir: str,
    version: str,
    write_to_disk: bool = True,
    *,
    description: str = "",
    context: str = "",
    bump_type: str | None = None,
) -> str:
    """Read the JSONL file for a version, generate markdown, optionally write .md alongside it.

    Returns the generated markdown text. When write_to_disk is False, computes the
    markdown without touching the filesystem (used to preview content before pre-checks).

    When ``description`` and ``context`` are provided, they are passed through to
    ``generate_version_section()`` so release metadata appears in the output.
    """
    jsonl_path = os.path.join(changes_dir, f"{version}.jsonl")
    entries = parse_jsonl(jsonl_path)
    md = generate_version_section(version, entries, description=description, context=context, bump_type=bump_type)

    if write_to_disk:
        md_path = os.path.join(changes_dir, f"{version}.md")
        # Skip the write when content is unchanged, so regeneration doesn't
        # needlessly dirty already-committed per-version files.
        existing = None
        if os.path.exists(md_path):
            with open(md_path, "r", encoding="utf-8") as f:
                existing = f.read()
        if existing != md:
            with open(md_path, "w", encoding="utf-8") as f:
                f.write(md)

    return md


def _deduplicate_entries(entries: list[ChangelogEntry]) -> list[ChangelogEntry]:
    """Remove duplicate entries based on commit hash sets.

    Two entries are duplicates when they have the same set of commits.
    The first occurrence wins (preserves order).
    """
    seen: set[frozenset[str]] = set()
    result: list[ChangelogEntry] = []
    for entry in entries:
        key = frozenset(entry.commits)
        if key not in seen:
            seen.add(key)
            result.append(entry)
    return result


def _generate_consolidated_section(
    stable_version: str,
    all_entries: list[ChangelogEntry],
    prerelease_versions: list[str],
    prerelease_entries_by_version: dict[str, list[ChangelogEntry]],
    *,
    description: str = "",
    context: str = "",
    bump_type: str | None = None,
) -> str:
    """Generate a consolidated section for a stable version with pre-release predecessors.

    Produces:
    1. The stable heading (``## 0.43.0``) with ALL entries deduplicated
    2. A note listing the pre-release cycle
    3. Individual pre-release headings (``### 0.43.0-alpha.0``) with their entries
    """
    # Deduplicate across all entries (stable delta + all pre-releases)
    deduped = _deduplicate_entries(all_entries)
    parts: list[str] = []

    # Generate the consolidated stable section
    stable_section = generate_version_section(
        stable_version, deduped,
        description=description, context=context,
        bump_type=bump_type,
    )
    parts.append(stable_section.rstrip("\n"))

    # Add pre-release cycle note
    cycle = ", ".join(prerelease_versions)
    parts.append("")
    parts.append(f"Pre-release cycle: {cycle}")

    # Add individual pre-release sub-sections
    for pre_ver in prerelease_versions:
        pre_entries = prerelease_entries_by_version[pre_ver]
        user_facing = [e for e in pre_entries if e.user_facing]
        if not user_facing:
            parts.append("")
            parts.append(f"### {pre_ver}")
            parts.append("")
            parts.append("- No user-facing changes.")
        else:
            # Bucket by type, same as generate_version_section
            buckets: dict[str, list[str]] = {}
            for entry in user_facing:
                key = entry.type if entry.type in ("breaking", "feature", "fix") else "_other"
                buckets.setdefault(key, []).append(entry.description or "")

            parts.append("")
            parts.append(f"### {pre_ver}")

            for type_key, header in _TYPE_ORDER:
                descs = buckets.get(type_key)
                if not descs:
                    continue
                parts.append("")
                parts.append(f"#### {header}")
                parts.append("")
                for desc in descs:
                    parts.append(f"- {desc}")

            other = buckets.get("_other")
            if other:
                parts.append("")
                parts.append(f"#### Other")
                parts.append("")
                for desc in other:
                    parts.append(f"- {desc}")

    parts.append("")  # trailing newline
    return "\n".join(parts)


def _read_changelog_format(project_path: str) -> str:
    """Read changelog_format from project config, defaulting to 'grouped'."""
    config_path = os.path.join(project_path, ".rlsbl", "config.json")
    try:
        import json

        with open(config_path, "r", encoding="utf-8") as f:
            config = json.load(f)
    except (OSError, json.JSONDecodeError):
        return "grouped"

    fmt = config.get("changelog_format", "grouped")
    if fmt != "grouped":
        print(
            f"Warning: unrecognized changelog_format '{fmt}', falling back to 'grouped'",
            file=sys.stderr,
        )
        fmt = "grouped"
    return fmt


def generate_changelog(
    project_path: str,
    *,
    write_to_disk: bool = True,
    version_override: str | None = None,
    description: str = "",
    context: str = "",
    changes_dir_override: str | None = None,
    changelog_output_path: str | None = None,
    releases_dir_override: str | None = None,
    bump_type: str | None = None,
) -> str:
    """Generate the complete CHANGELOG.md from .rlsbl/changes/ JSONL files.

    1. Reads changelog_format from config (only "grouped" supported).
    2. Reads unreleased.jsonl (if non-empty) for an Unreleased section.
    3. Reads all versioned JSONL files sorted newest-first.
    4. Generates per-version .md files alongside the JSONL files (when write_to_disk).
    5. Writes CHANGELOG.md at project root (when write_to_disk).
    6. Returns the generated content.

    When write_to_disk is False, computes and returns the markdown content without
    modifying the filesystem. This lets callers preview the changelog before
    pre-release checks run, so an aborted release leaves a clean working tree.

    When version_override is provided AND unreleased entries exist, the section
    heading is "## {version_override}" instead of "## Unreleased". Versioned
    sections (from existing JSONL files) are unaffected. Default None preserves
    the original behaviour exactly.

    ``description`` and ``context`` are applied to the unreleased section only
    (the current release being prepared). Previously released version sections
    read their description and context from archived release files at
    ``.rlsbl/releases/v{version}.toml``.

    ``changes_dir_override`` overrides the default ``.rlsbl/changes/`` path.
    Used in explicit releasable mode where the changes dir lives under the
    releasable directory.

    ``changelog_output_path`` overrides the default CHANGELOG.md output location.
    Used in explicit releasable mode to write CHANGELOG.md into the releasable
    directory instead of the project root.

    ``releases_dir_override`` overrides the default ``.rlsbl/releases/`` path
    used for the archived-release-file metadata backfill (description,
    context, bump type of versioned sections). Used in explicit releasable
    mode where v{version}.toml archives live under the releasable directory.

    ``bump_type`` is passed through to ``generate_version_section()`` for the
    unreleased section. For versioned sections, the bump type is read from the
    archived release file.
    """
    _read_changelog_format(project_path)

    changes_dir = changes_dir_override or get_changes_dir(project_path)
    sections: list[str] = []

    # Unreleased entries
    unreleased = read_unreleased(changes_dir)
    if unreleased:
        heading = version_override if version_override else "Unreleased"
        sections.append(generate_version_section(
            heading, unreleased, description=description, context=context,
            bump_type=bump_type,
        ))

    # Versioned entries (newest first).
    # Generate per-version .md files for all versions (including pre-releases),
    # then build consolidated sections for CHANGELOG.md.
    versioned = list_versioned_files(changes_dir)

    # Always generate individual per-version .md files.
    for version, _jsonl_path in versioned:
        ver_desc, ver_ctx, ver_bump = _read_release_metadata_full(
            project_path, version, releases_dir=releases_dir_override,
        )
        generate_version_file(
            changes_dir, version, write_to_disk=write_to_disk,
            description=ver_desc, context=ver_ctx,
            bump_type=ver_bump or None,
        )

    # Group versions by their base version for consolidation.
    # Preserves newest-first ordering from list_versioned_files.
    base_groups: dict[str, list[str]] = {}
    base_order: list[str] = []
    for version, _jsonl_path in versioned:
        base = _base_version(version)
        if base not in base_groups:
            base_groups[base] = []
            base_order.append(base)
        base_groups[base].append(version)

    for base in base_order:
        group = base_groups[base]
        prerelease_versions = [v for v in group if _is_prerelease(v)]
        has_stable = base in group

        if has_stable and prerelease_versions:
            # Consolidate: stable version exists alongside pre-releases.
            # Collect all entries from the stable delta and all pre-releases.
            all_entries: list[ChangelogEntry] = []
            prerelease_entries_map: dict[str, list[ChangelogEntry]] = {}

            for ver in group:
                jsonl_path = os.path.join(changes_dir, f"{ver}.jsonl")
                entries = parse_jsonl(jsonl_path)
                all_entries.extend(entries)
                if _is_prerelease(ver):
                    prerelease_entries_map[ver] = entries

            # Pre-release versions in ascending order for the cycle note
            # (group is newest-first from list_versioned_files, reverse it).
            prerelease_asc = list(reversed(prerelease_versions))

            ver_desc, ver_ctx, ver_bump = _read_release_metadata_full(
                project_path, base, releases_dir=releases_dir_override,
            )
            section = _generate_consolidated_section(
                base,
                all_entries,
                prerelease_asc,
                prerelease_entries_map,
                description=ver_desc,
                context=ver_ctx,
                bump_type=ver_bump or None,
            )
            sections.append(section)
        else:
            # No consolidation needed: either all pre-releases or a lone stable.
            # Emit each version individually.
            for ver in group:
                ver_desc, ver_ctx, ver_bump = _read_release_metadata_full(
                    project_path, ver, releases_dir=releases_dir_override,
                )
                md = generate_version_section(
                    ver,
                    parse_jsonl(os.path.join(changes_dir, f"{ver}.jsonl")),
                    description=ver_desc,
                    context=ver_ctx,
                    bump_type=ver_bump or None,
                )
                sections.append(md)

    body = "\n".join(sections)
    content = f"{_HEADER_COMMENT}\n\n# Changelog\n\n{body}"

    if write_to_disk:
        changelog_path = changelog_output_path or os.path.join(project_path, "CHANGELOG.md")
        with open(changelog_path, "w", encoding="utf-8") as f:
            f.write(content)

    return content
