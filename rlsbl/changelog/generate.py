"""Generate a Markdown CHANGELOG.md from structured JSONL changelog entries, grouping them by version with configurable formatting.

Per-version file permission model:

- ``x.y.z.jsonl`` -- the finalized, immutable changelog record. Locked to
  0o444 at finalization; never rewritten in place.
- ``x.y.z.md`` -- a regenerated derivative of the JSONL. Normally writable,
  but a user or tool may reasonably lock it (mirroring the 444 .jsonl it sits
  beside). ``generate_version_file`` therefore compares content first and,
  when it must rewrite the .md, writes atomically (tmp-in-same-dir +
  ``os.replace``) with the replacement carrying the file's ORIGINAL mode
  (never assuming 444), so a deliberate lock survives regeneration and a crash
  mid-write can never leave a truncated file.
"""

from __future__ import annotations

import os
import sys
from dataclasses import dataclass

import tomlkit

from ..errors import ReleaseFileError
from ..release_file import VALID_BUMP_TYPES, read_release_file
from .files import get_changes_dir, list_versioned_files, read_unreleased
from .schema import ChangelogEntry, parse_jsonl
from .. import effects

_HEADER_COMMENT = "<!-- Generated by rlsbl from .rlsbl/changes/ — do not edit -->"


def _base_version(version: str) -> str:
    """Strip the pre-release suffix from a version string.

    ``"0.43.0-alpha.0"`` -> ``"0.43.0"``
    ``"1.0.0"`` -> ``"1.0.0"``
    """
    return version.split("-", 1)[0]


def _is_prerelease(version: str) -> bool:
    """Return True if the version has a pre-release suffix."""
    return "-" in version


# Type name -> display header, in canonical order.
_TYPE_ORDER: list[tuple[str, str]] = [
    ("breaking", "Breaking"),
    ("feature", "Features"),
    ("fix", "Fixes"),
]


@dataclass(frozen=True)
class ArchiveMetadata:
    """What a regenerated changelog section reads out of a release archive.

    The absent-archive case is this dataclass with every field at its default:
    a version whose archive was never written renders its entries with no
    description, which is the state a pre-archive release legitimately leaves.
    An archive that EXISTS but cannot be read is not this -- it raises.
    """

    description: str = ""
    context: str = ""
    bump: str = ""
    never_released: bool = False


_ABSENT_ARCHIVE = ArchiveMetadata()


def _legacy_bump_error(toml_path: str) -> ReleaseFileError | None:
    """The legacy-bump diagnostic for an archive the schema just refused.

    ``bump = "hotfix"`` was renamed to ``"infra"``, and the schema's enum now
    refuses the old value -- correctly, but with a diagnostic that names the
    enum rather than the migration. This re-reads the refused document (only on
    the error path, which already ends the read) and, when the cause really is
    a legacy bump, raises the message that names what to do about it.
    """
    try:
        with open(toml_path, "r", encoding="utf-8") as f:
            data = tomlkit.load(f)
    except (OSError, tomlkit.exceptions.ParseError):
        return None
    bump = data.get("bump", "")
    if not isinstance(bump, str):
        return None
    bump = bump.strip()
    if not bump or bump in VALID_BUMP_TYPES:
        return None
    return ReleaseFileError(
        f'archived release file {toml_path} carries an unknown '
        f'bump={bump!r}. If this is the legacy "hotfix" value, migrate it '
        f'to "infra" (run the fleet archive migration or edit the file); '
        f'valid bump types are {", ".join(VALID_BUMP_TYPES)}.'
    )


def read_archive_metadata(project_path: str, version: str, *,
                          releases_dir: str | None = None) -> ArchiveMetadata:
    """Read one version's archived release file, through the VALIDATING reader.

    Looks for ``v{version}.toml`` in ``releases_dir`` (default:
    ``<project_path>/.rlsbl/releases/``; releasable releases archive under the
    releasable's own releases dir).

    An ABSENT archive yields :data:`_ABSENT_ARCHIVE` -- empty metadata. That is
    a real state: a version released before rlsbl archived a release file per
    version has no archive, and its section renders without a description.

    An archive that EXISTS and cannot be read is a HARD ERROR naming the file.
    This path used to parse the document raw and turn any failure -- bad TOML,
    a missing ``format_version`` gate, a field of the wrong type -- into an
    empty description, which ``changelog generate`` then committed over the
    version's real description in both CHANGELOG.md and the read-only
    per-version ``.md``. Silently losing a shipped release's prose is the one
    thing that read must not do.
    """
    if releases_dir is None:
        releases_dir = os.path.join(project_path, ".rlsbl", "releases")
    toml_path = os.path.join(releases_dir, f"v{version}.toml")
    if not os.path.isfile(toml_path):
        return _ABSENT_ARCHIVE

    try:
        cfg = read_release_file(toml_path)
    except ReleaseFileError as exc:
        legacy = _legacy_bump_error(toml_path)
        if legacy is not None:
            raise legacy from exc
        raise
    except OSError as exc:
        raise ReleaseFileError(
            f"archived release file {toml_path} could not be read: {exc}"
        ) from exc

    return ArchiveMetadata(
        description=cfg.description.strip(),
        context=cfg.context.strip(),
        bump=cfg.bump.strip(),
        never_released=bool(cfg.never_released),
    )


# The annotation a never-released version's section carries. Such a version has
# real finalized changelog files -- entries were written and locked before the
# release was abandoned -- so the section is RENDERED rather than hidden, and the
# annotation is what keeps a reader from taking it for a release that happened.
NEVER_RELEASED_NOTE = (
    "**Never released.** This version number exists in the release record, but "
    "no release was ever published under it."
)


def generate_version_section(
    version: str,
    entries: list[ChangelogEntry],
    *,
    description: str = "",
    context: str = "",
    bump_type: str | None = None,
    never_released: bool = False,
) -> str:
    """Generate markdown for one version section.

    Only includes entries where user_facing=True. Groups by type under
    sub-headers (Breaking, Features, Fixes, Other). Empty groups are omitted.
    If no user-facing entries exist, emits a single "No user-facing changes." bullet.

    If all entries share a release_type (e.g., "ota" or "build"), a marker
    is appended to the version heading.

    When ``description`` is provided, it is added as a paragraph after the
    version heading and before the first type group. When ``context`` is
    provided, it is rendered as a collapsible ``<details>`` block after the
    description.

    ``never_released`` renders :data:`NEVER_RELEASED_NOTE` between the heading
    and the description. The section is still produced in full: a version the
    release record records as never released can carry finalized changelog
    files, and dropping the section would lose them.
    """
    # Determine release type marker from entries
    release_types = {e.release_type for e in entries if e.release_type}
    release_marker = ""
    if len(release_types) == 1:
        rt = release_types.pop()
        release_marker = f" ({rt.upper()})"

    user_facing = [e for e in entries if e.user_facing]

    if not user_facing:
        section = f"## {version}{release_marker}\n\n"
        if never_released:
            section += f"{NEVER_RELEASED_NOTE}\n\n"
        if description:
            section += f"{description}\n\n"
        if context:
            section += (
                "<details>\n<summary>Context</summary>\n\n"
                f"{context}\n\n</details>\n\n"
            )
        if bump_type == "infra" and description:
            section += f"### Infrastructure\n\n- {description}\n"
        else:
            section += "- No user-facing changes.\n"
        return section

    # Bucket entries by type.
    buckets: dict[str, list[str]] = {}
    for entry in user_facing:
        key = entry.type if entry.type in ("breaking", "feature", "fix") else "_other"
        desc = entry.description or ""
        if entry.packages:
            prefix = "[" + ", ".join(sorted(entry.packages)) + "] "
            desc = prefix + desc
        buckets.setdefault(key, []).append(desc)

    parts: list[str] = [f"## {version}{release_marker}"]

    if never_released:
        parts.append("")
        parts.append(NEVER_RELEASED_NOTE)

    if description:
        parts.append("")
        parts.append(description)

    if context:
        parts.append("")
        parts.append("<details>")
        parts.append("<summary>Context</summary>")
        parts.append("")
        parts.append(context)
        parts.append("")
        parts.append("</details>")

    for type_key, header in _TYPE_ORDER:
        descs = buckets.get(type_key)
        if not descs:
            continue
        parts.append("")
        parts.append(f"### {header}")
        parts.append("")
        for desc in descs:
            parts.append(f"- {desc}")

    other = buckets.get("_other")
    if other:
        parts.append("")
        parts.append("### Other")
        parts.append("")
        for desc in other:
            parts.append(f"- {desc}")

    parts.append("")  # trailing newline
    return "\n".join(parts)


def _atomic_write_preserving_mode(path: str, content: str) -> None:
    """Atomically write *content* to *path*, preserving its EXACT mode.

    Writes to a tmp file in the same directory and ``os.replace``s it into
    place, so a crash mid-write can never leave a truncated file. ``os.replace``
    is a directory operation, so it succeeds even when *path* itself is a
    read-only file -- there is no need to unlock the target first (unlike
    ``writable_jsonl``, which relocks to 0o444). The replacement carries the
    target's ORIGINAL mode when the file exists (a per-version .md may be
    deliberately locked to any read-only mode; regeneration must not silently
    change it); a brand-new file uses the umask-derived default, matching the
    prior ``open(path, "w")`` behavior.
    """
    effects.atomic_write_text(path, content, preserve_mode=True)


def generate_version_file(
    changes_dir: str,
    version: str,
    write_to_disk: bool = True,
    *,
    description: str = "",
    context: str = "",
    bump_type: str | None = None,
    never_released: bool = False,
) -> str:
    """Read the JSONL file for a version, generate markdown, optionally write .md alongside it.

    Returns the generated markdown text. When write_to_disk is False, computes the
    markdown without touching the filesystem (used to preview content before pre-checks).

    When ``description`` and ``context`` are provided, they are passed through to
    ``generate_version_section()`` so release metadata appears in the output, and
    so is ``never_released``.
    """
    jsonl_path = os.path.join(changes_dir, f"{version}.jsonl")
    entries = parse_jsonl(jsonl_path)
    md = generate_version_section(
        version, entries, description=description, context=context,
        bump_type=bump_type, never_released=never_released,
    )

    if write_to_disk:
        md_path = os.path.join(changes_dir, f"{version}.md")
        # Skip the write when content is unchanged, so regeneration doesn't
        # needlessly dirty already-committed per-version files.
        existing = None
        if os.path.exists(md_path):
            with open(md_path, "r", encoding="utf-8") as f:
                existing = f.read()
        # Compare-first (above) happens BEFORE any write, so unchanged content
        # is a pure no-op: no write, mtime untouched. When content differs, the
        # atomic writer replaces the .md in place, carrying its original mode so
        # a deliberate read-only lock survives regeneration.
        if existing != md:
            _atomic_write_preserving_mode(md_path, md)

    return md


def _deduplicate_entries(entries: list[ChangelogEntry]) -> list[ChangelogEntry]:
    """Remove duplicate entries based on commit hash sets.

    Two entries are duplicates when they have the same set of commits.
    The first occurrence wins (preserves order).
    """
    seen: set[frozenset[str]] = set()
    result: list[ChangelogEntry] = []
    for entry in entries:
        key = frozenset(entry.commits)
        if key not in seen:
            seen.add(key)
            result.append(entry)
    return result


def _generate_consolidated_section(
    stable_version: str,
    all_entries: list[ChangelogEntry],
    prerelease_versions: list[str],
    prerelease_entries_by_version: dict[str, list[ChangelogEntry]],
    *,
    description: str = "",
    context: str = "",
    bump_type: str | None = None,
    never_released: bool = False,
    never_released_prereleases: frozenset[str] | set[str] | tuple = (),
) -> str:
    """Generate a consolidated section for a stable version with pre-release predecessors.

    Produces:
    1. The stable heading (``## 0.43.0``) with ALL entries deduplicated
    2. A note listing the pre-release cycle
    3. Individual pre-release headings (``### 0.43.0-alpha.0``) with their entries

    ``never_released`` annotates the stable heading; ``never_released_prereleases``
    names the pre-release versions whose own archives record that fate, and
    annotates each of their sub-headings. A pre-release is claimed and
    abandoned the same way a stable version is, and its sub-section here is the
    only place it appears in CHANGELOG.md -- unannotated, it reads as a release
    that happened.
    """
    # Deduplicate across all entries (stable delta + all pre-releases)
    deduped = _deduplicate_entries(all_entries)
    parts: list[str] = []

    # Generate the consolidated stable section
    stable_section = generate_version_section(
        stable_version, deduped,
        description=description, context=context,
        bump_type=bump_type, never_released=never_released,
    )
    parts.append(stable_section.rstrip("\n"))

    # Add pre-release cycle note
    cycle = ", ".join(prerelease_versions)
    parts.append("")
    parts.append(f"Pre-release cycle: {cycle}")

    # Add individual pre-release sub-sections
    for pre_ver in prerelease_versions:
        pre_entries = prerelease_entries_by_version[pre_ver]
        user_facing = [e for e in pre_entries if e.user_facing]
        pre_never_released = pre_ver in never_released_prereleases
        if not user_facing:
            parts.append("")
            parts.append(f"### {pre_ver}")
            if pre_never_released:
                parts.append("")
                parts.append(NEVER_RELEASED_NOTE)
            parts.append("")
            parts.append("- No user-facing changes.")
        else:
            # Bucket by type, same as generate_version_section
            buckets: dict[str, list[str]] = {}
            for entry in user_facing:
                key = entry.type if entry.type in ("breaking", "feature", "fix") else "_other"
                buckets.setdefault(key, []).append(entry.description or "")

            parts.append("")
            parts.append(f"### {pre_ver}")
            if pre_never_released:
                parts.append("")
                parts.append(NEVER_RELEASED_NOTE)

            for type_key, header in _TYPE_ORDER:
                descs = buckets.get(type_key)
                if not descs:
                    continue
                parts.append("")
                parts.append(f"#### {header}")
                parts.append("")
                for desc in descs:
                    parts.append(f"- {desc}")

            other = buckets.get("_other")
            if other:
                parts.append("")
                parts.append(f"#### Other")
                parts.append("")
                for desc in other:
                    parts.append(f"- {desc}")

    parts.append("")  # trailing newline
    return "\n".join(parts)


def _read_changelog_format(project_path: str) -> str:
    """Read changelog_format from project config, defaulting to 'grouped'."""
    config_path = os.path.join(project_path, ".rlsbl", "config.json")
    try:
        import json

        with open(config_path, "r", encoding="utf-8") as f:
            config = json.load(f)
    except (OSError, json.JSONDecodeError):
        return "grouped"

    fmt = config.get("changelog_format", "grouped")
    if fmt != "grouped":
        print(
            f"Warning: unrecognized changelog_format '{fmt}', falling back to 'grouped'",
            file=sys.stderr,
        )
        fmt = "grouped"
    return fmt


def generate_changelog(
    project_path: str,
    *,
    write_to_disk: bool = True,
    version_override: str | None = None,
    description: str = "",
    context: str = "",
    changes_dir_override: str | None = None,
    changelog_output_path: str | None = None,
    releases_dir_override: str | None = None,
    bump_type: str | None = None,
) -> str:
    """Generate the complete CHANGELOG.md from .rlsbl/changes/ JSONL files.

    1. Reads changelog_format from config (only "grouped" supported).
    2. Reads unreleased.jsonl (if non-empty) for an Unreleased section.
    3. Reads all versioned JSONL files sorted newest-first.
    4. Generates per-version .md files alongside the JSONL files (when write_to_disk).
    5. Writes CHANGELOG.md at project root (when write_to_disk).
    6. Returns the generated content.

    When write_to_disk is False, computes and returns the markdown content without
    modifying the filesystem. This lets callers preview the changelog before
    pre-release checks run, so an aborted release leaves a clean working tree.

    When version_override is provided, the section heading is
    "## {version_override}" instead of "## Unreleased", and the section is
    emitted even when unreleased.jsonl is empty (that is what an infra release
    is). Versioned sections (from existing JSONL files) are unaffected. With
    version_override None and no unreleased entries, no section is emitted.

    ``description`` and ``context`` are applied to the unreleased section only
    (the current release being prepared). Previously released version sections
    read their description and context from archived release files at
    ``.rlsbl/releases/v{version}.toml``.

    ``changes_dir_override`` overrides the default ``.rlsbl/changes/`` path.
    Used in explicit releasable mode where the changes dir lives under the
    releasable directory.

    ``changelog_output_path`` overrides the default CHANGELOG.md output location.
    Used in explicit releasable mode to write CHANGELOG.md into the releasable
    directory instead of the project root.

    ``releases_dir_override`` overrides the default ``.rlsbl/releases/`` path
    used for the archived-release-file metadata backfill (description,
    context, bump type of versioned sections). Used in explicit releasable
    mode where v{version}.toml archives live under the releasable directory.

    ``bump_type`` is passed through to ``generate_version_section()`` for the
    unreleased section. For versioned sections, the bump type is read from the
    archived release file.
    """
    _read_changelog_format(project_path)

    changes_dir = changes_dir_override or get_changes_dir(project_path)
    sections: list[str] = []

    # Unreleased entries.
    #
    # A version_override means a release is being assembled, and that section
    # is emitted whether or not unreleased.jsonl has entries: an EMPTY
    # unreleased.jsonl is precisely what an infra release looks like (it
    # forbids user-facing entries), and skipping it shipped every infra
    # release with no CHANGELOG.md section at all. With no override, an empty
    # file still emits nothing -- a bare "## Unreleased / No user-facing
    # changes." block would be noise.
    unreleased = read_unreleased(changes_dir)
    if unreleased or version_override:
        heading = version_override if version_override else "Unreleased"
        sections.append(generate_version_section(
            heading, unreleased, description=description, context=context,
            bump_type=bump_type,
        ))

    # Versioned entries (newest first).
    # Generate per-version .md files for all versions (including pre-releases),
    # then build consolidated sections for CHANGELOG.md.
    versioned = list_versioned_files(changes_dir)

    # Always generate individual per-version .md files. Each version's archive
    # metadata is kept: the section pass below asks for the same versions, and
    # reading every archive twice is the cost of a hundred-version project's
    # regeneration paid twice over.
    meta_by_version: dict[str, ArchiveMetadata] = {}
    for version, _jsonl_path in versioned:
        meta = read_archive_metadata(
            project_path, version, releases_dir=releases_dir_override,
        )
        meta_by_version[version] = meta
        generate_version_file(
            changes_dir, version, write_to_disk=write_to_disk,
            description=meta.description, context=meta.context,
            bump_type=meta.bump or None,
            never_released=meta.never_released,
        )

    # Group versions by their base version for consolidation.
    # Preserves newest-first ordering from list_versioned_files.
    base_groups: dict[str, list[str]] = {}
    base_order: list[str] = []
    for version, _jsonl_path in versioned:
        base = _base_version(version)
        if base not in base_groups:
            base_groups[base] = []
            base_order.append(base)
        base_groups[base].append(version)

    for base in base_order:
        group = base_groups[base]
        prerelease_versions = [v for v in group if _is_prerelease(v)]
        has_stable = base in group

        if has_stable and prerelease_versions:
            # Consolidate: stable version exists alongside pre-releases.
            # Collect all entries from the stable delta and all pre-releases.
            all_entries: list[ChangelogEntry] = []
            prerelease_entries_map: dict[str, list[ChangelogEntry]] = {}

            for ver in group:
                jsonl_path = os.path.join(changes_dir, f"{ver}.jsonl")
                entries = parse_jsonl(jsonl_path)
                all_entries.extend(entries)
                if _is_prerelease(ver):
                    prerelease_entries_map[ver] = entries

            # Pre-release versions in ascending order for the cycle note
            # (group is newest-first from list_versioned_files, reverse it).
            prerelease_asc = list(reversed(prerelease_versions))

            meta = meta_by_version[base]
            # Each pre-release's OWN fate, read from its own archive: the base
            # version's archive says nothing about whether an alpha in its
            # cycle was ever released.
            never_released_pres = frozenset(
                ver for ver in prerelease_asc
                if meta_by_version[ver].never_released
            )
            section = _generate_consolidated_section(
                base,
                all_entries,
                prerelease_asc,
                prerelease_entries_map,
                description=meta.description,
                context=meta.context,
                bump_type=meta.bump or None,
                never_released=meta.never_released,
                never_released_prereleases=never_released_pres,
            )
            sections.append(section)
        else:
            # No consolidation needed: either all pre-releases or a lone stable.
            # Emit each version individually.
            for ver in group:
                meta = meta_by_version[ver]
                md = generate_version_section(
                    ver,
                    parse_jsonl(os.path.join(changes_dir, f"{ver}.jsonl")),
                    description=meta.description,
                    context=meta.context,
                    bump_type=meta.bump or None,
                    never_released=meta.never_released,
                )
                sections.append(md)

    body = "\n".join(sections)
    content = f"{_HEADER_COMMENT}\n\n# Changelog\n\n{body}"

    if write_to_disk:
        changelog_path = changelog_output_path or os.path.join(project_path, "CHANGELOG.md")
        with effects.open_write(changelog_path, "w", encoding="utf-8") as f:
            f.write(content)

    return content
