def check_hashes_resolve(entries: list[ChangelogEntry]) -> tuple[bool, list[str]]:
    """Check that every hash in every entry resolves via git rev-parse."""
    details: list[str] = []

    # Collect all hashes for batch resolution
    all_hashes: list[str] = []
    for entry in entries:
        all_hashes.extend(entry.commits)
    resolved = resolve_hashes(all_hashes)

    # Report per-entry with context
    for i, entry in enumerate(entries):
        if not entry.commits:
            continue
        bad_hashes = [h for h in entry.commits if resolved.get(h) is None]
        if not bad_hashes:
            continue
        total = len(entry.commits)
        n_valid = total - len(bad_hashes)
        for h in bad_hashes:
            details.append(
                f"entry {i + 1} in unreleased.jsonl: hash {h} does not resolve "
                f"({n_valid} of {total} commits still valid)"
            )

    return (len(details) == 0, details)


#: What :func:`_foreign_owner_description` answers when nothing in the
#: workspace claims a single one of the commit's files -- every path it touches
#: is tool-owned, so no member and no releasable owns it.
NO_DECLARED_OWNER = "no member or releasable this workspace declares"


def _foreign_owner_description(sha: str, scope) -> str:
    """Who owns the files of a commit the asking *scope* does not claim.

    Named for a message, so it answers in the workspace's own vocabulary: a
    member (with the releasable it belongs to), or a releasable's own state
    directory, which belongs to no member at all.  Returns a short phrase, or
    a plain statement when nothing in the workspace claims the files.
    """
    from ..git_util import commit_files as _commit_files
    from ..ownership import member_name, owner_of, state_dir_releasable

    members: dict[str, str | None] = {}
    state_owners: set[str] = set()

    for path in _commit_files(sha, operation="changelog range check"):
        if scope.claims(path):
            continue
        owner = owner_of(path, scope.members)
        if owner is not None:
            releasable = owner.get("releasable")
            members[member_name(owner)] = (
                releasable if isinstance(releasable, str) else None
            )
            continue
        state_owner = state_dir_releasable(path)
        if state_owner is not None:
            state_owners.add(state_owner)

    parts = []
    for name in sorted(members):
        releasable = members[name]
        if releasable:
            parts.append(f"member '{name}' (releasable '{releasable}')")
        else:
            parts.append(f"member '{name}' (in no releasable)")
    for name in sorted(state_owners):
        parts.append(f"releasable '{name}'s own state directory")

    if not parts:
        return NO_DECLARED_OWNER
    return ", ".join(parts)


def _out_of_scope_detail(raw: str, sha: str, entry: ChangelogEntry, scope) -> str:
    """The finding for an entry naming a commit this changelog does not cover.

    Deliberately NOT the out-of-range sentence: this commit IS between this
    checkout's nearest release commit and HEAD. What is wrong is where the
    entry was filed, and the remedy is to move it, not to repair a hash.

    Two remedies, because there are two cases. When another member owns the
    commit's files the entry belongs in that member's changelog, so it is
    removed here and added there. When NOTHING owns them -- every path the
    commit touches is tool-owned, rlsbl's own bookkeeping -- there is no
    owning member's directory to add it from, and telling the reader to go to
    one names a place that does not exist. Such a commit needs no changelog
    coverage anywhere, so the entry is simply removed.
    """
    owner = _foreign_owner_description(sha, scope)
    finding = (
        f"hash in the unreleased range but outside this changelog's scope: "
        f"{raw} ({sha}) -- its files belong to {owner}, while this changelog "
        f"covers {scope.describe()}. "
    )
    if owner == NO_DECLARED_OWNER:
        return finding + (
            f"Every file it touches is tool-owned, so no changelog covers it "
            f"and there is nowhere to move the entry to: remove it with "
            f"`{_removal_remedy(entry, [sha])}`."
        )
    return finding + (
        f"The entry is filed under the wrong releasable: remove it here with "
        f"`{_removal_remedy(entry, [sha])}`, then add it from the owning "
        f"member's directory with `rlsbl changelog add --commits {sha} "
        f"--description \"...\" --type feature`."
    )


def check_in_range(entries: list[ChangelogEntry], releases_dir: str,
                   tag_glob: str | None = None, scope=None) -> tuple[bool, list[str]]:
    """Check that every resolved hash is in the unreleased range.

    Unreleased range: the commits since the release the RELEASE RECORD release commits this
    checkout to -- the highest archived version whose ``candidate_sha`` this
    history contains -- or all commits when the release record records none.
    ``releases_dir`` is that release record; ``tag_glob`` names the tag scheme, used
    to detect a tag that disagrees with a release commit.

    When *scope* is set (monorepo mode), only commits touching files owned
    by the scope's members are considered in-range.  *scope* is an
    :class:`~rlsbl.ownership.OwnershipScope`.

    A hash outside that set fails for one of two DIFFERENT reasons, and they
    get different messages. Out of range means the commit is not between the
    anchoring release and HEAD -- a stale hash, or work that already shipped.
    Out of scope means it is in the range and belongs to another releasable's
    territory: a cross-filed entry, which used to be reported as out of range
    and sent its reader hunting for a rewrite that never happened.
    """
    details: list[str] = []
    range_commits = set(_git_log_hashes(
        unreleased_range(releases_dir, tag_glob=tag_glob)))

    in_scope = filter_commits_for_scope(
        range_commits, scope, operation="changelog range check",
    )

    all_hashes: list[str] = []
    for entry in entries:
        all_hashes.extend(entry.commits)
    resolved = resolve_hashes(all_hashes)

    reported: set[str] = set()
    for entry in entries:
        for raw in entry.commits:
            full = resolved.get(raw)
            if full is None or full in in_scope or full in reported:
                continue
            reported.add(full)
            if full in range_commits:
                details.append(_out_of_scope_detail(raw, full, entry, scope))
            else:
                details.append(f"hash not in unreleased range: {raw} ({full})")

    return (len(details) == 0, details)


def check_coverage(entries: list[ChangelogEntry], releases_dir: str,
                   tag_glob: str | None = None, scope=None) -> tuple[bool, list[str]]:
    """Check that every unreleased commit appears in at least one entry.

    The unreleased range comes from the RELEASE RECORD at ``releases_dir`` -- see
    :func:`check_in_range`. Commits with the ``Autogenerated: true`` trailer
    are automatically exempted -- they are release infrastructure and don't
    need coverage. When *scope* is set (monorepo mode), only commits touching
    files the scope's members own require coverage -- a commit whose every
    file belongs to some other member is filtered out.  *scope* is an
    :class:`~rlsbl.ownership.OwnershipScope`.
    """
    details: list[str] = []
    unreleased_commits = set(_git_log_hashes(
        unreleased_range(releases_dir, tag_glob=tag_glob)))

    # In monorepo mode, filter to commits touching files this scope owns
    skipped_outside_project = 0
    if scope is not None:
        project_commits = filter_commits_for_scope(
            unreleased_commits, scope, operation="changelog coverage check",
        )
        skipped_outside_project = len(unreleased_commits) - len(project_commits)
        unreleased_commits = project_commits

    # Collect all resolved hashes from entries
    all_hashes: list[str] = []
    for entry in entries:
        all_hashes.extend(entry.commits)
    resolved = resolve_hashes(all_hashes)
    covered = {full for full in resolved.values() if full is not None}

    # Filter exempt commits from the uncovered set only
    uncovered_commits = sorted(c for c in unreleased_commits if c not in covered)
    non_exempt, exempt_stats = filter_exempt_commits(uncovered_commits)

    uncovered = 0
    for commit in non_exempt:
        uncovered += 1
        details.append(f"unreleased commit not covered: {commit[:12]}")

    if exempt_stats.autogenerated > 0:
        details.append(f"skipped {exempt_stats.autogenerated} autogenerated commit(s)")
    if exempt_stats.changelog_only > 0:
        details.append(f"skipped {exempt_stats.changelog_only} changelog-only commit(s)")
    if skipped_outside_project > 0:
        details.append(f"skipped {skipped_outside_project} commit(s) outside package directory")

    return (uncovered == 0, details)


def _removal_remedy(entry: ChangelogEntry, stale_hashes: list[str]) -> str:
    """The ``changelog remove`` invocation that deletes *entry*.

    Printed verbatim into a finding, so it has to be runnable as written. The
    entry's ULID id addresses it exactly and survives every unrelated edit to
    the file, so it is preferred. A legacy line written before ids existed
    carries none and is addressed by a commit it names instead -- which
    ``changelog remove`` accepts even when git cannot resolve that commit,
    since an unresolvable hash is the very condition this remedy is printed
    under.
    """
    if entry.id:
        return f"rlsbl changelog remove --id {entry.id}"
    return f"rlsbl changelog remove --commits {stale_hashes[0]}"


def check_no_orphans(
    entries: list[ChangelogEntry],
    releases_dir: str,
    tag_glob: str | None = None,
    scope=None,
) -> tuple[bool, list[str]]:
    """Flag entries where all commits are stale (unresolvable or out of range).

    An entry is fully orphaned when ALL its hashes are unresolvable.
    An entry is effectively orphaned when every hash is either
    unresolvable or outside the unreleased range (the RELEASE RECORD's range at
    ``releases_dir`` — see :func:`check_in_range`) — no commit is both
    valid and in range.  *scope* is an
    :class:`~rlsbl.ownership.OwnershipScope`.

    The two ways a hash can be outside the scoped range are counted apart and
    named apart, exactly as :func:`check_in_range` names them: a commit
    another releasable owns is *out of scope*, and calling it out of range
    would say the history no longer contains it, which is false.
    """
    details: list[str] = []
    range_commits = set(_git_log_hashes(
        unreleased_range(releases_dir, tag_glob=tag_glob)))

    unreleased_commits = filter_commits_for_scope(
        range_commits, scope, operation="changelog orphan check",
    )

    for i, entry in enumerate(entries):
        if not entry.commits:
            continue
        resolved = resolve_hashes(entry.commits)
        n_unresolvable = sum(1 for v in resolved.values() if v is None)
        resolvable_shas = {v for v in resolved.values() if v is not None}
        outside = {sha for sha in resolvable_shas if sha not in unreleased_commits}
        n_out_of_scope = sum(1 for sha in outside if sha in range_commits)
        n_out_of_range = len(outside) - n_out_of_scope
        n_in_range = len(resolvable_shas) - len(outside)

        if n_unresolvable == len(entry.commits):
            # Fully orphaned: all hashes unresolvable
            stale_list = ", ".join(entry.commits)
            details.append(
                f"entry {i + 1} in unreleased.jsonl: all commits are stale "
                f"({n_unresolvable} unresolvable: {stale_list}) — run "
                f"`rlsbl changelog remap` to update stale SHAs, or "
                f"`{_removal_remedy(entry, list(entry.commits))}` if "
                f"the entry is genuinely obsolete"
            )
        elif n_in_range == 0 and (n_unresolvable > 0 or outside):
            # Effectively orphaned: mix of unresolvable, out-of-range and
            # out-of-scope hashes, with no hash that is both valid and in
            # this scope's range.
            stale_hashes = [h for h in entry.commits if resolved.get(h) is None]
            stale_hashes.extend(
                h for h in entry.commits
                if resolved.get(h) is not None
                and resolved[h] not in unreleased_commits
            )
            stale_list = ", ".join(stale_hashes)
            parts = []
            if n_unresolvable > 0:
                parts.append(f"{n_unresolvable} unresolvable")
            if n_out_of_range > 0:
                parts.append(f"{n_out_of_range} out of range")
            if n_out_of_scope > 0:
                parts.append(
                    f"{n_out_of_scope} in range but owned by another releasable"
                )
            details.append(
                f"entry {i + 1} in unreleased.jsonl: all commits are stale "
                f"({', '.join(parts)}: {stale_list}) — run "
                f"`rlsbl changelog remap` to update stale SHAs, or "
                f"`{_removal_remedy(entry, stale_hashes)}` if "
                f"the entry is genuinely obsolete"
            )

    return (len(details) == 0, details)


def check_schema(entries: list[ChangelogEntry]) -> tuple[bool, list[str]]:
    """Check that every entry passes schema validation."""
    details: list[str] = []
    for i, entry in enumerate(entries):
        errors = validate_schema(entry)
        for error in errors:
            details.append(f"entry {i + 1}: {error}")

    return (len(details) == 0, details)


def check_has_user_facing(entries: list[ChangelogEntry]) -> tuple[bool, list[str]]:
    """Check that at least one entry is user-facing."""
    user_facing = [e for e in entries if e.user_facing]
    if user_facing:
        return True, []
    return False, ["no user-facing changelog entries — every release must have at least one"]


def check_batch_size_commits(
    entries: list[ChangelogEntry],
    config: dict,
    version: str = "unreleased",
) -> tuple[bool, list[str]]:
    """Check that no entry has more commits than ``max_commits_per_entry``.

    ``config`` is the resolved batch_limits config (see
    :func:`_get_batch_limits_config`). Per-entry exclusions (matched by
    ``version`` + 1-based line number) silence the check for those entries.
    """
    max_commits = config.get("max_commits_per_entry", _BATCH_LIMITS_DEFAULTS["max_commits_per_entry"])
    exclusions = config.get("exclusions", [])

    exempted_entries: set[tuple[str, int]] = set()
    for excl in exclusions:
        if not isinstance(excl, dict):
            continue
        for entry_ref in excl.get("entries", []) or []:
            if not isinstance(entry_ref, dict):
                continue
            v = entry_ref.get("version")
            ln = entry_ref.get("line")
            if v is not None and isinstance(ln, int):
                exempted_entries.add((v, ln))

    details: list[str] = []
    for i, entry in enumerate(entries):
        line_num = i + 1
        if (version, line_num) in exempted_entries:
            continue
        if len(entry.commits) > max_commits:
            short_commits = ", ".join(c[:7] for c in entry.commits)
            details.append(
                f"{version}.jsonl line {line_num}: {len(entry.commits)} commits "
                f"(max: {max_commits}) [{short_commits}]"
            )
    if details:
        details.append(
            "Hint: add an exclusion to batch_limits.exclusions in .rlsbl/config.json, "
            "or use `rlsbl changelog add --allow-batch` to auto-create one."
        )
    return (len(details) == 0, details)


def check_batch_size_entries(
    entries_by_version: dict[str, list[ChangelogEntry]],
    config: dict,
) -> tuple[bool, list[str]]:
    """Check that no commit appears in more than ``max_entries_per_commit`` entries.

    ``entries_by_version`` maps version label (e.g. ``"unreleased"`` or
    ``"0.32.0"``) to its entry list, so the check spans across ALL JSONL
    files, not just unreleased. Per-commit exclusions in ``config``
    silence specific hashes.
    """
    max_entries = config.get("max_entries_per_commit", _BATCH_LIMITS_DEFAULTS["max_entries_per_commit"])
    exclusions = config.get("exclusions", [])

    exempted_commits: set[str] = set()
    for excl in exclusions:
        if not isinstance(excl, dict):
            continue
        for commit in excl.get("commits", []) or []:
            if isinstance(commit, str):
                resolved = resolve_hash(commit)
                if resolved is None:
                    # An exclusion commit hash that does not resolve points at a
                    # commit that is not in history (rebased/scrubbed away, or a
                    # typo). It cannot legitimately match any entry: entries store
                    # full, resolvable hashes (`changelog add` resolves via
                    # git rev-parse before writing), so a valid entry never
                    # carries an unresolvable string. Tolerating it would silently
                    # mask an invalid present config value. Fail loudly instead --
                    # fix the hash, remove the stale exclusion, or run
                    # `rlsbl changelog remap` after a history rewrite.
                    raise ConfigError(
                        f"Invalid batch_limits exclusion in .rlsbl/config.json: "
                        f"commit hash {commit!r} does not resolve to any commit in "
                        f"history. Remove the stale exclusion or run "
                        f"`rlsbl changelog remap` after a history rewrite."
                    )
                exempted_commits.add(resolved)

    appearances: dict[str, list[tuple[str, int]]] = {}
    for version, entries in entries_by_version.items():
        for i, entry in enumerate(entries):
            for commit in entry.commits:
                appearances.setdefault(commit, []).append((version, i + 1))

    details: list[str] = []
    for commit in sorted(appearances):
        locations = appearances[commit]
        if commit in exempted_commits:
            continue
        if len(locations) > max_entries:
            loc_str = ", ".join(f"{v}.jsonl:{ln}" for v, ln in locations)
            details.append(
                f"commit {commit[:7]}: appears in {len(locations)} entries "
                f"(max: {max_entries}) [{loc_str}]"
            )
    return (len(details) == 0, details)


def _read_all_versioned_entries(changes_dir: str) -> dict[str, list[ChangelogEntry]]:
    """Read entries from unreleased.jsonl AND every x.y.z.jsonl in changes_dir.

    Returns a mapping ``{version_label: entries}`` where ``version_label`` is
    ``"unreleased"`` or the bare semver string (e.g. ``"0.32.0"``).
    Files that fail to parse are skipped silently -- other checks surface
    such errors separately.
    """
    result: dict[str, list[ChangelogEntry]] = {
        "unreleased": read_unreleased(changes_dir),
    }
    for version, path in list_versioned_files(changes_dir):
        try:
            result[version] = parse_jsonl(path)
        except (ChangelogError, OSError):
            continue
    return result


