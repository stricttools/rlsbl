def validate_unreleased(changes_dir: str, tag_glob: str | None = None, scope=None, *, config: dict, bump_type: str | None = None) -> dict:
    """Run all 8 validation checks on unreleased.jsonl.

    Returns a dict with:
    - check names as keys, (passed, details) tuples as values
    - "passed": overall bool (True only if all checks pass)

    Uses validation cache: if the cache is valid and HEAD hasn't changed,
    skips full revalidation. The unreleased range comes from the RELEASE RECORD --
    the release archives beside ``changes_dir`` -- and ``tag_glob`` names the
    tag scheme those archives are checked against (e.g. ``mylib@v*`` or
    ``go/v*``). When *scope* is set (monorepo mode), coverage and range
    checks only consider commits touching files the scope's members own.
    *scope* is an :class:`~rlsbl.ownership.OwnershipScope`.

    The two batch_limits checks (``batch_size_commits`` and
    ``batch_size_entries``) read configuration via
    :func:`_get_batch_limits_config` from the provided config dict. The
    cross-version ``batch_size_entries`` check reads every
    ``x.y.z.jsonl`` file in ``changes_dir`` so it can detect commits
    that appear in too many entries across versions.
    """
    entries = read_unreleased(changes_dir)
    batch_config = _get_batch_limits_config(config)

    # Check cache
    if _is_cache_valid(changes_dir):
        cached_sha = _read_cache(changes_dir)
        head = _git_head()
        if cached_sha == head:
            # Nothing changed since last validation
            return {
                "passed": True,
                "checks": {
                    "hashes_resolve": (True, []),
                    "in_range": (True, []),
                    "coverage": (True, []),
                    "no_orphans": (True, []),
                    "schema": (True, []),
                    "batch_size_commits": (True, []),
                    "batch_size_entries": (True, []),
                    "user_facing": (True, []),
                },
            }
        # Cache is valid but HEAD moved: only validate new entries
        # (entries added since the cached state). Since we can't easily
        # determine which entries are new without more metadata, run full
        # validation but update cache on success.

    entries_by_version = _read_all_versioned_entries(changes_dir)

    releases_dir = releases_dir_for_changes_dir(changes_dir)
    checks = {
        "hashes_resolve": check_hashes_resolve(entries),
        "in_range": check_in_range(entries, releases_dir, tag_glob, scope=scope),
        "coverage": check_coverage(entries, releases_dir, tag_glob, scope=scope),
        "no_orphans": check_no_orphans(entries, releases_dir, tag_glob, scope=scope),
        "schema": check_schema(entries),
        "batch_size_commits": check_batch_size_commits(entries, batch_config, version="unreleased"),
        "batch_size_entries": check_batch_size_entries(entries_by_version, batch_config),
        "user_facing": check_has_user_facing(entries),
    }

    # Infra releases exempt the user_facing requirement but forbid
    # user-facing entries (use patch/minor/major for those).
    if bump_type == "infra":
        checks["user_facing"] = (True, [])
        has_user_facing = any(e.user_facing for e in entries)
        if has_user_facing:
            checks["infra_no_user_facing"] = (
                False,
                ["infra releases must not have user-facing entries — use patch, minor, or major instead"],
            )

    overall = all(passed for passed, _ in checks.values())

    if overall:
        _write_cache(changes_dir)

    return {
        "passed": overall,
        "checks": checks,
    }
