# Defaults applied when batch_limits keys are absent or malformed.
_BATCH_LIMITS_DEFAULTS = {
    "max_commits_per_entry": 5,
    "max_entries_per_commit": 5,
    "exclusions": [],
}


def _get_batch_limits_config(config) -> dict:
    """Return the resolved batch_limits config with defaults applied.

    ``config`` is the project config dict (already loaded).
    Reads the raw ``batch_limits`` section via
    :func:`get_changelog_validation_config` and guarantees that all three
    expected keys are present with sane types:

    - ``max_commits_per_entry`` (int)
    - ``max_entries_per_commit`` (int)
    - ``exclusions`` (list)

    A missing key keeps its documented default. A key that is *present*
    but has the wrong type is a hard error (:class:`ConfigError`) naming
    the key, the offending value, and the accepted type -- invalid config
    must never be silently replaced with a default.
    """
    raw = get_changelog_validation_config(config) or {}
    resolved: dict = {}

    for key, default in _BATCH_LIMITS_DEFAULTS.items():
        if key not in raw:
            resolved[key] = default
            continue
        value = raw[key]
        # bool is a subclass of int, so guard against accidental bool-as-int.
        if not isinstance(value, type(default)) or (
            isinstance(value, bool) and not isinstance(default, bool)
        ):
            raise ConfigError(
                f"Invalid batch_limits.{key} in .rlsbl/config.json: "
                f"{value!r} (type {type(value).__name__}). "
                f"Must be of type {type(default).__name__}."
            )
        resolved[key] = value

    return resolved



def _git_head() -> str | None:
    """Get the current HEAD commit hash."""
    try:
        result = effects.run(
            ["git", "rev-parse", "HEAD"],
            capture_output=True,
            text=True,
            timeout=10,
        )
        if result.returncode != 0:
            return None
        sha = result.stdout.strip()
        return sha if len(sha) == 40 else None
    except (subprocess.TimeoutExpired, FileNotFoundError, OSError):
        return None


