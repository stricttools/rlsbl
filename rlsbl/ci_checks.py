# A conclusion GitHub records for a job its ``if`` condition excluded. It is the
# ABSENCE of a verdict, never a verdict -- which is why neither gate accepts it,
# and also why :func:`latest_check_runs` may drop one that a later run answered.
SKIPPED_CONCLUSION = "skipped"

# The separator GitHub puts between a matrix job's name and its leg parameters:
# ``cli-ci / test`` expands to ``cli-ci / test (3.12)``. Used to recognize a
# skipped job's own legs, and nothing else -- ``cli-ci / test-extra`` is a
# DIFFERENT job and can never cover ``cli-ci / test``.
MATRIX_LEG_SUFFIX = " ("


def _check_run_order(run):
    """Recency key for one check run: ``started_at``, then numeric ``id``."""
    return (run.get("started_at") or "", int(run.get("id") or 0))


def has_verdict(run):
    """True when *run* concluded something other than ``skipped``.

    A check still in flight has no conclusion at all, and ``skipped`` is the
    ABSENCE of one, so neither can supersede a skip -- only a real verdict can.
    """
    return (
        run.get("status") == "completed"
        and run.get("conclusion") != SKIPPED_CONCLUSION
    )


def latest_check_runs(check_runs, regex, *, exclude_run_id=None):
    """Matching check runs, collapsed to one verdict per job.

    Mirrors the publish gate's jq pipeline: filter by name, drop this
    workflow's own runs, group by name ACROSS EVERY CHECK SUITE on the commit
    and keep the newest (``started_at``, then numeric ``id``) so a retried run
    supersedes the stale one it replaced.

    Recency alone cannot decide a skip, and that is not a detail. A ``run_all``
    dispatch (see :data:`RUN_ALL_REMEDY`) deliberately puts TWO check runs of
    the same name on one commit: ``skipped`` from the push-triggered suite
    whose paths filter found nothing, and a real conclusion from the dispatched
    suite. rlsbl dispatches immediately after pushing the candidate, while the
    push run's project jobs are still queued behind the router's ``detect``
    job -- so GitHub stamps the skip LATER than the dispatched run's verdict as
    a matter of course. Collapsing purely by time hands the gate the skip and
    refuses a commit whose jobs all ran and passed.

    So a skip never wins over a verdict: when the latest check run for a name
    is ``skipped``, it is replaced by the latest COMPLETED non-skipped check
    run of that same name, in whichever suite and whatever order the two were
    recorded. Success passes, failure fails -- nothing is waived. When every
    check run for that name is skipped (or none has concluded), the skip
    stands and the gate refuses.

    One more thing a per-name collapse cannot see: GitHub does not expand a
    matrix for a job its ``if`` skipped. The whole job collapses to ONE check
    run under the unsuffixed name (``cli-ci / test``), while the run that
    actually executes it emits one per leg (``cli-ci / test (3.12)``). The two
    never share a name, so the skip would outlive the run that answered it. A
    ``skipped`` check run is therefore also dropped when a completed,
    non-skipped check run for the SAME job -- its matrix expansion, by name --
    exists; the legs are then judged on their own conclusions, so a red leg
    still fails the gate. Nothing else can cover a skip: not a sibling job, not
    a merely prefix-sharing name, and not a leg that was itself skipped.
    """
    pattern = re.compile(regex)
    grouped: dict[str, list] = {}
    for run in check_runs:
        name = run.get("name") or ""
        if not pattern.search(name):
            continue
        if exclude_run_id and f"/actions/runs/{exclude_run_id}/" in (
            run.get("details_url") or ""
        ):
            continue
        grouped.setdefault(name, []).append(run)

    by_name: dict[str, dict] = {}
    for name, runs in grouped.items():
        chosen = max(runs, key=_check_run_order)
        if chosen.get("conclusion") == SKIPPED_CONCLUSION:
            verdicts = [r for r in runs if has_verdict(r)]
            if verdicts:
                chosen = max(verdicts, key=_check_run_order)
        by_name[name] = chosen

    kept = []
    for name in sorted(by_name):
        run = by_name[name]
        if run.get("conclusion") == SKIPPED_CONCLUSION and any(
            other.startswith(name + MATRIX_LEG_SUFFIX)
            and has_verdict(by_name[other])
            for other in by_name
        ):
            continue
        kept.append(run)
    return kept


def failing_check_runs(runs):
    """``(name, conclusion)`` for every run that did not conclude success.

    An incomplete run counts as failing here: the release gate only asks
    after every workflow run for the commit has already concluded, so a check
    still in flight at that point is not a pass either.
    """
    problems = []
    for run in runs:
        if run.get("status") != "completed":
            problems.append((run.get("name") or "?", run.get("status") or "pending"))
        elif run.get("conclusion") != PASSING_CONCLUSION:
            problems.append((run.get("name") or "?", run.get("conclusion") or "none"))
    return problems


def _decode_paginated(raw, key):
    """Collect ``key`` out of every page ``gh api --paginate`` concatenated.

    ``--paginate`` on a non-array response emits one JSON object per page back
    to back, so the stream is decoded rather than parsed as one document.
    """
    items = []
    decoder = json.JSONDecoder()
    idx = 0
    text = (raw or "").strip()
    while idx < len(text):
        obj, end = decoder.raw_decode(text, idx)
        items.extend(obj.get(key) or [])
        idx = end
        while idx < len(text) and text[idx] in " \t\r\n":
            idx += 1
    return items


def _gh_json(path, *, paginate=False, cwd=None, config=None):
    """GET *path* through ``gh api``, returning the raw stdout."""
    from .utils import run_gh

    argv = [
        "api",
        # ``--method GET`` is not decoration: the observe allowlist pins
        # ``gh api`` to the GET form, because the bare prefix would legalize
        # POST.  Without it this read matches no prefix, so a preview RECORDS
        # it and the gate reads a carrier where it expected JSON.
        "--method", "GET",
    ]
    if paginate:
        argv.append("--paginate")
    argv.append(path)
    return run_gh(argv, config=config, cwd=cwd)


def _job_verdict(job):
    """One job, in the record shape the collapse logic reads.

    Actions names a commit's check runs after the jobs that produced them, so
    a job record carries exactly the fields
    :func:`latest_check_runs` needs. ``html_url`` is carried as
    ``details_url`` because that is where the run id lives for the
    ``exclude_run_id`` filter, in the same ``/actions/runs/<id>/`` form the
    check-run payload uses.
    """
    return {
        "name": job.get("name") or "",
        "status": job.get("status"),
        "conclusion": job.get("conclusion"),
        "started_at": job.get("started_at") or "",
        "id": job.get("id") or 0,
        "details_url": job.get("html_url") or "",
        "run_id": job.get("run_id"),
        "run_attempt": job.get("run_attempt"),
    }


def fetch_run_jobs(run_id, *, cwd=None, config=None):
    """Every job of *run_id*'s LATEST attempt, as verdict records.

    Two reads, both keyed by the run id the caller already holds: the run
    object (for ``run_attempt``), then the ATTEMPT-SCOPED job list.

    The unscoped ``/actions/runs/<id>/jobs`` collection is never read, and
    that is deliberate rather than defensive. It answers for a run's whole
    history without saying which attempt a job belongs to, while every caller
    here wants the attempt that just concluded -- an in-place rerun keeps the
    run id and only the attempt advances. It is also the endpoint that 404s on
    repositories where the run object and the attempt-scoped job list both
    answer normally, which is how a green candidate's release aborted on a
    bare ``gh: Not Found (HTTP 404)``. There is one endpoint for jobs, and it
    is this one.
    """
    run_obj = json.loads(
        _gh_json(
            f"repos/{{owner}}/{{repo}}/actions/runs/{run_id}",
            cwd=cwd, config=config,
        )
        or "{}"
    )
    attempt = int(run_obj.get("run_attempt") or 1)
    raw = _gh_json(
        f"repos/{{owner}}/{{repo}}/actions/runs/{run_id}/attempts/{attempt}"
        f"/jobs?per_page=100",
        paginate=True, cwd=cwd, config=config,
    )
    return [_job_verdict(job) for job in _decode_paginated(raw, "jobs")]


def fetch_ci_jobs(run_ids, *, cwd=None, config=None):
    """The jobs of every run in *run_ids*, as one flat list of verdicts.

    The release gate collapses these by name across runs
    (:func:`latest_check_runs`), so a member's job in a ``run_all`` dispatch
    supersedes the same member's skipped job in the push run.
    """
    jobs = []
    for run_id in run_ids:
        jobs.extend(fetch_run_jobs(run_id, cwd=cwd, config=config))
    return jobs


