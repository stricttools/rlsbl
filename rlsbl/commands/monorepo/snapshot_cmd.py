"""Monorepo snapshot command: generate or verify .rlsbl-monorepo/snapshot.json."""

import sys

from ...snapshot import check_snapshot, generate_snapshot, write_snapshot
from ...utils import commit_files_if_changed
from ...workspace import find_workspace_root, load_workspace
from ...workspace_graph import WorkspaceGraph


def _cmd_snapshot(flags, project_root=None):
    """Generate or check the monorepo snapshot."""
    start = str(project_root) if project_root else "."
    root = find_workspace_root(start)
    if root is None:
        print("Error: No workspace found. Run 'rlsbl monorepo init' first.", file=sys.stderr)
        sys.exit(1)

    projects = load_workspace(root)
    if not projects:
        print("No projects in workspace.")
        return

    graph = WorkspaceGraph(root, projects)

    check = flags.get("check", False)

    if check:
        if check_snapshot(root, projects, graph):
            print("Snapshot is up-to-date.")
        else:
            print("Snapshot is stale or missing.", file=sys.stderr)
            sys.exit(1)
    else:
        snapshot = generate_snapshot(root, projects, graph)
        rel_path = write_snapshot(root, snapshot)
        print(f"Wrote {rel_path}")

        commit_files_if_changed("snapshot", [rel_path], skip_message="Snapshot unchanged.", autogenerated=True)
