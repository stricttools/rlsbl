def _enforce_gate(plan):
    """Refuse the undo when the evidence gate did not clear.

    PUBLISHED -> route to `release yank` / `release deprecate` (no bypass).
    INCONCLUSIVE / all-inconclusive -> hard block (same semantics as the
    non-latest path). Applies to BOTH the latest and non-latest paths.
    """
    gr = plan.gate_result
    if gr is None or gr.verdict == Verdict.CLEARED:
        return
    has_published = any(e.kind == EvidenceKind.PUBLISHED for e in gr.evidence)
    print(f"Error: cannot undo {plan.tag} -- {gr.reason}", file=sys.stderr)
    for e in gr.evidence:
        print(f"  {e.source}/{e.target}: {e.kind.value} -- {e.message}", file=sys.stderr)
    if has_published:
        v = plan.version
        print(
            "\nThis release appears to be PUBLISHED; undoing it is unsafe. "
            "Use a registry-aware removal instead:",
            file=sys.stderr,
        )
        print(f"  rlsbl release yank {v}       # remove it from registries", file=sys.stderr)
        print(f"  rlsbl release deprecate {v}  # mark it deprecated in place", file=sys.stderr)
    else:
        v = plan.version
        print(
            "\nVerify publication status manually and retry, or use "
            f"`rlsbl release yank {v}` / `rlsbl release deprecate {v}` "
            "if the version was published.",
            file=sys.stderr,
        )
    sys.exit(1)


def _print_plan(plan):
    """Print every write, deletion and commit the apply would perform.

    The plan used to name only the reverts, while the apply also wrote and
    committed the audit record, the restored changelog and the restored release
    file -- three commits a preview never mentioned. Steps whose commit is
    conditional say so rather than being left out.
    """
    kind = "latest" if plan.is_latest else "non-latest"
    print(f"Undo plan for {plan.tag} ({kind} release):")
    audit_path = os.path.join(plan.audit_dir, "undo-audit.json")
    print(f"  - Write {audit_path} and commit it "
          f'("chore: audit record for undo of {plan.tag}")')
    if plan.github_release_exists:
        print(f"  - Delete the GitHub Release for {plan.tag}")
    else:
        print(f"  - GitHub Release for {plan.tag}: none found (skip)")
    print(f"  - Delete git tag {plan.tag} (local + remote)")
    for ct in plan.companion_tags:
        print(f"  - Delete companion tag {ct} (local + remote)")
    if plan.revert_shas:
        print(f"  - Revert {len(plan.revert_shas)} release commit(s) (newest first):")
        for sha, subject in plan.revert_shas:
            print(f"      {sha[:10]}  {subject}")
    else:
        # Only the non-latest path gets here: the latest path refuses when it
        # cannot locate the release's version-bump commit.
        print("  - No commit revert (non-latest release -- history moved on)")
    print(f"  - Un-finalize {plan.version}.jsonl back into unreleased.jsonl "
          f"(merging anything added since) and regenerate CHANGELOG.md")
    print(f'  - Commit the restored changelog ("chore: restore changelog after '
          f'undo of {plan.tag}"), when it changed anything')
    if not plan.captured_finalize_release_file:
        print(f"  - Restore unreleased.toml from v{plan.version}.toml and commit "
              f'it ("chore: restore release file after undo of {plan.tag}"), '
              f"when it changed anything")
    print("  - Push the branch to the remote")
    print("  - Clear any in-progress release state")
    if plan.gate_result is not None:
        print("  Evidence:")
        for e in plan.gate_result.evidence:
            print(f"    {e.source}/{e.target}: {e.kind.value} -- {e.message}")


