def _resolve_context(ctx):
    """Detect the monorepo / releasable context shared by both undo paths."""
    monorepo_name = None
    monorepo_project_path = None
    releasable_name = None
    releasable_config_dir = None
    releasables = None
    start_path = str(ctx.project_root)
    ws_root = find_workspace_root(start_path)
    if ws_root:
        project = resolve_project(ws_root, start_path)
        if project is None:
            print("Error: current directory is inside a monorepo but not inside any project.", file=sys.stderr)
            sys.exit(1)
        monorepo_name = project["name"]
        monorepo_project_path = project["path"]
        from ..targets import resolve_releasable_config_dir
        releasable_config_dir = resolve_releasable_config_dir(project, ws_root)

        from ..workspace import load_releasables, load_workspace as _load_ws, resolve_releasable_for_project
        ws_projects = _load_ws(ws_root)
        releasables = load_releasables(ws_root, ws_projects)
        rel = resolve_releasable_for_project(project, releasables)
        if rel:
            releasable_name = rel.name

    project_path = os.path.join(ws_root, monorepo_project_path) if monorepo_name else str(ctx.project_root or ".")
    return SimpleNamespace(
        start_path=start_path,
        ws_root=ws_root,
        monorepo_name=monorepo_name,
        monorepo_project_path=monorepo_project_path,
        releasable_name=releasable_name,
        releasable_config_dir=releasable_config_dir,
        releasables=releasables,
        project_path=project_path,
    )


def _ledger_dir(uc):
    """The release archives for the project or releasable being undone."""
    return os.path.join(_audit_dir(uc), "releases")


def _find_latest_release(uc):
    """The version ``undo`` reverts, and its tag -- selected from the LEDGER.

    ``undo`` used to ask ``git describe --tags --abbrev=0`` which release was
    the latest, so a release whose tag had already been half-deleted was
    invisible to the command whose whole job is deleting it, and a hand-made
    tag could nominate a release that never happened. The archives answer
    which version is latest; the tag is then derived by translation
    (:func:`_build_tag_from_version`).

    Only the archive's EXISTENCE is read here, not its anchor: everything
    after this point -- the commit walk, the tag deletion, the revert --
    operates on the tag namespace, so undo is an observe-and-repair layer over
    tags in the same sense ``release reconcile`` is, and refusing to start
    because an anchor and a tag disagree would refuse exactly the repair the
    operator came for. The anchor IS read for the predecessor boundary, where
    it decides which commits belong to this release (see :func:`_build_plan`).

    Returns ``(version, tag)``, or exits when nothing is recorded.
    """
    from ..release_file import list_archived_versions

    versions = list_archived_versions(_ledger_dir(uc))
    if not versions:
        print("Error: no releases recorded. Nothing to undo.", file=sys.stderr)
        sys.exit(1)
    return versions[0], _build_tag_from_version(uc, versions[0])


def _version_and_msg(uc, tag):
    """Return (bare_version, expected_version_bump_message) for a tag."""
    if uc.releasable_name or uc.monorepo_name:
        from ..tag_glob import TagMode, parse_version_tag
        parsed = parse_version_tag(tag, mode=TagMode.PRERELEASE_INCLUSIVE)
        version_part = f"v{parsed.version}" if parsed else tag
        name = uc.releasable_name or uc.monorepo_name
        return version_part.lstrip("v"), f"{name}: release {version_part}"
    return tag.lstrip("v"), tag


def _build_tag_from_version(uc, version):
    """Build the release tag string for a given version (non-latest path)."""
    member = resolve_member_context(
        uc.start_path, releasable_config_dir=uc.releasable_config_dir,
    )
    entries = member.targets
    if not entries:
        return f"v{version}"
    target_obj = TARGETS[entries[0].name]
    if uc.releasable_name and uc.ws_root:
        from ..workspace import load_releasables as _lr, load_workspace as _lw
        _rels = _lr(uc.ws_root, _lw(uc.ws_root))
        _rel = next((r for r in _rels if r.name == uc.releasable_name), None)
        if _rel and _rel.effective_tag_format:
            from .release.validate import _format_releasable_tag
            return _format_releasable_tag(_rel.effective_tag_format, uc.releasable_name, version)
        return target_obj.monorepo_tag_format(uc.monorepo_name, version, path=uc.monorepo_project_path)
    if uc.monorepo_name:
        return target_obj.monorepo_tag_format(uc.monorepo_name, version, path=uc.monorepo_project_path)
    return target_obj.tag_format(version)


def _classify_release_commit(subject, expected_msg):
    """Return the shape of a release commit, or None if it is not one."""
    if subject == expected_msg:
        return "version_bump"
    if _FINALIZE_CHANGELOG_RE.match(subject):
        return "finalize_changelog"
    if _FINALIZE_RELEASE_FILE_RE.match(subject):
        return "finalize_release_file"
    if _CLEAN_STALE_RE.match(subject):
        return "clean_stale"
    if _REGEN_MD_RE.match(subject):
        return "regenerate_md"
    if _SNAPSHOT_RE.match(subject):
        return "snapshot"
    return None


def _die(*lines):
    """Print an operator-facing refusal and exit, having changed nothing."""
    for line in lines:
        print(line, file=sys.stderr)
    sys.exit(1)


def _release_anchor(uc, version, tag):
    """The commit the LEDGER records *version* as having shipped from.

    Read from the archive DIRECTLY rather than through
    :func:`rlsbl.ledger.read_entry`, which refuses when the version's tag and
    the anchor disagree. Undo is the repair path for exactly that state and is
    about to delete the tag, so a disagreement is reported as a warning and the
    ARCHIVE wins: it is written by the release flow, committed, and rewritten by
    rlsbl only through its own documented unlock paths, while a tag is a ref
    anyone can move.
    """
    from ..release_file import archived_release_path, read_release_file

    path = archived_release_path(_ledger_dir(uc), version)
    try:
        cfg = read_release_file(path)
    except Exception as exc:
        _die(
            f"Error: the release archive for {version} could not be read: {path}",
            f"  {exc}",
            "  Undo refused: nothing was destroyed. That archive is what records "
            "which commit the release shipped from.",
        )
    if getattr(cfg, "unanchorable", False) or not getattr(cfg, "candidate_sha", None):
        _die(
            f"Error: the release archive for {version} records no commit: {path}",
            "  Undo cannot find the release's own commits without it, and "
            "deleting the tag while",
            "  leaving the version files bumped is the half-undone state this "
            "command exists to avoid.",
            "  Backfill the anchor (scripts/backfill_release_anchors.py) and "
            "re-run.",
        )
    anchor = cfg.candidate_sha
    try:
        anchor = run("git", ["rev-parse", "--verify", f"{anchor}^{{commit}}"],
                     timeout=30).strip()
    except Exception:
        _die(
            f"Error: the commit the release archive records for {version} is not "
            f"in this repository: {cfg.candidate_sha}",
            f"  archive: {path}",
            "  Fetch the missing history (git fetch --unshallow) and re-run.",
        )

    tag_sha = ""
    try:
        tag_sha = run("git", ["rev-list", "-n", "1", tag], timeout=30).strip()
    except Exception:
        pass
    if tag_sha and tag_sha != anchor:
        print(
            f"warning: the tag {tag} points at {tag_sha[:12]} but the release "
            f"archive anchors {version} at {anchor[:12]}. The archive is what "
            f"undo reverts from; the tag is deleted either way.",
            file=sys.stderr,
        )
    return anchor


def _predecessor_anchor(uc, version):
    """The commit the release BELOW *version* shipped from, or None.

    The boundary survives that release's tag being deleted, because it is read
    from the archive rather than from ``git describe``.
    """
    from ..ledger import read_entry
    from ..release_file import list_archived_versions

    versions = list_archived_versions(_ledger_dir(uc))
    try:
        below = versions[versions.index(version) + 1:]
    except ValueError:
        below = []
    for prev in below:
        try:
            entry = read_entry(_ledger_dir(uc), prev, cwd=uc.project_path)
        except Exception as exc:
            # An unreadable predecessor archive (a tag that disagrees with its
            # anchor, say) only widens the search range, and the version-bump
            # subject is version-specific, so a wider range cannot match an
            # older release's bump. Said out loud rather than swallowed.
            print(
                f"warning: the release archive for {prev} could not be read "
                f"({exc}); looking further back for the boundary of "
                f"{version}'s commits.",
                file=sys.stderr,
            )
            continue
        if entry.anchored:
            return entry.candidate_sha
    return None


def _log_commits(range_spec):
    """``[(sha, subject)]`` for a git range, newest first."""
    try:
        out = run("git", ["log", "--format=%H%x1f%s", range_spec], timeout=60)
    except Exception:
        return None
    commits = []
    for line in out.splitlines():
        sha, _sep, subject = line.partition("\x1f")
        if sha.strip():
            commits.append((sha.strip(), subject.strip()))
    return commits


def _collect_release_commits(uc, version, tag, expected_msg):
    """The release's own commits, newest-first, located through the LEDGER.

    The search range is ``<predecessor's anchor>..<this release's anchor>``,
    both read from the archives. Inside it the version-bump commit is
    identified and everything release-shaped from the bump up to the anchor is
    collected; foreign commits in between (a fix-forward) are left alone, and
    the predecessor's own finalization commits are below the bump and so out of
    the collected set.

    Returns ``(revert_shas, captured_finalize_changelog,
    captured_finalize_release_file, anchor)``. Refuses -- loudly, before
    anything is destroyed -- when the version-bump commit cannot be found: a
    silent "no release commits found" is how undo used to delete a tag and a
    GitHub Release while leaving the version files bumped.
    """
    anchor = _release_anchor(uc, version, tag)
    predecessor = _predecessor_anchor(uc, version)
    range_spec = f"{predecessor}..{anchor}" if predecessor else anchor

    commits = _log_commits(range_spec)
    if commits is None:
        _die(
            f"Error: could not read the commits of release {tag}: "
            f"git log {range_spec} failed.",
            "  Undo refused: nothing was destroyed.",
        )

    bump_indexes = [
        i for i, (_sha, subject) in enumerate(commits)
        if _classify_release_commit(subject, expected_msg) == "version_bump"
    ]
    if not bump_indexes:
        anchor_subject = commits[0][1] if commits else "(no commits in range)"
        _die(
            f"Error: could not find the version-bump commit of {tag}.",
            f"  The release archive anchors {version} at {anchor[:12]} "
            f'("{anchor_subject}").',
            f"  Searched {range_spec} for a commit whose subject is exactly "
            f'"{expected_msg}"',
            f"  and found none among its {len(commits)} commit(s).",
            "  Undo refused: nothing was destroyed. Deleting the tag and the "
            "GitHub Release while",
            "  leaving the version files bumped is the half-undone state this "
            "command exists to avoid.",
            f"  Inspect the range (git log --oneline {range_spec}); if the "
            "release's commits were",
            "  rewritten, repair the ledger and the tags first "
            "(`rlsbl release reconcile`).",
        )
    if len(bump_indexes) > 1:
        shas = ", ".join(commits[i][0][:10] for i in bump_indexes)
        _die(
            f"Error: {len(bump_indexes)} commits in {range_spec} carry the "
            f'version-bump subject "{expected_msg}": {shas}.',
            "  Undo refused: nothing was destroyed. rlsbl will not guess which "
            "one shipped the release.",
        )

    # Everything release-shaped from the bump commit up to the anchor. The list
    # is newest-first, so the bump is the LAST element of the slice.
    span = commits[: bump_indexes[0] + 1]
    collected = []
    captured_cl = False
    captured_rf = False
    for sha, subject in span:
        shape = _classify_release_commit(subject, expected_msg)
        if shape is None:
            continue
        collected.append((sha, subject))
        if shape == "finalize_changelog":
            captured_cl = True
        elif shape == "finalize_release_file":
            captured_rf = True
    return collected, captured_cl, captured_rf, anchor


def _commit_paths(sha):
    """Every path a commit touches (empty for a merge, which shows no diff)."""
    try:
        out = run("git", ["show", "--pretty=format:", "--name-only", sha],
                  timeout=60)
    except Exception:
        return []
    return [p.strip() for p in out.splitlines() if p.strip()]


def _refuse_foreign_work_above_anchor(anchor, revert_shas, tag):
    """Refuse when work above the released commit endangers the revert.

    A commit between the anchor and HEAD is safe when either it is entirely
    rlsbl's own bookkeeping (the finalization commits, and anything else in the
    tool-owned set) or it touches none of the files the revert touches -- a
    post-release hook writing its own notes cannot conflict with reverting a
    version bump. Anything else is refused BEFORE the first deletion: reverting
    the bump underneath somebody's edit of the same file is how a rollback ends
    up mid-conflict, and by then the tag and the GitHub Release are gone.
    """
    from ..ownership import is_tool_owned_path

    if not revert_shas:
        return
    reverted_paths = set()
    for sha, _subject in revert_shas:
        reverted_paths.update(_commit_paths(sha))
    if not reverted_paths:
        return

    span = _log_commits(f"{anchor}..HEAD")
    if span is None:
        _die(
            f"Error: could not read the commits above the released commit "
            f"{anchor[:12]}.",
            "  Undo refused: nothing was destroyed.",
        )
    for sha, subject in span:
        paths = _commit_paths(sha)
        if paths and all(is_tool_owned_path(p) for p in paths):
            continue
        overlap = sorted(set(paths) & reverted_paths)
        if not overlap:
            continue
        _die(
            f"Error: cannot undo {tag} -- commit {sha[:12]} "
            f'("{subject}") sits above the released commit and changes files '
            f"the undo must revert:",
            *[f"    {p}" for p in overlap],
            "  Reverting the release underneath it would leave the rollback "
            "mid-conflict, with the",
            "  tag and the GitHub Release already deleted.",
            "  Undo refused: nothing was destroyed. Move that work aside (or "
            "revert it yourself)",
            "  and re-run.",
        )


def _plan_companion_tags(uc, tag, version):
    """Enumerate the version's non-primary refs to delete (releasable mode only).

    Asks the same ``expected_refs`` authority the release's tag step asked when
    it CREATED them, so undo cannot leave behind a ref the release made. A
    recorded alias is included: it addresses the version being undone.

    Degrades to an empty list on any failure, with the traceback printed. Undo
    is a repair path, and refusing to remove the primary tag because a member's
    config no longer resolves would strand the release entirely.
    """
    if not (uc.releasable_name and uc.ws_root):
        return []
    try:
        from ..commands.release.execute import release_ref_context
        from ..workspace import (
            get_releasable_dir,
            load_releasables,
            load_workspace,
            members_of,
        )

        ws_projects = load_workspace(uc.ws_root)
        member_paths = [p["path"] for p in members_of(uc.releasable_name, ws_projects)]
        rel_cfg_dir = get_releasable_dir(str(uc.ws_root), uc.releasable_name)

        rel = next(
            (r for r in load_releasables(uc.ws_root, ws_projects)
             if r.name == uc.releasable_name),
            None,
        )
        tag_fmt = rel.effective_tag_format if rel else None

        member = resolve_member_context(
            uc.start_path, releasable_config_dir=uc.releasable_config_dir,
        )
        entries = member.targets
        if not entries:
            return []
        expected = TARGETS[entries[0].name].expected_refs(
            version,
            release_ref_context(
                monorepo_root=uc.ws_root, git_root=uc.project_path,
                monorepo_name=uc.monorepo_name,
                monorepo_project_path=uc.monorepo_project_path,
                releasable_name=uc.releasable_name,
                releasable_tag_format=tag_fmt,
                member_package_paths=member_paths,
                releasable_config_dir=rel_cfg_dir,
            ),
        )
        return [t for t in expected.tags if t != tag]
    except Exception:
        traceback.print_exc()
        return []


def _gh_release_exists(tag, ctx):
    try:
        run_gh(["release", "view", tag], config=ctx.config)
        return True
    except Exception:
        return False


def _plan_gate(uc, ctx, version):
    """Run the registry evidence gate for the release (both paths).

    Resolution goes through MemberContext so targets/paths inherit
    releasable-level config. ``resolved_targets`` is available on the
    context for future per-pipeline evidence checks, but the evidence
    gate currently operates per-target-object only.
    """
    member = resolve_member_context(
        uc.start_path, releasable_config_dir=uc.releasable_config_dir,
    )
    try:
        entries = member.targets
    except Exception:
        entries = []
    target_objects = [TARGETS[e.name] for e in entries] if entries else []
    return run_evidence_gate(target_objects, uc.start_path, version, ctx)


def _audit_dir(uc):
    if uc.releasable_name and uc.ws_root:
        from ..workspace import get_releasable_dir
        return get_releasable_dir(str(uc.ws_root), uc.releasable_name)
    return os.path.join(uc.project_path, ".rlsbl")


def _build_plan(uc, flags, ctx):
    """Compute the full UndoPlan for either path, before any mutation."""
    version_flag = flags.get("version")
    is_latest = not version_flag
    if is_latest:
        version, tag = _find_latest_release(uc)
        _tag_version, expected_msg = _version_and_msg(uc, tag)
        revert_shas, cap_cl, cap_rf, anchor = _collect_release_commits(
            uc, version, tag, expected_msg,
        )
        # The one guard left, and it fires before anything is destroyed: work
        # above the released commit that touches what the revert touches.
        _refuse_foreign_work_above_anchor(anchor, revert_shas, tag)
    else:
        version = version_flag.lstrip("v")
        tag = _build_tag_from_version(uc, version)
        revert_shas, cap_cl, cap_rf = [], False, False

    return UndoPlan(
        tag=tag,
        is_latest=is_latest,
        version=version,
        revert_shas=revert_shas,
        companion_tags=_plan_companion_tags(uc, tag, version),
        github_release_exists=_gh_release_exists(tag, ctx),
        gate_result=_plan_gate(uc, ctx, version),
        project_path=uc.project_path,
        ws_root=uc.ws_root,
        releasable_name=uc.releasable_name,
        monorepo_name=uc.monorepo_name,
        monorepo_project_path=uc.monorepo_project_path,
        audit_dir=_audit_dir(uc),
        captured_finalize_changelog=cap_cl,
        captured_finalize_release_file=cap_rf,
    )


