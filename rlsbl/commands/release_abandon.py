"""``rlsbl release abandon``: record an abandoned release attempt's version as never released.

A release attempt that stops before the step that records it leaves a version
number claimed and unrecorded: the in-progress state file names it, and the
version files usually name it too, because the version write comes early. The
release record then holds nothing for that number, and the release flow
refuses to guess what it is.

Abandoning writes the one record that settles it: the version's archive with
the ``never_released`` fate. From there the release flow bumps from that
version when the version files name it, and never releases under it again.
The in-progress state file is deleted, and the archive is committed with the
``Autogenerated`` trailer, as one operation.

What it does not do: revert commits. The attempt's version-bump commit (and
anything else it pushed) stays where it is -- the version files naming a
never-released number is exactly the state the next release bumps from.

The version comes from the in-progress state file when there is one, and from
the version files when it is gone. A re-run after an abandon that committed its
archive but stopped before deleting the state file finishes it: when the state
file names a version already recorded never released, the archive is committed
if the earlier run had not committed it, and the state file is deleted. It refuses, before anything is written:

* when there is nothing to abandon -- no in-progress state, and the version
  files name a version the record already holds (released or never released);
* when the version it would abandon is already archived as a release;
* when that version is below the latest release: a number below it is never
  recorded as never released;
* when the attempt's tag exists (locally or on origin) with no archive: the
  tag is evidence of a release, and ``rlsbl release backfill`` adopts it as
  that release (a tag only on origin is fetched first);
* when the attempt's GitHub Release exists with no tag anywhere: that is a
  published release, and ``rlsbl release undo`` applies.

Every probe that cannot answer is a hard error, never read as "absent".
"""

import subprocess
import sys

from ..errors import RlsblError


# The command line every remedy prints. Stated once, so the refusals of
# `release run`, `release undo` and the executor cannot drift from it.
ABANDON_INVOCATION = "rlsbl release abandon --approve-consequential"

_HEADER = [
    "Written by `rlsbl release abandon`: a release attempt claimed this version",
    "number and was abandoned before the step that records a release, so no",
    "release was ever published under it. The release flow bumps from it when",
    "the version files name it, and never releases under it again. bump is",
    "derived by version arithmetic against the latest release.",
]


class AbandonError(RlsblError):
    """A probe could not answer, so nothing was abandoned."""


def abandon_remedy(version):
    """The remedy sentence every in-flight refusal prints for an unrecorded attempt."""
    return (
        f"To abandon {version} instead, run `{ABANDON_INVOCATION}`: it records "
        f"{version} as never released and deletes the in-progress state file. "
        f"The attempt's commits stay where they are, and the next release bumps "
        f"from {version} when the version files name it."
    )


def leftover_state_remedy(version, archive_path, state_path):
    """The remedy for a state file whose version is already recorded never released."""
    return (
        f"{version} is recorded as never released ({archive_path}), so this "
        f"in-progress state file is left over from an attempt that was already "
        f"abandoned. Delete it, then re-run: {state_path}"
    )


def _die(*lines):
    for line in lines:
        print(line, file=sys.stderr)
    sys.exit(1)


def _github_release_exists(tag, config):
    """Does a GitHub Release stand under *tag*? True, False, or a hard error.

    Only gh's own "release not found" answer means absent. gh missing or
    unauthenticated, a network failure, anything else: the question was not
    answered, and abandoning a version whose Release may exist would record a
    published version as never released.
    """
    from ..utils import check_gh_auth, check_gh_installed, run_gh

    if not check_gh_installed() or not check_gh_auth():
        raise AbandonError(
            f"cannot tell whether a GitHub Release exists for {tag}: the gh CLI "
            f"is not installed or not authenticated. Install and authenticate "
            f"gh (gh auth login), then re-run."
        )
    try:
        run_gh(["release", "view", tag, "--json", "tagName"], config=config)
        return True
    except subprocess.CalledProcessError as exc:
        text = f"{exc.stderr or ''}{exc.stdout or ''}".lower()
        if "release not found" in text:
            return False
        raise AbandonError(
            f"cannot tell whether a GitHub Release exists for {tag}: gh release "
            f"view failed ({str(exc.stderr or exc).strip()}). Resolve the "
            f"GitHub access problem, then re-run."
        ) from exc


def _version_files_version(uc):
    """The version the version files name, or a refusal when they disagree."""
    from ..member_context import resolve_member_context
    from ..targets import TARGETS

    if uc.releasable_name and uc.ws_root:
        from ..workspace import read_releasable_version
        return read_releasable_version(str(uc.ws_root), uc.releasable_name)

    member = resolve_member_context(
        uc.start_path, releasable_config_dir=uc.releasable_config_dir,
    )
    versions = {
        name: TARGETS[name].read_version(path)
        for name, path in member.target_paths.items()
    }
    distinct = sorted(set(versions.values()))
    if not distinct:
        _die(
            "Error: this project declares no release target, so no version "
            "file names a version to abandon.",
        )
    if len(distinct) > 1:
        _die(
            "Error: the version files disagree, so which version to abandon is "
            "not decided:",
            *(f"  {name}: {version}" for name, version in sorted(versions.items())),
            "  Nothing was changed. Make them agree, then re-run.",
        )
    return distinct[0]


def _latest_release(releases_dir):
    """The highest archived version that was released, or None."""
    from ..release_file import list_archived_versions
    from ..release_record import read_version_fate

    for candidate in list_archived_versions(releases_dir):
        if read_version_fate(releases_dir, candidate).released:
            return candidate
    return None


def _adopt_with_backfill(version, archive_path, *, fetch_tag=None):
    """The remedy for a tag that stands with no archive: backfill adopts it."""
    lines = [
        f"  The release record holds no archive for {version} ({archive_path}), "
        f"and a tag is evidence of a release, so {version} is not recorded as "
        f"never released. Nothing was changed.",
    ]
    if fetch_tag:
        lines.append(
            "  Fetch the tag, then record the release it is evidence of: "
            "`rlsbl release backfill` adopts a version tag no archive records "
            "as released from the commit it names. Preview first, then write:"
        )
        lines.append(f"    git fetch origin tag {fetch_tag}")
    else:
        lines.append(
            "  Record the release the tag is evidence of: `rlsbl release "
            "backfill` adopts a version tag no archive records as released "
            "from the commit it names. Preview first, then write:"
        )
    lines.append("    rlsbl release backfill --dry-run")
    lines.append("    rlsbl release backfill --approve-consequential")
    return lines


def run_cmd(flags, *, ctx):
    """Record the abandoned attempt's version as never released."""
    from .release.release_state import clear_release_state, load_release_state
    from .release.validate import (
        ReleaseValidationError,
        behind_latest_release_text,
        is_behind,
    )
    from .undo import (
        _build_tag_from_version,
        _in_progress_state_path,
        _release_record_dir,
        _resolve_context,
    )
    from ..release_backfill import derive_bump
    from ..release_file import archived_release_path, write_archived_release_file
    from ..release_record import VersionFate, read_version_fate
    from ..utils import (
        LocalTagState,
        RemoteTagState,
        commit_files,
        local_tag_state,
        remote_tag_commit,
        working_tree_paths,
    )
    from .. import effects

    dry_run = flags.get("dry-run", False)
    uc = _resolve_context(ctx)
    state_path = _in_progress_state_path(uc)
    releases_dir = _release_record_dir(uc)

    try:
        state = load_release_state(state_path)
    except Exception as exc:
        _die(
            f"Error: the in-progress release state could not be read: {state_path}",
            f"  {exc}",
            "  Nothing was changed: which version the attempt claimed is unknown.",
        )

    if state is not None:
        version = str(state.get("new_version") or "").strip()
        if not version:
            _die(
                f"Error: the in-progress release state names no version: "
                f"{state_path}",
                "  Nothing was changed: which version the attempt claimed is "
                "unknown.",
            )
    else:
        version = _version_files_version(uc)

    archive_path = archived_release_path(releases_dir, version)
    fate = read_version_fate(releases_dir, version, cwd=uc.project_path)
    if state is not None and fate is VersionFate.NEVER_RELEASED:
        # An earlier abandon wrote the archive and stopped before its commit,
        # or after it and before deleting the state file. The archive is
        # already the record; finish whichever part is left.
        uncommitted = working_tree_paths(
            uc.project_path, paths=[archive_path], untracked="all",
        )
        if uncommitted:
            commit_files(
                f"chore: record {version} as never released (abandoned release attempt)",
                [archive_path],
                cwd=uc.project_path,
            )
        clear_release_state(state_path)
        verb = "would complete" if dry_run else "completed"
        print(
            f"This run {verb} the earlier abandon of {version}: the release "
            f"record already holds {version} as never released ({archive_path})."
        )
        if uncommitted:
            verb = "Would commit" if dry_run else "Committed"
            print(f"{verb} that archive, which the earlier run had not committed.")
        verb = "Would delete" if dry_run else "Deleted"
        print(f"{verb} the in-progress release state: {state_path}")
        return
    if state is None and fate is not VersionFate.ABSENT:
        held = "released" if fate.released else "never released"
        _die(
            f"Error: there is nothing to abandon: no release is in progress "
            f"({state_path} does not exist), and the version files name "
            f"{version}, which the release record already holds as {held}: "
            f"{archive_path}",
            "  Nothing was changed.",
        )
    if fate is not VersionFate.ABSENT:
        _die(
            f"Error: {version} is already archived, as a release: {archive_path}",
            "  Abandoning writes that archive, so there is nothing left for it "
            "to record. Nothing was changed.",
        )

    latest = _latest_release(releases_dir)
    try:
        behind = latest is not None and is_behind(version, latest)
    except ReleaseValidationError as exc:
        _die(f"Error: {exc}")
    if behind:
        if state is None:
            _die(
                "Error: " + behind_latest_release_text(
                    version, latest, named_by="the version files say",
                ),
                f"  Set the version files to {latest}: they then name the "
                f"latest release, and there is no abandoned version for them "
                f"to name.",
            )
        _die(
            "Error: " + behind_latest_release_text(
                version, latest, named_by="the in-progress release state names",
            ),
            f"  The state file: {state_path}",
        )

    tag = str((state or {}).get("tag") or "").strip() or _build_tag_from_version(
        uc, version,
    )
    if local_tag_state(tag, uc.project_path) is LocalTagState.PRESENT:
        _die(f"Error: the attempt's tag {tag} exists in this repository.",
             *_adopt_with_backfill(version, archive_path))
    remote = remote_tag_commit(tag, cwd=uc.project_path)
    if remote.state is RemoteTagState.INCONCLUSIVE:
        _die(
            f"Error: cannot tell whether the attempt's tag {tag} exists on "
            f"origin: {remote.error}",
            "  Nothing was changed. Resolve the remote access problem, then "
            "re-run.",
        )
    if remote.state is RemoteTagState.PRESENT:
        _die(f"Error: the attempt's tag {tag} exists on origin at "
             f"{remote.commit}.",
             *_adopt_with_backfill(version, archive_path, fetch_tag=tag))
    try:
        release_exists = _github_release_exists(tag, ctx.config)
    except AbandonError as exc:
        _die(f"Error: {exc}", "  Nothing was changed.")
    if release_exists:
        _die(f"Error: a GitHub Release exists for the attempt's tag {tag}.",
             "  That is a published release, and `rlsbl release undo` reverts "
             "it. Nothing was changed.")

    write_archived_release_file(
        releases_dir, version,
        bump=derive_bump(version, latest),
        include=[],
        description=f"Abandoned release attempt: {version} was never released.",
        candidate_sha=None,
        tree_hashes=None,
        never_released=True,
        header_comments=_HEADER,
    )
    try:
        commit_files(
            f"chore: record {version} as never released (abandoned release attempt)",
            [archive_path],
            cwd=uc.project_path,
        )
    except Exception:
        # The archive and its commit are one operation: an archive left behind
        # uncommitted would stand in the tree as a record no commit carries.
        effects.chmod(archive_path, 0o644)
        effects.remove(archive_path, missing_ok=True)
        raise
    if state is not None:
        clear_release_state(state_path)

    verb = "Would record" if dry_run else "Recorded"
    print(f"{verb} {version} as never released: {archive_path}")
    if state is not None:
        verb = "Would delete" if dry_run else "Deleted"
        print(f"{verb} the in-progress release state: {state_path}")
    print(
        f"The next release bumps from {version} when the version files name it, "
        f"and never releases under {version}."
    )
