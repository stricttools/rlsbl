def _compare_versions(local, remote):
    """Compare two semver version strings.

    Returns "AHEAD" if local > remote, "BEHIND" if local < remote,
    "SAME" if equal, or "ERROR" if either version cannot be parsed.
    """
    import re
    pattern = re.compile(r"^(\d+)\.(\d+)\.(\d+)")
    m_local = pattern.match(local)
    m_remote = pattern.match(remote)
    if not m_local or not m_remote:
        return "ERROR"
    local_tuple = (int(m_local.group(1)), int(m_local.group(2)), int(m_local.group(3)))
    remote_tuple = (int(m_remote.group(1)), int(m_remote.group(2)), int(m_remote.group(3)))
    if local_tuple > remote_tuple:
        return "AHEAD"
    elif local_tuple < remote_tuple:
        return "BEHIND"
    return "SAME"


def _collect_status(registry, target_path=".", *, tag_glob=None, ctx, project=None,
                    flags=None, changes_dir=None, scope=None):
    """Collect status data as a dict.

    When tag_glob is set (monorepo mode), it scopes the ledger read so
    coverage is computed against this project's own releases.

    When *scope* is set (monorepo mode), unreleased commits are filtered to
    those touching a file the scope's members own, so the count reflects
    actual project-specific changes. A releasable's scope spans every member
    -- a commit touching ANY member is the releasable's commit -- and a root
    member's scope covers every file no other member claims.

    changes_dir overrides where the JSONL changelog lives; releasable members
    keep theirs under the releasable, not the member package.

    When flags contains "registry": True, queries the package registry
    for the latest published version and computes drift.

    Returns ``(data, latest)`` -- the machine payload and the
    :class:`~rlsbl.ledger.LatestReleaseFact` it was built from. The fact comes
    back because the payload flattens it into two nullable fields, and the
    human line is rendered by the fact's OWN renderer (``label()``) rather
    than by a second annotation pass over those fields.

    Exits and prints an error if the project does not exist.
    """
    if flags is None:
        flags = {}
    reg = TARGETS[registry]

    if not reg.check_project_exists(target_path):
        print(f"No {registry} project found in current directory.", file=sys.stderr)
        sys.exit(1)

    version = reg.read_version(target_path)
    vars_dict = reg.template_vars(target_path, ctx)
    name = vars_dict.get("name") or "(unknown)"

    root_str = str(ctx.project_root)

    # Git branch
    try:
        branch = get_current_branch(cwd=root_str)
    except GitError:
        branch = "(detached HEAD)"
    except Exception as e:
        print(f"Warning: could not determine branch: {e}", file=sys.stderr)
        branch = None

    # The latest release FACT: the highest version this project's release
    # ledger records, whether or not this checkout contains it. Deliberately
    # NOT the range anchor below -- reporting the highest release IN this
    # history as "the latest release" silently hides a checkout that predates
    # one, so the discrepancy is annotated instead.
    ledger_dir = releases_dir_for_changes_dir(
        changes_dir or get_changes_dir(target_path)
    )
    latest = latest_release_fact(ledger_dir, tag_glob=tag_glob, cwd=root_str)

    # Clean tree
    try:
        clean = is_clean_tree()
    except Exception as e:
        print(f"Warning: could not check working tree status: {e}", file=sys.stderr)
        clean = None

    # Changelog (generated from JSONL)
    changelog_path = os.path.join(root_str, "CHANGELOG.md")
    if os.path.exists(changelog_path):
        entry = extract_changelog_entry(changelog_path, version)
        changelog = bool(entry)
    else:
        changelog = None

    # Count unreleased commits since the release the LEDGER anchors this
    # checkout to (excluding autogenerated and changelog-only commits,
    # consistent with validate's coverage check). Computed independently of
    # JSONL setup so the "commits ahead" warning works for any project with a
    # previous release. The anchor is scoped by tag_glob, so monorepo projects
    # compare against their own last release, not some other project's.
    commits_ahead = None
    unreleased_commits = None
    all_unreleased = None
    exempted_count = 0
    anchor = range_anchor(ledger_dir, tag_glob=tag_glob, cwd=root_str)
    scoped_tag = tag_for_version(tag_glob, anchor.version) if anchor else None
    try:
        range_spec = f"{anchor.candidate_sha}..HEAD" if anchor else "HEAD"
        result = effects.run(
            ["git", "log", "--format=%H", range_spec],
            capture_output=True, text=True, timeout=30,
        )
        if result.returncode == 0:
            all_unreleased = [
                line.strip()
                for line in result.stdout.strip().splitlines()
                if line.strip()
            ]
            # Scope FIRST, then exempt -- the order the authoritative coverage
            # check uses. Exempting first would count another project's
            # changelog churn as this project's exempted commits.
            in_scope = all_unreleased
            if scope is not None and in_scope:
                keep = filter_commits_for_scope(
                    set(in_scope), scope, operation="status coverage",
                )
                in_scope = [c for c in in_scope if c in keep]
            non_exempt, _exempt_stats = filter_exempt_commits(in_scope)
            unreleased_commits = non_exempt
            exempted_count = len(in_scope) - len(non_exempt)
            # Only set commits_ahead when there's a prior tag — without
            # a tag, "ahead of nothing" is meaningless and we don't warn.
            if scoped_tag is not None:
                commits_ahead = len(unreleased_commits)
    except (subprocess.TimeoutExpired, FileNotFoundError, OSError):
        pass

    # JSONL changelog coverage (non-releasable projects don't use changelogs)
    is_non_releasable = project is not None and not project.is_releasable
    jsonl_coverage = "non-releasable -- no changelog" if is_non_releasable else "not set up"
    resolved_changes_dir = changes_dir or get_changes_dir(target_path)
    if not is_non_releasable and os.path.isdir(resolved_changes_dir):
        try:
            entries = read_unreleased(resolved_changes_dir)
            # Count covered commits
            all_hashes = []
            for entry in entries:
                all_hashes.extend(entry.commits)
            resolved = resolve_hashes(all_hashes)
            covered_shas = {full for full in resolved.values() if full is not None}

            if unreleased_commits is not None and all_unreleased is not None:
                total = len(unreleased_commits)
                covered = sum(1 for c in unreleased_commits if c in covered_shas)
                if exempted_count > 0:
                    jsonl_coverage = (
                        f"{covered}/{total} commits covered"
                        f" ({exempted_count} exempted)"
                    )
                else:
                    jsonl_coverage = f"{covered}/{total} commits covered"
            else:
                jsonl_coverage = f"{len(entries)} entries"
        except Exception as e:
            print(f"Warning: could not compute JSONL coverage: {e}", file=sys.stderr)

    # CI workflows. Route through the shared router discovery rather than
    # probing a hardcoded ci.yml: scaffold names CI files per target
    # (ci-go.yml, ci-pypi.yml, ...), and the hardcoded probe reported
    # "CI: missing" on every such repo.
    ci = [os.path.basename(p) for p in discover_project_ci_sources(root_str)]
    publish = os.path.exists(os.path.join(root_str, ".github", "workflows", "publish.yml")) or os.path.exists(
        os.path.join(root_str, ".github", "workflows", "workflow.yml")
    )

    # Registry version query (only when --registry flag is set)
    registry_version = None
    drift = None
    if flags.get("registry"):
        from ..config import suppresses_publish
        is_private = suppresses_publish(ctx.config)
        from ..targets import targets_with_version_queries

        if is_private:
            drift = "PRIVATE"
        elif registry not in targets_with_version_queries():
            # This ecosystem has no latest-version API at all, which is not a
            # failed query: the target would answer "Unknown registry", and
            # rendering that as ERROR read exactly like a timeout or an HTTP
            # 500. The set that CAN answer is derived from the targets that
            # implement query_latest_version, never hand-listed here.
            drift = "NO_REGISTRY_API"
        else:
            from ..registry import query_registry_version
            result = query_registry_version(name, registry)
            if result["status"] == "found":
                registry_version = result["version"]
                drift = _compare_versions(version, registry_version)
            elif result["status"] == "not_found":
                drift = "UNPUBLISHED"
            else:
                drift = "ERROR"

    return {
        "name": name,
        "version": version,
        "target": registry,
        "branch": branch,
        "latest_release": latest.version,
        "latest_release_in_checkout": latest.in_checkout,
        "clean": clean,
        "changelog": changelog,
        "jsonl_coverage": jsonl_coverage,
        "commits_ahead": commits_ahead,
        "range_anchor_tag": scoped_tag,
        "ci": ci,
        "publish": publish,
        "registry_version": registry_version,
        "drift": drift,
    }, latest


def run_cmd(registry, args, flags, ctx):
    """Status command handler.

    Shows a quick 'where am I' summary: package info, git state, changelog, CI.
    Returns the collected status dict -- the caller (the CLI handler) hands it
    to the framework as the command's machine payload.  Human output is printed
    here unless ``flags["json"]`` is set, in which case machine mode owns
    stdout and nothing human may reach it.
    """
    project_root = ctx.project_root
    root_str = str(project_root)

    # Detect monorepo context early so coverage uses scoped tags
    # and detect_targets can use releasable config inheritance
    monorepo_project = None
    monorepo_count = None
    releasable_info = None  # (releasable_name, tag_format, version)
    releasable_config_dir = None
    releasable_changes_dir = None
    releasable_members = None
    ws_projects = None
    try:
        ws_root = find_workspace_root(root_str)
        if ws_root is not None:
            ws_projects = load_workspace(ws_root)
            monorepo_count = len(ws_projects)
            monorepo_project = resolve_project(ws_root, root_str)
            # Resolve the releasable this member belongs to
            if monorepo_project:
                from ..workspace import load_releasables, resolve_releasable_for_project, read_releasable_version
                releasables = load_releasables(ws_root, ws_projects)
                rel = resolve_releasable_for_project(monorepo_project, releasables)
                if rel:
                    try:
                        rel_ver = read_releasable_version(ws_root, rel.name)
                    except Exception:
                        rel_ver = None
                    releasable_info = (rel.name, rel.effective_tag_format, rel_ver)
                    # A releasable member's JSONL is under the releasable, and
                    # its commit scope spans every member.
                    from ..workspace import get_releasable_changes_dir, members_of
                    releasable_changes_dir = get_releasable_changes_dir(ws_root, rel.name)
                    releasable_members = members_of(rel.name, ws_projects)
            if monorepo_project:
                from ..targets import resolve_releasable_config_dir
                releasable_config_dir = resolve_releasable_config_dir(monorepo_project, ws_root)
    except Exception as e:
        print(f"Warning: could not detect monorepo context: {e}", file=sys.stderr)

    # Build per-target path mapping from detect_targets
    target_entries = detect_targets(root_str, releasable_config_dir=releasable_config_dir)
    target_paths = {entry.name: entry.path for entry in target_entries}

    # Use per-target path for the primary registry
    primary_path = target_paths.get(registry, root_str)

    if releasable_info:
        # A releasable member: use the releasable's tag glob (shared resolver).
        from ..tag_glob import releasable_tag_glob
        tag_glob = releasable_tag_glob(releasable_info[1], releasable_info[0])
    elif monorepo_project:
        target = TARGETS[registry]
        tag_glob = target.monorepo_tag_glob(monorepo_project["name"], path=monorepo_project["path"])
    else:
        tag_glob = None

    # The ownership scope this status reports on: a releasable's members when
    # in one, otherwise the single member the cwd resolves to. Attribution
    # always sees the whole workspace member list.
    status_scope = None
    if monorepo_project is not None and ws_projects is not None:
        from ..ownership import OwnershipScope
        if releasable_members:
            status_scope = OwnershipScope.for_members(ws_projects, releasable_members)
        else:
            status_scope = OwnershipScope.for_member(ws_projects, monorepo_project)

    data, latest = _collect_status(
        registry, primary_path, tag_glob=tag_glob,
        ctx=ctx, project=monorepo_project, flags=flags,
        changes_dir=releasable_changes_dir, scope=status_scope,
    )

    if flags.get("json"):
        return data

    print(f"Package:   {data['name']}")

    # Show version info for all detected targets with per-target paths
    for entry_name, entry_path in target_paths.items():
        r_mod = TARGETS[entry_name]
        if r_mod.check_project_exists(entry_path):
            ver = r_mod.read_version(entry_path)
            file = r_mod.version_file() or "git tag"
            path_info = f", path={entry_path}" if entry_path != "." else ""
            print(f"Version:   {ver} ({entry_name}, {file}{path_info})")

    # Registry version (only when --registry flag is set)
    drift = data.get("drift")
    if drift is not None:
        reg_ver = data.get("registry_version")
        if drift == "PRIVATE":
            print("Registry:  (skipped, private project)")
        elif drift == "UNPUBLISHED":
            print(f"Registry:  (not found on {data['target']})")
        elif drift == "NO_REGISTRY_API":
            print(f"Registry:  (no version API for {data['target']})")
        elif drift == "ERROR":
            print("Registry:  (query failed)")
        elif reg_ver is not None:
            print(f"Registry:  {reg_ver} ({data['target']}, {drift})")

    # Git info
    if data["branch"] is not None:
        print(f"Branch:    {data['branch']}")
    else:
        print("Branch:    (not a git repo)")

    # Latest release, annotated by the fact's own renderer: "(none)", the
    # bare version, "(not in this checkout's history)", or "(commit not
    # recoverable)" for a version recorded unanchorable. Rendering it here
    # from the payload's two flattened fields dropped that last case, since
    # the payload cannot express it.
    print(f"Released:  {latest.label()}")

    # Clean tree
    if data["clean"] is not None:
        print(f"Clean:     {'yes' if data['clean'] else 'no'}")
    else:
        print("Clean:     (unknown)")

    # Changelog
    if data["changelog"] is None:
        print("Changelog: (not found)")
    elif data["changelog"]:
        print(f"Changelog: has entry for {data['version']}")
    else:
        print(f"Changelog: no entry for {data['version']}")

    # JSONL changelog coverage
    print(f"JSONL:     {data['jsonl_coverage']}")

    # CI workflows (every discovered source, not a single hardcoded name)
    ci_sources = data["ci"]
    print(f"CI:        {', '.join(ci_sources) if ci_sources else 'missing'}")
    print(f"Publish:   {'yes' if data['publish'] else 'missing'}")

    # Commits-ahead warning: surfaces unreleased work that might otherwise
    # sit silently (e.g., post-release wrapper commits never released).
    # Only printed when there is a prior tag AND unreleased commits exist.
    commits_ahead = data.get("commits_ahead")
    commits_ahead_tag = data.get("range_anchor_tag")
    if (
        commits_ahead is not None
        and commits_ahead > 0
        and commits_ahead_tag is not None
    ):
        plural = "commit" if commits_ahead == 1 else "commits"
        print(
            f"! {commits_ahead} {plural} ahead of {commits_ahead_tag} "
            f"— run `rlsbl release` or investigate"
        )

    # Monorepo awareness (detection already done above)
    if monorepo_count is not None:
        if releasable_info:
            rel_name, rel_tag_fmt, rel_ver = releasable_info
            print(f"Releasable: {rel_name}")
            if rel_ver:
                from ..commands.release.validate import _format_releasable_tag
                rel_tag = _format_releasable_tag(rel_tag_fmt, rel_name, rel_ver)
                print(f"Rel. version: {rel_ver}")
                print(f"Rel. tag:  {rel_tag}")
        elif monorepo_project is not None:
            target = TARGETS[registry]
            mono_tag = target.monorepo_tag_format(
                monorepo_project["name"], data["version"],
                path=monorepo_project["path"],
            )
            print(f"Mono tag:  {mono_tag}")
        print(f"Part of monorepo ({monorepo_count} project{'s' if monorepo_count != 1 else ''}). Run 'rlsbl monorepo status' for all.")

    return data
