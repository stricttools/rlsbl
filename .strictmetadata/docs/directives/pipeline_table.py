"""Custom selfdoc directive: table-pipelines.

Renders the pipeline types table from its committed rendering
(``internal/pipelines/pipeline-types.json``). The rows are generated by
``internal/pipelines/gen`` from the pipeline types the Go code declares, and a
freshness test keeps the committed file in step with them; this directive only
renders them, so documenting the pipelines needs no rlsbl build.
"""

import importlib.util
import json
from pathlib import Path

_spec = importlib.util.spec_from_file_location(
    "rlsbl_docs_matrix", Path(__file__).with_name("_matrix.py")
)
_matrix = importlib.util.module_from_spec(_spec)
_spec.loader.exec_module(_matrix)

TABLE_PATH = _matrix.repo_root() / "internal" / "pipelines" / "pipeline-types.json"

# The shape version this directive reads; another is refused rather than
# read as if its keys meant the same.
FORMAT_VERSION = 1


def resolve(attrs, config, body):
    """Return the pipeline types as a Markdown table."""
    with open(TABLE_PATH, encoding="utf-8") as f:
        table = json.load(f)
    if table.get("format_version") != FORMAT_VERSION:
        raise ValueError(
            f"{TABLE_PATH} has format_version {table.get('format_version')!r}; "
            f"this directive reads {FORMAT_VERSION}"
        )
    if not table["rows"]:
        raise ValueError(f"{TABLE_PATH} lists no pipeline type")
    return _matrix.render_rows(table["headers"], table["rows"])
