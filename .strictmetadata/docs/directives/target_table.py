"""Custom selfdoc directive: table-targets.

Renders the release target table from the committed support matrix
(``internal/targets/support-matrix.json``). The rows are generated by
``internal/targets/gen`` and committed; this directive only renders them, so
documenting the targets needs no rlsbl build.
"""

import importlib.util
from pathlib import Path

_spec = importlib.util.spec_from_file_location(
    "rlsbl_docs_matrix", Path(__file__).with_name("_matrix.py")
)
_matrix = importlib.util.module_from_spec(_spec)
_spec.loader.exec_module(_matrix)


def resolve(attrs, config, body):
    """Return the target table as a Markdown table."""
    return _matrix.render_table("targets", "No release targets registered.\n")
