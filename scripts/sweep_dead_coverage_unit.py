#!/usr/bin/env python3
"""Fleet sweep: remove the dead ``coverage_unit`` key from live rlsbl configs.

The ``changeset-file`` coverage mode was deleted from rlsbl, and with it the
``coverage_unit`` config key. Live configs that still carry the key now declare
a setting nothing reads, and the strictspec config schema no longer models it.
This script strips the key from every live config across ``~/Projects``.

Scope rules (deliberate, not options):

- Only *live* configs: ``<repo>/.rlsbl/config.json`` and
  ``<repo>/.rlsbl-monorepo/releasables/<name>/config.json``.
- ``.rlsbl/bases/`` copies are SKIPPED entirely -- scaffold merge bases are
  owned by the scaffold orphan sweep, not by this one.
- ``~/Projects/.archive/`` is skipped entirely.
- Repos whose working tree carries changes beyond the config files this script
  would touch are SKIPPED and reported, so another session's work is never
  swept up into an unrelated commit.

Each swept repo is committed with ``rlsbl commit`` (Autogenerated trailer, so
the commit is changelog-coverage exempt).

Usage::

    scripts/sweep_dead_coverage_unit.py --dry-run
    scripts/sweep_dead_coverage_unit.py --apply
"""

import argparse
import json
import os
import subprocess
import sys


KEY = "coverage_unit"
PROJECTS = os.path.expanduser("~/Projects")
SKIP_DIR_NAMES = {".git", "node_modules", ".venv", "__pycache__", "dist", "build", ".archive"}
# Another session's dirty tree -- never entered by this sweep.
SKIP_REPO_PATHS = {os.path.join(PROJECTS, "predraw")}


def find_config_files(base):
    """Return live rlsbl config.json paths under *base*, newest-first sorted.

    Skips anything under ``.rlsbl/bases/`` (scaffold merge bases) and the
    globally excluded directories.
    """
    configs = []
    for root, dirs, _files in os.walk(base):
        dirs[:] = [d for d in dirs if d not in SKIP_DIR_NAMES]
        if os.sep + os.path.join(".rlsbl", "bases") in root + os.sep:
            continue

        standalone = os.path.join(root, ".rlsbl", "config.json")
        if os.path.isfile(standalone):
            configs.append(standalone)

        releasables_dir = os.path.join(root, ".rlsbl-monorepo", "releasables")
        if os.path.isdir(releasables_dir):
            for rel_name in sorted(os.listdir(releasables_dir)):
                rel_config = os.path.join(releasables_dir, rel_name, "config.json")
                if os.path.isfile(rel_config):
                    configs.append(rel_config)

    return sorted(set(configs))


def repo_root_for(path):
    """Return the git top-level for *path*, or None when it is not in a repo."""
    try:
        out = subprocess.run(
            ["git", "rev-parse", "--show-toplevel"],
            cwd=os.path.dirname(path), capture_output=True, text=True, check=True,
        )
    except (subprocess.CalledProcessError, OSError):
        return None
    return out.stdout.strip() or None


def has_key(path):
    """True when *path* is a JSON object carrying the dead key."""
    try:
        with open(path, "r", encoding="utf-8") as f:
            data = json.load(f)
    except (json.JSONDecodeError, OSError):
        return False
    return isinstance(data, dict) and KEY in data


def strip_key(path):
    """Remove the dead key from *path*, preserving 2-space JSON formatting."""
    with open(path, "r", encoding="utf-8") as f:
        data = json.load(f)
    del data[KEY]
    with open(path, "w", encoding="utf-8") as f:
        f.write(json.dumps(data, indent=2, ensure_ascii=False) + "\n")


def dirty_paths(repo):
    """Return the set of repo-relative paths git reports as changed."""
    out = subprocess.run(
        ["git", "status", "--porcelain"],
        cwd=repo, capture_output=True, text=True, check=True,
    )
    paths = set()
    for line in out.stdout.splitlines():
        if not line.strip():
            continue
        entry = line[3:]
        if " -> " in entry:
            entry = entry.split(" -> ", 1)[1]
        paths.add(entry.strip().strip('"'))
    return paths


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    group = parser.add_mutually_exclusive_group(required=True)
    group.add_argument("--dry-run", action="store_true", help="report only")
    group.add_argument("--apply", action="store_true", help="strip the key and commit")
    args = parser.parse_args()

    configs = find_config_files(PROJECTS)

    # Group the configs that still carry the key by repo.
    by_repo = {}
    for path in configs:
        repo = repo_root_for(path)
        if repo is None or repo in SKIP_REPO_PATHS:
            continue
        if has_key(path):
            by_repo.setdefault(repo, []).append(path)

    swept, skipped_dirty, failed = [], [], []

    for repo in sorted(by_repo):
        paths = by_repo[repo]
        rel = sorted(os.path.relpath(p, repo) for p in paths)
        try:
            dirty = dirty_paths(repo)
        except subprocess.CalledProcessError as exc:
            failed.append((repo, rel, f"git status failed: {exc}"))
            continue

        foreign = dirty - set(rel)
        if foreign:
            skipped_dirty.append((repo, rel, sorted(foreign)))
            continue

        if args.dry_run:
            swept.append((repo, rel))
            continue

        for p in paths:
            strip_key(p)
        try:
            subprocess.run(
                ["rlsbl", "commit", "-m",
                 "config: drop the dead coverage_unit key", *rel],
                cwd=repo, check=True,
            )
        except (subprocess.CalledProcessError, OSError) as exc:
            failed.append((repo, rel, f"rlsbl commit failed: {exc}"))
            continue
        swept.append((repo, rel))

    label = "would sweep" if args.dry_run else "swept"
    print(f"{label}: {len(swept)} repo(s)")
    for repo, rel in swept:
        print(f"  {repo}: {', '.join(rel)}")
    print(f"skipped (dirty tree): {len(skipped_dirty)} repo(s)")
    for repo, rel, foreign in skipped_dirty:
        print(f"  {repo}: {', '.join(rel)} -- foreign changes: {', '.join(foreign[:5])}")
    if failed:
        print(f"FAILED: {len(failed)} repo(s)")
        for repo, rel, why in failed:
            print(f"  {repo}: {', '.join(rel)} -- {why}")
        return 1
    return 0


if __name__ == "__main__":
    sys.exit(main())
