"""Custom selfdoc directive: table-pipelines.

Renders the pipeline type table from the committed support matrix
(``rlsbl/data/support-matrix.json``). The rows are generated by
``rlsbl.pipelines.introspect`` and committed; this directive only renders them,
so documenting the pipelines does not require importing rlsbl.
"""

import importlib.util
from pathlib import Path

_spec = importlib.util.spec_from_file_location(
    "rlsbl_docs_matrix", Path(__file__).with_name("_matrix.py")
)
_matrix = importlib.util.module_from_spec(_spec)
_spec.loader.exec_module(_matrix)


def resolve(attrs, config, body):
    """Return the pipeline table as a Markdown table."""
    return _matrix.render_table("pipelines", "No pipeline types registered.\n")
