_PRODUCER_AND_CONCURRENT_EDIT = """#!/bin/sh
set -e
# A producer: the release commits what it generates.
cp src.txt generated.txt
# Another session edits a tracked file in the working tree mid-release.
printf 'edited by another session mid-release\\n' > "$RLSBL_TEST_LIVE/notes.txt"
"""


class TestReleaseRunsInTheCheckout:
    def test_a_successful_release_leaves_other_sessions_edits_byte_for_byte(
        self, tmp_path, monkeypatch,
    ):
        repo = _project(tmp_path, pre_checks=_PRODUCER_AND_CONCURRENT_EDIT)
        monkeypatch.setenv("RLSBL_TEST_LIVE", str(repo))
        # Another session's uncommitted work, before the release starts.
        (repo / "README.md").write_text("another session's README edit\n")
        (repo / "src.txt").write_text("UNCOMMITTED SOURCE\n")
        (repo / "wip.txt").write_text("another session's untracked file\n")
        readme, src, wip = (_bytes(repo / n) for n in ("README.md", "src.txt", "wip.txt"))

        result = _release(repo, monkeypatch)

        assert result.exit_code == 0, result.stderr + result.stdout
        assert "Releasing from the release checkout" in result.stdout
        assert "README.md" in result.stderr, "ignored changes are listed"
        # The release shipped and the branch is its last commit, on origin too.
        head = git(repo, "rev-parse", "refs/heads/main")
        assert git(repo, "ls-remote", "origin", "refs/heads/main").split()[0] == head
        assert git(repo, "rev-parse", "v1.0.1^{commit}")
        # Uncommitted source never reached the generated file the release committed.
        assert git(repo, "show", "v1.0.1:generated.txt") == "committed source"
        assert (repo / "generated.txt").read_text() == "committed source\n"
        # Every other session's edit is exactly as it was.
        assert _bytes(repo / "README.md") == readme
        assert _bytes(repo / "src.txt") == src
        assert _bytes(repo / "wip.txt") == wip
        assert (repo / "notes.txt").read_text() == "edited by another session mid-release\n"
        # ...and none of it is in the release.
        for name in ("README.md", "src.txt", "notes.txt"):
            assert git(repo, "show", f"{head}:{name}") != (repo / name).read_text().rstrip("\n")
        assert git(repo, "ls-tree", "--name-only", head, "wip.txt") == ""
        assert json.loads((repo / "package.json").read_text())["version"] == "1.0.1"
        assert sorted(_status(repo).splitlines()) == [
            " M README.md", " M notes.txt", " M src.txt", "?? wip.txt",
        ]
        assert not (repo / ".rlsbl" / "releases" / "in-progress.json").exists()

    def test_a_failed_release_leaves_other_sessions_edits_byte_for_byte(
        self, tmp_path, monkeypatch,
    ):
        repo = _project(tmp_path, pre_checks=_PRODUCER_AND_CONCURRENT_EDIT)
        monkeypatch.setenv("RLSBL_TEST_LIVE", str(repo))
        pin = git(repo, "rev-parse", "HEAD")
        hook = _reject_pushes(tmp_path / "remote")
        (repo / "README.md").write_text("another session's README edit\n")
        (repo / "src.txt").write_text("UNCOMMITTED SOURCE\n")
        readme, src = _bytes(repo / "README.md"), _bytes(repo / "src.txt")

        result = _release(repo, monkeypatch)

        assert result.exit_code != 0
        assert "before the release candidate was pushed" in result.stderr
        # The branch is back where the release found it, with nothing of it
        # in the working tree, and every other session's edit is intact.
        assert git(repo, "rev-parse", "refs/heads/main") == pin
        assert json.loads((repo / "package.json").read_text())["version"] == "1.0.0"
        assert not (repo / "generated.txt").exists()
        assert _bytes(repo / "README.md") == readme
        assert _bytes(repo / "src.txt") == src
        assert (repo / "notes.txt").read_text() == "edited by another session mid-release\n"
        assert sorted(_status(repo).splitlines()) == [
            " M README.md", " M notes.txt", " M src.txt",
        ]
        assert not (repo / ".rlsbl" / "releases" / "in-progress.json").exists()

        # The fix the message names: address the error, re-run the release.
        hook.unlink()
        again = _release(repo, monkeypatch)
        assert again.exit_code == 0, again.stderr + again.stdout
        assert git(repo, "rev-parse", "v1.0.1^{commit}")

    def test_the_branch_moving_mid_release_is_refused(self, tmp_path, monkeypatch):
        """The compare-and-swap: a commit that lands on the branch between the
        release's last look and its advance is never overwritten."""
        repo = _project(tmp_path)
        pin = git(repo, "rev-parse", "HEAD")
        real_advance = release_checkout.advance_live_branch
        moved = {}

        def someone_commits_first(new_sha, **kwargs):
            if not moved:
                _write(repo / "notes.txt", "someone else's commit\n")
                git(repo, "add", "notes.txt")
                git(repo, "commit", "-q", "-m", "chore: someone else",
                    "--trailer", "Autogenerated: true")
                moved["sha"] = git(repo, "rev-parse", "HEAD")
            return real_advance(new_sha, **kwargs)

        monkeypatch.setattr(release_checkout, "advance_live_branch", someone_commits_first)
        result = _release(repo, monkeypatch)

        assert result.exit_code != 0
        assert "moved while the release was running" in result.stderr
        assert moved["sha"][:12] in result.stderr
        assert git(repo, "rev-parse", "refs/heads/main") == moved["sha"]
        assert git(repo, "rev-parse", f"{moved['sha']}~1") == pin
        assert json.loads((repo / "package.json").read_text())["version"] == "1.0.0"
        assert _status(repo) == ""
        assert git(repo, "ls-remote", "origin", "refs/heads/main").split()[0] == pin
        assert not (repo / ".rlsbl" / "releases" / "in-progress.json").exists()

        # The fix the refusal names: take the commits in (this one carries the
        # Autogenerated trailer, so the changelog already accounts for it) and
        # re-run the release.
        monkeypatch.setattr(release_checkout, "advance_live_branch", real_advance)
        again = _release(repo, monkeypatch)
        assert again.exit_code == 0, again.stderr + again.stdout
        assert subprocess.run(
            ["git", "merge-base", "--is-ancestor", moved["sha"], "v1.0.1"],
            cwd=repo,
        ).returncode == 0

    def test_an_uncommitted_edit_to_a_file_the_release_writes_refuses_it(
        self, tmp_path, monkeypatch,
    ):
        repo = _project(tmp_path)
        pin = git(repo, "rev-parse", "HEAD")
        (repo / "package.json").write_text(
            json.dumps({"name": "pkg", "version": "1.0.0", "private": False}, indent=2) + "\n"
        )
        (repo / "README.md").write_text("unrelated edit\n")

        result = _release(repo, monkeypatch)

        assert result.exit_code != 0
        assert "package.json" in result.stderr
        assert "Commit those changes" in result.stderr
        assert git(repo, "rev-parse", "refs/heads/main") == pin
        assert not (repo / ".rlsbl" / "releases" / "in-progress.json").exists()

        # The fix it names: commit the change, then re-run.
        git(repo, "add", "package.json")
        git(repo, "commit", "-q", "-m", "chore: package metadata",
            "--trailer", "Autogenerated: true")
        again = _release(repo, monkeypatch)
        assert again.exit_code == 0, again.stderr + again.stdout
        assert (repo / "README.md").read_text() == "unrelated edit\n"

    def test_dry_run_reports_a_dirty_tree_and_exits_zero(self, tmp_path, monkeypatch):
        repo = _project(tmp_path)
        pin = git(repo, "rev-parse", "HEAD")
        (repo / "package.json").write_text('{"name": "pkg", "version": "1.0.0"}\n')
        (repo / "README.md").write_text("unrelated edit\n")

        result = _release(repo, monkeypatch, "--dry-run")

        assert result.exit_code == 0, result.stderr + result.stdout
