class TestPrepareCheckout:
    def test_created_under_the_git_common_dir_and_detached(self, tmp_path):
        repo = _project(tmp_path)
        head = git(repo, "rev-parse", "HEAD")
        path = release_checkout.prepare_checkout(str(repo), head)
        assert path == os.path.realpath(repo / ".git" / "rlsbl" / "release-checkout")
        assert git(path, "rev-parse", "HEAD") == head
        assert git(path, "symbolic-ref", "-q", "HEAD", check=False) == ""
        assert _status(path) == ""

    def test_reused_reset_and_cleaned_but_ignored_files_kept(self, tmp_path):
        repo = _project(tmp_path)
        head = git(repo, "rev-parse", "HEAD")
        path = Path(release_checkout.prepare_checkout(str(repo), head))
        (path / "README.md").write_text("scribbled by a previous release\n")
        (path / "stray.txt").write_text("untracked leftover\n")
        (path / "node_modules").mkdir()
        (path / "node_modules" / "cache").write_text("warm\n")

        again = release_checkout.prepare_checkout(str(repo), head)

        assert again == str(path)
        assert (path / "README.md").read_text() == "# pkg\n"
        assert not (path / "stray.txt").exists()
        assert (path / "node_modules" / "cache").read_text() == "warm\n"

    def test_a_foreign_directory_is_refused_and_deleting_it_clears(self, tmp_path):
        repo = _project(tmp_path)
        head = git(repo, "rev-parse", "HEAD")
        squatter = repo / ".git" / "rlsbl" / "release-checkout"
        squatter.mkdir(parents=True)
        (squatter / "something").write_text("not ours\n")
        with pytest.raises(release_checkout.ReleaseCheckoutError) as exc:
            release_checkout.prepare_checkout(str(repo), head)
        assert str(squatter) in str(exc.value)
        assert "Delete" in str(exc.value)
        # The fix the refusal names.
        import shutil
        shutil.rmtree(squatter)
        path = release_checkout.prepare_checkout(str(repo), head)
        assert git(path, "rev-parse", "HEAD") == head


def _enter(repo):
    """Enter the release checkout of *repo*'s main as a release would."""
    head = git(repo, "rev-parse", "refs/heads/main")
    return release_checkout.entered(str(repo), branch="main", sha=head, cwd=str(repo))


class TestAdvance:
    def test_only_the_release_s_paths_are_written_back(self, tmp_path, monkeypatch):
        repo = _project(tmp_path)
        (repo / "README.md").write_text("another session's edit\n")
        (repo / "scratch.txt").write_text("another session's new file\n")
        before_readme = _bytes(repo / "README.md")
        with _enter(repo) as co:
            _write(Path(co.path) / "package.json", '{"version": "1.0.1"}\n')
            _write(Path(co.path) / "generated.txt", "generated\n")
            new = _commit_all(co.path, "release")
            release_checkout.advance_live_branch("HEAD", rerun="re-run it")
        assert git(repo, "rev-parse", "refs/heads/main") == new
        assert (repo / "package.json").read_text() == '{"version": "1.0.1"}\n'
        assert (repo / "generated.txt").read_text() == "generated\n"
        assert _bytes(repo / "README.md") == before_readme
        assert (repo / "scratch.txt").read_text() == "another session's new file\n"
        assert sorted(_status(repo).splitlines()) == [" M README.md", "?? scratch.txt"]

    def test_an_uncommitted_edit_to_a_written_path_refuses_naming_it(self, tmp_path):
        repo = _project(tmp_path)
        pin = git(repo, "rev-parse", "HEAD")
        (repo / "package.json").write_text("another session's edit\n")
        with _enter(repo) as co:
            _write(Path(co.path) / "package.json", '{"version": "1.0.1"}\n')
            _commit_all(co.path, "release")
            with pytest.raises(release_checkout.LiveTreeConflictError) as exc:
                release_checkout.advance_live_branch("HEAD", rerun="re-run it")
        assert "package.json" in str(exc.value)
        assert git(repo, "rev-parse", "refs/heads/main") == pin
        assert (repo / "package.json").read_text() == "another session's edit\n"

    def test_a_branch_that_moved_is_refused_and_nothing_is_written(self, tmp_path):
        repo = _project(tmp_path)
        with _enter(repo) as co:
            _write(Path(co.path) / "package.json", '{"version": "1.0.1"}\n')
            _commit_all(co.path, "release")
            # Another session commits on the live branch meanwhile.
            _write(repo / "notes.txt", "committed by someone else\n")
            moved = _commit_all(repo, "someone else's commit")
            with pytest.raises(release_checkout.BranchMovedError) as exc:
                release_checkout.advance_live_branch("HEAD", rerun="re-run it")
        assert moved[:12] in str(exc.value)
        assert git(repo, "rev-parse", "refs/heads/main") == moved
        assert json.loads((repo / "package.json").read_text())["version"] == "1.0.0"
        assert _status(repo) == ""

    def test_unwind_takes_the_advance_back(self, tmp_path):
        repo = _project(tmp_path)
        pin = git(repo, "rev-parse", "HEAD")
        (repo / "README.md").write_text("another session's edit\n")
        with _enter(repo) as co:
            _write(Path(co.path) / "package.json", '{"version": "1.0.1"}\n')
            _commit_all(co.path, "release")
            release_checkout.advance_live_branch("HEAD", rerun="re-run it")
            assert release_checkout.unwind_last_advance() == (True, None)
        assert git(repo, "rev-parse", "refs/heads/main") == pin
        assert json.loads((repo / "package.json").read_text())["version"] == "1.0.0"
        assert _status(repo) == " M README.md"

    def test_unwind_refuses_when_something_was_committed_on_top(self, tmp_path):
        repo = _project(tmp_path)
        with _enter(repo) as co:
            _write(Path(co.path) / "package.json", '{"version": "1.0.1"}\n')
            _commit_all(co.path, "release")
            release_checkout.advance_live_branch("HEAD", rerun="re-run it")
            _write(repo / "notes.txt", "on top\n")
            on_top = _commit_all(repo, "on top")
            ok, reason = release_checkout.unwind_last_advance()
        assert not ok and "committed on top" in reason
        assert git(repo, "rev-parse", "refs/heads/main") == on_top


class TestWriteScope:
    def test_standalone_scope_and_partition(self, tmp_path):
        repo = _project(tmp_path)
        scope = release_checkout.write_scope(
            live_root=str(repo), project_dirs=[(str(repo), None)],
            state_homes=[str(repo / ".rlsbl")],
        )
        assert {".rlsbl", "CHANGELOG.md", "package.json"} <= set(scope)
        blocking, ignored = release_checkout.partition_changes(
            [(" M", "package.json"), (" M", "README.md"),
             ("??", ".rlsbl/releases/unreleased.toml"), ("??", "x/y.txt")],
            scope,
        )
        assert [p for _s, p in blocking] == [
            "package.json", ".rlsbl/releases/unreleased.toml",
        ]
        assert [p for _s, p in ignored] == ["README.md", "x/y.txt"]

    def test_rlsbl_s_own_bookkeeping_is_never_counted(self, tmp_path):
        repo = _project(tmp_path)
        _write(repo / ".rlsbl" / "releases" / "in-progress.json", "{}\n")
        _write(repo / ".rlsbl" / "lock", "")
        assert release_checkout.live_changes(str(repo)) == []


