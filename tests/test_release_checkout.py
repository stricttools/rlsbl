"""The release runs in a detached checkout of the committed commit.

Covers :mod:`rlsbl.release_checkout` and the release commands' way into it:

- another session's uncommitted edits to files the release does not write
  neither block a release nor leak into it, and remain byte for byte through
  a successful release and through a failed one;
- uncommitted source never reaches a file the release generates and commits;
- the branch advances only by compare-and-swap from where the release left
  it, and a branch that moved mid-release is refused with nothing written;
- an uncommitted change to a path the release writes refuses it, naming the
  path, and ``--dry-run`` reports the same instead of refusing;
- every refusal that names a fix is followed by performing that fix, and the
  refusal clears.

The end-to-end tests drive ``rlsbl release run`` through the CLI dispatch
against a real repository and a bare local remote; only the GitHub side (gh)
is stubbed.
"""

import json
import os
import subprocess
from contextlib import contextmanager
from pathlib import Path
from unittest.mock import patch

import pytest

from githarness import add_remote, git, init_repo, record_release
from rlsbl import app, release_checkout


# ---------------------------------------------------------------------------
# Fixture: an npm project one covered commit ahead of v1.0.0, with a remote
# ---------------------------------------------------------------------------


def _write(path, text):
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text(text)


def _commit_all(repo, message, *, autogenerated=False):
    git(repo, "add", "-A")
    args = ["commit", "-q", "-m", message]
    if autogenerated:
        args += ["--trailer", "Autogenerated: true"]
    git(repo, *args)
    return git(repo, "rev-parse", "HEAD")


def _project(tmp_path, *, pre_checks=None):
    """A releasable npm project and its bare remote; returns the repo path."""
    repo = tmp_path / "repo"
    init_repo(repo)
    _write(repo / "package.json",
           json.dumps({"name": "pkg", "version": "1.0.0"}, indent=2) + "\n")
    _write(repo / "CHANGELOG.md",
           "<!-- Generated by rlsbl from .rlsbl/changes/ -- do not edit -->\n\n"
           "# Changelog\n\n## 1.0.0\n\n- Initial release.\n")
    _write(repo / "README.md", "# pkg\n")
    _write(repo / "notes.txt", "notes\n")
    _write(repo / "src.txt", "committed source\n")
    _write(repo / ".gitignore", "node_modules/\n")
    _write(repo / ".rlsbl" / "config.json",
           json.dumps({"publish_mode": "ci", "targets": ["npm"], "tag": False,
                       "pipelines": {}}) + "\n")
    _write(repo / ".rlsbl" / "changes" / "unreleased.jsonl", "")
    if pre_checks is not None:
        _write(repo / ".rlsbl" / "hooks" / "pre-checks.sh", pre_checks)
    _commit_all(repo, "initial")
    record_release(repo, "v1.0.0")

    _write(repo / "feature.txt", "a feature\n")
    feature = _commit_all(repo, "add feature")
    entry = {
        "format_version": 1, "commits": [feature], "user_facing": True,
        "description": "**A feature.** It does a thing.", "type": "feature",
    }
    _write(repo / ".rlsbl" / "changes" / "unreleased.jsonl", json.dumps(entry) + "\n")
    _commit_all(repo, "changelog: add feature entry", autogenerated=True)
    _write(repo / ".rlsbl" / "releases" / "unreleased.toml",
           'format_version = 1\nbump = "patch"\ninclude = ["npm"]\n'
           'exclude = []\ndescription = "a patch release"\n')
    _commit_all(repo, "add release file", autogenerated=True)
    add_remote(repo, tmp_path / "remote")
    return repo


def _fake_gh(args, **_kwargs):
    if args[:2] == ["release", "view"]:
        raise subprocess.CalledProcessError(1, ["gh", *args])
    return ""


@contextmanager
def _github_stubbed():
    """The GitHub half of a release, stubbed; git and the remote are real."""
    with (
        patch("rlsbl.commands.release.validate_gh_cli"),
        patch("rlsbl.commands.release.validate_gh_push_access"),
        patch("rlsbl.commands.release.run_gh", side_effect=_fake_gh),
    ):
        yield


def _release(repo, monkeypatch, *extra):
    monkeypatch.chdir(repo)
    with _github_stubbed():
        return app.test(
            ["release", "run", "--no-watch", "--approve-consequential", *extra]
        )


def _bytes(path):
    return Path(path).read_bytes()


def _status(repo):
    # Not through the harness's git(): it strips the output, and with it the
    # leading space of the first record's status column.
    return subprocess.run(
        ["git", "status", "--porcelain", "--untracked-files=all"],
        cwd=str(repo), capture_output=True, text=True, check=True,
    ).stdout.rstrip("\n")


def _reject_pushes(remote):
    hook = remote / "hooks" / "pre-receive"
    hook.write_text("#!/bin/sh\necho 'push refused by the test remote' >&2\nexit 1\n")
    hook.chmod(0o755)
    return hook


