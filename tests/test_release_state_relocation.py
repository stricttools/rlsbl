class TestBatchOrchestratorAlignment:
    """The batch orchestrator delegates to run_cmd per releasable; the
    releasable-aware state resolver and step model must hold end-to-end:
    the release completes, state is cleared, and the representative
    member's .rlsbl/ stays clean."""

    def test_batch_releasable_release_leaves_no_state(
        self, tmp_project, bypass_upfront_validation,
    ):
        from rlsbl.commands.monorepo.batch_release import _cmd_batch_release

        core = _setup_releasable_workspace(tmp_project)

        # Batch release file for the releasable
        releases_dir = tmp_project / ".rlsbl-monorepo" / "releases"
        releases_dir.mkdir(parents=True)
        (releases_dir / "unreleased.toml").write_text(
            '[releasables.alpha]\n'
            'bump = "patch"\n'
            'include = ["npm"]\n'
            'exclude = []\n'
            'description = "test release"\n'
        )
        _git(tmp_project, "add", ".rlsbl-monorepo/releases/unreleased.toml")
        _git(tmp_project, "commit", "-q", "-m", "add batch release file",
             "--trailer", "Autogenerated: true")

        fake_run = _fake_run_factory()
        with (
            patch("rlsbl.commands.release.check_gh_installed", return_value=True),
            patch("rlsbl.commands.release.check_gh_auth", return_value=True),
            patch("rlsbl.commands.release.push_if_needed"),
            patch("rlsbl.commands.release.run_gh", return_value=""),
            patch("rlsbl.commands.release.run", side_effect=fake_run),
            patch("rlsbl.commands.release.remote_branch_exists", return_value=True),
            # The mocked release pushes the tag; model the remote as having it
            # so the batch archive gate (item_is_released) sees it as released.
            patch("rlsbl.commands.monorepo.batch_plan.tag_exists_on_remote",
                  return_value=True),
        ):
            _cmd_batch_release(
                {"yes": True, "quiet": True, "dry-run": False},
                tmp_project,
            )

        # Release completed: state cleared from the releasable location
        assert not os.path.exists(_releasable_state_path(tmp_project))
        # Representative member stays clean
        assert not (core / ".rlsbl" / "releases").exists()
        # Version bump actually happened
        pkg = json.loads((core / "package.json").read_text())
        assert pkg["version"] == "1.0.1"
        # Batch file finalized
        assert not (releases_dir / "unreleased.toml").exists()


