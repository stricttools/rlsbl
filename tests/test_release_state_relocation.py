"""Tests for releasable release state relocation.

Releasable releases used to write in-progress.json under the representative
member's ``.rlsbl/releases/`` — polluting the member package with state that
belongs to the releasable. The state now lives at
``.rlsbl-monorepo/releasables/<name>/releases/in-progress.json`` and ALL
derivations (executor, run guard, resume CLI, scrub) go through one resolver.

Covers:
- A releasable release writes ZERO files under the representative's
  ``.rlsbl/releases/`` — the preserved state (on post-release failure)
  lands in the releasable's own releases dir, and resume completes from it.
- The run guard reads the releasable state path, and detects legacy state
  at the old representative location with a migration-hint error.
- resolve_resume_source: member-dir resolution, workspace-root resolution
  (single in-flight releasable), ambiguity error, legacy-location error.
- Scrub state (scrub-result.json) relocates the same way.
- The changelog exemption already covers the new state path.
"""

import json
import os
import subprocess
from pathlib import Path
from unittest.mock import MagicMock, patch

import pytest

from rlsbl.commands.release import resume_cmd, run_cmd
from rlsbl.commands.release.release_state import (
    StateResolutionError,
    get_state_path,
    load_release_state,
    resolve_releasable_dir,
    resolve_resume_source,
    save_release_state,
)
from rlsbl.context import create_context
from rlsbl.release_file import ReleaseConfig
from rlsbl.utils import run as real_run
from rlsbl.workspace import (
    Releasable,
    get_releasable_dir,
    get_releasable_changes_dir,
    save_workspace,
    write_releasable_version,
)


