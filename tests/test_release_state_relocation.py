class TestResolveReleasableDir:

    def test_member_resolves(self, tmp_project):
        core = _setup_releasable_workspace(tmp_project)
        result = resolve_releasable_dir(str(core), str(tmp_project))
        assert result is not None
        assert os.path.realpath(result) == os.path.realpath(
            get_releasable_dir(str(tmp_project), "alpha")
        )

    def test_none_without_workspace(self, tmp_project):
        assert resolve_releasable_dir(str(tmp_project), None) is None

    def test_none_for_non_member(self, tmp_project):
        _setup_releasable_workspace(tmp_project)
        other = tmp_project / "packages" / "other"
        other.mkdir(parents=True)
        assert resolve_releasable_dir(str(other), str(tmp_project)) is None


