class TestResolveResumeSource:

    def test_standalone(self, tmp_project):
        project_dir, state_path = resolve_resume_source(None, cwd=".")
        assert project_dir == "."
        assert state_path == get_state_path(".")

    def test_member_dir_resolves_releasable_path(self, tmp_project, monkeypatch):
        core = _setup_releasable_workspace(tmp_project)
        monkeypatch.chdir(core)

        project_dir, state_path = resolve_resume_source(
            str(tmp_project), cwd=".",
        )
        assert os.path.realpath(project_dir) == os.path.realpath(str(core))
        assert os.path.realpath(state_path) == os.path.realpath(
            _releasable_state_path(tmp_project)
        )

    def test_member_dir_legacy_state_errors_with_hint(
        self, tmp_project, monkeypatch,
    ):
        core = _setup_releasable_workspace(tmp_project)
        legacy_path = get_state_path(str(core))
        save_release_state(legacy_path, {"completed_steps": []})
        monkeypatch.chdir(core)

        with pytest.raises(StateResolutionError, match="legacy location"):
            resolve_resume_source(str(tmp_project), cwd=".")

    def test_workspace_root_single_inflight_releasable(self, tmp_project):
        core = _setup_releasable_workspace(tmp_project)
        rel_state_path = _releasable_state_path(tmp_project)
        save_release_state(rel_state_path, {
            "new_version": "1.0.1",
            "completed_steps": [],
            "monorepo_name": "core",
            "releasable_name": "alpha",
        })

        project_dir, state_path = resolve_resume_source(
            str(tmp_project), cwd=str(tmp_project),
        )
        assert os.path.realpath(project_dir) == os.path.realpath(str(core))
        assert os.path.realpath(state_path) == os.path.realpath(rel_state_path)

    def test_workspace_root_no_inflight_errors(self, tmp_project):
        _setup_releasable_workspace(tmp_project)
        with pytest.raises(StateResolutionError, match="cannot resume from monorepo root"):
            resolve_resume_source(str(tmp_project), cwd=str(tmp_project))

    def test_workspace_root_ambiguous_errors(self, tmp_project):
        """Two releasables mid-release: resume from root must error clearly."""
        _setup_releasable_workspace(tmp_project)
        # Add a second releasable with in-flight state
        beta_dir = get_releasable_dir(str(tmp_project), "beta")
        os.makedirs(beta_dir, exist_ok=True)
        save_release_state(
            get_state_path("", releasable_dir=beta_dir),
            {"completed_steps": []},
        )
        save_release_state(
            _releasable_state_path(tmp_project, "alpha"),
            {"completed_steps": [], "monorepo_name": "core"},
        )

        with pytest.raises(StateResolutionError) as exc_info:
            resolve_resume_source(str(tmp_project), cwd=str(tmp_project))
        assert "alpha" in str(exc_info.value)
        assert "beta" in str(exc_info.value)


