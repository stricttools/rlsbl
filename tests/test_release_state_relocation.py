class TestGuardReleasableAwareness:

    def test_guard_blocks_on_releasable_state(self, tmp_project, capsys):
        core = _setup_releasable_workspace(tmp_project)

        rel_state_path = _releasable_state_path(tmp_project)
        save_release_state(rel_state_path, {
            "new_version": "1.0.1",
            "completed_steps": ["VERSION_BUMPED", "COMMITTED"],
        })

        with pytest.raises(SystemExit):
            run_cmd(
                _rc(),
                {"yes": True, "quiet": True, "skip-lock": True},
                ctx=_make_ctx(core, tmp_project),
            )

        captured = capsys.readouterr()
        assert "previous release is in progress" in captured.err

    def test_guard_detects_legacy_state_with_migration_hint(
        self, tmp_project, capsys,
    ):
        """In-flight state at the OLD representative location must not be
        silently ignored: the guard errors with a migration hint."""
        core = _setup_releasable_workspace(tmp_project)

        legacy_path = get_state_path(str(core))
        save_release_state(legacy_path, {
            "new_version": "1.0.1",
            "completed_steps": ["VERSION_BUMPED"],
        })

        with pytest.raises(SystemExit):
            run_cmd(
                _rc(),
                {"yes": True, "quiet": True, "skip-lock": True},
                ctx=_make_ctx(core, tmp_project),
            )

        captured = capsys.readouterr()
        assert "legacy location" in captured.err
        assert legacy_path in captured.err
        assert _releasable_state_path(tmp_project) in captured.err


