class TestScrubStateRelocation:

    def test_stale_scrub_result_read_from_releasable_path(
        self, tmp_project, capsys,
    ):
        """Scrub reads scrub-result.json from the releasable releases dir
        for releasable member projects."""
        from rlsbl.commands.release.release_state import get_scrub_result_path
        from rlsbl.commands.release_scrub import run_cmd as scrub_run_cmd

        core = _setup_releasable_workspace(tmp_project)
        rel_dir = get_releasable_dir(str(tmp_project), "alpha")
        scrub_path = get_scrub_result_path(str(core), releasable_dir=rel_dir)
        os.makedirs(os.path.dirname(scrub_path), exist_ok=True)
        with open(scrub_path, "w") as f:
            json.dump({"new_head": "stale_sha", "completed_steps": []}, f)

        flags = {
            "pattern": "secret", "replace": "XXX",
            "reason": "test", "entire-history": True,
        }
        mod = "rlsbl.commands.release_scrub"
        with pytest.raises(SystemExit) as exc_info:
            with (
                patch(f"{mod}.require_tool"),
                patch(f"{mod}.run", MagicMock(
                    side_effect=["safegit 0.22.0", "different_sha"],
                )),
            ):
                scrub_run_cmd(flags, ctx=_make_ctx(core, tmp_project))
        assert exc_info.value.code == 1

        captured = capsys.readouterr()
        assert "stale scrub-result.json" in captured.err
        assert scrub_path in captured.err


