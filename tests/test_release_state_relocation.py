def _git(repo, *args):
    subprocess.run(
        ["git"] + list(args),
        cwd=str(repo),
        check=True,
        capture_output=True,
        text=True,
    )


def _git_head(repo):
    result = subprocess.run(
        ["git", "rev-parse", "HEAD"],
        cwd=str(repo),
        capture_output=True,
        text=True,
        check=True,
    )
    return result.stdout.strip()


def _rc(description="test release"):
    return ReleaseConfig(
        bump="patch",
        include=["npm"],
        exclude=[],
        description=description,
    )


def _setup_releasable_workspace(root):
    """Workspace with releasable 'alpha' whose sole member is packages/core.

    Returns the member (representative) directory path.
    """
    _git(root, "init", "-q", "-b", "main")
    _git(root, "config", "user.email", "test@test.local")
    _git(root, "config", "user.name", "Test")

    core = root / "packages" / "core"
    core.mkdir(parents=True)
    (core / "package.json").write_text(
        json.dumps({"name": "core", "version": "1.0.0"}, indent=2) + "\n"
    )
    (core / "CHANGELOG.md").write_text(
        "<!-- Generated by rlsbl from .rlsbl/changes/ -- do not edit -->\n\n"
        "# Changelog\n\n## 1.0.0\n\n- Initial release.\n"
    )
    (core / ".rlsbl").mkdir()
    (core / ".rlsbl" / "config.json").write_text(
        json.dumps({"publish_mode": "ci", "targets": ["npm"], "pipelines": {}}) + "\n"
    )

    save_workspace(
        str(root),
        [{"path": "packages/core", "name": "core", "releasable": "alpha"}],
        releasables=[Releasable(name="alpha")],
    )
    write_releasable_version(str(root), "alpha", "1.0.0")
    changes_dir = get_releasable_changes_dir(str(root), "alpha")
    os.makedirs(changes_dir, exist_ok=True)
    with open(os.path.join(changes_dir, "unreleased.jsonl"), "w") as f:
        f.write("")
    rel_dir = get_releasable_dir(str(root), "alpha")
    with open(os.path.join(rel_dir, "config.json"), "w") as f:
        f.write("{}\n")

    _git(root, "add", ".rlsbl-monorepo", "packages")
    _git(root, "commit", "-q", "-m", "initial")
    _git(root, "tag", "alpha@v1.0.0")

    # Member-scoped feature commit
    (core / "feature.txt").write_text("new feature\n")
    _git(root, "add", "packages/core/feature.txt")
    _git(root, "commit", "-q", "-m", "add feature")
    feature_sha = _git_head(root)

    # Cover it in the releasable-level changelog
    entry = {
        "commits": [feature_sha],
        "user_facing": True,
        "description": "**New feature.** A shiny new thing.",
        "type": "feature",
    }
    with open(os.path.join(changes_dir, "unreleased.jsonl"), "w") as f:
        f.write(json.dumps(entry) + "\n")
    _git(root, "add", os.path.relpath(changes_dir, str(root)))
    _git(root, "commit", "-q", "-m", "changelog: add feature entry",
         "--trailer", "Autogenerated: true")

    return core


def _make_ctx(member_dir, root):
    return create_context(Path(str(member_dir)), workspace_root=Path(str(root)))


def _fake_run_factory():
    def fake_run(cmd, args=None, timeout=120, env=None, cwd=None):
        if cmd == "gh":
            return ""
        if cmd == "git" and args and args[0] == "push":
            return ""
        if cmd == "git" and args and args[0] == "fetch":
            return ""
        if cmd == "git" and args and args[:2] == ["rev-list", "--count"] and any("origin/" in a for a in args):
            return "0"
        return real_run(cmd, args=args, timeout=timeout, env=env, cwd=cwd)
    return fake_run


def _releasable_state_path(root, name="alpha"):
    return get_state_path(
        "", releasable_dir=get_releasable_dir(str(root), name),
    )


# ---------------------------------------------------------------------------
# Executor writes state to the releasable location
# ---------------------------------------------------------------------------


class TestReleasableStateRelocation:

    def test_failed_release_preserves_state_at_releasable_path(
        self, tmp_project, capsys,
    ):
        """A releasable release that fails post-release (GitHub Release
        creation) preserves its state under the releasable's dir and writes
        NOTHING under the representative member's .rlsbl/releases/."""
        core = _setup_releasable_workspace(tmp_project)

        def failing_run_gh(args, **kwargs):
            if args and args[0] == "release" and args[1] in ("create", "view"):
                raise subprocess.CalledProcessError(1, f"gh release {args[1]}")
            return ""

        fake_run = _fake_run_factory()
        with pytest.raises(SystemExit):
            with (
                patch("rlsbl.commands.release.check_gh_installed", return_value=True),
                patch("rlsbl.commands.release.check_gh_auth", return_value=True),
                patch("rlsbl.commands.release.push_if_needed"),
                patch("rlsbl.commands.release.run_gh", side_effect=failing_run_gh),
                patch("rlsbl.commands.release.run", side_effect=fake_run),
                patch("rlsbl.commands.release.remote_branch_exists", return_value=True),
            ):
                run_cmd(
                    _rc(),
                    {"yes": True, "quiet": True, "skip-lock": True},
                    ctx=_make_ctx(core, tmp_project),
                )

        # State preserved at the releasable location
        rel_state_path = _releasable_state_path(tmp_project)
        assert os.path.exists(rel_state_path), (
            "in-progress.json must live under the releasable's releases dir"
        )
        state = load_release_state(rel_state_path)
        assert state["releasable_name"] == "alpha"
        assert "PUSHED" in state["completed_steps"]

        # ZERO pollution of the representative member
        rep_releases = core / ".rlsbl" / "releases"
        assert not rep_releases.exists(), (
            "releasable release must not create files under the "
            "representative's .rlsbl/releases/"
        )

    def test_resume_from_releasable_state_completes(self, tmp_project):
        """Resume picks up the releasable-located state and clears it."""
        core = _setup_releasable_workspace(tmp_project)

        # First, produce a preserved state via a failed GH release
        def failing_run_gh(args, **kwargs):
            if args and args[0] == "release" and args[1] in ("create", "view"):
                raise subprocess.CalledProcessError(1, f"gh release {args[1]}")
            return ""

        fake_run = _fake_run_factory()
        with pytest.raises(SystemExit):
            with (
                patch("rlsbl.commands.release.check_gh_installed", return_value=True),
                patch("rlsbl.commands.release.check_gh_auth", return_value=True),
                patch("rlsbl.commands.release.push_if_needed"),
                patch("rlsbl.commands.release.run_gh", side_effect=failing_run_gh),
                patch("rlsbl.commands.release.run", side_effect=fake_run),
                patch("rlsbl.commands.release.remote_branch_exists", return_value=True),
            ):
                run_cmd(
                    _rc(),
                    {"yes": True, "quiet": True, "skip-lock": True},
                    ctx=_make_ctx(core, tmp_project),
                )

        rel_state_path = _releasable_state_path(tmp_project)
        saved = load_release_state(rel_state_path)
        assert saved is not None

        # Resume with a working gh: completes and clears the state
        with (
            patch("rlsbl.commands.release.push_if_needed"),
            patch("rlsbl.commands.release.run_gh", return_value=""),
            patch("rlsbl.commands.release.run", side_effect=_fake_run_factory()),
        ):
            resume_cmd(
                saved,
                {"yes": True, "quiet": True, "skip-lock": True},
                ctx=_make_ctx(core, tmp_project),
            )

        assert not os.path.exists(rel_state_path)
        assert not (core / ".rlsbl" / "releases").exists()


