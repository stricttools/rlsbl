"""Tests for rlsbl.utils.commit_files."""

import shutil
import subprocess
from unittest.mock import patch, call

import pytest

from conftest import commit_invocations, dirty_run_side_effect
from rlsbl.utils import commit_files


class TestCommitFilesSafegit:
    """Tests for the safegit path."""

    @patch("rlsbl.utils.run", side_effect=dirty_run_side_effect())
    @patch("shutil.which", return_value="/usr/bin/safegit")
    def test_calls_safegit_with_correct_args(self, mock_which, mock_run):
        result = commit_files("test message", ["file1.py", "file2.py"])
        assert result is True
        assert commit_invocations(mock_run) == [
            call(
                "safegit",
                ["commit", "--trailer", "Autogenerated: true", "-m", "test message", "--", "file1.py", "file2.py"],
                cwd=None,
            )
        ]


class TestCommitFilesRealSafegit:
    """Exercise the REAL safegit binary, not a mocked argv.

    Regression: rlsbl passed ``--yes`` to ``safegit commit``. When strictcli
    replaced the inferred "mutating => confirm" rule with the declared
    ``consequential`` one, ``--yes`` became a banned flag name and every
    ``rlsbl commit`` / ``rlsbl changelog add`` auto-commit died with
    ``error: unknown flag '--yes'``. An argv-pinning mock cannot catch that --
    only running the real callee can. This test is the tripwire for any future
    flag rename on safegit's side: it fails here instead of mid-release.
    """

    def test_commits_through_real_safegit(self, tmp_path, monkeypatch):
        if shutil.which("safegit") is None:
            pytest.skip("safegit not on PATH")
        subprocess.run(["git", "init", "-q", "-b", "main"], cwd=str(tmp_path), check=True)
        subprocess.run(["git", "config", "user.email", "t@t.local"], cwd=str(tmp_path), check=True)
        subprocess.run(["git", "config", "user.name", "T"], cwd=str(tmp_path), check=True)
        (tmp_path / "gen.txt").write_text("generated\n")

        assert commit_files(
            "test message", ["gen.txt"], cwd=str(tmp_path), allow_failure=False
        ) is True

        log = subprocess.run(
            ["git", "log", "-1", "--pretty=%B"], cwd=str(tmp_path),
            capture_output=True, text=True, check=True,
        ).stdout
        assert "test message" in log
        assert "Autogenerated: true" in log


