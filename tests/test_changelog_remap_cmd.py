class TestRemapNoSourceError:
    """Test that no source flags produce a hard error."""

    def test_no_source_exits(self, tmp_path):
        project, _ = _setup_standalone_project(tmp_path)
        flags = {
            "map-file": None,
            "from-journal": False,
            "stdin": False,
            "dry-run": False,
        }
        with pytest.raises(SystemExit) as exc_info:
            cmd_remap(flags, project_root=project)
        assert exc_info.value.code == 1
