# _parse_sha_map_lines tests
# ---------------------------------------------------------------------------


class TestParseShaMapLines:
    """Tests for the ``old_sha new_sha`` line parser."""

    def test_parses_two_column_lines(self):
        lines = [
            "abc123 def456\n",
            "111aaa 222bbb\n",
        ]
        result = _parse_sha_map_lines(lines)
        assert result == {"abc123": "def456", "111aaa": "222bbb"}

    def test_skips_blank_lines_and_comments(self):
        lines = [
            "# comment\n",
            "\n",
            "   \n",
            "abc123 def456\n",
        ]
        result = _parse_sha_map_lines(lines)
        assert result == {"abc123": "def456"}

    def test_ignores_extra_columns(self):
        """git's post-rewrite hook may emit extra fields after the two SHAs."""
        lines = ["old_sha new_sha extra_field\n"]
        result = _parse_sha_map_lines(lines)
        assert result == {"old_sha": "new_sha"}

    def test_warns_on_single_column(self, capsys):
        lines = ["only_one_field\n"]
        result = _parse_sha_map_lines(lines)
        assert result == {}
        captured = capsys.readouterr()
        assert "malformed" in captured.err


