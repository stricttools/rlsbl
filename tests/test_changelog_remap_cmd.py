# ---------------------------------------------------------------------------


class TestRemapViaMapFile:
    """Test remapping a single entry via --map-file."""

    def test_remap_single_entry_via_map_file(self, tmp_path, monkeypatch):
        project, changes = _setup_standalone_project(tmp_path)
        unreleased = changes / "unreleased.jsonl"
        _write_entries(str(unreleased), [
            ChangelogEntry(commits=["old_aaa"], user_facing=False),
            ChangelogEntry(
                commits=["old_bbb"],
                user_facing=True,
                description="A feature",
                type="feature",
            ),
        ])

        # Write a map file
        map_file = tmp_path / "map.txt"
        map_file.write_text("old_aaa new_aaa\nold_bbb new_bbb\n")

        # Stub out commit_files to avoid needing a real git repo
        import rlsbl.commands.changelog_cmd as mod
        committed = []
        monkeypatch.setattr(mod, "commit_files", lambda *a, **kw: committed.append((a, kw)))

        flags = {
            "map-file": str(map_file),
            "from-journal": False,
            "stdin": False,
            "dry-run": False,
        }
        cmd_remap(flags, project_root=project)

        # Verify the JSONL was rewritten
        updated = parse_jsonl(str(unreleased))
        assert updated[0].commits == ["new_aaa"]
        assert updated[1].commits == ["new_bbb"]
        assert updated[1].description == "A feature"

        # Verify auto-commit was called
        assert len(committed) == 1
        assert committed[0][1].get("autogenerated") is True


