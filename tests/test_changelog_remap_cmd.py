# ---------------------------------------------------------------------------
# cmd_remap: unmapped hash warning
# ---------------------------------------------------------------------------


class TestRemapUnmappedWarning:
    """Test that unmapped hashes are reported as warnings."""

    def test_unmapped_hash_reported(self, tmp_path, monkeypatch, capsys):
        project, changes = _setup_standalone_project(tmp_path)
        unreleased = changes / "unreleased.jsonl"
        _write_entries(str(unreleased), [
            ChangelogEntry(commits=["mapped_hash", "orphan_hash"], user_facing=False),
        ])

        map_file = tmp_path / "map.txt"
        map_file.write_text("mapped_hash new_mapped\n")

        import rlsbl.commands.changelog_cmd as mod
        monkeypatch.setattr(mod, "commit_files", lambda *a, **kw: None)

        flags = {
            "map-file": str(map_file),
            "from-journal": False,
            "stdin": False,
            "dry-run": False,
        }
        cmd_remap(flags, project_root=project)

        captured = capsys.readouterr()
        assert "unmapped hash" in captured.err
        assert "orphan_hash" in captured.err

        # The mapped hash should still have been remapped
        updated = parse_jsonl(str(unreleased))
        assert updated[0].commits == ["new_mapped", "orphan_hash"]


