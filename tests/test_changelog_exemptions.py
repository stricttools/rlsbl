class TestExemptionRegistry:
    def test_empty_registry_check_returns_not_exempt(self):
        """An empty registry never exempts anything."""
        from rlsbl.changelog.exemptions import ExemptionRegistry

        reg = ExemptionRegistry()
        exempt, reason = reg.check("abc123")
        assert exempt is False
        assert reason is None

    def test_empty_registry_filter_returns_all(self):
        """An empty registry returns all commits and zero stats."""
        from rlsbl.changelog.exemptions import ExemptionRegistry, ExemptionStats

        reg = ExemptionRegistry()
        remaining, stats = reg.filter_commits(["a", "b", "c"])
        assert remaining == ["a", "b", "c"]
        assert stats == ExemptionStats()

    def test_register_adds_rule(self):
        """Registering a rule makes it appear in rules list."""
        from rlsbl.changelog.exemptions import ExemptionRegistry

        reg = ExemptionRegistry()
        reg.register("test_rule", lambda sha: True, "test reason")
        assert len(reg.rules) == 1
        assert reg.rules[0].name == "test_rule"

    def test_check_returns_first_matching_rule(self):
        """check() returns the first matching rule's reason."""
        from rlsbl.changelog.exemptions import ExemptionRegistry

        reg = ExemptionRegistry()
        reg.register("first", lambda sha: sha == "a", "first reason")
        reg.register("second", lambda sha: True, "second reason")
        exempt, reason = reg.check("a")
        assert exempt is True
        assert reason == "first reason"

    def test_check_skips_non_matching_rules(self):
        """check() skips rules that don't match."""
        from rlsbl.changelog.exemptions import ExemptionRegistry

        reg = ExemptionRegistry()
        reg.register("never", lambda sha: False, "never")
        reg.register("always", lambda sha: True, "always reason")
        exempt, reason = reg.check("anything")
        assert exempt is True
        assert reason == "always reason"

    def test_rules_property_returns_copy(self):
        """Modifying the returned rules list doesn't affect the registry."""
        from rlsbl.changelog.exemptions import ExemptionRegistry

        reg = ExemptionRegistry()
        reg.register("r1", lambda sha: True, "reason")
        rules = reg.rules
        rules.clear()
        assert len(reg.rules) == 1


class TestRuleOrdering:
    def test_first_match_wins_for_stats(self):
        """When a commit matches both rules, only the first increments stats."""
        from rlsbl.changelog.exemptions import ExemptionRegistry, ExemptionStats

        reg = ExemptionRegistry()
        reg.register("autogenerated", lambda sha: True, "auto")
        reg.register("changelog_only", lambda sha: True, "changelog")
        remaining, stats = reg.filter_commits(["abc"])
        assert remaining == []
        assert stats.autogenerated == 1
        assert stats.changelog_only == 0

    def test_second_rule_counted_when_first_does_not_match(self):
        """When a commit only matches the second rule, it's counted correctly."""
        from rlsbl.changelog.exemptions import ExemptionRegistry

        reg = ExemptionRegistry()
        reg.register("autogenerated", lambda sha: False, "auto")
        reg.register("changelog_only", lambda sha: True, "changelog")
        remaining, stats = reg.filter_commits(["abc"])
        assert remaining == []
        assert stats.autogenerated == 0
        assert stats.changelog_only == 1


class TestCreateDefaultRegistry:
    def test_registry_has_two_rules(self):
        """Default registry has exactly 2 rules in the correct order."""
        from rlsbl.changelog.exemptions import create_default_registry

        reg = create_default_registry()
        assert len(reg.rules) == 2
        assert reg.rules[0].name == "autogenerated"
        assert reg.rules[1].name == "changelog_only"

    def test_exempts_autogenerated_commit(self, git_repo):
        """A commit with the Autogenerated: true trailer is exempted."""
        from rlsbl.changelog.exemptions import create_default_registry

        _run_git(git_repo, "commit", "--allow-empty", "-m", "auto\n\nAutogenerated: true")
        sha = _git_head(git_repo)
        reg = create_default_registry()
        exempt, reason = reg.check(sha)
        assert exempt is True
        assert "Autogenerated" in reason

    def test_exempts_changelog_only_commit(self, git_repo):
        """A commit that only touches changelog files is exempted."""
        from rlsbl.changelog.exemptions import create_default_registry

        unreleased = git_repo / ".rlsbl" / "changes" / "unreleased.jsonl"
        unreleased.write_text('{"commits":["abc"],"user_facing":false}\n')
        _run_git(git_repo, "add", ".rlsbl/changes/unreleased.jsonl")
        _run_git(git_repo, "commit", "-m", "add changelog entry")
        sha = _git_head(git_repo)
        reg = create_default_registry()
        exempt, reason = reg.check(sha)
        assert exempt is True
        assert "changelog" in reason.lower()

    def test_does_not_exempt_normal_commit(self, git_repo):
        """A normal commit is not exempted by the default registry."""
        from rlsbl.changelog.exemptions import create_default_registry

        sha = _make_commit(git_repo, "code.py", "normal change")
        reg = create_default_registry()
        exempt, reason = reg.check(sha)
        assert exempt is False
        assert reason is None

    def test_filter_commits_matches_filter_exempt_commits(self, git_repo):
        """Default registry's filter_commits produces the same result as
        the legacy filter_exempt_commits wrapper."""
        from rlsbl.changelog.exemptions import create_default_registry
        from rlsbl.changelog.validate import filter_exempt_commits

        # Make one of each type
        _run_git(git_repo, "commit", "--allow-empty", "-m", "auto\n\nAutogenerated: true")
        sha_auto = _git_head(git_repo)

        unreleased = git_repo / ".rlsbl" / "changes" / "unreleased.jsonl"
        unreleased.write_text('{"commits":["abc"],"user_facing":false}\n')
        _run_git(git_repo, "add", ".rlsbl/changes/unreleased.jsonl")
        _run_git(git_repo, "commit", "-m", "changelog entry")
        sha_changelog = _git_head(git_repo)

        sha_normal = _make_commit(git_repo, "code.py", "normal change")

        commits = [sha_auto, sha_changelog, sha_normal]

        # Both should produce identical results
        reg = create_default_registry()
        reg_remaining, reg_stats = reg.filter_commits(commits)
        legacy_remaining, legacy_stats = filter_exempt_commits(commits)

        assert reg_remaining == legacy_remaining
        assert reg_stats.autogenerated == legacy_stats.autogenerated
        assert reg_stats.changelog_only == legacy_stats.changelog_only


