        _git(mock_git_repo, "add", "feature.txt")
        _git(mock_git_repo, "commit", "-q", "-m", "add feature")
        feature_sha = _git_head(mock_git_repo)

        entry = {
            "commits": [feature_sha],
            "user_facing": True,
            "description": "**New feature.** A shiny new thing.",
            "type": "feature",
        }
        (changes_dir / "unreleased.jsonl").write_text(json.dumps(entry) + "\n")
        _git(mock_git_repo, "add", ".rlsbl/changes/unreleased.jsonl")
        _git(mock_git_repo, "commit", "-q", "-m", "changelog: add entry",
             "--trailer", "Autogenerated: true")

