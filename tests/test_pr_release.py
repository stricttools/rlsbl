        assert "v1.0.1" in tags, f"Imperative mode should create v1.0.1 tag, got: {tags}"

        # Should NOT have created a release branch
        branches = _git_output(mock_git_repo, "branch", "--list", "release/v*")
        assert branches == "", f"Imperative mode should not create release branches, got: {branches}"


