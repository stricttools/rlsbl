class TestResumeAfterTagPushFailure:
    """Resume after release completed through tag creation but push failed."""

    def test_resume_after_push_failure(self, mock_git_repo):
        """Simulate release through TAGGED, then resume picks up at push."""
        _setup_releasable_npm_project(mock_git_repo)

        # Simulate a partial release: version bumped, committed, changelog
        # finalized, release file finalized, tagged, but push failed.
        pkg = json.loads((mock_git_repo / "package.json").read_text())
        pkg["version"] = "1.0.1"
        (mock_git_repo / "package.json").write_text(
            json.dumps(pkg, indent=2) + "\n"
        )
        _git(mock_git_repo, "add", "package.json")
        _git(mock_git_repo, "commit", "-q", "-m", "v1.0.1")
        _git(mock_git_repo, "tag", "v1.0.1")

        # Create the in-progress state as if push failed after tagging
        state_path = _make_in_progress_state(
            mock_git_repo,
            completed_steps=[
                "VERSION_BUMPED", "COMMITTED", "CHANGELOG_FINALIZED",
                "RELEASE_FILE_FINALIZED", "TAGGED",
            ],
        )

        # Resume should pick up at the push step
        fake_run_ok = _fake_run_factory()
        with (
            patch("rlsbl.commands.release.push_if_needed"),
            patch("rlsbl.commands.release.run_gh", return_value=""),
            patch("rlsbl.commands.release.run", side_effect=fake_run_ok),
        ):
            resume_cmd(
                load_release_state(state_path),
                {"yes": True, "quiet": True},
                ctx=_make_ctx(mock_git_repo),
            )

        # State file should be cleared on success
        assert not os.path.exists(state_path), \
            "in-progress.json should be deleted after successful resume"


class TestResumeAfterGitHubReleaseFailure:
    """Resume after push succeeded but GitHub Release creation failed."""

    def test_resume_creates_github_release(self, mock_git_repo):
        _setup_releasable_npm_project(mock_git_repo)

        # Simulate a full release except GH Release: bump, commit, finalize,
        # tag, push all done.
        pkg = json.loads((mock_git_repo / "package.json").read_text())
        pkg["version"] = "1.0.1"
        (mock_git_repo / "package.json").write_text(
            json.dumps(pkg, indent=2) + "\n"
        )
        _git(mock_git_repo, "add", "package.json")
        _git(mock_git_repo, "commit", "-q", "-m", "v1.0.1")
        _git(mock_git_repo, "tag", "v1.0.1")

        state_path = _make_in_progress_state(
            mock_git_repo,
            completed_steps=[
                "VERSION_BUMPED", "COMMITTED", "CHANGELOG_FINALIZED",
                "RELEASE_FILE_FINALIZED", "TAGGED", "PUSHED",
            ],
        )

        # Track gh calls; simulate: release view fails (no release yet),
        # release create succeeds.
        gh_calls = []
        release_exists = [False]

        def tracking_run_gh(args, **kwargs):
            gh_calls.append(list(args))
            if args and args[0] == "release":
                if args[1] == "view":
                    if not release_exists[0]:
                        raise subprocess.CalledProcessError(1, "gh release view")
                    return ""
                if args[1] == "create":
                    release_exists[0] = True
                    return ""
            return ""

        fake_run_ok = _fake_run_factory()
        with (
            patch("rlsbl.commands.release.push_if_needed"),
            patch("rlsbl.commands.release.run_gh", side_effect=tracking_run_gh),
            patch("rlsbl.commands.release.run", side_effect=fake_run_ok),
        ):
            resume_cmd(
                load_release_state(state_path),
                {"yes": True, "quiet": True},
                ctx=_make_ctx(mock_git_repo),
            )

        # Verify gh release create was called
        create_calls = [c for c in gh_calls if c[:2] == ["release", "create"]]
        assert len(create_calls) > 0, (
            f"Expected gh release create call, got calls: {gh_calls}"
        )

        # State file should be cleared
        assert not os.path.exists(state_path), \
            "in-progress.json should be deleted after successful resume"


