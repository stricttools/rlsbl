class TestGitHubReleaseFailurePreservesState:
    """When GitHub Release creation fails, in-progress.json is preserved."""

    def test_state_preserved_on_gh_release_failure(self, mock_git_repo, capsys):
        _setup_releasable_npm_project(mock_git_repo)

        state_path = get_state_path(str(mock_git_repo))

        def failing_run_gh(args, **kwargs):
            if args and args[0] == "release" and args[1] in ("create", "view"):
                raise subprocess.CalledProcessError(1, f"gh release {args[1]}")
