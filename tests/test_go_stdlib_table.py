"""The committed Go standard-library table ``check-name --target go`` reads.

The table is generated by ``scripts/gen_go_stdlib_table.py`` from ``go list
std`` and committed; rlsbl never asks a Go toolchain at run time. These tests
pin its shape and, when a Go toolchain is on PATH, its freshness.
"""

import importlib.util
import json
import os
import re
import shutil

import pytest

REPO_ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
GENERATOR = os.path.join(REPO_ROOT, "scripts", "gen_go_stdlib_table.py")
TABLE = os.path.join(REPO_ROOT, "rlsbl", "data", "go-stdlib-packages.json")


def _load_generator():
    spec = importlib.util.spec_from_file_location("gen_go_stdlib_table", GENERATOR)
    module = importlib.util.module_from_spec(spec)
    spec.loader.exec_module(module)
    return module


def _release_line(version):
    """``go1.26.6`` -> ``(1, 26)``."""
    match = re.fullmatch(r"go(\d+)\.(\d+)(?:\.\d+)?", version)
    assert match, f"unrecognized Go version {version!r}"
    return int(match.group(1)), int(match.group(2))


def _table():
    with open(TABLE, encoding="utf-8") as handle:
        return json.load(handle)


class TestTableShape:

    def test_stamp_names_generator_source_and_toolchain(self):
        table = _table()
        assert table["generator"] == "scripts/gen_go_stdlib_table.py"
        assert "go list std" in table["source"]
        _release_line(table["go_version"])

    def test_packages_are_sorted_unique_and_importable(self):
        packages = _table()["packages"]
        assert packages == sorted(set(packages))
        for path in packages:
            parts = path.split("/")
            assert "internal" not in parts and "vendor" not in parts, path

    def test_platform_specific_packages_are_included(self):
        packages = set(_table()["packages"])
        assert {"syscall/js", "log/syslog", "testing", "encoding/json"} <= packages

    def test_the_package_loader_reads_the_committed_file(self):
        from rlsbl.go_package_name import stdlib_import_paths

        assert stdlib_import_paths() == tuple(_table()["packages"])


class TestTableFreshness:

    def test_table_matches_go_list_std(self):
        if shutil.which("go") is None:
            pytest.skip(
                "no Go toolchain on PATH: the freshness of rlsbl/data/go-stdlib-packages.json "
                "against `go list std` cannot be checked on this machine"
            )
        generator = _load_generator()
        local = generator.toolchain_version()
        stamped = _table()["go_version"]
        if _release_line(local) < _release_line(stamped):
            pytest.skip(
                f"local Go toolchain {local} is older than the table's {stamped}: "
                "an older release line cannot judge a newer table"
            )
        fresh = generator.render_table(generator.list_std_packages(), local)
        committed = json.loads(open(TABLE, encoding="utf-8").read())
        fresh_doc = json.loads(fresh)
        assert fresh_doc["packages"] == committed["packages"], (
            f"rlsbl/data/go-stdlib-packages.json (from {stamped}) no longer matches "
            f"`go list std` under {local}. Regenerate it with "
            "`uv run python scripts/gen_go_stdlib_table.py` and commit the result."
        )
        assert _release_line(local) == _release_line(stamped), (
            f"the local Go toolchain {local} is on a newer release line than the "
            f"table's stamp {stamped}. Regenerate it with "
            "`uv run python scripts/gen_go_stdlib_table.py` and commit the result."
        )
