"""Regression test: a successful release must produce the per-version .md file.

After `rlsbl release`, `.rlsbl/changes/x.y.z.md` should exist alongside
`.rlsbl/changes/x.y.z.jsonl`. Previously, `finalize_version()` renamed the
JSONL but nothing called `generate_version_file()` to create the markdown,
so the .md file was missing from every release.
"""

import json
import os
import subprocess
from unittest.mock import patch

import pytest

from pathlib import Path
from rlsbl.context import ProjectContext

from rlsbl.release_file import ReleaseConfig


def _rc(bump="patch", include=None, exclude=None):
    """Shorthand for creating a ReleaseConfig with sensible defaults."""
    return ReleaseConfig(
        bump=bump,
        include=include or ["npm"],
        exclude=exclude or [],
    )


def _git(repo, *args):
    subprocess.run(
        ["git"] + list(args),
        cwd=str(repo),
        check=True,
        capture_output=True,
        text=True,
    )


def _git_head(repo):
    result = subprocess.run(
        ["git", "rev-parse", "HEAD"],
        cwd=str(repo),
        capture_output=True,
        text=True,
        check=True,
    )
    return result.stdout.strip()


def _setup_releasable_npm_project(repo):
    """Create a git repo with a tagged v1.0.0 release and an unreleased commit
    covered by an unreleased.jsonl entry. Ready for `rlsbl release patch`.

    The JSONL changelog commit uses the ``Autogenerated: true`` trailer
    (the same trailer that ``rlsbl changelog add`` produces) so it is
    automatically exempted from coverage checks.
    """
    _git(repo, "init", "-q", "-b", "main")
    _git(repo, "config", "user.email", "test@test.local")
    _git(repo, "config", "user.name", "Test")

    # Initial release: package.json @ 1.0.0
    (repo / "package.json").write_text(
        json.dumps({"name": "test-pkg", "version": "1.0.0"}, indent=2) + "\n"
    )
    (repo / "CHANGELOG.md").write_text(
        "# Changelog\n\n## 1.0.0\n\n- Initial release.\n"
    )
    changes_dir = repo / ".rlsbl" / "changes"
    changes_dir.mkdir(parents=True)
    (changes_dir / "unreleased.jsonl").write_text("")
    (repo / ".rlsbl" / "config.json").write_text(
        json.dumps({"private": False, "targets": ["npm"]}) + "\n"
    )
    _git(repo, "add", "package.json", "CHANGELOG.md", ".rlsbl/changes/unreleased.jsonl", ".rlsbl/config.json")
    _git(repo, "commit", "-q", "-m", "initial")
    _git(repo, "tag", "v1.0.0")

    # Make an unreleased feature commit
    (repo / "feature.txt").write_text("new feature\n")
    _git(repo, "add", "feature.txt")
    _git(repo, "commit", "-q", "-m", "add feature")
    feature_sha = _git_head(repo)

    # Cover it with a JSONL entry. The changelog commit itself uses the
    # Autogenerated trailer so it is exempted from coverage.
    entry = {
        "commits": [feature_sha],
        "user_facing": True,
        "description": "**Add feature.** New feature is now available.",
        "type": "feature",
    }
    (changes_dir / "unreleased.jsonl").write_text(json.dumps(entry) + "\n")
    _git(repo, "add", ".rlsbl/changes/unreleased.jsonl")
    _git(
        repo, "commit", "-q", "-m", "changelog: add feature entry",
        "--trailer", "Autogenerated: true",
    )


class TestReleaseFinalizeMd:
    """Regression test: per-version .md file must be generated during release."""

    def test_release_generates_per_version_md(self, tmp_project):
        """A successful release must create .rlsbl/changes/1.0.1.md."""
        _setup_releasable_npm_project(tmp_project)

        from rlsbl.commands.release import run_cmd
        from rlsbl.utils import run as real_run

        def fake_run(cmd, args=None, timeout=120, env=None):
            """Intercept gh and git-push calls; let everything else through."""
            full = [cmd] + (args or [])
            # Skip gh CLI calls
            if cmd == "gh":
                return ""
            # Skip git push
            if cmd == "git" and args and args[0] == "push":
                return ""
            return real_run(cmd, args=args, timeout=timeout, env=env)

        with (
            patch("rlsbl.commands.release.check_gh_installed", return_value=True),
            patch("rlsbl.commands.release.check_gh_auth", return_value=True),
            patch("rlsbl.commands.release.push_if_needed"),
            patch("rlsbl.commands.release.run", side_effect=fake_run),
        ):
            run_cmd(
                _rc(),
                {
                    "yes": True,
                    "quiet": True,
                },
            
                ctx=ProjectContext(project_root=Path("."), workspace_root=None, config={"private": False, "pipelines": {}}),
)

        changes_dir = tmp_project / ".rlsbl" / "changes"

        # The JSONL file must exist (finalize_version renamed unreleased.jsonl)
        assert (changes_dir / "1.0.1.jsonl").exists(), (
            "1.0.1.jsonl should exist after release"
        )

        # The per-version .md file must exist (this is the regression target)
        md_path = changes_dir / "1.0.1.md"
        assert md_path.exists(), (
            "1.0.1.md should be generated during release finalization"
        )

        # The .md file should contain the changelog section with our feature entry
        md_content = md_path.read_text()
        assert "1.0.1" in md_content, (
            "per-version .md should contain the version heading"
        )
        assert "Add feature" in md_content, (
            "per-version .md should contain the feature description"
        )
