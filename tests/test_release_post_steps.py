class TestSuccessMarksAllSteps:
    """A fully successful release marks every canonical step before the
    state file is cleared."""

    def test_all_steps_marked_before_clear(self, mock_git_repo):
        _setup_npm_project(mock_git_repo)
        state_path = get_state_path(str(mock_git_repo))

        from rlsbl.commands.release.release_state import (
            clear_release_state as real_clear,
        )

        snapshots = []

        def capturing_clear(path):
            state = load_release_state(path)
            if state is not None:
                snapshots.append(state)
            real_clear(path)

        fake_run = _fake_run_factory()
        with (
            patch("rlsbl.commands.release.check_gh_installed", return_value=True),
            patch("rlsbl.commands.release.check_gh_auth", return_value=True),
            patch("rlsbl.commands.release.push_if_needed"),
            patch("rlsbl.commands.release.run_gh", return_value=""),
            patch("rlsbl.commands.release.run", side_effect=fake_run),
            patch("rlsbl.commands.release.remote_branch_exists", return_value=True),
            patch("rlsbl.commands.release.execute.clear_release_state",
                  side_effect=capturing_clear),
        ):
            run_cmd(
                _rc(),
                {"yes": True, "quiet": True},
                ctx=_make_ctx(mock_git_repo),
            )

        assert not os.path.exists(state_path)
        assert len(snapshots) == 1, "state should be cleared exactly once"
        final = snapshots[0]
        assert set(final["completed_steps"]) == set(RELEASE_STEPS), (
            "every canonical step must have a success marker on a fully "
            f"successful release; got {sorted(final['completed_steps'])}"
        )
        assert not final.get("failed_steps")


