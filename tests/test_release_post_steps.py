"""Tests for post-release step tracking: markers, fatality classes, and
incremental resume of the post-release phase.

Covers:
- A fully successful release records a marker for EVERY canonical step
  before the state file is cleared (provable completeness).
- Pipeline publish failure is FATAL: state preserved, resumable (it used
  to be downgraded to a warning -- silent degradation for local pipelines).
- Resume re-attempts publish after a publish failure.
- Resume skips already-completed post-release steps (e.g. does not
  re-upload assets when ASSETS_UPLOADED is marked).
- Deploy and post-release hook failures are non-fatal but recorded as
  failure markers and loudly named in the completion summary.
"""

import json
import os
import subprocess
from pathlib import Path
from unittest.mock import patch

import pytest

from rlsbl.commands.release import resume_cmd, run_cmd
from rlsbl.commands.release.release_state import (
    MUTATING_STEPS,
    RELEASE_STEPS,
    get_state_path,
    load_release_state,
    save_release_state,
)
from rlsbl.context import ProjectContext
from rlsbl.release_file import ReleaseConfig
from rlsbl.utils import run as real_run


# ---------------------------------------------------------------------------
# Helpers (conventions follow tests/test_release_resume.py)
