def _make_in_progress_state(repo, *, completed_steps=None, failed_steps=None,
                            version="1.0.1", branch="main"):
    """Write an in-progress.json state file and return its path."""
    state_path = get_state_path(str(repo))
    pre_sha = _git_head(repo)
    state = {
        "new_version": version,
        "tag": f"v{version}",
        "branch": branch,
        "pre_release_sha": pre_sha,
        "bump_type": "patch",
        "registry": "npm",
        "completed_steps": completed_steps or [],
        "failed_steps": failed_steps or {},
        "companion_tags": [],
        "monorepo_name": None,
        "releasable_name": None,
        "commit_msg": f"v{version}",
        "description": "test release",
        "context": "",
        "include": ["npm"],
        "exclude": [],
        "preid": "",
        "blog": False,
    }
    save_release_state(state_path, state)
    return state_path


def _bump_and_tag(repo, version="1.0.1"):
    """Simulate the mutating phase already done: bump, commit, tag."""
    pkg = json.loads((repo / "package.json").read_text())
    pkg["version"] = version
    (repo / "package.json").write_text(json.dumps(pkg, indent=2) + "\n")
    _git(repo, "add", "package.json")
    _git(repo, "commit", "-q", "-m", f"v{version}")
    record_release(repo, f"v{version}")


def _setup_subtree_monorepo(repo, project_path="packages/mylib", name="mylib",
                            version="1.0.1", mirror_remote=None):
    """A monorepo whose only releasable declares a ``subtree_remote``, staged at
    the point a resume re-enters the post-GitHub-Release phase.

    Returns the project directory. The release is already tagged and its
    state file records every mutating step, so the resume goes straight to
    the mirror publishing block.

    *mirror_remote* is the mirror's git URL. Pass a local bare repository (see
    ``_bare_mirror``) for a test that lets the mirror steps really run; the
    default names a remote nothing can reach, for tests about what happens when
    they fail.
    """
    from rlsbl.workspace import save_workspace

    proj_dir = repo / project_path
    proj_dir.mkdir(parents=True)
    (proj_dir / "package.json").write_text(
        json.dumps({"name": name, "version": version}, indent=2) + "\n"
    )
    (proj_dir / ".rlsbl").mkdir()
    (proj_dir / ".rlsbl" / "config.json").write_text(
        json.dumps({"publish_mode": "none", "targets": ["npm"]}) + "\n"
    )
    make_workspace(
        str(repo),
        [{"path": project_path, "name": name, "releasable": name}],
        releasables=[{
            "name": name,
            "subtree_remote": mirror_remote or "/nonexistent/mirror.git",
        }],
    )
    _git(repo, "add", "-A")
    _git(repo, "commit", "-q", "-m", f"{name}@v{version}")
    tag = f"{name}@v{version}"
    _git(repo, "tag", tag)

    from rlsbl.commands.release.release_state import resolve_releasable_dir
    state_path = get_state_path(
        str(proj_dir),
        releasable_dir=resolve_releasable_dir(str(proj_dir), str(repo)),
    )
    save_release_state(state_path, {
        "new_version": version,
        "tag": tag,
        "branch": "main",
        "pre_release_sha": _git_head(repo),
        "candidate_sha": _git_head(repo),
        "pin_sha": _git_head(repo),
        "bump_type": "patch",
        "registry": "npm",
        "completed_steps": list(MUTATING_STEPS),
        "failed_steps": {},
        "companion_tags": [],
        "monorepo_name": name,
        # make_workspace derives one releasable per member, named after it.
        "releasable_name": name,
        "commit_msg": tag,
        "description": "test release",
        "context": "",
        "include": ["npm"],
        "exclude": [],
        "preid": "",
        "blog": False,
    })
    return str(proj_dir)


def _bare_mirror(path):
    """A local bare repository standing in for the mirror remote.

    Every mirror push in this file goes here: the suite never reaches a real
    remote, and the reconciler's force-with-lease, scaffold layer and tag push
    are all exercised for real against it.
    """
    path.mkdir(parents=True, exist_ok=True)
    subprocess.run(["git", "init", "-q", "--bare"], cwd=str(path), check=True)
    return str(path)


def _mirror_refs(remote, cwd):
    """``{refname: sha}`` on the mirror, tags peeled to their commits."""
    from rlsbl.mirror_publication import parse_ls_remote

    out = subprocess.run(
        ["git", "ls-remote", remote], cwd=str(cwd),
        capture_output=True, text=True, check=True,
    ).stdout
    return parse_ls_remote(out)


def _make_subtree_ctx(repo, project_dir):
    return ProjectContext(
        project_root=Path(project_dir),
        workspace_root=Path(str(repo)),
        config={"publish_mode": "none", "pipelines": {}},
    )


class _RecordingPipeline:
    """Fake pipeline that records publish calls; optionally fails."""

    # validate_pipeline_config checks .local for required-env validation
    local = False

    def __init__(self, fail=False):
        self.fail = fail
        self.publish_calls = []

    def publish(self, path, version, *, ctx):
        self.publish_calls.append((path, version))
        if self.fail:
            raise RuntimeError("registry rejected the upload")


