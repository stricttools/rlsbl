class TestPublishFailureIsFatal:
    """Pipeline publish failure aborts the release with preserved state
    (previously it was downgraded to a warning and the release completed)."""

    def test_publish_failure_preserves_state_and_aborts(
        self, mock_git_repo, capsys,
    ):
        _setup_npm_project(mock_git_repo)
        state_path = get_state_path(str(mock_git_repo))

        failing = _RecordingPipeline(fail=True)
        fake_run = _fake_run_factory()
        with pytest.raises(SystemExit) as exc_info:
            with (
                patch("rlsbl.commands.release.check_gh_installed", return_value=True),
                patch("rlsbl.commands.release.check_gh_auth", return_value=True),
                patch("rlsbl.commands.release.push_if_needed"),
                patch("rlsbl.commands.release.run_gh", return_value=""),
                patch("rlsbl.commands.release.run", side_effect=fake_run),
                patch("rlsbl.commands.release.remote_branch_exists", return_value=True),
                patch("rlsbl.commands.release.load_pipelines",
                      return_value={"npm": failing}),
            ):
                run_cmd(
                    _rc(),
                    {"quiet": True},
                    ctx=_make_ctx(mock_git_repo),
                )

        assert exc_info.value.code == 1
        assert failing.publish_calls, "publish must have been attempted"

        # State preserved and resumable
        assert os.path.exists(state_path), (
            "publish failure must preserve in-progress.json for resume"
        )
        state = load_release_state(state_path)
        assert "PUSHED" in state["completed_steps"]
        assert "PIPELINES_PUBLISHED" not in state["completed_steps"]
        assert "PIPELINES_PUBLISHED" in state.get("failed_steps", {})

        captured = capsys.readouterr()
        assert "publish failed" in captured.err
        assert "resume" in captured.err

    def test_resume_reattempts_publish(self, mock_git_repo):
        """After a publish failure, resume re-attempts the publish step."""
        _setup_npm_project(mock_git_repo)
        _bump_and_tag(mock_git_repo)

        state_path = _make_in_progress_state(
            mock_git_repo,
            completed_steps=list(MUTATING_STEPS) + ["ASSETS_UPLOADED"],
            failed_steps={"PIPELINES_PUBLISHED": "registry rejected the upload"},
        )

        recording = _RecordingPipeline()
        fake_run = _fake_run_factory()
        with (
            patch("rlsbl.commands.release.push_if_needed"),
            patch("rlsbl.commands.release.run_gh", return_value=""),
            patch("rlsbl.commands.release.run", side_effect=fake_run),
            patch("rlsbl.commands.release.load_pipelines",
                  return_value={"npm": recording}),
        ):
            resume_cmd(
                load_release_state(state_path),
                {"quiet": True},
                ctx=_make_ctx(mock_git_repo),
            )

        assert recording.publish_calls, (
            "resume must re-attempt the failed publish step"
        )
        assert not os.path.exists(state_path)


