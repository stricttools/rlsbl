class TestNonFatalFailures:
    """"Non-fatal" means the release is NOT rolled back and stays resumable.

    It never meant "exit 0". A release that ends with a failed step reports
    that failure through its exit code and keeps its state file, so
    `rlsbl release resume` can re-attempt the step. The single decision
    point is the completion epilogue: any failure marker => nonzero, state
    preserved.
    """

    def test_deploy_failure_exits_nonzero_and_preserves_state(
        self, mock_git_repo, capsys,
    ):
        """A deploy failure does not roll the release back, but it must not
        be reported as success either: nonzero exit, state preserved."""
        from rlsbl.deploy import DeployResult

        _setup_npm_project(mock_git_repo)
        state_path = get_state_path(str(mock_git_repo))

        deploy_cfg = [{"name": "prod", "type": "ssh"}]
        fake_run = _fake_run_factory()
        with (
            patch("rlsbl.commands.release.check_gh_installed", return_value=True),
            patch("rlsbl.commands.release.check_gh_auth", return_value=True),
            patch("rlsbl.commands.release.push_if_needed"),
            patch("rlsbl.commands.release.run_gh", return_value=""),
            patch("rlsbl.commands.release.run", side_effect=fake_run),
            patch("rlsbl.commands.release.remote_branch_exists", return_value=True),
            patch("rlsbl.commands.release.read_deploy_config",
                  return_value=(deploy_cfg, [])),
            patch("rlsbl.commands.release.deploy_target",
                  return_value=DeployResult("prod", False, "ssh timed out")),
        ):
            with pytest.raises(SystemExit) as exc_info:
                run_cmd(
                    _rc(),
                    {"quiet": True},
                    ctx=_make_ctx(mock_git_repo),
                )

        assert exc_info.value.code == 1
        assert os.path.exists(state_path), (
            "a failed step must leave the state file behind so "
            "`rlsbl release resume` stays reachable"
        )
        state = load_release_state(state_path)
        assert "DEPLOYED" in state.get("failed_steps", {})

        captured = capsys.readouterr()
        assert "DEPLOYED" in captured.err
        assert "ssh timed out" in captured.err

    def test_post_hook_failure_exits_nonzero_and_preserves_state(
        self, mock_git_repo, capsys,
    ):
        """A post-release hook failure is not fatal to the published release,
        but it is still a failed step: nonzero exit, state preserved."""
        _setup_npm_project(mock_git_repo)
        state_path = get_state_path(str(mock_git_repo))

        from rlsbl.commands.release.hooks import (
            run_release_hook as real_run_release_hook,
        )

        def failing_post_hook(hook_name, *args, **kwargs):
            if hook_name == "post-release":
                raise RuntimeError("hook exploded")
            return real_run_release_hook(hook_name, *args, **kwargs)

        fake_run = _fake_run_factory()
        with (
            patch("rlsbl.commands.release.check_gh_installed", return_value=True),
            patch("rlsbl.commands.release.check_gh_auth", return_value=True),
            patch("rlsbl.commands.release.push_if_needed"),
            patch("rlsbl.commands.release.run_gh", return_value=""),
            patch("rlsbl.commands.release.run", side_effect=fake_run),
            patch("rlsbl.commands.release.remote_branch_exists", return_value=True),
            patch("rlsbl.commands.release.hooks.run_release_hook",
                  side_effect=failing_post_hook),
        ):
            with pytest.raises(SystemExit) as exc_info:
                run_cmd(
                    _rc(),
                    {"quiet": True},
                    ctx=_make_ctx(mock_git_repo),
                )

        assert exc_info.value.code == 1
        assert os.path.exists(state_path)
        state = load_release_state(state_path)
        assert "POST_HOOKS_RUN" in state.get("failed_steps", {})

        captured = capsys.readouterr()
        assert "POST_HOOKS_RUN" in captured.err
        assert "hook exploded" in captured.err

    def test_mirror_convergence_failure_exits_nonzero_and_preserves_state(
        self, mock_git_repo, capsys,
    ):
        """A mirror the reconciler cannot converge is a tracked step, not a
        bare warning: nonzero exit, marker recorded, state preserved, and the
        marker names the command that heals it."""
        project_dir = _setup_subtree_monorepo(mock_git_repo)
        from rlsbl.commands.release.release_state import resolve_releasable_dir
        state_path = get_state_path(
            project_dir,
            releasable_dir=resolve_releasable_dir(project_dir, str(mock_git_repo)),
        )

        with (
            patch("rlsbl.commands.release.push_if_needed"),
            patch("rlsbl.commands.release.run_gh", return_value=""),
            patch("rlsbl.commands.release.run_gh_unscoped", return_value=""),
            patch("rlsbl.commands.release.run", side_effect=_fake_run_factory()),
            patch(
                "rlsbl.commands.monorepo.mirror_cmd.converge_branch",
                side_effect=RuntimeError("the mirror is unreachable"),
            ),
        ):
            with pytest.raises(SystemExit) as exc_info:
                resume_cmd(
                    load_release_state(state_path),
                    {"quiet": True, "skip-lock": True},
                    ctx=_make_subtree_ctx(mock_git_repo, project_dir),
                )

        assert exc_info.value.code == 1
        assert os.path.exists(state_path)
        state = load_release_state(state_path)
        marker = state["failed_steps"]["SUBTREE_PUBLISHED"]
        assert "the mirror is unreachable" in marker
        assert "rlsbl monorepo mirror mylib" in marker

        err = capsys.readouterr().err
        assert "SUBTREE_PUBLISHED" in err

    def test_mirror_release_failure_exits_nonzero_and_preserves_state(
        self, mock_git_repo, capsys, tmp_path,
    ):
        """Same for the mirror's tag and Release: a warning is not an outcome,
        and the marker names both healers."""
        mirror = _bare_mirror(tmp_path / "mirror.git")
        project_dir = _setup_subtree_monorepo(
            mock_git_repo, mirror_remote=mirror,
        )
        from rlsbl.commands.release.release_state import resolve_releasable_dir
        state_path = get_state_path(
            project_dir,
            releasable_dir=resolve_releasable_dir(project_dir, str(mock_git_repo)),
        )

        def failing_mirror(*args, **kwargs):
            raise RuntimeError("mirror repo not found")

        with (
            patch("rlsbl.commands.release.push_if_needed"),
            patch("rlsbl.commands.release.run_gh", return_value=""),
            patch("rlsbl.commands.release.run_gh_unscoped",
                  side_effect=failing_mirror),
            patch("rlsbl.commands.release.run", side_effect=_fake_run_factory()),
        ):
            with pytest.raises(SystemExit) as exc_info:
                resume_cmd(
                    load_release_state(state_path),
                    {"quiet": True, "skip-lock": True},
                    ctx=_make_subtree_ctx(mock_git_repo, project_dir),
                )

        assert exc_info.value.code == 1
        assert os.path.exists(state_path)
        state = load_release_state(state_path)
        marker = state["failed_steps"]["MIRROR_RELEASED"]
        assert "rlsbl monorepo mirror mylib" in marker
        assert "rlsbl release reconcile" in marker
        # The branch step still succeeded on its own.
        assert "SUBTREE_PUBLISHED" in state["completed_steps"]

        err = capsys.readouterr().err
        assert "MIRROR_RELEASED" in err

    def test_a_converged_mirror_gets_one_tag_one_release_and_no_branch_write(
        self, mock_git_repo, tmp_path,
    ):
        """The whole mirror step against a real (local) mirror remote.

        The mirror is converged FIRST, at exactly the commit the release is
        staged on, so the branch has nothing left to do -- which is what makes
        the assertion meaningful: publishing the version must add exactly one
        tag and one GitHub Release, and must not move ``main``.
        """
        from rlsbl.commands.monorepo import mirror_cmd
        from rlsbl.commands.monorepo.mirror_cmd import converge_branch

        mirror = _bare_mirror(tmp_path / "mirror.git")
        project_dir = _setup_subtree_monorepo(
            mock_git_repo, mirror_remote=mirror,
        )
        from rlsbl.commands.release.release_state import resolve_releasable_dir
        state_path = get_state_path(
            project_dir,
            releasable_dir=resolve_releasable_dir(project_dir, str(mock_git_repo)),
        )

        converge_branch(
            mirror, str(mock_git_repo), "packages/mylib",
            os.path.join(project_dir, ".rlsbl", "config.json"),
        )
        before = _mirror_refs(mirror, mock_git_repo)
        assert "refs/heads/main" in before
        assert not [r for r in before if r.startswith("refs/tags/")]

        gh_calls = []

        def fake_gh(args, **kwargs):
            gh_calls.append(list(args))
            if args[:2] == ["release", "view"]:
                raise RuntimeError("not found")
            return ""

        with (
            patch("rlsbl.commands.release.push_if_needed"),
            patch("rlsbl.commands.release.run_gh", return_value=""),
            patch("rlsbl.commands.release.run_gh_unscoped", side_effect=fake_gh),
            patch("rlsbl.commands.release.run", side_effect=_fake_run_factory()),
        ):
            resume_cmd(
                load_release_state(state_path),
                {"quiet": True, "skip-lock": True},
                ctx=_make_subtree_ctx(mock_git_repo, project_dir),
            )

        assert not os.path.exists(state_path), "a clean release clears its state"

        after = _mirror_refs(mirror, mock_git_repo)
        assert after["refs/heads/main"] == before["refs/heads/main"], (
            "publishing a version must not move the mirror's branch"
        )
        tags = {r: sha for r, sha in after.items() if r.startswith("refs/tags/")}
        assert list(tags) == ["refs/tags/v1.0.1"]
        # The tag names the subtree split of the release's ledger anchor,
        # which this fixture stages at HEAD.
        from rlsbl.mirror_publication import split_commit_for

        anchor = subprocess.run(
            ["git", "rev-parse", "HEAD"], cwd=str(mock_git_repo),
            capture_output=True, text=True, check=True,
        ).stdout.strip()
        assert tags["refs/tags/v1.0.1"] == split_commit_for(
            str(mock_git_repo), "packages/mylib", anchor,
        )

        creates = [c for c in gh_calls if c[:2] == ["release", "create"]]
        assert len(creates) == 1
        assert creates[0][2] == "v1.0.1"
        assert "--repo" in creates[0]

    def test_a_completed_mirror_step_is_not_re_converged_on_resume(
        self, mock_git_repo, tmp_path,
    ):
        """A resume skips the mirror steps their markers say are done.

        Every other step in the flow reads its success marker before acting;
        the mirror block did not, so a resume after a LATER step failed
        re-converged a mirror that was already converged and re-published a
        version already on it.
        """
        import rlsbl.commands.monorepo.mirror_cmd as mirror_cmd
        import rlsbl.mirror_publication as mirror_publication

        mirror = _bare_mirror(tmp_path / "mirror.git")
        project_dir = _setup_subtree_monorepo(
            mock_git_repo, mirror_remote=mirror,
        )
        from rlsbl.commands.release.release_state import resolve_releasable_dir
        state_path = get_state_path(
            project_dir,
            releasable_dir=resolve_releasable_dir(project_dir, str(mock_git_repo)),
        )
        state = load_release_state(state_path)
        state["completed_steps"] = list(state["completed_steps"]) + [
            "SUBTREE_PUBLISHED", "MIRROR_RELEASED",
        ]
        save_release_state(state_path, state)

        converged = []
        published = []
        with (
            patch("rlsbl.commands.release.push_if_needed"),
            patch("rlsbl.commands.release.run_gh", return_value=""),
            patch("rlsbl.commands.release.run_gh_unscoped", return_value=""),
            patch("rlsbl.commands.release.run", side_effect=_fake_run_factory()),
            patch.object(
                mirror_cmd, "converge_branch",
                side_effect=lambda *a, **k: converged.append(a),
            ),
            patch.object(
                mirror_publication, "publish_version",
                side_effect=lambda **k: published.append(k),
            ),
        ):
            resume_cmd(
                load_release_state(state_path),
                {"quiet": True, "skip-lock": True},
                ctx=_make_subtree_ctx(mock_git_repo, project_dir),
            )

        assert converged == [], "a completed mirror branch step was re-run"
        assert published == [], "a completed mirror release step was re-run"

    def test_the_mirror_release_notes_file_stays_out_of_the_release_cwd(
        self, mock_git_repo, tmp_path, monkeypatch,
    ):
        """The mirror's Release body is written where the release keeps state.

        It used to be written into whatever directory the release ran from,
        where a stray ``.rlsbl-notes-*.tmp`` is a file in somebody's working
        tree.
        """
        mirror = _bare_mirror(tmp_path / "mirror.git")
        project_dir = _setup_subtree_monorepo(
            mock_git_repo, mirror_remote=mirror,
        )
        from rlsbl.commands.release.release_state import resolve_releasable_dir
        releasable_dir = resolve_releasable_dir(project_dir, str(mock_git_repo))
        state_path = get_state_path(project_dir, releasable_dir=releasable_dir)

        notes_paths = []

        def fake_gh(args, **kwargs):
            if "--notes-file" in args:
                notes_paths.append(args[args.index("--notes-file") + 1])
            if args[:2] == ["release", "view"]:
                raise RuntimeError("not found")
            return ""

        with (
            patch("rlsbl.commands.release.push_if_needed"),
            patch("rlsbl.commands.release.run_gh", return_value=""),
            patch("rlsbl.commands.release.run_gh_unscoped", side_effect=fake_gh),
            patch("rlsbl.commands.release.run", side_effect=_fake_run_factory()),
        ):
            resume_cmd(
                load_release_state(state_path),
                {"quiet": True, "skip-lock": True},
                ctx=_make_subtree_ctx(mock_git_repo, project_dir),
            )

        assert notes_paths, "the mirror Release must be created from a notes file"
        for path in notes_paths:
            assert os.path.dirname(path), (
                f"the mirror notes file has no directory of its own: {path}"
            )
            assert os.path.realpath(os.path.dirname(path)) == os.path.realpath(
                os.path.join(str(mock_git_repo), releasable_dir, "releases")
            ), path

