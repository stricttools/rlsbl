class TestIncrementalPostReleaseResume:

    def test_resume_skips_uploaded_assets_and_proceeds_to_publish(
        self, mock_git_repo,
    ):
        """ASSETS_UPLOADED success marker gates resume-skip: assets are not
        re-uploaded, and the flow proceeds to publish."""
        _setup_npm_project(mock_git_repo)
        _bump_and_tag(mock_git_repo)

        state_path = _make_in_progress_state(
            mock_git_repo,
            completed_steps=list(MUTATING_STEPS) + ["ASSETS_UPLOADED"],
        )

        recording = _RecordingPipeline()
        fake_run = _fake_run_factory()
        with (
            patch("rlsbl.commands.release.push_if_needed"),
            patch("rlsbl.commands.release.run_gh", return_value=""),
            patch("rlsbl.commands.release.run", side_effect=fake_run),
            patch("rlsbl.commands.release.upload_release_assets") as mock_upload,
            patch("rlsbl.commands.release.load_pipelines",
                  return_value={"npm": recording}),
        ):
            resume_cmd(
                load_release_state(state_path),
                {"yes": True, "quiet": True},
                ctx=_make_ctx(mock_git_repo),
            )

        mock_upload.assert_not_called()
        assert recording.publish_calls, "resume must proceed to publish"
        assert not os.path.exists(state_path)

    def test_resume_after_kill_during_assets(self, mock_git_repo):
        """State with only the mutating steps (killed during asset upload)
        is resumable: assets are uploaded and the release completes."""
        _setup_npm_project(mock_git_repo)
        _bump_and_tag(mock_git_repo)

        state_path = _make_in_progress_state(
            mock_git_repo,
            completed_steps=list(MUTATING_STEPS),
        )

        fake_run = _fake_run_factory()
        with (
            patch("rlsbl.commands.release.push_if_needed"),
            patch("rlsbl.commands.release.run_gh", return_value=""),
            patch("rlsbl.commands.release.run", side_effect=fake_run),
            patch("rlsbl.commands.release.upload_release_assets") as mock_upload,
        ):
            resume_cmd(
                load_release_state(state_path),
                {"yes": True, "quiet": True},
                ctx=_make_ctx(mock_git_repo),
            )

        mock_upload.assert_called_once()
        assert not os.path.exists(state_path)


