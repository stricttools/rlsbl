def _rc(bump="patch", include=None, exclude=None, description="test release"):
    return ReleaseConfig(
        bump=bump,
        include=include or ["npm"],
        exclude=exclude or [],
        description=description,
    )


def _git(repo, *args):
    subprocess.run(
        ["git"] + list(args),
        cwd=str(repo),
        check=True,
        capture_output=True,
        text=True,
    )


def _git_head(repo):
    result = subprocess.run(
        ["git", "rev-parse", "HEAD"],
        cwd=str(repo),
        capture_output=True,
        text=True,
        check=True,
    )
    return result.stdout.strip()


def _setup_npm_project(repo):
    """Create an npm project at v1.0.0 with one unreleased commit."""
    (repo / "package.json").write_text(
        json.dumps({"name": "test-pkg", "version": "1.0.0"}, indent=2) + "\n"
    )
    (repo / "CHANGELOG.md").write_text(
        "<!-- Generated by rlsbl from .rlsbl/changes/ -- do not edit -->\n\n"
        "# Changelog\n\n## 1.0.0\n\n- Initial release.\n"
    )
    changes_dir = repo / ".rlsbl" / "changes"
    changes_dir.mkdir(parents=True)
    (changes_dir / "unreleased.jsonl").write_text("")
    (repo / ".rlsbl" / "config.json").write_text(
        json.dumps({"private": False, "targets": ["npm"]}) + "\n"
    )
    _git(repo, "add",
         "package.json", "CHANGELOG.md",
         ".rlsbl/changes/unreleased.jsonl", ".rlsbl/config.json")
    _git(repo, "commit", "-q", "-m", "initial")
    _git(repo, "tag", "v1.0.0")

    (repo / "feature.txt").write_text("new feature\n")
    _git(repo, "add", "feature.txt")
    _git(repo, "commit", "-q", "-m", "add feature")
    feature_sha = _git_head(repo)

    entry = {
        "commits": [feature_sha],
        "user_facing": True,
        "description": "**New feature.** A shiny new thing.",
        "type": "feature",
    }
    (changes_dir / "unreleased.jsonl").write_text(json.dumps(entry) + "\n")
    _git(repo, "add", ".rlsbl/changes/unreleased.jsonl")
    _git(repo, "commit", "-q", "-m", "changelog: add feature entry",
         "--trailer", "Autogenerated: true")


def _make_ctx(repo, config=None):
    return ProjectContext(
        project_root=Path(str(repo)),
        workspace_root=None,
        config=config or {"private": False, "pipelines": {}},
    )


def _fake_run_factory():
    def fake_run(cmd, args=None, timeout=120, env=None, cwd=None):
        if cmd == "gh":
            return ""
        if cmd == "git" and args and args[0] == "push":
            return ""
        if cmd == "git" and args and args[0] == "fetch":
            return ""
        if cmd == "git" and args and args[:2] == ["rev-list", "--count"] and any("origin/" in a for a in args):
            return "0"
        return real_run(cmd, args=args, timeout=timeout, env=env, cwd=cwd)
    return fake_run


_RUN_CMD_PATCHES = (
    ("rlsbl.commands.release.check_gh_installed", {"return_value": True}),
    ("rlsbl.commands.release.check_gh_auth", {"return_value": True}),
    ("rlsbl.commands.release.remote_branch_exists", {"return_value": True}),
)


def _make_in_progress_state(repo, *, completed_steps=None, failed_steps=None,
                            version="1.0.1", branch="main"):
    """Write an in-progress.json state file and return its path."""
    state_path = get_state_path(str(repo))
    pre_sha = _git_head(repo)
    state = {
        "new_version": version,
        "tag": f"v{version}",
        "branch": branch,
        "pre_release_sha": pre_sha,
        "bump_type": "patch",
        "registry": "npm",
        "completed_steps": completed_steps or [],
        "failed_steps": failed_steps or {},
        "companion_tags": [],
        "monorepo_name": None,
        "releasable_name": None,
        "commit_msg": f"v{version}",
        "description": "test release",
        "context": "",
        "include": ["npm"],
        "exclude": [],
        "preid": "",
        "blog": False,
    }
    save_release_state(state_path, state)
    return state_path


def _bump_and_tag(repo, version="1.0.1"):
    """Simulate the mutating phase already done: bump, commit, tag."""
    pkg = json.loads((repo / "package.json").read_text())
    pkg["version"] = version
    (repo / "package.json").write_text(json.dumps(pkg, indent=2) + "\n")
    _git(repo, "add", "package.json")
    _git(repo, "commit", "-q", "-m", f"v{version}")
    _git(repo, "tag", f"v{version}")


class _RecordingPipeline:
    """Fake pipeline that records publish calls; optionally fails."""

    # validate_pipeline_config checks .local for required-env validation
    local = False

    def __init__(self, fail=False):
        self.fail = fail
        self.publish_calls = []

    def publish(self, path, version, *, ctx):
        self.publish_calls.append((path, version))
        if self.fail:
            raise RuntimeError("registry rejected the upload")


