"""A root publisher's missing check regex is refused before anything relies on it.

A workspace root member that publishes must declare ``publish_gate_check_regex``
(its CI is hand-authored, so rlsbl cannot infer the check-run names publishing
waits for). ``monorepo sync`` refuses a root publisher without it; the root's
own release and ``monorepo add`` used to go through and leave that refusal to
the next sync. Both refuse up front now, naming the root releasable's
``config.json``, and the fix they name clears the refusal.
"""

import json
import os
import subprocess

import pytest

from test_changelog_home import _run_release, _setup_releasable_workspace

from rlsbl.workspace import WORKSPACE_DIR, WORKSPACE_FILE, get_releasable_dir


RELEASABLE = "solo"
REGEX = "^test$"


def _rel_config_path(root):
    return os.path.join(get_releasable_dir(str(root), RELEASABLE), "config.json")


def _set_regex(root, value):
    path = _rel_config_path(root)
    with open(path) as f:
        data = json.load(f)
    if value is None:
        data.pop("publish_gate_check_regex", None)
    else:
        data["publish_gate_check_regex"] = value
    with open(path, "w") as f:
        f.write(json.dumps(data) + "\n")
    subprocess.run(
        ["git", "commit", "-q", "-am", "root config", "--trailer", "Autogenerated: true"],
        cwd=str(root), check=True, capture_output=True, timeout=30,
    )


@pytest.fixture
def root_publisher(tmp_project):
    """A workspace whose root member publishes npm and names no check regex."""
    _setup_releasable_workspace(tmp_project, member_path=".", releasable_name=RELEASABLE)
    _set_regex(tmp_project, None)
    return tmp_project


def test_the_root_release_refuses_before_any_mutation(root_publisher, capsys):
    head = subprocess.run(
        ["git", "rev-parse", "HEAD"], cwd=str(root_publisher),
        check=True, capture_output=True, text=True, timeout=30,
    ).stdout
    with pytest.raises(SystemExit):
        _run_release(root_publisher, root_publisher)
    err = capsys.readouterr().err
    assert "publish_gate_check_regex" in err
    assert _rel_config_path(root_publisher) in err
    assert subprocess.run(
        ["git", "rev-parse", "HEAD"], cwd=str(root_publisher),
        check=True, capture_output=True, text=True, timeout=30,
    ).stdout == head

    # The named fix: add the key to the named file.
    _set_regex(root_publisher, REGEX)
    _run_release(root_publisher, root_publisher)


def test_monorepo_add_refuses_before_writing_workspace_toml(root_publisher, capsys):
    from rlsbl.commands.monorepo.commands import _cmd_add

    (root_publisher / "lib").mkdir()
    (root_publisher / "lib" / "go.mod").write_text("module example.com/lib\n\ngo 1.22\n")
    ws_path = root_publisher / WORKSPACE_DIR / WORKSPACE_FILE
    before = ws_path.read_text()

    with pytest.raises(SystemExit):
        _cmd_add(["lib"], {"releasable": "lib"}, root_publisher)
    err = capsys.readouterr().err
    assert "publish_gate_check_regex" in err and _rel_config_path(root_publisher) in err
    assert ws_path.read_text() == before

    _set_regex(root_publisher, REGEX)
    _cmd_add(["lib"], {"releasable": "lib"}, root_publisher, dry_run=True)
    assert "Would add project 'lib'" in capsys.readouterr().out


def test_a_root_that_publishes_nothing_needs_no_regex(root_publisher):
    from rlsbl.commands.monorepo.publish_inline import root_publisher_check_regex_problem

    assert root_publisher_check_regex_problem(str(root_publisher)) is not None
    with open(root_publisher / ".rlsbl" / "config.json") as f:
        data = json.load(f)
    data["publish_mode"] = "none"
    (root_publisher / ".rlsbl" / "config.json").write_text(json.dumps(data))
    assert root_publisher_check_regex_problem(str(root_publisher)) is None
