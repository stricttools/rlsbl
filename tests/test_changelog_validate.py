class TestMonorepoValidation:
    """Integration tests for validate_unreleased with tag_glob (monorepo mode)."""

    def test_validate_with_tag_glob_passes(self, monorepo_fixture):
        """validate_unreleased with correct tag_glob passes when all commits are covered."""
        root = monorepo_fixture.root
        python_dir = monorepo_fixture.python_dir

        # Add a commit touching python/ files
        src_dir = python_dir / "src"
        src_dir.mkdir(exist_ok=True)
        (src_dir / "lib.py").write_text("x = 1\n")
        _run_git(root, "add", "python/src/lib.py")
        _run_git(root, "commit", "-q", "-m", "add python lib")
        sha = _git_head(root)

        # Add a JSONL entry covering that commit
        changes_dir = str(python_dir / ".rlsbl" / "changes")
        from rlsbl.changelog.files import append_entry
        from rlsbl.changelog.schema import ChangelogEntry
        append_entry(changes_dir, ChangelogEntry(commits=[sha], user_facing=False))

        result = validate_unreleased(changes_dir, tag_glob="mypylib@v*")
        assert result["passed"] is True
        for check_name, (passed, _details) in result["checks"].items():
            assert passed is True, f"check {check_name} failed: {_details}"

    def test_validate_without_tag_glob_fails_in_monorepo(self, monorepo_fixture):
        """Without tag_glob, validation fails because plain v* tags don't exist."""
        root = monorepo_fixture.root
        python_dir = monorepo_fixture.python_dir

        # Add a commit touching python/ files
        src_dir = python_dir / "src"
        src_dir.mkdir(exist_ok=True)
        (src_dir / "lib.py").write_text("y = 2\n")
        _run_git(root, "add", "python/src/lib.py")
        _run_git(root, "commit", "-q", "-m", "add python lib 2")
        sha = _git_head(root)

        # Add a JSONL entry covering that commit
        changes_dir = str(python_dir / ".rlsbl" / "changes")
        from rlsbl.changelog.files import append_entry
        from rlsbl.changelog.schema import ChangelogEntry
        append_entry(changes_dir, ChangelogEntry(commits=[sha], user_facing=False))

        # Without tag_glob, _get_last_version_tag() with --match 'v*' can't
        # find 'mypylib@v0.1.0', so range becomes "HEAD" (all commits).
        # The initial and workspace commits are not covered, so coverage fails.
        result = validate_unreleased(changes_dir)
        assert result["passed"] is False
        passed, details = result["checks"]["coverage"]
        assert passed is False
        assert any("not covered" in d for d in details)


class TestTrailerOnlyExemption:
    """Tests that only the Autogenerated: true trailer grants exemption.

    The old path-pattern system (_is_changelog_only_commit) has been removed.
    Commits touching only changelog files are NOT exempt unless they carry
    the trailer.
    """

    def test_changelog_only_commit_not_exempt_without_trailer(self, git_repo):
        """A commit that ONLY touches .rlsbl/changes/unreleased.jsonl is NOT
        exempt when it lacks the Autogenerated: true trailer."""
        sha_code = _make_commit(git_repo, "code.py", "add code")
        entries = [ChangelogEntry(commits=[sha_code], user_facing=False)]

        # Commit that only touches changelog files, but no trailer
        unreleased = git_repo / ".rlsbl" / "changes" / "unreleased.jsonl"
        unreleased.write_text(
            json.dumps({"commits": [sha_code], "user_facing": False}) + "\n"
        )
        _run_git(git_repo, "add", ".rlsbl/changes/unreleased.jsonl")
        _run_git(git_repo, "commit", "-m", "add changelog entry")

        passed, details = check_coverage(entries)
        assert passed is False, (
            "changelog-only commit without trailer should NOT be exempt"
        )
        assert any("not covered" in d for d in details)

    def test_changelog_only_commit_exempt_with_trailer(self, git_repo):
        """A commit that ONLY touches changelog files IS exempt when it
        carries the Autogenerated: true trailer."""
        sha_code = _make_commit(git_repo, "code.py", "add code")
        entries = [ChangelogEntry(commits=[sha_code], user_facing=False)]

        # Commit that only touches changelog files, WITH the trailer
        unreleased = git_repo / ".rlsbl" / "changes" / "unreleased.jsonl"
        unreleased.write_text(
            json.dumps({"commits": [sha_code], "user_facing": False}) + "\n"
        )
        _run_git(git_repo, "add", ".rlsbl/changes/unreleased.jsonl")
        _run_git(
            git_repo, "commit", "-m",
            "add changelog entry\n\nAutogenerated: true",
        )

        passed, details = check_coverage(entries)
        assert passed is True, (
            f"changelog-only commit with trailer should be exempt: {details}"
        )
        assert any("skipped 1 autogenerated" in d for d in details)
