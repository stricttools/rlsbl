class TestIsChangelogOnlyCommit:
    """Integration tests for _is_changelog_only_commit with real git commits."""

    def test_commit_touching_only_unreleased_jsonl(self, git_repo):
        """A commit touching only unreleased.jsonl is changelog-only."""
        unreleased = git_repo / ".rlsbl" / "changes" / "unreleased.jsonl"
        unreleased.write_text('{"commits":["abc"],"user_facing":false}\n')
        _run_git(git_repo, "add", ".rlsbl/changes/unreleased.jsonl")
        _run_git(git_repo, "commit", "-m", "add entry")
        sha = _git_head(git_repo)
        assert _is_changelog_only_commit(sha) is True

    def test_commit_touching_source_and_changelog(self, git_repo):
        """A commit touching both source and changelog is NOT changelog-only."""
        unreleased = git_repo / ".rlsbl" / "changes" / "unreleased.jsonl"
        unreleased.write_text('{"commits":["abc"],"user_facing":false}\n')
        src_file = git_repo / "src.py"
        src_file.write_text("x = 1\n")
        _run_git(git_repo, "add", ".rlsbl/changes/unreleased.jsonl")
        _run_git(git_repo, "add", "src.py")
        _run_git(git_repo, "commit", "-m", "mixed commit")
        sha = _git_head(git_repo)
        assert _is_changelog_only_commit(sha) is False

    def test_commit_touching_only_changelog_md(self, git_repo):
        """A commit touching only CHANGELOG.md is changelog-only."""
        changelog = git_repo / "CHANGELOG.md"
        changelog.write_text("# Changelog\n")
        _run_git(git_repo, "add", "CHANGELOG.md")
        _run_git(git_repo, "commit", "-m", "update changelog")
        sha = _git_head(git_repo)
        assert _is_changelog_only_commit(sha) is True

    def test_commit_touching_only_releases_dir(self, git_repo):
        """A commit touching only .rlsbl/releases/ files is changelog-only."""
        releases_dir = git_repo / ".rlsbl" / "releases"
        releases_dir.mkdir(parents=True, exist_ok=True)
        (releases_dir / "unreleased.toml").write_text("bump = 'patch'\n")
        _run_git(git_repo, "add", ".rlsbl/releases/unreleased.toml")
        _run_git(git_repo, "commit", "-m", "add release file")
        sha = _git_head(git_repo)
        assert _is_changelog_only_commit(sha) is True

    def test_commit_touching_releases_and_source(self, git_repo):
        """A commit touching .rlsbl/releases/ AND source is NOT changelog-only."""
