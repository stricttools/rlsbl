class TestIsAutogenerated:
    """Unit tests for _is_autogenerated."""

    def test_commit_with_trailer_is_autogenerated(self, git_repo):
        """A commit with the Autogenerated: true trailer returns True."""
        _run_git(git_repo, "commit", "--allow-empty", "-m", "auto commit\n\nAutogenerated: true")
        sha = _git_head(git_repo)
        assert _is_autogenerated(sha) is True

    def test_commit_without_trailer_is_not_autogenerated(self, git_repo):
        """A normal commit without the trailer returns False."""
        sha = _make_commit(git_repo, "code.py", "normal commit")
        assert _is_autogenerated(sha) is False

    def test_commit_with_false_trailer(self, git_repo):
        """A commit with Autogenerated: false returns False."""
        _run_git(git_repo, "commit", "--allow-empty", "-m", "manual\n\nAutogenerated: false")
        sha = _git_head(git_repo)
        assert _is_autogenerated(sha) is False

    def test_invalid_sha_returns_false(self, git_repo):
        """Invalid SHA returns False."""
        assert _is_autogenerated("0" * 40) is False

    def test_commit_with_other_trailers(self, git_repo):
        """A commit with other trailers but not Autogenerated returns False."""
        _run_git(git_repo, "commit", "--allow-empty", "-m", "change\n\nSigned-off-by: test")
        sha = _git_head(git_repo)
        assert _is_autogenerated(sha) is False

    def test_commit_with_mixed_trailers(self, git_repo):
        """A commit with Autogenerated: true among other trailers returns True."""
        _run_git(
            git_repo, "commit", "--allow-empty", "-m",
            "auto\n\nSigned-off-by: test\nAutogenerated: true",
        )
        sha = _git_head(git_repo)
        assert _is_autogenerated(sha) is True


