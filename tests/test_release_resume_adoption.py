def _stopped_releasable_with_a_dev_node(root):
    """A workspace release of ``alpha`` stopped after its candidate was pushed.

    The workspace declares a dev node, ``conformance`` (``dev_only = true``,
    ``releasable = false``), beside ``alpha``'s one member. Returns
    ``(core_dir, state_path, pin_sha)``: the release was pinned at
    ``pin_sha``, created the version-bump commit, and pushed it as the
    candidate; nothing after that commit is the release's own.
    """
    from test_empty_candidate_window import _prepare_resumable_candidate
    from test_representative_write_elimination import (
        _setup_releasable_workspace,
    )

    core = _setup_releasable_workspace(root)
    workspace_toml = root / ".rlsbl-monorepo" / "workspace.toml"
    workspace_toml.write_text(
        workspace_toml.read_text()
        + '\n[[projects]]\npath = "conformance"\nname = "conformance"\n'
        'dev_only = true\nreleasable = false\n'
    )
    (root / "conformance").mkdir()
    (root / "conformance" / "pinned.json").write_text("{}\n")
    _git(root, "add", "-A")
    _git(root, "commit", "-q", "-m", "declare the conformance dev node",
         "--trailer", "Autogenerated: true")
    pin_sha = _git_head(root)

    state_path, _bump_sha = _prepare_resumable_candidate(
        root, core, unrelated_path="packages/core/unrelated.txt",
    )
    # The helper commits one more change after the bump; it is ordinary work
    # inside alpha's territory, so record it as the operator would.
    unrelated = _git_head(root)
    changes = root / ".rlsbl-monorepo" / "releasables" / "alpha" / "changes"
    unreleased = changes / "unreleased.jsonl"
    unreleased.write_text(
        unreleased.read_text()
        + json.dumps({"format_version": 1, "commits": [unrelated],
                      "user_facing": False}) + "\n"
    )
    _git(root, "add", "-A")
    _git(root, "commit", "-q", "-m", "changelog: cover the unrelated work")

    state = load_release_state(state_path)
    state["pin_sha"] = pin_sha
    state["pre_release_sha"] = pin_sha
    from rlsbl.commands.release.release_state import save_release_state
    save_release_state(state_path, state)
    return core, state_path, pin_sha


class TestResumeInAWorkspaceAsksCoverageOfItsOwnReleasable:
    """The adoption condition asks the question `changelog-coverage` asks.

    A commit that touches only a dev node belongs to no releasable:
    ``changelog-coverage`` does not ask for an entry, ``rlsbl unreleased``
    does not count it, and ``rlsbl changelog add`` refuses to record it. A
    resume that adopted such a commit asked coverage of it anyway, over the
    whole repository rather than the releasable's territory, and refused it
    with a remedy that cannot run -- the stopped release could not complete.
    """

    def test_a_commit_touching_only_a_dev_node_is_adopted(self, tmp_project):
        from test_empty_candidate_window import _run_resume

        core, state_path, pin_sha = _stopped_releasable_with_a_dev_node(
            tmp_project,
        )
        (tmp_project / "conformance" / "pinned.json").write_text('{"a": 1}\n')
        _git(tmp_project, "add", "conformance/pinned.json")
        _git(tmp_project, "commit", "-q", "-m",
             "conformance: record the emitted shape")
        tip = _git_head(tmp_project)

        _run_resume(tmp_project, core, remote_head=pin_sha)

        assert _git_output(
            tmp_project, "rev-list", "-n", "1", "alpha@v1.0.1",
        ) == tip, "the release must complete, tagging the adopted tip"
        assert not os.path.exists(state_path)

    def test_an_uncovered_commit_inside_the_releasable_is_still_refused(
        self, tmp_project, capsys,
    ):
        from test_empty_candidate_window import _run_resume

        core, state_path, pin_sha = _stopped_releasable_with_a_dev_node(
            tmp_project,
        )
        (core / "work.txt").write_text("work\n")
        _git(tmp_project, "add", "packages/core/work.txt")
        _git(tmp_project, "commit", "-q", "-m", "fix: work nobody recorded")
        work = _git_head(tmp_project)

        with pytest.raises(SystemExit) as exc:
            _run_resume(tmp_project, core, remote_head=pin_sha)

        assert exc.value.code == 1
        err = capsys.readouterr().err
        assert "Resume aborted" in err
        assert work[:12] in err
        assert os.path.exists(state_path)
