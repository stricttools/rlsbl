"""`rlsbl release resume` adopts what was committed after a release stopped.

A release that stops -- a red CI verdict, a dead network, an interrupted run --
leaves its state file behind and the branch open.  Work then continues on that
branch: the fix the operator commits, and whatever else another session lands
beside it.  Resuming is supposed to take all of it: resume re-pins at the
current tip, so the tip is what gets pushed as the candidate, gated, and
tagged.

It did not.  Once the stopped release had recorded ``CI_VERIFIED`` the pin
stayed where the original run put it, and every later commit was read as a
ride-in the range-pin guard refuses.  The refusal offered two resolutions, and
a repository on the fleet's release-branch-only workflow could execute
neither: recording the commits and "starting a fresh release" is refused by
``release run`` for as long as the state file exists, and moving the commits
onto a branch of their own is not something that workflow does.  A stopped
release plus any later commit was a repository nobody could release.

Resume now adopts those commits, under one condition checked before anything
mutates: each of them must already be covered by a changelog entry, or be
exempt from coverage under the rules ``changelog-coverage`` applies
(``Autogenerated: true``, changelog-only, the release's own commits, and in a
workspace every commit outside the releasable's territory).  An
uncovered commit is still refused -- but the refusal names a remedy that can
actually be run, and the version's changelog therefore describes everything
the tag will contain.
"""

