def _stopped_past_the_gate(repo):
    """A release stopped right after its CI gate went green.

    The shape a real stopped release was found in: the version bump is
    committed and pushed, CI concluded green on it, and the run died before
    finalizing anything.  ``unreleased.jsonl`` is still open, so the version's
    changelog has not been written yet.
    """
    return _in_flight_past_the_gate(repo, extra_release_commit=False)


def _commit_work(repo, name, message):
    """Commit ordinary work on the release branch, as another session would."""
    (repo / name).write_text(f"{name}\n")
    _git(repo, "add", name)
    _git(repo, "commit", "-q", "-m", message)
    return _git_head(repo)


def _cover(repo, sha):
    """Run the remedy the refusal names: `rlsbl changelog add --no-user-facing`."""
    cmd_add(
        {
            "commits": sha,
            "user-facing": False,
            "description": "",
            "type": "",
        },
        project_root=str(repo),
    )


