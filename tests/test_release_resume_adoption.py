class TestResumeAdoptsCoveredCommits:

    def test_a_covered_commit_made_after_the_stop_is_adopted(self, mock_git_repo):
        """The tip -- not the stale candidate -- is pushed, gated and tagged."""
        state_path, old_candidate = _stopped_past_the_gate(mock_git_repo)

        work = _commit_work(mock_git_repo, "work.txt", "fix: work from another session")
        _cover(mock_git_repo, work)
        tip = _git_head(mock_git_repo)
        assert tip != old_candidate, "fixture precondition: the tip has moved"

        gated = []
        pinned = {}

        def fake_wait(sha, **kwargs):
            gated.append(sha)
            pinned.update(load_release_state(state_path) or {})
            return "green", []

        _resume(
            mock_git_repo,
            load_release_state(state_path),
            {"quiet": True},
            ci_side_effect=fake_wait,
        )

        assert gated == [tip], (
            "the adopted tip must be re-gated by CI; the recorded verdict "
            f"covers only {old_candidate[:12]}. Gated: {gated}"
        )
        assert pinned.get("pin_sha") == tip, (
            "resume must re-pin at the current tip so the adopted commits are "
            "inside the release rather than foreign to it"
        )
        assert _git_output(mock_git_repo, "rev-list", "-n", "1", "v1.0.1") == tip, (
            "the tag must land on the commit CI just verified -- the tip that "
            "contains the adopted work"
        )

    def test_an_exempt_commit_needs_no_entry_of_its_own(self, mock_git_repo):
        """The coverage rules are the changelog check's, trailer included."""
        state_path, _ = _stopped_past_the_gate(mock_git_repo)

        (mock_git_repo / "generated.txt").write_text("generated\n")
        _git(mock_git_repo, "add", "generated.txt")
        _git(
            mock_git_repo, "commit", "-q", "-m", "chore: regenerate",
            "--trailer", "Autogenerated: true",
        )
        tip = _git_head(mock_git_repo)

        _resume(mock_git_repo, load_release_state(state_path), {"quiet": True})

        assert _git_output(mock_git_repo, "rev-list", "-n", "1", "v1.0.1") == tip


class TestResumeRefusesUncoveredCommits:

    def test_an_uncovered_commit_refuses_with_a_remedy_that_can_be_run(
        self, mock_git_repo, capsys,
    ):
        state_path, _ = _stopped_past_the_gate(mock_git_repo)
        work = _commit_work(
            mock_git_repo, "work.txt", "fix: work nobody recorded",
        )

        output = _resume_expect_abort(
            mock_git_repo,
            load_release_state(state_path),
            {"quiet": True},
            capsys,
        )

        assert work[:12] in output, "the uncovered commit must be named"
        assert "fix: work nobody recorded" in output, (
            "its subject must be shown, so the operator can judge it"
        )
        assert "rlsbl changelog add --commits" in output, (
            "the remedy must be a runnable command line"
        )
        assert "--no-user-facing" in output
        assert "rlsbl release resume" in output, (
            "the remedy must end at the command that continues this release"
        )
        assert "fresh release" not in output, (
            "a fresh release is refused while the state file exists, so "
            "naming it sends the operator into a second refusal"
        )

    def test_nothing_mutates_when_the_coverage_condition_fails(
        self, mock_git_repo, capsys,
    ):
        state_path, candidate = _stopped_past_the_gate(mock_git_repo)
        work = _commit_work(mock_git_repo, "work.txt", "fix: work nobody recorded")
        before = _git_head(mock_git_repo)
        state_before = open(state_path, "rb").read()

        _resume_expect_abort(
            mock_git_repo,
            load_release_state(state_path),
            {"quiet": True},
            capsys,
        )

        assert _git_head(mock_git_repo) == before == work, (
            "the refusal must come before any mutation, and the commit it "
            "refuses is never rolled back"
        )
        assert "v1.0.1" not in _git_output(mock_git_repo, "tag", "-l").split()
        assert open(state_path, "rb").read() == state_before, (
            "the release state must be untouched by a refused resume"
        )

    def test_the_named_remedy_clears_the_refusal(self, mock_git_repo, capsys):
        """Remedy truthfulness: run what the error says, resume goes through."""
        state_path, _ = _stopped_past_the_gate(mock_git_repo)
        work = _commit_work(mock_git_repo, "work.txt", "fix: work nobody recorded")

        output = _resume_expect_abort(
            mock_git_repo,
            load_release_state(state_path),
            {"quiet": True},
            capsys,
        )
        assert f"rlsbl changelog add --commits {work[:12]}" in output, (
            "the remedy must name the very commit it refused"
        )

        _cover(mock_git_repo, work)
        tip = _git_head(mock_git_repo)

        _resume(mock_git_repo, load_release_state(state_path), {"quiet": True})

        assert _git_output(mock_git_repo, "rev-list", "-n", "1", "v1.0.1") == tip
        assert not os.path.exists(state_path), (
            "the resume the remedy unblocked must complete the release"
        )


class TestReleaseRunStillRefusesWhileStopped:
    """The other half of the deadlock stays exactly as it was.

    `release run` must keep refusing while a state file exists -- resume is the
    door, and the refusal points at it.  Only the resume side was wrong.
    """

    def test_release_run_refuses_and_points_at_resume(self, mock_git_repo, capsys):
        _setup_releasable_npm_project(mock_git_repo)
        state_path = _make_in_progress_state(
            mock_git_repo,
            completed_steps=[
                "VERSION_BUMPED", "COMMITTED", "SNAPSHOT_REGENERATED",
                "BRANCH_PUSHED", "CI_VERIFIED",
            ],
        )
        _commit_work(mock_git_repo, "work.txt", "fix: work from another session")

        with pytest.raises(SystemExit) as exc:
            with (
                patch("rlsbl.commands.release.check_gh_installed", return_value=True),
                patch("rlsbl.commands.release.check_gh_auth", return_value=True),
                patch("rlsbl.commands.release.run", side_effect=_fake_run_factory()),
                patch("rlsbl.commands.release.remote_branch_exists", return_value=True),
            ):
                run_cmd(_rc(), {"quiet": False}, ctx=_make_ctx(mock_git_repo))

        assert exc.value.code == 1
        err = capsys.readouterr().err
        assert "previous release is in progress" in err
        assert "rlsbl release resume" in err
        assert os.path.exists(state_path), "the refusal must not clear the state"


def test_the_state_path_helper_agrees_with_the_fixture(mock_git_repo):
    """Guard the fixture's own assumption about where the state file lives."""
    state_path, _ = _stopped_past_the_gate(mock_git_repo)
    assert state_path == get_state_path(str(mock_git_repo))


