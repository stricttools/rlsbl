"""A release, and `rlsbl watch` on a released commit, require the publish runs to have started.

A published Release starts its publish workflows, and GitHub reports no error
when it starts none. The release used to end with success anyway, and ``rlsbl
watch`` on the released commit found no runs and exited 0. Both now require a
run for the tag of every workflow in the tagged commit's tree that the Release
starts; the fix the error names (``rlsbl release retry``, which dispatches the
workflows at the tag, then ``rlsbl watch``) is applied here and seen to clear it.
"""

import json
import subprocess
from io import StringIO
from unittest.mock import patch

import pytest

from githarness import record_release

PUBLISH = """\
name: Publish
on:
  release:
    types: [published]
  workflow_dispatch:
jobs:
  publish:
    runs-on: ubuntu-latest
    steps:
      - run: echo publish
"""


def _git(repo, *args):
    return subprocess.run(
        ["git", *args], cwd=repo, check=True, capture_output=True, text=True,
    ).stdout.strip()


def _commit_workflow(repo):
    wf = repo / ".github" / "workflows"
    wf.mkdir(parents=True, exist_ok=True)
    (wf / "publish.yml").write_text(PUBLISH)
    _git(repo, "add", ".github/workflows/publish.yml")
    _git(repo, "commit", "-q", "-m", "add publish workflow",
         "--trailer", "Autogenerated: true")


class FakeGitHub:
    """Answers the Release, Actions, and runs questions; records creations."""

    def __init__(self):
        self.runs = []
        self.created = []

    def __call__(self, args, *_config, **kwargs):
        args = list(args)
        if args[:2] == ["release", "view"]:
            if "--json" in args and "author" in args:
                return "smm-h"
            if args[2] in self.created:
                return ""
            raise subprocess.CalledProcessError(1, "gh release view")
        if args[:2] == ["release", "create"]:
            self.created.append(args[2])
            return ""
        if args[:3] == ["api", "--method", "GET"]:
            path = args[3]
            if path.endswith("/actions/permissions"):
                return json.dumps({"enabled": True})
            if "/runs?" in path:
                return json.dumps({"workflow_runs": self.runs})
            if "/actions/workflows/" in path:
                return "active"
        return ""


@pytest.fixture(autouse=True)
def _no_discovery_wait(monkeypatch):
    monkeypatch.setattr("rlsbl.publish_workflows.DISCOVERY_SECONDS", 0)


def _release(repo, gh):
    from rlsbl.commands.release import run_cmd
    from rlsbl.context import ProjectContext
    from rlsbl.release_file import ReleaseConfig

    with (
        patch("rlsbl.commands.release.check_gh_installed", return_value=True),
        patch("rlsbl.commands.release.check_gh_auth", return_value=True),
        patch("rlsbl.commands.release.validate_gh_push_access"),
        patch("rlsbl.commands.release.validate_branch_and_remote",
              return_value="main"),
        patch("rlsbl.commands.release.push_if_needed"),
        patch("rlsbl.commands.release.resolve_tag_push_plan", return_value=False),
        patch("rlsbl.commands.release.run_gh", side_effect=gh),
    ):
        run_cmd(
            ReleaseConfig(bump="patch", include=["npm"], exclude=[],
                          description="test release"),
            {"quiet": True, "watch": False},
            ctx=ProjectContext(
                project_root=repo, workspace_root=None,
                config={"publish_mode": "ci", "pipelines": {}},
            ),
        )


class TestTheRelease:

    def test_a_release_whose_publish_run_never_started_fails(
        self, mock_git_repo, capsys,
    ):
        from test_post_push_failure_state import _setup_npm_project

        _setup_npm_project(mock_git_repo)
        _commit_workflow(mock_git_repo)
        gh = FakeGitHub()
        with pytest.raises(SystemExit) as exc:
            _release(mock_git_repo, gh)
        assert exc.value.code == 1
        err = capsys.readouterr().err
        assert "no run of .github/workflows/publish.yml started" in err
        assert "rlsbl release retry" in err
        assert gh.created == ["v1.0.1"], "the Release itself was created"

    def test_a_release_whose_publish_run_started_succeeds(self, mock_git_repo):
        from test_post_push_failure_state import _setup_npm_project

        _setup_npm_project(mock_git_repo)
        _commit_workflow(mock_git_repo)
        gh = FakeGitHub()
        gh.runs = [{"event": "release", "head_branch": "v1.0.1", "id": 7}]
        _release(mock_git_repo, gh)


class TestWatch:
    """`rlsbl watch <sha>` on a released commit."""

    def _released_repo(self, repo):
        (repo / ".rlsbl").mkdir(exist_ok=True)
        (repo / ".rlsbl" / "config.json").write_text(
            '{"publish_mode": "ci"}\n'
        )
        (repo / "package.json").write_text(
            '{"name": "watched", "version": "1.0.0"}\n'
        )
        _git(repo, "add", "-A")
        _git(repo, "commit", "-q", "-m", "project")
        _commit_workflow(repo)
        sha = _git(repo, "rev-parse", "HEAD")
        record_release(repo, "v1.0.0", sha=sha)
        return sha

    def _watch(self, sha, gh):
        from rlsbl.commands import watch

        def watch_gh(args, **kwargs):
            if list(args)[:2] == ["repo", "view"]:
                return json.dumps({"nameWithOwner": "o/r", "name": "r"})
            return gh(args, **kwargs)

        with (
            patch("rlsbl.commands.watch.run_gh", side_effect=watch_gh),
            patch("rlsbl.commands.watch.poll_runs", return_value=[]),
            patch("sys.stderr", new_callable=StringIO) as err,
            pytest.raises(SystemExit) as exc,
        ):
            watch.run_cmd(None, [sha], {})
        return exc.value.code, err.getvalue()

    def test_no_publish_run_is_a_hard_error_until_the_retry_dispatch(
        self, mock_git_repo,
    ):
        sha = self._released_repo(mock_git_repo)
        gh = FakeGitHub()
        code, err = self._watch(sha, gh)
        assert code == 1
        assert "no run of .github/workflows/publish.yml started" in err
        # `rlsbl release retry` dispatches the workflow at the tag:
        gh.runs = [{"event": "workflow_dispatch", "head_branch": "v1.0.0",
                    "id": 8}]
        code, err = self._watch(sha, gh)
        assert code == 0
        assert "no run of" not in err


class TestThePreflight:
    """The release refuses, before pushing anything, a Release that would
    start no publish workflow."""

    CI_PIPELINE = {"npm": {"type": "npm", "local": False, "provenance": False,
                           "target": "npm"}}

    def _release_with_ci_pipeline(self, repo, gh):
        from rlsbl.commands.release import run_cmd
        from rlsbl.context import ProjectContext
        from rlsbl.release_file import ReleaseConfig

        pushed = []
        with (
            patch("rlsbl.commands.release.check_gh_installed", return_value=True),
            patch("rlsbl.commands.release.check_gh_auth", return_value=True),
            patch("rlsbl.commands.release.validate_gh_push_access"),
            patch("rlsbl.commands.release.validate_branch_and_remote",
                  return_value="main"),
            patch("rlsbl.commands.release.push_if_needed",
                  side_effect=lambda *a, **k: pushed.append(a)),
            patch("rlsbl.commands.release.resolve_tag_push_plan",
                  return_value=False),
            patch("rlsbl.commands.release.run_gh", side_effect=gh),
        ):
            try:
                run_cmd(
                    ReleaseConfig(bump="patch", include=["npm"], exclude=[],
                                  description="test release"),
                    {"quiet": True, "watch": False},
                    ctx=ProjectContext(
                        project_root=repo, workspace_root=None,
                        config={"publish_mode": "ci", "targets": ["npm"],
                                "pipelines": self.CI_PIPELINE},
                    ),
                )
            finally:
                self.pushed = pushed

    def test_no_publish_workflow_is_refused_before_anything_is_pushed(
        self, mock_git_repo, capsys,
    ):
        from test_post_push_failure_state import _setup_npm_project

        _setup_npm_project(mock_git_repo)
        head = _git(mock_git_repo, "rev-parse", "HEAD")
        with pytest.raises(SystemExit) as exc:
            self._release_with_ci_pipeline(mock_git_repo, FakeGitHub())
        assert exc.value.code == 1
        assert "no workflow in .github/workflows/" in capsys.readouterr().err
        assert self.pushed == []
        assert _git(mock_git_repo, "rev-parse", "HEAD") == head

    def test_the_committed_publish_workflow_clears_it(self, mock_git_repo):
        from test_post_push_failure_state import _setup_npm_project

        _setup_npm_project(mock_git_repo)
        _commit_workflow(mock_git_repo)
        gh = FakeGitHub()
        gh.runs = [{"event": "release", "head_branch": "v1.0.1", "id": 9}]
        self._release_with_ci_pipeline(mock_git_repo, gh)
        assert gh.created == ["v1.0.1"]
