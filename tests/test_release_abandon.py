class TestAbandoning:

    def test_the_version_comes_from_the_state_file(self, tmp_path, monkeypatch):
        repo = build(tmp_path, files="0.29.4")
        state_path = _stall(repo, "0.29.4")
        head = git(repo, "rev-parse", "HEAD")

        result = abandon(repo, monkeypatch)

        assert result.exit_code == 0, result.stderr + result.stdout
        releases = release_record_dir(repo)
        assert read_version_fate(releases, "0.29.4") is VersionFate.NEVER_RELEASED
        assert not (repo / ".rlsbl/releases/in-progress.json").exists()
        # One commit, carrying the archive and the generated-file trailer.
        assert git(repo, "rev-list", "--count", f"{head}..HEAD") == "1"
        assert git(repo, "diff-tree", "--no-commit-id", "--name-only", "-r",
                   "HEAD") == ".rlsbl/releases/v0.29.4.toml"
        assert "Autogenerated: true" in git(repo, "log", "-1", "--format=%B")
        assert git(repo, "status", "--porcelain") == ""
        assert state_path in result.stdout

    def test_the_state_files_version_wins_over_the_version_files(
        self, tmp_path, monkeypatch,
    ):
        """An attempt that stopped before the version write still claimed its number."""
        repo = build(tmp_path)
        _stall(repo, "0.29.4")

        result = abandon(repo, monkeypatch)

        assert result.exit_code == 0, result.stderr + result.stdout
        assert read_version_fate(
            release_record_dir(repo), "0.29.4",
        ) is VersionFate.NEVER_RELEASED

    def test_without_a_state_file_the_version_files_name_it(
        self, tmp_path, monkeypatch,
    ):
        repo = build(tmp_path, files="0.29.4")

        result = abandon(repo, monkeypatch)

        assert result.exit_code == 0, result.stderr + result.stdout
        archive = read_release_file(
            str(Path(release_record_dir(repo)) / "v0.29.4.toml"),
        )
        assert archive.never_released is True
        assert archive.bump == "patch"
        assert git(repo, "status", "--porcelain") == ""

    def test_a_dry_run_writes_nothing(self, tmp_path, monkeypatch):
        repo = build(tmp_path, files="0.29.4")
        state_path = _stall(repo, "0.29.4")
        head = git(repo, "rev-parse", "HEAD")

        result = abandon(repo, monkeypatch, dry_run=True)

        assert result.exit_code == 0, result.stderr + result.stdout
        assert not (Path(release_record_dir(repo)) / "v0.29.4.toml").exists()
        assert (repo / ".rlsbl/releases/in-progress.json").exists()
        _untouched(repo, head)
        assert state_path in result.stdout

    def test_a_rerun_finishes_an_interrupted_abandon(self, tmp_path, monkeypatch):
        """The archive is committed, but the state file outlived the first run."""
        repo = build(tmp_path, files="0.29.4", never_released=("0.29.4",))
        state_path = _stall(repo, "0.29.4")
        head = git(repo, "rev-parse", "HEAD")

        result = abandon(repo, monkeypatch)

        assert result.exit_code == 0, result.stderr + result.stdout
        assert not (repo / ".rlsbl/releases/in-progress.json").exists()
        assert "completed the earlier" in result.stdout, result.stdout
        assert state_path in result.stdout
        # Nothing else is written: the archive is already the record.
        _untouched(repo, head)

    def test_a_rerun_commits_an_archive_the_earlier_run_left_uncommitted(
        self, tmp_path, monkeypatch,
    ):
        """The earlier run stopped between writing the archive and its commit."""
        repo = build(tmp_path, files="0.29.4")
        _stall(repo, "0.29.4")
        archive_release(release_record_dir(repo), "0.29.4", None, never_released=True)
        head = git(repo, "rev-parse", "HEAD")

        result = abandon(repo, monkeypatch)

        assert result.exit_code == 0, result.stderr + result.stdout
        assert not (repo / ".rlsbl/releases/in-progress.json").exists()
        assert git(repo, "rev-list", "--count", f"{head}..HEAD") == "1"
        assert git(repo, "diff-tree", "--no-commit-id", "--name-only", "-r",
                   "HEAD") == ".rlsbl/releases/v0.29.4.toml"
        assert "Committed that archive" in result.stdout, result.stdout
        assert git(repo, "status", "--porcelain") == ""

    def test_a_dry_run_of_the_rerun_deletes_nothing(self, tmp_path, monkeypatch):
        repo = build(tmp_path, files="0.29.4", never_released=("0.29.4",))
        _stall(repo, "0.29.4")

        result = abandon(repo, monkeypatch, dry_run=True)

        assert result.exit_code == 0, result.stderr + result.stdout
        assert (repo / ".rlsbl/releases/in-progress.json").exists()
        assert "Would delete" in result.stdout, result.stdout


