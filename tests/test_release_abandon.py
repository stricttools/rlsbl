class TestRefusals:

    def test_nothing_to_abandon_at_a_released_version(self, tmp_path, monkeypatch):
        repo = build(tmp_path)
        head = git(repo, "rev-parse", "HEAD")

        result = abandon(repo, monkeypatch)

        assert result.exit_code == 1
        assert "nothing to abandon" in result.stderr, result.stderr
        assert "0.29.3" in result.stderr and "released" in result.stderr
        _untouched(repo, head)

    def test_nothing_to_abandon_at_a_never_released_version(
        self, tmp_path, monkeypatch,
    ):
        repo = build(tmp_path, files="0.29.4", never_released=("0.29.4",))
        head = git(repo, "rev-parse", "HEAD")

        result = abandon(repo, monkeypatch)

        assert result.exit_code == 1
        assert "nothing to abandon" in result.stderr, result.stderr
        assert "never released" in result.stderr
        _untouched(repo, head)

    def test_version_files_behind_the_latest_release_are_refused(
        self, tmp_path, monkeypatch,
    ):
        repo = build(tmp_path, files="0.29.1")
        head = git(repo, "rev-parse", "HEAD")

        result = abandon(repo, monkeypatch)

        assert result.exit_code == 1
        assert "behind the latest release" in result.stderr, result.stderr
        assert "0.29.1" in result.stderr and "0.29.3" in result.stderr
        assert "at least 0.29.3" in result.stderr, result.stderr
        assert not (Path(release_record_dir(repo)) / "v0.29.1.toml").exists()
        _untouched(repo, head)

    def test_following_the_behind_fix_clears_the_refusal(
        self, tmp_path, monkeypatch,
    ):
        repo = build(tmp_path, files="0.29.1")
        assert abandon(repo, monkeypatch).exit_code == 1

        # The named fix: set the version files to the latest release.
        _write_version(repo, "0.29.3")
        _commit_all(repo, "0.29.3")

        result = abandon(repo, monkeypatch)
        assert "behind the latest release" not in result.stderr, result.stderr
        # What remains is the plain truth: 0.29.3 is released, nothing to abandon.
        assert "nothing to abandon" in result.stderr, result.stderr

    def test_a_state_file_naming_a_version_behind_the_latest_is_refused(
        self, tmp_path, monkeypatch,
    ):
        repo = build(tmp_path)
        _stall(repo, "0.29.1")
        head = git(repo, "rev-parse", "HEAD")

        result = abandon(repo, monkeypatch)

        assert result.exit_code == 1
        assert "behind the latest release" in result.stderr, result.stderr
        assert "0.29.1" in result.stderr and "0.29.3" in result.stderr
        assert (repo / ".rlsbl/releases/in-progress.json").exists()
        assert not (Path(release_record_dir(repo)) / "v0.29.1.toml").exists()
        _untouched(repo, head)

    def test_a_released_version_in_the_state_file_is_refused(
        self, tmp_path, monkeypatch,
    ):
        repo = build(tmp_path)
        _stall(repo, "0.29.3")

        result = abandon(repo, monkeypatch)

        assert result.exit_code == 1
        assert "already archived" in result.stderr, result.stderr

    def test_a_local_tag_is_refused(self, tmp_path, monkeypatch):
        repo = build(tmp_path, files="0.29.4")
        git(repo, "tag", "v0.29.4")
        head = git(repo, "rev-parse", "HEAD")

        result = abandon(repo, monkeypatch)

        assert result.exit_code == 1
        assert "v0.29.4" in result.stderr
        assert "rlsbl release backfill" in result.stderr, result.stderr
        assert "release undo" not in result.stderr, result.stderr
        assert not (Path(release_record_dir(repo)) / "v0.29.4.toml").exists()
        _untouched(repo, head)

    def test_following_the_local_tag_remedy_clears_the_refusal(
        self, tmp_path, monkeypatch,
    ):
        """Backfill adopts the tag as a release; the tag refusal is gone."""
        repo = build(tmp_path, files="0.29.4")
        git(repo, "tag", "v0.29.4")
        assert abandon(repo, monkeypatch).exit_code == 1

        backfilled = rlsbl.app.test(
            ["release", "backfill", "--approve-consequential"]
        )
        assert backfilled.exit_code == 0, backfilled.stderr + backfilled.stdout
        assert read_version_fate(
            release_record_dir(repo), "0.29.4",
        ) is VersionFate.RECORDED

        result = abandon(repo, monkeypatch)
        assert "tag v0.29.4 exists" not in result.stderr, result.stderr
        assert "nothing to abandon" in result.stderr, result.stderr

    def test_a_tag_on_origin_is_refused(self, tmp_path, monkeypatch):
        repo = build(tmp_path, files="0.29.4")
        git(repo, "tag", "v0.29.4")
        git(repo, "push", "-q", "origin", "v0.29.4")
        git(repo, "tag", "-d", "v0.29.4")

        result = abandon(repo, monkeypatch)

        assert result.exit_code == 1
        assert "on origin" in result.stderr, result.stderr
        assert "git fetch origin tag v0.29.4" in result.stderr, result.stderr
        assert "rlsbl release backfill" in result.stderr, result.stderr
        assert "release undo" not in result.stderr, result.stderr
        assert not (Path(release_record_dir(repo)) / "v0.29.4.toml").exists()

    def test_following_the_origin_tag_remedy_clears_the_refusal(
        self, tmp_path, monkeypatch,
    ):
        repo = build(tmp_path, files="0.29.4")
        git(repo, "tag", "v0.29.4")
        git(repo, "push", "-q", "origin", "v0.29.4")
        git(repo, "tag", "-d", "v0.29.4")
        assert abandon(repo, monkeypatch).exit_code == 1

        # The named fix: fetch the tag, then backfill adopts it.
        git(repo, "fetch", "-q", "origin", "tag", "v0.29.4")
        backfilled = rlsbl.app.test(
            ["release", "backfill", "--approve-consequential"]
        )
        assert backfilled.exit_code == 0, backfilled.stderr + backfilled.stdout

        result = abandon(repo, monkeypatch)
        assert "on origin" not in result.stderr, result.stderr
        assert "nothing to abandon" in result.stderr, result.stderr

    def test_a_github_release_is_refused(self, tmp_path, monkeypatch):
        repo = build(tmp_path, files="0.29.4")
        head = git(repo, "rev-parse", "HEAD")

        result = abandon(repo, monkeypatch, release_exists=True)

        assert result.exit_code == 1
        assert "GitHub Release" in result.stderr, result.stderr
        assert "rlsbl release undo" in result.stderr
        _untouched(repo, head)

    def test_an_unanswerable_github_probe_is_refused(self, tmp_path, monkeypatch):
        """gh failing for any reason but "release not found" answers nothing."""
        repo = build(tmp_path, files="0.29.4")
        monkeypatch.chdir(repo)

        def failing_gh(args, **_kw):
            raise subprocess.CalledProcessError(1, "gh", stderr="HTTP 502")

        with (
            patch("rlsbl.utils.check_gh_installed", return_value=True),
            patch("rlsbl.utils.check_gh_auth", return_value=True),
            patch("rlsbl.utils.run_gh", side_effect=failing_gh),
        ):
            result = rlsbl.app.test(
                ["release", "abandon", "--approve-consequential"]
            )

        assert result.exit_code == 1
        assert "cannot tell whether a GitHub Release exists" in result.stderr
        assert not (Path(release_record_dir(repo)) / "v0.29.4.toml").exists()

    def test_gh_saying_release_not_found_is_absent(self, tmp_path, monkeypatch):
        repo = build(tmp_path, files="0.29.4")
        monkeypatch.chdir(repo)

        def missing(args, **_kw):
            raise subprocess.CalledProcessError(1, "gh", stderr="release not found")

        with (
            patch("rlsbl.utils.check_gh_installed", return_value=True),
            patch("rlsbl.utils.check_gh_auth", return_value=True),
            patch("rlsbl.utils.run_gh", side_effect=missing),
        ):
            result = rlsbl.app.test(
                ["release", "abandon", "--approve-consequential"]
            )

        assert result.exit_code == 0, result.stderr + result.stdout

    def test_disagreeing_version_files_are_refused(self, tmp_path, monkeypatch):
        repo = build(tmp_path, files="0.29.4")
        (repo / ".rlsbl" / "config.json").write_text(json.dumps({
            "publish_mode": "ci", "targets": ["npm", "pypi"],
        }) + "\n")
        (repo / "pyproject.toml").write_text(
            '[project]\nname = "pkg"\nversion = "0.29.5"\n'
        )
        _commit_all(repo, "a second target")

        result = abandon(repo, monkeypatch)

        assert result.exit_code == 1
        assert "disagree" in result.stderr, result.stderr
        assert "0.29.4" in result.stderr and "0.29.5" in result.stderr


def test_the_abandoned_version_is_bumped_from(tmp_path, monkeypatch):
    """End to end: abandon, then the release flow bumps from the abandoned number."""
    from test_release_version_fate import compute

    repo = build(tmp_path, files="0.29.4")
    _stall(repo, "0.29.4")

    assert abandon(repo, monkeypatch).exit_code == 0

    assert compute(repo, "patch") == ("0.29.4", "0.29.5", "patch", "v0.29.5")


def test_an_abandoned_number_is_never_reused(tmp_path, monkeypatch):
    """The attempt stopped before its version write: the files still name 0.29.3."""
    from rlsbl.commands.release.validate import ReleaseValidationError
    from test_release_version_fate import compute

    repo = build(tmp_path)
    _stall(repo, "0.29.4")
    assert abandon(repo, monkeypatch).exit_code == 0

    with pytest.raises(ReleaseValidationError) as exc:
        compute(repo, "patch")
    assert "never released" in str(exc.value)

    _write_version(repo, "0.29.4")
    _commit_all(repo, "0.29.4")
    assert compute(repo, "patch")[1] == "0.29.5"


