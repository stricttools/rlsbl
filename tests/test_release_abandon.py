def _released_releasable(tmp_path):
    """Workspace with releasable ``alpha`` (sole member packages/core).

    1.0.0 is released (archived and tagged ``alpha@v1.0.0``), and the version
    files were then bumped to 1.0.1 by an attempt that never recorded it.
    Returns the workspace root and the member directory.
    """
    from conftest import with_root_member
    from githarness import add_remote, init_repo
    from rlsbl.workspace import (
        Releasable,
        get_releasable_changes_dir,
        get_releasable_dir,
        save_workspace,
        write_releasable_version,
    )

    ws = tmp_path / "ws"
    init_repo(ws)
    core = ws / "packages" / "core"
    core.mkdir(parents=True)
    (core / "package.json").write_text(
        json.dumps({"name": "core", "version": "1.0.0"}, indent=2) + "\n"
    )
    (core / ".rlsbl").mkdir()
    (core / ".rlsbl" / "config.json").write_text(
        json.dumps({"publish_mode": "ci", "targets": ["npm"]}) + "\n"
    )
    (ws / ".gitignore").write_text(
        ".rlsbl-monorepo/releasables/*/releases/in-progress.json\n"
    )
    save_workspace(
        str(ws),
        with_root_member(
            [{"path": "packages/core", "name": "core", "releasable": "alpha"}],
        ),
        releasables=[Releasable(name="alpha")],
    )
    write_releasable_version(str(ws), "alpha", "1.0.0")
    changes = Path(get_releasable_changes_dir(str(ws), "alpha"))
    changes.mkdir(parents=True, exist_ok=True)
    (changes / "unreleased.jsonl").write_text("")
    rel_dir = Path(get_releasable_dir(str(ws), "alpha"))
    (rel_dir / "config.json").write_text("{}\n")
    sha = _commit_all(ws, "alpha: release v1.0.0")
    git(ws, "tag", "alpha@v1.0.0")
    archive_release(str(rel_dir / "releases"), "1.0.0", sha)
    _commit_all(ws, "chore: archive the release record")
    add_remote(ws, tmp_path / "ws-origin.git")

    write_releasable_version(str(ws), "alpha", "1.0.1")
    (core / "package.json").write_text(
        json.dumps({"name": "core", "version": "1.0.1"}, indent=2) + "\n"
    )
    _commit_all(ws, "alpha: release v1.0.1")
    return ws, core


def _stall_releasable(ws, version):
    from rlsbl.workspace import get_releasable_dir

    rel_dir = get_releasable_dir(str(ws), "alpha")
    path = get_state_path(str(ws / "packages" / "core"), releasable_dir=rel_dir)
    save_release_state(path, {
        "new_version": version,
        "tag": f"alpha@v{version}",
        "branch": "main",
        "bump_type": "patch",
        "completed_steps": ["VERSION_BUMPED", "COMMITTED", "BRANCH_PUSHED"],
        "failed_steps": {},
        "include": ["npm"],
        "exclude": [],
    })
    return Path(path)


class TestAReleasable:

    def test_the_releasables_attempt_is_abandoned(self, tmp_path, monkeypatch):
        ws, core = _released_releasable(tmp_path)
        state_path = _stall_releasable(ws, "1.0.1")
        head = git(ws, "rev-parse", "HEAD")

        result = abandon(core, monkeypatch)

        assert result.exit_code == 0, result.stderr + result.stdout
        releases = ws / ".rlsbl-monorepo" / "releasables" / "alpha" / "releases"
        assert read_version_fate(str(releases), "1.0.1") is VersionFate.NEVER_RELEASED
        assert not state_path.exists()
        assert git(ws, "rev-list", "--count", f"{head}..HEAD") == "1"
        assert git(ws, "diff-tree", "--no-commit-id", "--name-only", "-r",
                   "HEAD") == ".rlsbl-monorepo/releasables/alpha/releases/v1.0.1.toml"
        # The member keeps no release state of its own.
        assert not (core / ".rlsbl" / "releases").exists()
        assert git(ws, "status", "--porcelain") == ""

    def test_a_released_version_in_the_state_file_is_refused(
        self, tmp_path, monkeypatch,
    ):
        ws, core = _released_releasable(tmp_path)
        state_path = _stall_releasable(ws, "1.0.0")
        head = git(ws, "rev-parse", "HEAD")

        result = abandon(core, monkeypatch)

        assert result.exit_code == 1
        assert "already archived" in result.stderr, result.stderr
        assert "1.0.0" in result.stderr
        assert state_path.exists()
        assert git(ws, "rev-parse", "HEAD") == head
        assert git(ws, "status", "--porcelain") == ""
