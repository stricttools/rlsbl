"""``rlsbl release abandon``: record an abandoned attempt's version as never released.

Every refusal leaves the repository untouched, and the success path writes the
never-released archive, deletes the in-progress state file, and commits the
archive with the Autogenerated trailer. A re-run after an abandon that stopped
between its commit and the state file's deletion finishes it.
"""

import json
import subprocess
from pathlib import Path
from unittest.mock import patch

import pytest

import rlsbl
from conftest import archive_release, release_record_dir
from githarness import git
from rlsbl.commands.release.release_state import get_state_path, save_release_state
from rlsbl.release_file import read_release_file
from rlsbl.release_record import VersionFate, read_version_fate
from test_release_version_fate import _commit_all, _write_version, build


def _stall(repo, version):
    """The state file an attempt that stopped before its archive step leaves."""
    path = get_state_path(str(repo))
    save_release_state(path, {
        "new_version": version,
        "tag": f"v{version}",
        "branch": "main",
        "bump_type": "patch",
        "completed_steps": ["VERSION_BUMPED", "COMMITTED", "BRANCH_PUSHED"],
        "failed_steps": {},
        "include": ["npm"],
        "exclude": [],
    })
    return path


def abandon(repo, monkeypatch, *, release_exists=False, dry_run=False):
    monkeypatch.chdir(repo)
    argv = ["release", "abandon", "--approve-consequential"]
    if dry_run:
        argv.insert(0, "--dry-run")
    with patch(
        "rlsbl.commands.release_abandon._github_release_exists",
        return_value=release_exists,
    ):
        return rlsbl.app.test(argv)


def _untouched(repo, head):
    assert git(repo, "rev-parse", "HEAD") == head
    assert git(repo, "status", "--porcelain") == ""


