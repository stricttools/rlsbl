"""``rlsbl release abandon``: record an abandoned attempt's version as never released.

Every refusal leaves the repository untouched, and the success path writes the
never-released archive, deletes the in-progress state file, and commits the
archive with the Autogenerated trailer.
"""

import json
import subprocess
from pathlib import Path
from unittest.mock import patch

import pytest

import rlsbl
from conftest import archive_release, release_record_dir
from githarness import git
from rlsbl.commands.release.release_state import get_state_path, save_release_state
from rlsbl.release_file import read_release_file
from rlsbl.release_record import VersionFate, read_version_fate
from test_release_version_fate import _commit_all, _write_version, build


def _stall(repo, version):
    """The state file an attempt that stopped before its archive step leaves."""
    path = get_state_path(str(repo))
    save_release_state(path, {
        "new_version": version,
        "tag": f"v{version}",
        "branch": "main",
        "bump_type": "patch",
        "completed_steps": ["VERSION_BUMPED", "COMMITTED", "BRANCH_PUSHED"],
        "failed_steps": {},
        "include": ["npm"],
        "exclude": [],
    })
    return path


def abandon(repo, monkeypatch, *, release_exists=False, dry_run=False):
    monkeypatch.chdir(repo)
    argv = ["release", "abandon", "--approve-consequential"]
    if dry_run:
        argv.insert(0, "--dry-run")
    with patch(
        "rlsbl.commands.release_abandon._github_release_exists",
        return_value=release_exists,
    ):
        return rlsbl.app.test(argv)


def _untouched(repo, head):
    assert git(repo, "rev-parse", "HEAD") == head
    assert git(repo, "status", "--porcelain") == ""


# --------------------------------------------------------------------------- #
# The success path
# --------------------------------------------------------------------------- #

class TestAbandoning:

    def test_the_version_comes_from_the_state_file(self, tmp_path, monkeypatch):
        repo = build(tmp_path, files="0.29.4")
        state_path = _stall(repo, "0.29.4")
        head = git(repo, "rev-parse", "HEAD")

        result = abandon(repo, monkeypatch)

        assert result.exit_code == 0, result.stderr + result.stdout
        releases = release_record_dir(repo)
        assert read_version_fate(releases, "0.29.4") is VersionFate.NEVER_RELEASED
        assert not (repo / ".rlsbl/releases/in-progress.json").exists()
        # One commit, carrying the archive and the generated-file trailer.
        assert git(repo, "rev-list", "--count", f"{head}..HEAD") == "1"
        assert git(repo, "diff-tree", "--no-commit-id", "--name-only", "-r",
                   "HEAD") == ".rlsbl/releases/v0.29.4.toml"
        assert "Autogenerated: true" in git(repo, "log", "-1", "--format=%B")
        assert git(repo, "status", "--porcelain") == ""
        assert state_path in result.stdout

    def test_the_state_files_version_wins_over_the_version_files(
        self, tmp_path, monkeypatch,
    ):
        """An attempt that stopped before the version write still claimed its number."""
        repo = build(tmp_path)
        _stall(repo, "0.29.4")

        result = abandon(repo, monkeypatch)

        assert result.exit_code == 0, result.stderr + result.stdout
        assert read_version_fate(
            release_record_dir(repo), "0.29.4",
        ) is VersionFate.NEVER_RELEASED

    def test_without_a_state_file_the_version_files_name_it(
        self, tmp_path, monkeypatch,
    ):
        repo = build(tmp_path, files="0.29.4")

        result = abandon(repo, monkeypatch)

        assert result.exit_code == 0, result.stderr + result.stdout
        archive = read_release_file(
            str(Path(release_record_dir(repo)) / "v0.29.4.toml"),
        )
        assert archive.never_released is True
        assert archive.bump == "patch"
        assert git(repo, "status", "--porcelain") == ""

    def test_a_dry_run_writes_nothing(self, tmp_path, monkeypatch):
        repo = build(tmp_path, files="0.29.4")
        state_path = _stall(repo, "0.29.4")
        head = git(repo, "rev-parse", "HEAD")

        result = abandon(repo, monkeypatch, dry_run=True)

        assert result.exit_code == 0, result.stderr + result.stdout
        assert not (Path(release_record_dir(repo)) / "v0.29.4.toml").exists()
        assert (repo / ".rlsbl/releases/in-progress.json").exists()
        _untouched(repo, head)
        assert state_path in result.stdout


