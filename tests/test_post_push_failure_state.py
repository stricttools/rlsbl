# Fix 1 + Fix 5: permanent push failure exits cleanly with resume guidance
# ---------------------------------------------------------------------------


class TestPermanentPushFailureCleanExit:
    """A permanent post-TAGGED push failure exits run_cmd via SystemExit(1)
    with resume guidance and no traceback; the local tag is preserved but the
    remote never receives it, so the item is NOT observably released."""

    def test_exits_cleanly_and_remote_lacks_tag(self, tmp_path, monkeypatch, capsys):
        repo = tmp_path / "repo"
        init_repo(repo)
        # Seed an initial commit before wiring the remote so add_remote can push.
        commit_file(repo, ".gitkeep", "", "seed")
        _setup_npm_project(repo)
        add_remote(repo, tmp_path / "remote")  # pushes main + tags
        monkeypatch.chdir(repo)  # release validation (clean-tree) runs in cwd

        from rlsbl.commands.monorepo.batch_plan import PlanItem, item_is_released

        def fake_run(cmd, args=None, timeout=120, env=None, cwd=None):
            # Permanent tag-push failure (branch push goes through real
            # push_if_needed, which is NOT patched, so the branch reaches the
            # bare remote -- but the tag never does).
            if cmd == "git" and args and args[0] == "push" and len(args) > 2 \
                    and args[2].startswith("v"):
                raise subprocess.CalledProcessError(
                    1, ["git", "push", "origin", args[2]],
                    stderr="fatal: remote rejected tag",
                )
            return real_run(cmd, args=args, timeout=timeout, env=env, cwd=cwd)

        with (
            patch("rlsbl.commands.release.check_gh_installed", return_value=True),
            patch("rlsbl.commands.release.check_gh_auth", return_value=True),
            patch("rlsbl.commands.release.validate_gh_push_access"),
            patch("rlsbl.commands.release.validate_branch_and_remote",
                  return_value="main"),
            patch("rlsbl.commands.release.execute.time.sleep"),
            patch("rlsbl.commands.release.run", side_effect=fake_run),
            patch("rlsbl.commands.release.run_gh", return_value=""),
        ):
            with pytest.raises(SystemExit) as exc:
                run_cmd(_rc(), {"yes": True, "quiet": False},
                        ctx=_ctx(repo))
        assert exc.value.code == 1

        err = capsys.readouterr().err
        assert "Traceback" not in err, "must not dump a Python traceback"
        assert "rlsbl release resume" in err, "must print resume guidance"

        # The local tag exists but the remote never received it.
        assert _git_out(repo, "tag", "-l", "v1.0.1") == "v1.0.1"
        remote_tag = _git_out(repo, "ls-remote", "--tags", "origin", "v1.0.1")
        assert remote_tag == "", "remote must NOT have the tag after the failure"

        # Fix 3a interaction: an item whose live version matches the target but
        # whose tag is only local is NOT observably released.
        item = PlanItem(
            name="test-pkg", base_version="1.0.0", target_version="1.0.1",
            tag="v1.0.1", registry="npm", bump="patch",
        )
        with patch(
            "rlsbl.commands.monorepo.batch_plan.read_live_version",
            return_value="1.0.1",
        ):
            # cwd is repo (monkeypatch.chdir above): the real ls-remote runs
            # against the bare remote, which lacks the tag.
            assert not item_is_released(str(repo), item, [], "packages"), \
                "a locally-tagged-but-unpushed item is not released"


# ---------------------------------------------------------------------------
# Fix 3a: item_is_released requires the tag on the remote (real bare remote)
# ---------------------------------------------------------------------------


class TestItemReleasedRequiresRemoteTag:
    """item_is_released flips from False to True only once the tag is pushed."""

    def test_local_then_pushed_tag(self, tmp_path):
        import os

        repo = tmp_path / "repo"
        init_repo(repo)
        commit_file(repo, "README.md", "# hi\n", "initial")
        add_remote(repo, tmp_path / "remote")

        from rlsbl.commands.monorepo.batch_plan import PlanItem, item_is_released

        # Create a local tag that is NOT pushed.
        _git(repo, "tag", "pkg@v0.2.0")

        item = PlanItem(
            name="pkg", base_version="0.1.0", target_version="0.2.0",
            tag="pkg@v0.2.0", registry="pypi", bump="minor",
        )

        cwd0 = os.getcwd()
        os.chdir(str(repo))
        try:
            with patch(
                "rlsbl.commands.monorepo.batch_plan.read_live_version",
                return_value="0.2.0",
            ):
                assert not item_is_released(str(repo), item, [], "packages"), \
                    "local-only tag must not count as released"
                # Push the tag: now the remote has it.
                _git(repo, "push", "-q", "origin", "pkg@v0.2.0")
                assert item_is_released(str(repo), item, [], "packages"), \
                    "a pushed tag must count as released"
        finally:
            os.chdir(cwd0)


