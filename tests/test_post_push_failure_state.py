"""Phase 1.7 post-push failure-state tests.

Covers the gaps closed in the release push-failure flow:

- Fix 1: an expected push failure exits run_cmd cleanly (SystemExit(1), no
  traceback) with resume guidance, instead of propagating a raw exception.
- Fix 2: a transient tag-push failure that clears on the in-handler retry
  recovers -- the release falls through into GITHUB_RELEASE rather than
  aborting.
- Fix 3: a batch item is only "released" when its tag exists on the REMOTE
  (not merely tagged locally); the archive gate also refuses while any item
  has in-progress release state.
- Fix 4: the branch-push skip uses a LIVE `git ls-remote` comparison, not the
  (possibly stale) local origin/<branch> tracking ref.
"""

import json
import subprocess
from pathlib import Path
from unittest.mock import patch

import pytest

from rlsbl.commands.release import run_cmd
from rlsbl.commands.release.release_state import get_state_path, load_release_state
from rlsbl.context import ProjectContext
from rlsbl.release_file import ReleaseConfig
from rlsbl.utils import run as real_run

from githarness import init_repo, commit_file, add_remote


# ---------------------------------------------------------------------------
# Helpers
# ---------------------------------------------------------------------------


def _rc(bump="patch"):
    return ReleaseConfig(
        bump=bump, include=["npm"], exclude=[], description="test release",
    )


def _git(repo, *args):
    subprocess.run(
        ["git"] + list(args), cwd=str(repo), check=True,
        capture_output=True, text=True,
    )


def _git_out(repo, *args):
    return subprocess.run(
        ["git"] + list(args), cwd=str(repo), check=True,
        capture_output=True, text=True,
    ).stdout.strip()


def _setup_npm_project(repo):
    """An npm project at v1.0.0 with one covered unreleased commit + release file."""
    (repo / "package.json").write_text(
        json.dumps({"name": "test-pkg", "version": "1.0.0"}, indent=2) + "\n"
    )
    (repo / "CHANGELOG.md").write_text(
        "<!-- Generated by rlsbl from .rlsbl/changes/ -- do not edit -->\n\n"
        "# Changelog\n\n## 1.0.0\n\n- Initial release.\n"
    )
    changes_dir = repo / ".rlsbl" / "changes"
    changes_dir.mkdir(parents=True)
    (changes_dir / "unreleased.jsonl").write_text("")
    (repo / ".rlsbl" / "config.json").write_text(
        json.dumps({"publish_mode": "ci", "targets": ["npm"]}) + "\n"
    )
    _git(repo, "add", "package.json", "CHANGELOG.md",
         ".rlsbl/changes/unreleased.jsonl", ".rlsbl/config.json")
    _git(repo, "commit", "-q", "-m", "initial")
    _git(repo, "tag", "v1.0.0")

    (repo / "feature.txt").write_text("new feature\n")
    _git(repo, "add", "feature.txt")
    _git(repo, "commit", "-q", "-m", "add feature")
    feature_sha = _git_out(repo, "rev-parse", "HEAD")
    entry = {
        "commits": [feature_sha],
        "user_facing": True,
        "description": "**New feature.** A shiny new thing.",
        "type": "feature",
    }
    (changes_dir / "unreleased.jsonl").write_text(json.dumps(entry) + "\n")
    _git(repo, "add", ".rlsbl/changes/unreleased.jsonl")
    _git(repo, "commit", "-q", "-m", "changelog: add feature entry",
         "--trailer", "Autogenerated: true")

    releases_dir = repo / ".rlsbl" / "releases"
    releases_dir.mkdir(parents=True)
    (releases_dir / "unreleased.toml").write_text(
        'bump = "patch"\ninclude = ["npm"]\nexclude = []\n'
        'description = "test release"\n'
    )
    _git(repo, "add", ".rlsbl/releases/unreleased.toml")
    _git(repo, "commit", "-q", "-m", "add release file",
         "--trailer", "Autogenerated: true")
    return feature_sha


def _ctx(repo):
    return ProjectContext(
        project_root=Path(str(repo)), workspace_root=None,
        config={"publish_mode": "ci", "pipelines": {}},
    )


# ---------------------------------------------------------------------------
# Fix 2: transient tag-push retry success reaches GITHUB_RELEASE
# ---------------------------------------------------------------------------


class TestTransientTagPushRetrySuccess:
    """A post-TAGGED tag-push failure that clears on the in-handler retry must
    recover and continue into GITHUB_RELEASE, not abort with resume guidance."""

    def test_transient_retry_reaches_github_release(self, mock_git_repo):
        _setup_npm_project(mock_git_repo)

        gh_calls = []
        tag_push_attempts = []

        def fake_run(cmd, args=None, timeout=120, env=None, cwd=None):
            if cmd == "git" and args and args[0] == "push" and len(args) > 2 \
                    and args[2].startswith("v"):
                tag_push_attempts.append(list(args))
                # Fail the first attempt only; the in-handler retry succeeds.
                if len(tag_push_attempts) == 1:
                    raise subprocess.CalledProcessError(
                        1, ["git", "push", "origin", args[2]],
                        stderr="fatal: transient network blip",
                    )
                return ""
            return real_run(cmd, args=args, timeout=timeout, env=env, cwd=cwd)

        def fake_run_gh(gh_args, **kwargs):
            gh_calls.append(list(gh_args))
            # gh release view fails -> creation proceeds -> GITHUB_RELEASE.
            if gh_args[:2] == ["release", "view"]:
                raise subprocess.CalledProcessError(1, "gh release view")
            return ""

        with (
            patch("rlsbl.commands.release.check_gh_installed", return_value=True),
            patch("rlsbl.commands.release.check_gh_auth", return_value=True),
            patch("rlsbl.commands.release.validate_gh_push_access"),
            patch("rlsbl.commands.release.validate_branch_and_remote",
                  return_value="main"),
            patch("rlsbl.commands.release.push_if_needed"),  # branch push OK
            patch("rlsbl.commands.release.tag_exists_on_remote",
                  return_value=False),  # tag not yet on remote -> push attempted
            patch("rlsbl.commands.release.execute.time.sleep"),  # no retry delay
            patch("rlsbl.commands.release.run", side_effect=fake_run),
            patch("rlsbl.commands.release.run_gh", side_effect=fake_run_gh),
        ):
            # No SystemExit: the recovered push falls through to completion.
            run_cmd(_rc(), {"yes": True, "quiet": True}, ctx=_ctx(mock_git_repo))

        assert len(tag_push_attempts) >= 2, \
            "the tag push must be retried after the transient failure"
        assert any(c[:2] == ["release", "create"] for c in gh_calls), \
            "recovery must fall through into GitHub Release creation"

        # A fully-completed release clears its state file.
        assert not load_release_state(get_state_path(str(mock_git_repo))), \
            "state must be cleared after the recovered release completes"


# ---------------------------------------------------------------------------
# Fix 4: branch-push skip uses a live ls-remote comparison
# ---------------------------------------------------------------------------


class TestLiveLsRemoteBranchSkip:
    """The branch push is skipped when a LIVE ls-remote shows the remote is
    already at the local HEAD -- even if the local origin/<branch> tracking
    ref is stale/absent (which is what the old rev-parse check relied on)."""

    def test_branch_push_skipped_via_live_ls_remote(self, mock_git_repo, capsys):
        _setup_npm_project(mock_git_repo)

        push_if_needed_called = []

        def fake_run(cmd, args=None, timeout=120, env=None, cwd=None):
            # Model the live remote as already at local HEAD: ls-remote of the
            # branch ref returns the current HEAD sha. (The old code queried the
            # local origin/<branch> tracking ref, which does not exist here, so
            # it would NOT skip -> this asserts the new live-query behavior.)
            if cmd == "git" and args and args[0] == "ls-remote" \
                    and len(args) >= 3 and args[2].startswith("refs/heads/"):
                head = real_run("git", ["rev-parse", "HEAD"]).strip()
                return f"{head}\t{args[2]}"
            return real_run(cmd, args=args, timeout=timeout, env=env, cwd=cwd)

        def fake_push_if_needed(branch, env=None, *, config):
            push_if_needed_called.append(branch)

        with (
            patch("rlsbl.commands.release.check_gh_installed", return_value=True),
            patch("rlsbl.commands.release.check_gh_auth", return_value=True),
            patch("rlsbl.commands.release.validate_gh_push_access"),
            patch("rlsbl.commands.release.validate_branch_and_remote",
                  return_value="main"),
            patch("rlsbl.commands.release.push_if_needed",
                  side_effect=fake_push_if_needed),
            patch("rlsbl.commands.release.tag_exists_on_remote",
                  return_value=True),  # tag already on remote -> tag push skipped
            patch("rlsbl.commands.release.run", side_effect=fake_run),
            patch("rlsbl.commands.release.run_gh", return_value=""),
        ):
            run_cmd(_rc(), {"yes": True, "quiet": False}, ctx=_ctx(mock_git_repo))

        assert push_if_needed_called == [], \
            "branch push must be skipped when the live remote is at local HEAD"
        assert "Skipping branch push (remote already at local HEAD)" \
            in capsys.readouterr().out


