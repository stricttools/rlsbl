# Fix 3b: archive gate refuses while any item has in-progress state
# ---------------------------------------------------------------------------


class TestArchiveRefusedWithInProgressState:
    """_archive_batch_if_complete must not finalize the batch file while any
    plan item still has an in-progress.json on disk."""

    def test_in_progress_state_blocks_archive(self, tmp_path):
        import os

        from rlsbl.commands.monorepo.batch_plan import BatchPlan, PlanItem
        from rlsbl.commands.monorepo.batch_release import (
            _archive_batch_if_complete, _plan_items_in_progress,
        )

        ws = tmp_path / "ws"
        pkg_dir = ws / "packages" / "alpha"
        (pkg_dir / ".rlsbl" / "releases").mkdir(parents=True)
        # Write an in-progress.json for alpha.
        (pkg_dir / ".rlsbl" / "releases" / "in-progress.json").write_text(
            json.dumps({"new_version": "0.2.0", "completed_steps": ["TAGGED"]})
        )

        projects = [{"name": "alpha", "path": "packages/alpha"}]
        plan = BatchPlan(
            section_type="packages",
            items={
                "alpha": PlanItem(
                    "alpha", "0.1.0", "0.2.0", "alpha@v0.2.0", "pypi", "minor",
                ),
            },
        )

        stranded = _plan_items_in_progress(plan, str(ws), projects)
        assert stranded == ["alpha"]

        batch_path = ws / ".rlsbl-monorepo" / "releases" / "unreleased.toml"
        batch_path.parent.mkdir(parents=True)
        batch_path.write_text("[packages.alpha]\nbump = \"minor\"\n")

        logs = []
        # plan_all_released short-circuits on the (missing) remote tag, so patch
        # it True to isolate the in-progress guard as the reason for refusal.
        with patch(
            "rlsbl.commands.monorepo.batch_release.plan_all_released",
            return_value=True,
        ):
            _archive_batch_if_complete(
                str(batch_path), plan, str(ws), projects, logs.append,
            )

        assert batch_path.exists(), \
            "batch file must NOT be archived while an item is in-progress"
        assert any("in-progress release state exists" in m for m in logs)
