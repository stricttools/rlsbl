const monorepoCleanupHelp = "Remove the old layout's release-state residue through saferm, which keeps an audit trail and can undo a deletion: " +
	"every .rlsbl/ directory (at the root, at a member's path, or anywhere a tracked file lies in one), .rlsbl-monorepo/, a versioned member's " +
	"own CHANGELOG.md in a workspace (its releasable's changelog is generated under .strictmetadata/changelog/), and the changelog validation " +
	"cache of a name no releasable is declared as. The changelog and release directories of an undeclared name are never removed: they are the " +
	"record of what that subject released, and are listed as kept. The removal of what git tracked is committed with the Autogenerated trailer " +
	"unless --no-auto-commit is passed. The residue is what the releasable-residue check reports. Under --dry-run the removals are listed and " +
	"nothing is removed. It works in a standalone repository too, whose old-layout .rlsbl/ is residue as well."

const monorepoRenameHelp = "Rename a releasable. Its [[releasables]] name and every member's releasable field are rewritten in place in " +
	"releasables.toml; its changelog, release, and run-state directories move to the new name; a file at its reserved changelog validation " +
	"cache path (which no rlsbl command writes) is removed through saferm when one is there; in the lifecycle-and-license record every open lifecycle period, license period, and identity of the old name is closed on today's " +
	"date and opened again under the new name, the releasable-name identity taking the new name and each identity the tag namespace the new name " +
	"renders; and the workspace's routers are regenerated. All of it is one commit, without the Autogenerated trailer, so changelog coverage " +
	"decides whether it needs an entry, and when it does the closing message prints the `rlsbl changelog add` line for it. When the tag format " +
	"holds {name}, the tags change spelling: each past release's archive records the tag it shipped under (shipped_as) where that tag stands at " +
	"its release commit, committed with the Autogenerated trailer; and the current version's tag under the new name is created at the commit of " +
	"its tag under the old name, recorded as a boundary alias in the transition record, and pushed to origin, the one remote write. Refused " +
	"before anything is written: a new name that is declared, a member's name, or holds another subject's state; uncommitted changes; a release " +
	"or batch release in progress; a batch release file naming the old releasable; a record without the releasable's open releasable-name " +
	"identity, or with a pending identity of it. A run whose declarations already name the new releasable and not the old completes an " +
	"interrupted rename, doing only what is left. Use --dry-run to print the plan."

func registerMonorepoMaintenance(r *commandSet) {
	r.add(command{
		path:   []string{"monorepo", "cleanup"},
		help:   monorepoCleanupHelp,
		effect: mutating,
		flags: []strictcli.Flag{
			strictcli.BoolFlag("auto-commit", "Commit the removals (committed when neither --auto-commit nor --no-auto-commit is passed)", strictcli.Optional()),
		},
		payload: cleanupPayloadSchema(),
		render:  renderCleanup,
		run:     runMonorepoCleanup,
	})
	r.add(command{
		path:          []string{"monorepo", "rename-releasable"},
		help:          monorepoRenameHelp,
		effect:        mutating,
		consequential: true,
		args: []strictcli.Arg{
			strictcli.NewArg("old_name", "The releasable's name now", strictcli.ArgRequired()),
			strictcli.NewArg("new_name", "The name it takes", strictcli.ArgRequired()),
		},
		run: runMonorepoRename,
	})
}

// runMonorepoCleanup removes the residue of a workspace or of a standalone
// repository: the old layout's .rlsbl/ of a standalone repository is
// residue too, which releasable-residue reports with this command as its
// fix.
func runMonorepoCleanup(ctx *strictcli.Context, kw map[string]any) (any, error) {
	dir, err := os.Getwd()
	if err != nil {
		return nil, err
	}
	ws, err := workspace.Discover(dir)
	if err != nil {
		return nil, err
	}
	repo, err := git.Open(ctx.Effects(), ws.Root)
	if err != nil {
		return nil, err
	}
	return monorepo.RunCleanup(ctx.Effects(), repo, ws, optionalBool(kw, "auto_commit", true), ctx.DryRun())
}

func cleanupPayloadSchema() map[string]any {
	entry := objectSchema(map[string]any{"path": stringSchema(), "directory": booleanSchema(), "reason": stringSchema()})
	return objectSchema(map[string]any{
		"removed":   arraySchema(entry),
		"kept":      arraySchema(entry),
		"committed": booleanSchema(),
		"dry_run":   booleanSchema(),
	})
}

func renderCleanup(payload any) string {
	p, err := decodePayload[monorepo.Cleanup](payload)
	if err != nil {
		return renderJSON(payload)
	}
	var lines []string
	if len(p.Removed) == 0 {
		lines = append(lines, "No residue to remove.")
	}
	verb := "Removed"
	if p.DryRun {
		verb = "Would remove"
	}
	for _, r := range p.Removed {
		lines = append(lines, fmt.Sprintf("%s %s: %s", verb, r.Path, r.Reason))
	}
	for _, r := range p.Kept {
		lines = append(lines, fmt.Sprintf("Kept %s: %s", r.Path, r.Reason))
	}
	if p.Committed {
		lines = append(lines, "Committed: "+monorepo.CleanupCommitMessage)
	} else if len(p.Removed) > 0 && !p.DryRun {
		lines = append(lines, "Nothing was committed.")
	}
	return strings.Join(lines, "\n")
}

func runMonorepoRename(ctx *strictcli.Context, kw map[string]any) (any, error) {
	_, repo, ws, err := loadMonorepoWorkspace(ctx, "rename-releasable")
	if err != nil {
		return nil, err
	}
	gh, err := github.New(ctx.Effects())
	if err != nil {
		return nil, err
	}
	actions, err := scaffold.ActionVersions()
	if err != nil {
		return nil, err
	}
	now := time.Now()
	old, new := strictcli.Get[string](kw, "old_name"), strictcli.Get[string](kw, "new_name")
	out, err := monorepo.RenameReleasable(ctx.Effects(), repo, ws, monorepo.RenameRequest{
		Old:    old,
		New:    new,
		DryRun: ctx.DryRun(),
		Now:    now,
		Say:    ctx.Out,
		Sync: func(renamed *workspace.Workspace) (workflows.SyncResult, error) {
			return workflows.Sync(ctx.Effects(), renamed, workflows.SyncInputs{
				Actions: actions,
				RootPublishWorkflow: func(root declarations.Member) (string, error) {
					return scaffold.MemberPublishWorkflow(ctx.Effects(), renamed, root, gh, now)
				},
			})
		},
	})
	if err != nil || ctx.DryRun() {
		return nil, err
	}
	renamed, err := workspace.Load(ws.Root)
	if err != nil {
		return nil, err
	}
	for _, line := range monorepo.RenameClosing(renamed, old, new, out) {
		ctx.Out(line)
	}
	return nil, nil
}
