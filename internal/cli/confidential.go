const confidentialGroupHelp = "Resolve the confidential-term hits of what this repository publishes. The confidential-term list " +
	"(" + confidential.ListRel + " under the home directory, encrypted with age to the identity in ~/" + confidential.IdentityRel + ", " +
	"and decrypted in memory only; a missing list has no terms) names terms that must not appear in anything public. A release " +
	"(and selfdoc's publishing) scans what it would push or publish, reports every hit at once, each with an id, its location, and " +
	"the text around it, and refuses while a hit has no resolution in .strictmetadata/confidential-hits/resolutions.toml. Each hit " +
	"is judged by the agent: one it is at least 70% certain is a false positive is recorded with judge-false-positive; every other " +
	"one goes to the owner, who has the text fixed or approves publishing it with approve-hit. The release records the resolutions " +
	"it used in the version's release archive. A hit id names the list entry, the matched text, and the words after it, so the same " +
	"phrase has the same id wherever it appears, and a resolution resolves it everywhere. The `confidential-terms` check reports " +
	"the hits of the next push."

const judgeFalsePositiveHelp = "Record the agent's judgment that a confidential-term hit is a false positive, in " +
	".strictmetadata/confidential-hits/resolutions.toml, and commit it with the Autogenerated trailer. --hit names a hit the " +
	"next push or a tracked file of this repository carries (the ids the confidential-terms check and the release's refusal " +
	"print); any other id is refused, naming the hits there are. --certainty is how certain, in percent, the agent is that the " +
	"hit is not confidential, from 70 to 100: a hit judged less certain is the owner's to resolve, with approve-hit or a fix. " +
	"--reason is one line, and is refused when it carries a confidential term, since the file is committed. The recorded " +
	"location has every confidential match redacted. A hit resolved already is refused."

const approveHitHelp = "Record the owner's approval to publish a confidential-term hit anyway, in " +
	".strictmetadata/confidential-hits/resolutions.toml, and commit it with the Autogenerated trailer. Only the owner approves " +
	"a hit: pass --approve-consequential only when the owner approved this specific hit, and give the owner's own reason in " +
	"--reason (one line, refused when it carries a confidential term, since the file is committed). --hit names a hit the next " +
	"push or a tracked file of this repository carries; any other id is refused, naming the hits there are. A hit resolved " +
	"already is refused."

func registerConfidential(r *commandSet) {
	r.group([]string{"confidential"}, confidentialGroupHelp)
	hit := strictcli.StringFlag("hit", "The hit's id, as the confidential-terms check and the release's refusal print it", strictcli.Required())
	r.add(command{
		path:   []string{"confidential", "judge-false-positive"},
		help:   judgeFalsePositiveHelp,
		effect: mutating,
		flags: []strictcli.Flag{
			hit,
			strictcli.IntFlag("certainty", fmt.Sprintf("How certain, in percent, the agent is that the hit is a false positive: %d to 100", confidential.MinimumCertainty), strictcli.Required()),
			strictcli.StringFlag("reason", "Why the hit is not confidential, in one line without the term", strictcli.Required()),
		},
		run: func(ctx *strictcli.Context, kw map[string]any) (any, error) {
			if err := requireNonEmpty(kw, "hit", "reason"); err != nil {
				return nil, err
			}
			return nil, resolveHit(ctx, strictcli.Get[string](kw, "hit"), func(m *confidential.Matcher, h confidential.Hit, on time.Time) (confidential.Resolution, error) {
				return confidential.NewFalsePositive(m, h, strictcli.Get[int](kw, "certainty"), strictcli.Get[string](kw, "reason"), on)
			})
		},
	})
	r.add(command{
		path:   []string{"confidential", "approve-hit"},
		help:   approveHitHelp,
		effect: mutating,
		// Publishing a confidential term is the owner's call alone.
		consequential: true,
		flags: []strictcli.Flag{
			hit,
			strictcli.StringFlag("reason", "The owner's reason for publishing the hit, in one line without the term", strictcli.Required()),
		},
		run: func(ctx *strictcli.Context, kw map[string]any) (any, error) {
			if err := requireNonEmpty(kw, "hit", "reason"); err != nil {
				return nil, err
			}
			return nil, resolveHit(ctx, strictcli.Get[string](kw, "hit"), func(m *confidential.Matcher, h confidential.Hit, on time.Time) (confidential.Resolution, error) {
				return confidential.NewApproval(m, h, strictcli.Get[string](kw, "reason"), on)
			})
		},
	})
}

// resolveHit records the resolution build makes for the hit id names, among
// the hits a resolution may name (checks.ResolvableHits), and commits it.
func resolveHit(ctx *strictcli.Context, id string, build func(*confidential.Matcher, confidential.Hit, time.Time) (confidential.Resolution, error)) error {
	if !confidential.ValidID(id) {
		return fmt.Errorf("--hit %q is not a hit id (%d lowercase hexadecimal digits, as the confidential-terms check prints them)", id, confidential.IDLength)
	}
	dir, err := os.Getwd()
	if err != nil {
		return err
	}
	termList, err := confidential.DefaultLocation()
	if err != nil {
		return err
	}
	now := time.Now()
	c, err := checks.NewContext(ctx.Effects(), checks.Inputs{Dir: dir, Now: now, TermList: termList})
	if err != nil {
		return err
	}
	scanner, hits, err := checks.ResolvableHits(c)
	if err != nil {
		return err
	}
	if !scanner.Active() {
		return fmt.Errorf("the repository is confidential (its lifecycle-and-license record holds a proprietary license in effect), so nothing it carries is scanned and there is no hit to resolve")
	}
	var found *confidential.Hit
	ids := map[string]bool{}
	for i, h := range hits {
		ids[h.ID] = true
		if h.ID == id && found == nil {
			found = &hits[i]
		}
	}
	if found == nil {
		if len(ids) == 0 {
			return fmt.Errorf("no hit %s: the next push and the tracked files carry no confidential-term hit (%s)", id, scanner.Status())
		}
		known := make([]string, 0, len(ids))
		for k := range ids {
			known = append(known, k)
		}
		sort.Strings(known)
		return fmt.Errorf("no hit %s: the hits the next push and the tracked files carry are %s; run `rlsbl check --name confidential-terms` for the next push's, with their locations", id, strings.Join(known, ", "))
	}
	resolution, err := build(scanner.Matcher(), *found, now)
	if err != nil {
		return err
	}
	root := c.Root()
	if err := confidential.AddResolution(effectsStoreWriter{ctx.Effects()}, root, scanner.Resolutions(), resolution); err != nil {
		return err
	}
	repo, err := git.Open(ctx.Effects(), root)
	if err != nil {
		return err
	}
	message := fmt.Sprintf("confidential: record the %s of hit %s", resolution.Decision, id)
	if ctx.DryRun() {
		ctx.Out(fmt.Sprintf("Would record hit %s as %s at %s, and commit %s", id, resolution.Decision, resolution.Location, confidential.StoreFile))
		return nil
	}
	if _, err := repo.Commit(git.CommitRequest{Message: message, Paths: []string{confidential.StoreFile, confidential.StoreManifest}, Autogenerated: true, RequireChange: true}); err != nil {
		return fmt.Errorf("%s is written but not committed: %w", confidential.StoreFile, err)
	}
	ctx.Out(fmt.Sprintf("Recorded hit %s as %s at %s, and committed %s", id, resolution.Decision, resolution.Location, confidential.StoreFile))
	return nil
}

// effectsStoreWriter writes the resolutions through the effects handle, so
// --dry-run records the writes instead of making them.
type effectsStoreWriter struct{ e *strictcli.Effects }

func (w effectsStoreWriter) WriteFile(path string, data []byte) error {
	_, err := w.e.Write(path, data)
	return err
}

func (w effectsStoreWriter) MkdirAll(path string) error {
	_, err := w.e.Mkdir(path)
	return err
}
