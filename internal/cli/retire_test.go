// gadgetHook is gadget's post-release hook script.
const gadgetHook = ".strictmetadata/release-hooks/gadget/post-release.sh"

// retireFixture is monorepoFixture with the record, a post-release hook
// for gadget, each member's own CI routed by a synced router, gadget's
// released history, and a scaffold state managing both members' CI files.
// gadget's package.json no longer depends on widget.
func retireFixture(t *testing.T) *testsupport.Repo {
	t.Helper()
	repo := monorepoFixture(t)
	decls := strings.Replace(monorepoWorkspace, "name = \"gadget\"\ntag_format = \"{name}@v{version}\"\npublish_mode = \"none\"\n",
		"name = \"gadget\"\ntag_format = \"{name}@v{version}\"\npublish_mode = \"none\"\nhooks = { post_release = [\"bash ../../"+gadgetHook+"\"] }\n", 1)
	files := map[string]string{
		declarations.ReleasablesFile:                         decls,
		"apps/gadget/package.json":                           "{\n  \"name\": \"gadget\",\n  \"version\": \"0.2.0\"\n}\n",
		lifecycle.RecordFile:                                 widgetAndGadgetRecord,
		lifecycle.ManifestFile:                               "owner = \"strictspec\"\n",
		gadgetHook:                                           "#!/usr/bin/env bash\necho released\n",
		"packages/widget/.github/workflows/ci.yml":           widgetCI,
		"apps/gadget/.github/workflows/ci.yml":               widgetCI,
		declarations.ChangelogDir("gadget") + "/0.2.0.jsonl": "",
		declarations.ReleasesDir("gadget") + "/v0.2.0.toml":  "",
	}
	state := scaffold.State{RlsblVersion: "0.131.0", Files: map[string]string{}}
	for _, p := range []string{"packages/widget/.github/workflows/ci.yml", "apps/gadget/.github/workflows/ci.yml"} {
		state.Files[p] = scaffold.FileHash([]byte(widgetCI))
		files[scaffold.BasePath(p)] = widgetCI
	}
	files[declarations.ScaffoldStateFile] = scaffold.RenderState(state)
	var paths []string
	for rel, content := range files {
		repo.Write(rel, content)
		paths = append(paths, rel)
	}
	repo.Commit("the retirement fixture", paths...)
	app := appWith(t, testsupport.NewFakeHTTP(t))
	if r := app.Test([]string{"monorepo", "sync", "--auto-commit"}); r.ExitCode != 0 {
		t.Fatalf("the sync: exit %d\n%s%s", r.ExitCode, r.Stdout, r.Stderr)
	}
	return repo
}

// The retirement checks: each passes once a releasable is retired and gone
// from the declarations, its history left in place.
var retirementChecks = []string{"releasable-residue", "workspace-ci-router", "workspace-ci-synced", "router-filters-fresh", "lifecycle-record-valid"}

func TestRetiringAReleasableTakesItOutOfTheWorkspaceInOneCommit(t *testing.T) {
	hygiene.Isolate(t)
	testsupport.FakeSafegit(t)
	testsupport.FakeDeletingSaferm(t)
	repo := retireFixture(t)
	app := appWith(t, testsupport.NewFakeHTTP(t))
	if !strings.Contains(readFile(t, repo, ".github/workflows/ci-router.yml"), "apps/gadget") {
		t.Fatal("the fixture's router does not route gadget")
	}
	before := repo.Head()
	r := app.Test([]string{"transition", "lifecycle", "--subject", "gadget", "--status", "retired", "--reason", "the owner ruled gadget deleted", "--approve-consequential"})
	if r.ExitCode != 0 {
		t.Fatalf("exit %d\n%s%s", r.ExitCode, r.Stdout, r.Stderr)
	}
	if n := repo.Git("rev-list", "--count", before+"..HEAD"); n != "1" {
		t.Fatalf("the retirement made %s commits, want one", n)
	}
	if got := repo.Git("log", "-1", "--format=%s%x00%(trailers:key=Autogenerated,valueonly)"); !strings.HasPrefix(got, "transition: gadget is retired\x00true") {
		t.Fatalf("the commit is %q", got)
	}
	if status := repo.Git("status", "--porcelain"); status != "" {
		t.Fatalf("the retirement left changes uncommitted:\n%s", status)
	}

	ws, err := declarations.Load(repo.Dir)
	if err != nil {
		t.Fatal(err)
	}
	if _, ok := ws.Releasable("gadget"); ok {
		t.Error("gadget is still a declared releasable")
	}
	if _, ok := ws.Member("gadget"); ok {
		t.Error("gadget is still a declared member")
	}
	if _, ok := ws.Member("widget"); !ok {
		t.Error("widget left the declarations too")
	}
	rec, err := lifecycle.Load(repo.Dir)
	if err != nil {
		t.Fatal(err)
	}
	var retired bool
	for _, l := range rec.Lifecycle() {
		retired = retired || (l.Subject == "gadget" && l.Status == lifecycle.StatusRetired && l.Open())
	}
	if !retired {
		t.Errorf("gadget has no open retired period: %+v", rec.Lifecycle())
	}
	for _, id := range rec.Identities() {
		if id.Subject == "gadget" && id.Open() {
			t.Errorf("gadget's identity %+v is still open, so its tags are not accounted for", id)
		}
		if id.Subject == "widget" && !id.Open() {
			t.Errorf("widget's identity %+v was closed", id)
		}
	}
	for _, gone := range []string{gadgetHook, scaffold.BasePath("apps/gadget/.github/workflows/ci.yml")} {
		if _, err := os.Stat(repo.Path(gone)); err == nil {
			t.Errorf("%s is still there", gone)
		}
	}
	for _, kept := range []string{declarations.ChangelogDir("gadget") + "/0.2.0.jsonl", declarations.ReleasesDir("gadget") + "/v0.2.0.toml", "apps/gadget/package.json", scaffold.BasePath("packages/widget/.github/workflows/ci.yml")} {
		if _, err := os.Stat(repo.Path(kept)); err != nil {
			t.Errorf("%s is gone: %v", kept, err)
		}
	}
	state := readFile(t, repo, declarations.ScaffoldStateFile)
	if strings.Contains(state, "apps/gadget") || !strings.Contains(state, "packages/widget") {
		t.Errorf("the scaffold state is\n%s", state)
	}
	if router := readFile(t, repo, ".github/workflows/ci-router.yml"); strings.Contains(router, "gadget") {
		t.Errorf("the router still mentions gadget:\n%s", router)
	}
	for _, name := range retirementChecks {
		mustCheckStatus(t, app, name, "pass")
	}
}

func TestADryRunOfARetirementWritesNothing(t *testing.T) {
	hygiene.Isolate(t)
	testsupport.FakeSafegit(t)
	testsupport.FakeDeletingSaferm(t)
	repo := retireFixture(t)
	app := appWith(t, testsupport.NewFakeHTTP(t))
	before := repo.Head()
	r := app.Test([]string{"transition", "lifecycle", "--subject", "gadget", "--status", "retired", "--reason", "the owner ruled gadget deleted", "--dry-run"})
	if r.ExitCode != 0 {
		t.Fatalf("exit %d\n%s%s", r.ExitCode, r.Stdout, r.Stderr)
	}
	if !strings.Contains(r.Stdout, "Would record gadget as retired") || !strings.Contains(r.Stdout, "take it out of the declarations") {
		t.Fatalf("the preview says:\n%s", r.Stdout)
	}
	if repo.Head() != before || repo.Git("status", "--porcelain") != "" {
		t.Fatal("the dry run wrote or committed")
	}
}

func TestRetiringAReleasableAnotherMemberDependsOnIsRefusedUntilTheDependencyIsSevered(t *testing.T) {
	hygiene.Isolate(t)
	testsupport.FakeSafegit(t)
	testsupport.FakeDeletingSaferm(t)
	repo := retireFixture(t)
	repo.CommitFile("apps/gadget/package.json", "{\n  \"name\": \"gadget\",\n  \"version\": \"0.2.0\",\n  \"dependencies\": {\"widget\": \"^0.1.0\"}\n}\n", "gadget depends on widget")
	app := appWith(t, testsupport.NewFakeHTTP(t))
	retire := []string{"transition", "lifecycle", "--subject", "widget", "--status", "retired", "--reason", "the owner ruled widget deleted", "--approve-consequential"}
	before := repo.Head()
	r := app.Test(retire)
	if r.ExitCode == 0 || !strings.Contains(r.Stderr, `"gadget" depends on "widget"`) || !strings.Contains(r.Stderr, "apps/gadget/package.json") {
		t.Fatalf("exit %d\n%s%s", r.ExitCode, r.Stdout, r.Stderr)
	}
	if repo.Head() != before || repo.Git("status", "--porcelain") != "" {
		t.Fatal("the refusal wrote or committed")
	}
	repo.CommitFile("apps/gadget/package.json", "{\n  \"name\": \"gadget\",\n  \"version\": \"0.2.0\"\n}\n", "gadget no longer depends on widget")
	if r := app.Test(retire); r.ExitCode != 0 {
		t.Fatalf("after severing: exit %d\n%s%s", r.ExitCode, r.Stdout, r.Stderr)
	}
}

