// retireGadget is the retirement of gadget, approved.
var retireGadget = []string{"transition", "lifecycle", "--subject", "gadget", "--status", "retired", "--reason", "the owner ruled gadget deleted", "--approve-consequential"}

// mustRefuseThenRetire runs retireGadget, which must be refused with every
// one of wants and write nothing, performs fix, and runs it again, which
// must retire gadget.
func mustRefuseThenRetire(t *testing.T, repo *testsupport.Repo, fix func(), wants ...string) {
	t.Helper()
	app := appWith(t, testsupport.NewFakeHTTP(t))
	before := repo.Head()
	status := repo.Git("status", "--porcelain")
	r := app.Test(retireGadget)
	if r.ExitCode == 0 {
		t.Fatalf("the retirement was not refused:\n%s", r.Stdout)
	}
	for _, want := range wants {
		if !strings.Contains(r.Stderr, want) {
			t.Fatalf("the refusal lacks %q:\n%s", want, r.Stderr)
		}
	}
	if repo.Head() != before || repo.Git("status", "--porcelain") != status {
		t.Fatal("the refusal wrote or committed")
	}
	fix()
	if r := app.Test(retireGadget); r.ExitCode != 0 {
		t.Fatalf("the retirement after the fix: exit %d\n%s%s", r.ExitCode, r.Stdout, r.Stderr)
	}
}

func TestRetiringWithAnUncommittedChangeToAPathItWritesIsRefusedUntilItIsCommitted(t *testing.T) {
	hygiene.Isolate(t)
	testsupport.FakeSafegit(t)
	testsupport.FakeDeletingSaferm(t)
	repo := retireFixture(t)
	repo.Write(gadgetHook, "#!/usr/bin/env bash\necho edited\n")
	mustRefuseThenRetire(t, repo, func() {
		repo.Commit("the edited hook", gadgetHook)
	}, "uncommitted changes", gadgetHook, "commit or revert them first")
}

func TestRetiringWithAnOptionsEntryScopedToALeavingMemberIsRefusedUntilTheEntryIsDeleted(t *testing.T) {
	hygiene.Isolate(t)
	testsupport.FakeSafegit(t)
	testsupport.FakeDeletingSaferm(t)
	repo := retireFixture(t)
	app := appWith(t, testsupport.NewFakeHTTP(t))
	if r := app.Test([]string{"options", "set", "rlsbl:dep-floors", "--current", "error", "--ideal", "error", "--reason", "gadget polices its floors", "--scope", "apps/gadget", "--auto-commit"}); r.ExitCode != 0 {
		t.Fatalf("options set: exit %d\n%s%s", r.ExitCode, r.Stdout, r.Stderr)
	}
	mustRefuseThenRetire(t, repo, func() {
		repo.Git("rm", "-r", "-q", ".strictmetadata/options")
		repo.Git("commit", "-q", "-m", "drop the entry")
	}, "scoped to a member of the releasable \"gadget\"", "apps/gadget", "Delete each entry from its document")
}

// Routers the workspace without the releasable cannot regenerate refuse
// the retirement before anything is written.
func TestRetiringIsRefusedBeforeAnyWriteWhenTheRoutersCannotBeRegenerated(t *testing.T) {
	hygiene.Isolate(t)
	testsupport.FakeSafegit(t)
	testsupport.FakeDeletingSaferm(t)
	repo := retireFixture(t)
	repo.CommitFile("packages/widget/.github/workflows/ci.yml", "jobs: [unclosed\n", "widget's CI does not parse")
	mustRefuseThenRetire(t, repo, func() {
		repo.CommitFile("packages/widget/.github/workflows/ci.yml", widgetCI, "widget's CI parses")
	}, "regenerates the workspace's routers without it", "nothing was written")
}

func TestRetiringAReleasableHoldingTheRootMemberIsRefusedUntilTheRootIsADevNode(t *testing.T) {
	hygiene.Isolate(t)
	testsupport.FakeSafegit(t)
	testsupport.FakeDeletingSaferm(t)
	repo := retireFixture(t)
	rooted := strings.Replace(readFile(t, repo, declarations.ReleasablesFile), "name = \"root\"\ndev_only = true\nreleasable = false\n", "name = \"root\"\nreleasable = \"gadget\"\n", 1)
	repo.CommitFile(declarations.ReleasablesFile, rooted, "the root member is gadget's")
	mustRefuseThenRetire(t, repo, func() {
		repo.CommitFile(declarations.ReleasablesFile, strings.Replace(rooted, "name = \"root\"\nreleasable = \"gadget\"\n", "name = \"root\"\nreleasable = false\ndev_only = true\n", 1), "the root member is a dev node")
	}, "holds the root member", "Make the root member a dev node")
}

func readFile(t *testing.T, repo *testsupport.Repo, rel string) string {
	t.Helper()
	data, err := os.ReadFile(repo.Path(rel))
	if err != nil {
		t.Fatal(err)
	}
	return string(data)
}
