func TestOptionsRegistryPrintsTheShippedDocument(t *testing.T) {
	hygiene.Isolate(t)
	reg, err := options.Shipped()
	if err != nil {
		t.Fatal(err)
	}
	r := appWith(t, testsupport.NewFakeHTTP(t)).Test([]string{"options", "registry"})
	if r.ExitCode != 0 || strings.TrimSuffix(r.Stdout, "\n") != strings.TrimSuffix(string(reg.Document()), "\n") {
		t.Fatalf("exit %d:\n%s%s", r.ExitCode, r.Stdout, r.Stderr)
	}
}

func TestOptionsRegistryJSONCarriesTheDeclarations(t *testing.T) {
	hygiene.Isolate(t)
	reg, err := options.Shipped()
	if err != nil {
		t.Fatal(err)
	}
	r := appWith(t, testsupport.NewFakeHTTP(t)).Test([]string{"options", "registry", "--json"})
	if r.ExitCode != 0 {
		t.Fatalf("exit %d:\n%s", r.ExitCode, r.Stderr)
	}
	p := jsonPayload(t, r)
	if p["format_version"].(float64) != 2 {
		t.Fatalf("format_version %v", p["format_version"])
	}
	declared := p["option"].([]any)
	if len(declared) != len(reg.Names()) {
		t.Fatalf("%d options in the payload, %d in the registry", len(declared), len(reg.Names()))
	}
	found := false
	for _, o := range declared {
		d := o.(map[string]any)
		if d["name"] == options.EcosystemTagging {
			found = d["values"] == "on > off" && d["default"] == "on" && d["subject"] == "project"
		}
	}
	if !found {
		t.Fatalf("ecosystem-tagging is not declared as registered: %v", declared)
	}
}

// optionsRepository is a repository with no release declarations, the
// working directory for the rest of the test, with safegit faked.
func optionsRepository(t *testing.T) *testsupport.Repo {
	t.Helper()
	testsupport.FakeSafegit(t)
	repo := testsupport.NewRepo(t)
	repo.CommitFile("README.md", "portal\n", "first")
	hygiene.Chdir(t, repo.Dir)
	return repo
}

func readText(t *testing.T, path string) string {
	t.Helper()
	data, err := os.ReadFile(path)
	if err != nil {
		t.Fatal(err)
	}
	return string(data)
}

func TestOptionsSetCreatesTheDocumentAndManifestAndCommits(t *testing.T) {
	hygiene.Isolate(t)
	repo := optionsRepository(t)
	r := appWith(t, testsupport.NewFakeHTTP(t)).Test([]string{"options", "set", "rlsbl:ecosystem-tagging", "--current", "off", "--ideal", "on", "--reason", "the topic is added once the repository is public"})
	if r.ExitCode != 0 || !strings.Contains(r.Stdout, "Created rlsbl:ecosystem-tagging in .strictmetadata/options/project.toml: current off, ideal on") || !strings.Contains(r.Stdout, "Committed.") {
		t.Fatalf("exit %d:\n%s%s", r.ExitCode, r.Stdout, r.Stderr)
	}
	doc := readText(t, repo.Path(".strictmetadata/options/project.toml"))
	if !strings.Contains(doc, "id = \"rlsbl:ecosystem-tagging\"\ncurrent = \"off\"\nideal = \"on\"") {
		t.Fatalf("project.toml:\n%s", doc)
	}
	if got := readText(t, repo.Path(".strictmetadata/options/manifest.toml")); got != "owner = \"strictspec\"\n" {
		t.Fatalf("manifest.toml: %q", got)
	}
	message := repo.Git("log", "-1", "--format=%B")
	if !strings.Contains(message, "rlsbl options set rlsbl:ecosystem-tagging") || !strings.Contains(message, "Autogenerated: true") {
		t.Fatalf("the commit: %q", message)
	}
	if status := repo.Git("status", "--porcelain"); status != "" {
		t.Fatalf("left uncommitted: %s", status)
	}
}

