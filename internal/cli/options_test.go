func TestOptionsSetUpdatesAnEntryKeepingEveryOtherLine(t *testing.T) {
	hygiene.Isolate(t)
	repo := optionsRepository(t)
	repo.Write(".strictmetadata/options/manifest.toml", "owner = \"strictspec\"\n")
	repo.Write(".strictmetadata/options/project.toml", "format_version = 1\n\n# Kept by hand.\n[[entry]]\nid = \"rlsbl:ecosystem-tagging\"\ncurrent = \"off\"\nideal = \"on\"\nreason = \"first\"\n")
	repo.Commit("options", ".strictmetadata/options/manifest.toml", ".strictmetadata/options/project.toml")
	r := appWith(t, testsupport.NewFakeHTTP(t)).Test([]string{"options", "set", "rlsbl:ecosystem-tagging", "--current", "off", "--ideal", "on", "--reason", "second", "--no-auto-commit"})
	if r.ExitCode != 0 || !strings.Contains(r.Stdout, "Updated rlsbl:ecosystem-tagging") || strings.Contains(r.Stdout, "Committed.") {
		t.Fatalf("exit %d:\n%s%s", r.ExitCode, r.Stdout, r.Stderr)
	}
	doc := readText(t, repo.Path(".strictmetadata/options/project.toml"))
	if !strings.Contains(doc, "# Kept by hand.") || !strings.Contains(doc, "reason = \"second\"") || strings.Contains(doc, "first") {
		t.Fatalf("project.toml:\n%s", doc)
	}
	if status := repo.Git("status", "--porcelain"); !strings.Contains(status, "project.toml") {
		t.Fatalf("--no-auto-commit committed: %q", status)
	}
}

func TestOptionsSetRefusesWhatStrictspecRefuses(t *testing.T) {
	hygiene.Isolate(t)
	repo := optionsRepository(t)
	app := appWith(t, testsupport.NewFakeHTTP(t))
	cases := []struct {
		name string
		argv []string
		want string
	}{
		{"another tool's id", []string{"strictcode:lint", "--current", "off", "--ideal", "error", "--reason", "x"}, "not of rlsbl"},
		{"a value the option does not declare", []string{"rlsbl:ecosystem-tagging", "--current", "maybe", "--ideal", "on", "--reason", "x"}, "refused, so nothing was written"},
		{"a scope where no member is declared", []string{"rlsbl:test-sandbox", "--current", "on", "--ideal", "on", "--reason", "x", "--scope", "packages/widget"}, "declares no members"},
		{"an empty scope", []string{"rlsbl:test-sandbox", "--current", "on", "--ideal", "on", "--reason", "x", "--scope", ""}, "--scope must not be empty"},
		{"an empty reason", []string{"rlsbl:ecosystem-tagging", "--current", "off", "--ideal", "on", "--reason", ""}, "--reason must not be empty"},
	}
	for _, c := range cases {
		r := app.Test(append([]string{"options", "set"}, c.argv...))
		if r.ExitCode != 1 || !strings.Contains(r.Stderr, c.want) {
			t.Errorf("%s: exit %d:\n%s", c.name, r.ExitCode, r.Stderr)
		}
	}
	if _, err := os.Stat(repo.Path(".strictmetadata/options/project.toml")); !os.IsNotExist(err) {
		t.Fatal("a refused entry was written")
	}
}

func TestOptionsSetRefusesAManifestNamingAnotherOwnerAndTheNamedLineFixesIt(t *testing.T) {
	hygiene.Isolate(t)
	repo := optionsRepository(t)
	repo.Write(".strictmetadata/options/manifest.toml", "owner = \"strictcode\"\n")
	app := appWith(t, testsupport.NewFakeHTTP(t))
	argv := []string{"options", "set", "rlsbl:ecosystem-tagging", "--current", "off", "--ideal", "on", "--reason", "not yet public"}
	r := app.Test(argv)
	if r.ExitCode != 1 || !strings.Contains(r.Stderr, "Write this line instead:\nowner = \"strictspec\"") {
		t.Fatalf("exit %d:\n%s", r.ExitCode, r.Stderr)
	}
	repo.Write(".strictmetadata/options/manifest.toml", "owner = \"strictspec\"\n")
	if r := app.Test(argv); r.ExitCode != 0 {
		t.Fatalf("the named line did not clear the refusal: exit %d:\n%s", r.ExitCode, r.Stderr)
	}
}
