// noticeFlags are deprecate's and yank's flags.
func noticeFlags(verb string) []strictcli.Flag {
	return []strictcli.Flag{
		strictcli.StringFlag("reason", "Why the version is "+verb+"; it opens the notice", strictcli.Optional()),
		strictcli.StringFlag("use", "The released version to use instead, bare (0.5.0); the notice names it", strictcli.Optional()),
	}
}

func registerReleaseOps(r *commandSet) {
	r.add(command{
		path:   []string{"release", "edit"},
		help:   releaseEditHelp,
		effect: mutating,
		args: []strictcli.Arg{
			strictcli.NewArg("version", "The released version whose Release is rewritten, bare (0.4.0)", strictcli.ArgRequired()),
		},
		run: func(ctx *strictcli.Context, kw map[string]any) (any, error) {
			version := strictcli.Get[string](kw, "version")
			if version == "" {
				return nil, emptyArgument("version")
			}
			dir, _, err := workingRepository()
			if err != nil {
				return nil, err
			}
			termList, err := confidential.ConfiguredLocation()
			if err != nil {
				return nil, err
			}
			return nil, releaseops.Edit(ctx, releaseops.EditRequest{Dir: dir, Version: version, TermList: termList})
		},
	})
	r.add(command{
		path:   []string{"release", "retry"},
		help:   releaseRetryHelp,
		effect: mutating,
		// Only a person decides that a release's publish runs start again:
		// a second publish run of a version that did publish fails, or
		// publishes twice where a registry allows it.
		consequential: true,
		flags: []strictcli.Flag{
			strictcli.BoolFlag("watch", "Watch the dispatched runs until they conclude (--no-watch prints the command that watches them)", strictcli.Required()),
		},
		run: func(ctx *strictcli.Context, kw map[string]any) (any, error) {
			dir, _, err := workingRepository()
			if err != nil {
				return nil, err
			}
			return nil, releaseops.Retry(ctx, releaseops.RetryRequest{Dir: dir, Watch: strictcli.Get[bool](kw, "watch"), Sleep: time.Sleep})
		},
	})
	r.add(command{
		path:   []string{"release", "undo"},
		help:   releaseUndoHelp,
		effect: mutating,
		// Undo deletes a GitHub Release and tags on origin, and reverts
		// commits on the release branch: only a person decides that.
		consequential: true,
		flags: []strictcli.Flag{
			strictcli.StringFlag("version", "An earlier release to undo, bare (0.3.0), without reverting its commits; the latest release when omitted", strictcli.Optional()),
		},
		run: func(ctx *strictcli.Context, kw map[string]any) (any, error) {
			req := releaseops.UndoRequest{Now: time.Now}
			var given bool
			if req.Version, given = strictcli.GetOpt[string](kw, "version"); given && req.Version == "" {
				return nil, emptyArgument("--version")
			}
			var err error
			if req.Dir, _, err = workingRepository(); err != nil {
				return nil, err
			}
			return nil, releaseops.Undo(ctx, req)
		},
	})
	r.add(command{
		path:   []string{"release", "abandon"},
		help:   releaseAbandonHelp,
		effect: mutating,
		// Recording a version as never released is permanent: the number is
		// never released under again.
		consequential: true,
		run: func(ctx *strictcli.Context, _ map[string]any) (any, error) {
			dir, _, err := workingRepository()
			if err != nil {
				return nil, err
			}
			return nil, releaseops.Abandon(ctx, releaseops.AbandonRequest{Dir: dir})
		},
	})
	r.add(command{
		path:   []string{"release", "retract"},
		help:   releaseRetractHelp,
		effect: mutating,
		// A retraction publishes a version every consumer of the module
		// sees, deletes GitHub Releases, and is permanent on the Go module
		// proxy: only a person decides it.
		consequential: true,
		flags: []strictcli.Flag{
			strictcli.StringFlag("versions", "A released version to retract, bare (0.5.0); repeatable, once per version", strictcli.Required(), strictcli.Repeatable(), strictcli.Unique(true)),
			strictcli.StringFlag("reason", "Why the versions are retracted: one line, the go.mod retract directive's comment", strictcli.Required()),
		},
		run: func(ctx *strictcli.Context, kw map[string]any) (any, error) {
			if err := requireNonEmpty(kw, "reason"); err != nil {
				return nil, err
			}
			versions, err := stringList(kw["versions"])
			if err != nil {
				return nil, err
			}
			for _, v := range versions {
				if v == "" {
					return nil, emptyArgument("--versions")
				}
			}
			req := releaseops.RetractRequest{Versions: versions, Reason: strictcli.Get[string](kw, "reason"), Now: time.Now}
			if req.Dir, _, err = workingRepository(); err != nil {
				return nil, err
			}
			if req.TermList, err = confidential.ConfiguredLocation(); err != nil {
				return nil, err
			}
			return nil, releaseops.Retract(ctx, req)
		},
	})
	for _, op := range []struct {
		name, help, verb string
		run              func(*strictcli.Context, releaseops.NoticeRequest) error
	}{
		{"deprecate", releaseDeprecateHelp, "deprecated", releaseops.Deprecate},
		{"yank", releaseYankHelp, "yanked", releaseops.Yank},
	} {
		r.add(command{
			path:   []string{"release", op.name},
			help:   op.help,
			effect: mutating,
			// A notice on a published Release, and a yank's registry writes,
			// are what consumers of the version see: only a person decides
			// them.
			consequential: true,
			args: []strictcli.Arg{
				strictcli.NewArg("version", "The released version, bare (0.3.0)", strictcli.ArgRequired()),
			},
			flags: noticeFlags(op.verb),
			run: func(ctx *strictcli.Context, kw map[string]any) (any, error) {
				req := releaseops.NoticeRequest{Version: strictcli.Get[string](kw, "version")}
				if req.Version == "" {
					return nil, emptyArgument("version")
				}
				var given bool
				if req.Reason, given = strictcli.GetOpt[string](kw, "reason"); given && req.Reason == "" {
					return nil, emptyArgument("--reason")
				}
				if req.Use, given = strictcli.GetOpt[string](kw, "use"); given && req.Use == "" {
					return nil, emptyArgument("--use")
				}
				var err error
				if req.Dir, _, err = workingRepository(); err != nil {
					return nil, err
				}
				if req.TermList, err = confidential.ConfiguredLocation(); err != nil {
					return nil, err
				}
				return nil, op.run(ctx, req)
			},
		})
	}
}

// emptyArgument refuses an argument given as the empty string.
func emptyArgument(name string) error {
	return errors.New(name + " must not be empty")
}
