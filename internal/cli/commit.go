package cli

import (
	"fmt"
	"os"
	"strings"

	"github.com/stricttools/strictcli/go/strictcli"

	"github.com/stricttools/rlsbl/internal/release"
)

const commitHelp = "Commit the named files through safegit with the Autogenerated: true trailer, marking the commit machine-made so changelog " +
	"coverage exempts it. Files are named relative to the working directory or absolutely, and must lie in the repository holding it; a named file " +
	"that did not change is left out of the commit, and a commit none of whose files changed is refused, as is a file git ignores. safegit must be on PATH."

// commitNoDryRun is why commit refuses --dry-run.
const commitNoDryRun = "the whole command is one safegit commit, and safegit, not rlsbl, decides what is staged, which hooks run, and whether " +
	"anything changes, so a preview could only echo the arguments given"

func registerCommit(r *commandSet) {
	r.add(command{
		path:     []string{"commit"},
		help:     commitHelp,
		effect:   mutating,
		noDryRun: commitNoDryRun,
		flags: []strictcli.Flag{
			strictcli.StringFlag("message", "The commit message; the Autogenerated: true trailer is added to it", strictcli.Required()),
		},
		args: []strictcli.Arg{
			strictcli.NewArg("files", "The files to commit", strictcli.ArgRequired(), strictcli.Variadic()),
		},
		run: runCommit,
	})
}

func runCommit(ctx *strictcli.Context, kw map[string]any) (any, error) {
	files, err := stringList(kw["files"])
	if err != nil {
		return nil, err
	}
	dir, err := os.Getwd()
	if err != nil {
		return nil, err
	}
	res, err := release.CommitFiles(ctx.Effects(), dir, strictcli.Get[string](kw, "message"), files)
	if err != nil {
		return nil, err
	}
	ctx.Out(fmt.Sprintf("Committed %s with the Autogenerated trailer.", strings.Join(res.Paths, ", ")))
	return nil, nil
}
