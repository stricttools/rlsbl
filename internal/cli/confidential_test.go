// confidentialProject is releaseCommandsProject with an unpushed commit
// naming "gizmo", a term of the list under the test's home directory, and
// the id of that hit.
func confidentialProject(t *testing.T) (*testsupport.Repo, string) {
	t.Helper()
	repo := releaseCommandsProject(t)
	testsupport.WriteTermList(t, testsupport.ConfigureTermList(t), testsupport.TermListOf("gizmo"))
	repo.CommitFile("notes.md", "ask Gizmo first\n", "Take notes")
	testsupport.FakeSafegit(t)
	r := appWith(t, testsupport.NewFakeHTTP(t)).Test([]string{"check", "--name", "confidential-terms"})
	m := regexp.MustCompile(`hit ([0-9a-f]{16})`).FindStringSubmatch(r.Stdout + r.Stderr)
	if r.ExitCode == 0 || m == nil {
		t.Fatalf("the check did not report the hit (exit %d):\n%s%s", r.ExitCode, r.Stdout, r.Stderr)
	}
	return repo, m[1]
}

func TestJudgeFalsePositiveRecordsAndCommitsTheJudgment(t *testing.T) {
	hygiene.Isolate(t)
	repo, id := confidentialProject(t)
	app := appWith(t, testsupport.NewFakeHTTP(t))
	r := app.Test([]string{"confidential", "judge-false-positive", "--hit", id, "--certainty", "85", "--reason", "an ordinary word in a note"})
	if r.ExitCode != 0 {
		t.Fatalf("exit %d:\n%s%s", r.ExitCode, r.Stdout, r.Stderr)
	}
	text := repo.Git("show", "HEAD:"+confidential.StoreFile)
	for _, want := range []string{`hit = "` + id + `"`, `location = "notes.md in commit `, `resolution = "false-positive"`, "certainty = 85", `reason = "an ordinary word in a note"`} {
		if !strings.Contains(text, want) {
			t.Errorf("the committed resolutions do not hold %q:\n%s", want, text)
		}
	}
	if strings.Contains(strings.ToLower(text), "gizmo") {
		t.Errorf("the committed resolutions carry the term:\n%s", text)
	}
	if !strings.Contains(repo.Git("log", "-1", "--format=%B"), "Autogenerated: true") {
		t.Errorf("the commit carries no Autogenerated trailer")
	}
	if r := app.Test([]string{"check", "--name", "confidential-terms"}); r.ExitCode != 0 {
		t.Fatalf("the judged hit still fails the check:\n%s%s", r.Stdout, r.Stderr)
	}
	if r := app.Test([]string{"confidential", "judge-false-positive", "--hit", id, "--certainty", "85", "--reason", "again"}); r.ExitCode == 0 || !strings.Contains(r.Stderr, "resolved already") {
		t.Errorf("a second judgment of the hit was accepted:\n%s%s", r.Stdout, r.Stderr)
	}
}

