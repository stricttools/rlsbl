// releaseCommandsProject is the standalone npm project portal at 0.4.0,
// released at its first commit, the working directory for the rest of the
// test.
func releaseCommandsProject(t *testing.T) *testsupport.Repo {
	t.Helper()
	repo := testsupport.NewRepo(t)
	repo.Write(".strictmetadata/releasables/releasables.toml", "format_version = 1\nrepository_layout = \"standalone\"\nrelease_branches = [\"main\"]\n\n[[releasables]]\nname = \"portal\"\ntag_format = \"v{version}\"\npublish_mode = \"ci\"\n\n[[members]]\npath = \".\"\nname = \"root\"\nreleasable = \"portal\"\n")
	repo.Write("package.json", "{\n  \"name\": \"portal\",\n  \"version\": \"0.4.0\"\n}\n")
	release := repo.Commit("the project", ".strictmetadata/releasables/releasables.toml", "package.json")
	repo.Write(".strictmetadata/releases/portal/v0.4.0.toml", "format_version = 2\nbump = \"minor\"\ninclude = [\"npm\"]\nexclude = []\ndescription = \"the first release\"\nrelease_commit = \""+release+"\"\n\n[released_trees]\n\".\" = \""+strings.Repeat("e", 40)+"\"\n")
	repo.Write(".strictmetadata/changelog/portal/0.4.0.jsonl", changelog.Serialize(changelog.Entry{ID: strings.Repeat("0", 47) + "1", Commits: []string{release}})+"\n")
	repo.Git("tag", "v0.4.0", release)
	repo.Commit("release 0.4.0\n\nAutogenerated: true", ".strictmetadata/releases/portal/v0.4.0.toml", ".strictmetadata/changelog/portal/0.4.0.jsonl")
	hygiene.Chdir(t, repo.Dir)
	return repo
}

func TestStatusThroughTheApplication(t *testing.T) {
	hygiene.Isolate(t)
	repo := releaseCommandsProject(t)
	repo.CommitFile("b.txt", "b\n", "a change")
	fake := testsupport.NewFakeHTTP(t, httpGet("https://registry.npmjs.org/portal", 200, `{"dist-tags":{"latest":"0.3.0"},"versions":{"0.3.0":{}}}`))
	app := appWith(t, fake)

	r := app.Test([]string{"status", "--json", "--registry"})
	if r.ExitCode != 0 {
		t.Fatalf("exit %d: %s%s", r.ExitCode, r.Stdout, r.Stderr)
	}
	p := jsonPayload(t, r)
	if p["name"] != "portal" || p["latest_release"] != "0.4.0" || p["commits_ahead"].(float64) != 1 || p["drift"] != "AHEAD" || p["registry_version"] != "0.3.0" {
		t.Fatalf("payload %v", p)
	}

	r = app.Test([]string{"status"})
	if r.ExitCode != 0 {
		t.Fatalf("exit %d: %s%s", r.ExitCode, r.Stdout, r.Stderr)
	}
	for _, want := range []string{"Package:   portal", "Version:   0.4.0 (npm, package.json)", "Released:  0.4.0", "Coverage:  0/1 commits covered (1 exempted)", "! 1 commit ahead of v0.4.0"} {
		if !strings.Contains(r.Stdout, want) {
			t.Errorf("%q is not in:\n%s", want, r.Stdout)
		}
	}
	if r := app.Test([]string{"status", "--target", "go"}); r.ExitCode != 1 || !strings.Contains(r.Stderr, "has no go target; its targets are npm") {
		t.Errorf("a target the member lacks: exit %d: %s", r.ExitCode, r.Stderr)
	}
}

// A fork whose upstream branch ref is missing is refused, naming the fetch
// that writes the ref; once the ref exists the upstream's history is left
// out of the range.
func TestStatusInAForkLeavesTheUpstreamsHistoryOut(t *testing.T) {
	hygiene.Isolate(t)
	repo := releaseCommandsProject(t)
	inherited := repo.CommitFile("upstream.txt", "u\n", "an upstream commit")
	repo.CommitFile(".strictmetadata/upstream/upstream.toml", "format_version = 1\nhost = \"github.com\"\nowner = \"acme\"\nrepo = \"gadget\"\nbranch = \"main\"\n", "declare the fork")
	app := appWith(t, testsupport.NewFakeHTTP(t))

	r := app.Test([]string{"status", "--json"})
	if r.ExitCode != 1 || !strings.Contains(r.Stderr, "git fetch --no-tags https://github.com/acme/gadget +refs/heads/main:refs/upstream/github.com/acme/gadget/main") {
		t.Fatalf("a fork without its upstream ref: exit %d: %s", r.ExitCode, r.Stderr)
	}
	repo.Git("update-ref", "refs/upstream/github.com/acme/gadget/main", inherited)
	r = app.Test([]string{"status", "--json"})
	if r.ExitCode != 0 {
		t.Fatalf("exit %d: %s%s", r.ExitCode, r.Stdout, r.Stderr)
	}
	// The release's archive commit and the upstream commit are the
	// upstream's history now; the declaration commit is this fork's own.
	if p := jsonPayload(t, r); p["commits_ahead"].(float64) != 1 {
		t.Fatalf("payload %v", p)
	}
}
