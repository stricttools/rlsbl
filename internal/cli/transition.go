func registerTransition(r *commandSet) {
	r.group([]string{"transition"}, transitionGroupHelp)
	reason := strictcli.StringFlag("reason", "Why, in the operator's own words; the record keeps it", strictcli.Required())
	subject := strictcli.StringFlag("subject", "The releasable (or, for a lifecycle, the member) the period is about", strictcli.Required())
	r.add(command{
		path:    []string{"transition", "show"},
		help:    transitionShowHelp,
		effect:  readOnly,
		payload: transitionShowPayloadSchema(),
		render:  renderTransitionShow,
		run: func(ctx *strictcli.Context, _ map[string]any) (any, error) {
			inv, dir, err := transitionInvocation(ctx)
			if err != nil {
				return nil, err
			}
			report, err := inv.Show(dir)
			if err != nil {
				return nil, err
			}
			return report, nil
		},
	})
	r.add(command{
		path:   []string{"transition", "lifecycle"},
		help:   transitionLifecycleHelp,
		effect: mutating,
		// A lifecycle decides whether a releasable may release at all.
		consequential: true,
		flags: []strictcli.Flag{
			subject,
			strictcli.StringFlag("status", "The status from today", strictcli.Required(), strictcli.Choices(
				strictcli.Ch(string(lifecycle.StatusActive), "released as usual"),
				strictcli.Ch(string(lifecycle.StatusOnHold), "its releases are refused until it is active again"),
				strictcli.Ch(string(lifecycle.StatusRetired), "its release history is closed, a record nothing releases from"),
			)),
			reason,
		},
		run: func(ctx *strictcli.Context, kw map[string]any) (any, error) {
			return nil, runPeriod(ctx, kw, "status", lifecycleops.Invocation.Lifecycle)
		},
	})
	r.add(command{
		path:   []string{"transition", "license"},
		help:   transitionLicenseHelp,
		effect: mutating,
		// A license is a legal decision only a person makes.
		consequential: true,
		flags: []strictcli.Flag{
			subject,
			strictcli.StringFlag("license", "The SPDX identifier of the license from today", strictcli.Required()),
			reason,
		},
		run: func(ctx *strictcli.Context, kw map[string]any) (any, error) {
			return nil, runPeriod(ctx, kw, "license", lifecycleops.Invocation.License)
		},
	})
	r.add(command{
		path:   []string{"transition", "identity"},
		help:   transitionIdentityHelp,
		effect: mutating,
		// An identity decides which tags and registry names belong to whom.
		consequential: true,
		flags: []strictcli.Flag{
			strictcli.StringFlag("subject", "The releasable or member the identity belonged to", strictcli.Required()),
			strictcli.StringFlag("facet", "Which identity it is", strictcli.Required(), strictcli.Choices(
				strictcli.Ch(string(lifecycle.FacetReleasableName), "the releasable's name"),
				strictcli.Ch(string(lifecycle.FacetPackageName), "a published package's name"),
				strictcli.Ch(string(lifecycle.FacetProjectName), "the project's name"),
				strictcli.Ch(string(lifecycle.FacetGoModulePath), "a Go module path"),
				strictcli.Ch(string(lifecycle.FacetTagFormat), "the tag format"),
				strictcli.Ch(string(lifecycle.FacetRepositoryURL), "the repository's URL"),
			)),
			strictcli.StringFlag("value", "The identity's value: the name, path, format, or URL", strictcli.Required()),
			strictcli.StringFlag("registry", "The registry the value is a name in; omitted for an identity that is not a registry name", strictcli.Optional(), strictcli.Choices(
				strictcli.Ch("npm", "the npm registry"),
				strictcli.Ch("pypi", "the Python Package Index"),
				strictcli.Ch("go", "the Go module proxy"),
			)),
			strictcli.StringFlag("tag-pattern", "A glob of the tags the identity owned while its period ran; repeatable", strictcli.Optional(), strictcli.Repeatable(), strictcli.Unique(true)),
			strictcli.StringFlag("from", "The identity's first day (YYYY-MM-DD); omitted, it starts today and closes the open identity of the facet", strictcli.Optional()),
			strictcli.StringFlag("until", "The first day after a closed identity (YYYY-MM-DD)", strictcli.Optional()),
			reason,
		},
		options: []strictcli.CmdOption{
			strictcli.WithConstraints(strictcli.Requires("until-needs-from", "until", "from")),
		},
		run: runTransitionIdentity,
	})
	r.add(command{
		path:   []string{"transition", "unversioned-tag"},
		help:   transitionUnversionedTagHelp,
		effect: mutating,
		// Declaring a tag outside the version model stops every check from
		// asking about it, for good.
		consequential: true,
		flags: []strictcli.Flag{
			strictcli.StringFlag("tag", "The tag that releases no version", strictcli.Required()),
			reason,
		},
		run: func(ctx *strictcli.Context, kw map[string]any) (any, error) {
			if err := requireNonEmpty(kw, "tag", "reason"); err != nil {
				return nil, err
			}
			inv, dir, err := transitionInvocation(ctx)
			if err != nil {
				return nil, err
			}
			return nil, inv.UnversionedTag(dir, strictcli.Get[string](kw, "tag"), strictcli.Get[string](kw, "reason"))
		},
	})
	r.add(command{
		path:   []string{"transition", "classify"},
		help:   transitionClassifyHelp,
		effect: mutating,
		// Making a releasable proprietary stops everything it publishes.
		consequential: true,
		flags: []strictcli.Flag{
			strictcli.StringFlag("subject", "The releasable made proprietary", strictcli.Required()),
			reason,
		},
		run: func(ctx *strictcli.Context, kw map[string]any) (any, error) {
			if err := requireNonEmpty(kw, "subject", "reason"); err != nil {
				return nil, err
			}
			inv, dir, err := transitionInvocation(ctx)
			if err != nil {
				return nil, err
			}
			return nil, inv.Classify(dir, strictcli.Get[string](kw, "subject"), strictcli.Get[string](kw, "reason"))
		},
	})
	r.add(command{
		path:   []string{"transition", "declassify"},
		help:   transitionDeclassifyHelp,
		effect: mutating,
		// An irreversible history rewrite, force-pushed, and a private
		// repository made public: only a person decides that.
		consequential: true,
		flags: []strictcli.Flag{
			strictcli.StringFlag("license", "<releasable>=<SPDX identifier>: the public license a proprietary releasable takes; one per proprietary releasable", strictcli.Required(), strictcli.Repeatable(), strictcli.Unique(true)),
			strictcli.StringFlag("reason", "Why the repository goes public; the record, the rewrite's archive, and the commit carry it", strictcli.Required()),
		},
		run: runTransitionDeclassify,
	})
	r.add(command{
		path:   []string{"transition", "init-minimal-record"},
		help:   transitionInitMinimalRecordHelp,
		effect: mutating,
		run: func(ctx *strictcli.Context, _ map[string]any) (any, error) {
			inv, dir, err := transitionInvocation(ctx)
			if err != nil {
				return nil, err
			}
			return nil, inv.InitMinimalRecord(dir)
		},
	})
}

// transitionInvocation is the invocation a transition command runs as,
// dated today, and the working directory.
func transitionInvocation(ctx *strictcli.Context) (lifecycleops.Invocation, string, error) {
	dir, err := os.Getwd()
	if err != nil {
		return lifecycleops.Invocation{}, "", err
	}
	indexPath, err := index.DefaultPath()
	if err != nil {
		return lifecycleops.Invocation{}, "", err
	}
	return lifecycleops.Invocation{E: ctx.Effects(), DryRun: ctx.DryRun(), Say: ctx.Out, Now: time.Now, IndexPath: indexPath}, dir, nil
}

// runPeriod runs a lifecycle or license change, the value read from flag.
func runPeriod(ctx *strictcli.Context, kw map[string]any, flag string, change func(lifecycleops.Invocation, lifecycleops.PeriodRequest) error) error {
	if err := requireNonEmpty(kw, "subject", flag, "reason"); err != nil {
		return err
	}
	inv, dir, err := transitionInvocation(ctx)
	if err != nil {
		return err
	}
	return change(inv, lifecycleops.PeriodRequest{Dir: dir, Subject: strictcli.Get[string](kw, "subject"), Value: strictcli.Get[string](kw, flag), Reason: strictcli.Get[string](kw, "reason")})
}

// parseDay reads a YYYY-MM-DD flag.
func parseDay(text, flag string) (time.Time, error) {
	t, err := time.Parse(time.DateOnly, text)
	if err != nil {
		return time.Time{}, fmt.Errorf("--%s %q is not a date; write it as YYYY-MM-DD", flag, text)
	}
	return t, nil
}

func runTransitionIdentity(ctx *strictcli.Context, kw map[string]any) (any, error) {
	if err := requireNonEmpty(kw, "subject", "value", "reason"); err != nil {
		return nil, err
	}
	patterns, err := optionalStrings(kw, "tag_pattern")
	if err != nil {
		return nil, err
	}
	req := lifecycleops.IdentityRequest{
		Subject:     strictcli.Get[string](kw, "subject"),
		Facet:       lifecycle.Facet(strictcli.Get[string](kw, "facet")),
		Value:       strictcli.Get[string](kw, "value"),
		Registry:    optionalString(kw, "registry"),
		TagPatterns: patterns,
		Reason:      strictcli.Get[string](kw, "reason"),
	}
	for _, p := range patterns {
		if p == "" {
			return nil, emptyArgument("--tag-pattern")
		}
	}
	if text, given := strictcli.GetOpt[string](kw, "from"); given {
		if req.From, err = parseDay(text, "from"); err != nil {
			return nil, err
		}
	}
	if text, given := strictcli.GetOpt[string](kw, "until"); given {
		if req.Until, err = parseDay(text, "until"); err != nil {
			return nil, err
		}
	}
	inv, dir, err := transitionInvocation(ctx)
	if err != nil {
		return nil, err
	}
	req.Dir = dir
	return nil, inv.Identity(req)
}

// parseLicenses reads the repeated --license <releasable>=<SPDX>.
func parseLicenses(values []string) (map[string]string, error) {
	out := map[string]string{}
	for _, v := range values {
		name, license, ok := strings.Cut(v, "=")
		if !ok || name == "" || license == "" {
			return nil, fmt.Errorf("--license %q is not <releasable>=<SPDX identifier>", v)
		}
		if _, dup := out[name]; dup {
			return nil, fmt.Errorf("--license names %q twice; a releasable takes one license", name)
		}
		out[name] = license
	}
	return out, nil
}

func runTransitionDeclassify(ctx *strictcli.Context, kw map[string]any) (any, error) {
	if err := requireNonEmpty(kw, "reason"); err != nil {
		return nil, err
	}
	values, err := optionalStrings(kw, "license")
	if err != nil {
		return nil, err
	}
	licenses, err := parseLicenses(values)
	if err != nil {
		return nil, err
	}
	inv, dir, err := transitionInvocation(ctx)
	if err != nil {
		return nil, err
	}
	return nil, inv.Declassify(lifecycleops.DeclassifyRequest{Dir: dir, Licenses: licenses, Reason: strictcli.Get[string](kw, "reason")})
}

func transitionShowPayloadSchema() map[string]any {
	str := map[string]any{"type": "string"}
	strs := map[string]any{"type": "array", "items": str}
	object := func(fields map[string]any) map[string]any {
		required := make([]any, 0, len(fields))
		names := make([]string, 0, len(fields))
		for name := range fields {
			names = append(names, name)
		}
		sort.Strings(names)
		for _, name := range names {
			required = append(required, name)
		}
		return map[string]any{"type": "object", "properties": fields, "required": required, "additionalProperties": false}
	}
	list := func(item map[string]any) map[string]any { return map[string]any{"type": "array", "items": item} }
	period := object(map[string]any{"subject": str, "value": str, "from": str, "until": str, "reason": str})
	return object(map[string]any{
		"record_file":  str,
		"present":      map[string]any{"type": "boolean"},
		"date":         str,
		"confidential": map[string]any{"type": "boolean"},
		"lifecycle":    list(period),
		"licenses":     list(period),
		"identities": list(object(map[string]any{"subject": str, "facet": str, "value": str, "registry": str, "tag_patterns": strs,
			"from": str, "until": str, "effective_version": str, "reason": str})),
		"registry_names":    list(object(map[string]any{"registry": str, "name": str, "subject": str, "recorded_since": str})),
		"unversioned_tags":  list(object(map[string]any{"tag": str, "reason": str, "recorded": str})),
		"codenames":         strs,
		"distinctive_terms": strs,
		"problems":          strs,
		"verdicts":          list(object(map[string]any{"rule": str, "class": str, "subject": str, "verdict": str, "detail": str})),
	})
}

func renderTransitionShow(payload any) string {
	p, err := decodePayload[lifecycleops.Report](payload)
	if err != nil {
		return renderJSON(payload)
	}
	var b strings.Builder
	state := "public"
	if p.Confidential {
		state = "confidential"
	}
	if !p.Present {
		fmt.Fprintf(&b, "%s does not exist: the repository is public.\n", p.RecordFile)
	} else {
		fmt.Fprintf(&b, "%s on %s: the repository is %s.\n", p.RecordFile, p.Date, state)
	}
	periods := func(title, value string, rows []lifecycleops.ReportPeriod) {
		if len(rows) == 0 {
			return
		}
		table := make([][]string, len(rows))
		for i, r := range rows {
			until := r.Until
			if until == "" {
				until = "(open)"
			}
			table[i] = []string{r.Subject, r.Value, r.From, until, r.Reason}
		}
		b.WriteString("\n" + title + "\n" + renderTable([]string{"subject", value, "from", "until", "reason"}, table))
	}
	periods("Lifecycle", "status", p.Lifecycle)
	periods("Licenses", "license", p.Licenses)
	if len(p.Identities) > 0 {
		table := make([][]string, len(p.Identities))
		for i, id := range p.Identities {
			span := id.From + " to " + id.Until
			switch {
			case id.EffectiveVersion != "":
				span = "pending, from " + id.EffectiveVersion
			case id.Until == "":
				span = id.From + " (open)"
			}
			table[i] = []string{id.Subject, id.Facet, id.Value, id.Registry, strings.Join(id.TagPatterns, " "), span}
		}
		b.WriteString("\nIdentities\n" + renderTable([]string{"subject", "facet", "value", "registry", "tags", "period"}, table))
	}
	if len(p.RegistryNames) > 0 {
		table := make([][]string, len(p.RegistryNames))
		for i, n := range p.RegistryNames {
			table[i] = []string{n.Registry, n.Name, n.Subject, n.RecordedSince}
		}
		b.WriteString("\nRegistry names\n" + renderTable([]string{"registry", "name", "subject", "since"}, table))
	}
	if len(p.UnversionedTags) > 0 {
		table := make([][]string, len(p.UnversionedTags))
		for i, u := range p.UnversionedTags {
			table[i] = []string{u.Tag, u.Recorded, u.Reason}
		}
		b.WriteString("\nTags that release no version\n" + renderTable([]string{"tag", "recorded", "reason"}, table))
	}
	if len(p.Codenames) > 0 || len(p.DistinctiveTerms) > 0 {
		fmt.Fprintf(&b, "\nCodenames: %s\nDistinctive terms: %s\n", strings.Join(p.Codenames, ", "), strings.Join(p.DistinctiveTerms, ", "))
	}
	if len(p.Problems) > 0 {
		b.WriteString("\nThe record is not valid:\n  " + strings.Join(p.Problems, "\n  ") + "\n")
	}
	b.WriteString("\nRules\n")
	for _, v := range p.Verdicts {
		who := v.Rule
		if v.Subject != "" {
			who += " (" + v.Subject + ")"
		}
		fmt.Fprintf(&b, "  %s: %s. %s\n", who, v.Verdict, v.Detail)
	}
	return strings.TrimRight(b.String(), "\n")
}
