// HookHash is the SHA-256 of a hook's content with trailing whitespace
// removed, so an editor's change to the final newline does not make a
// shipped hook look customized.
func HookHash(content string) string {
	sum := sha256.Sum256([]byte(strings.TrimRightFunc(content, unicode.IsSpace)))
	return hex.EncodeToString(sum[:])
}

// gitHook is one hook scaffold installs: its file name, its content, and
// every content rlsbl has shipped for it.
type gitHook struct {
	name    string
	content string
	shipped []string
}

var gitHooks = []gitHook{
	{name: "pre-push", content: PrePushHook, shipped: shippedPrePushHooks},
	{name: "post-rewrite", content: PostRewriteHook, shipped: []string{PostRewriteHook}},
}

// ShippedHook reports whether content is one rlsbl shipped for the named
// hook (the current one included).
func ShippedHook(name, content string) bool {
	for _, h := range gitHooks {
		if h.name != name {
			continue
		}
		hash := HookHash(content)
		for _, s := range h.shipped {
			if HookHash(s) == hash {
				return true
			}
		}
	}
	return false
}

// gitAnswer runs a git read in dir and returns its trimmed stdout; found is
// false when git exits non-zero.
func gitAnswer(r git.Runner, dir string, args ...string) (out string, found bool, err error) {
	argv := []interface{}{"git"}
	for _, a := range args {
		argv = append(argv, a)
	}
	c, err := r.Run(argv, strictcli.Cwd(dir), strictcli.Check(false))
	if err != nil {
		return "", false, fmt.Errorf("git %s in %s: %w", strings.Join(args, " "), dir, err)
	}
	if c.ExitCode() != 0 {
		return "", false, nil
	}
	return strings.TrimSpace(c.Stdout()), true, nil
}

// HooksDirectory is the directory git runs the repository's hooks from, as
// git itself answers it (core.hooksPath honored, a linked worktree's common
// directory). A core.hooksPath naming anything but the repository's own
// hooks directory is refused, naming the setting, where it is set, and the
// command that removes it: scaffold does not write hooks into a directory
// other repositories may share or the working tree may commit.
func HooksDirectory(r git.Runner, dir string) (string, error) {
	hooks, ok, err := gitAnswer(r, dir, "rev-parse", "--path-format=absolute", "--git-path", "hooks")
	if err != nil {
		return "", err
	}
	common, ok2, err := gitAnswer(r, dir, "rev-parse", "--path-format=absolute", "--git-common-dir")
	if err != nil {
		return "", err
	}
	if !ok || !ok2 || hooks == "" || common == "" {
		return "", fmt.Errorf("git could not say where %s runs its hooks from", dir)
	}
	standard := filepath.Join(common, "hooks")
	if samePath(hooks, standard) {
		return standard, nil
	}
	origin, _, err := gitAnswer(r, dir, "config", "--get", "--show-origin", "core.hooksPath")
	if err != nil {
		return "", err
	}
	source, value, _ := strings.Cut(origin, "\t")
	where, fix := "the git configuration", "removing it from the git configuration that sets it"
	if file, ok := strings.CutPrefix(source, "file:"); ok {
		where = file
		fix = "`git config --file " + file + " --unset core.hooksPath`"
	} else if source != "" {
		where = source
		fix = "removing it from " + source
	}
	if value == "" {
		value = "(unknown)"
	}
	return "", fmt.Errorf("core.hooksPath is set to %q (in %s), so git runs this repository's hooks from %s, not from %s; rlsbl scaffold installs its pre-push and post-rewrite hooks where git runs them and does not write into a directory core.hooksPath names. Remove the setting with %s, then run rlsbl scaffold again", value, where, hooks, standard, fix)
}

// samePath compares two paths after resolving symbolic links, falling back
// to the cleaned paths for one that does not exist yet.
func samePath(a, b string) bool {
	resolve := func(p string) string {
		if r, err := filepath.EvalSymlinks(p); err == nil {
			return r
		}
		return filepath.Clean(p)
	}
	return resolve(a) == resolve(b)
}

// hookChange is what installing one hook does.
type hookChange struct {
	name string
	path string
	// action is "install", "update", or "" when the hook is current.
	action  string
	content string
}

// planHooks reads the installed hooks under hooksDir and decides each one.
// A hook whose content rlsbl never shipped is refused before anything is
// written.
func planHooks(hooksDir string) ([]hookChange, error) {
	var changes []hookChange
	var refused []string
	for _, h := range gitHooks {
		path := filepath.Join(hooksDir, h.name)
		data, err := os.ReadFile(path)
		switch {
		case errors.Is(err, fs.ErrNotExist):
			changes = append(changes, hookChange{name: h.name, path: path, action: "install", content: h.content})
			continue
		case err != nil:
			return nil, fmt.Errorf("reading the %s hook: %w", h.name, err)
		}
		installed := string(data)
		switch {
		case HookHash(installed) == HookHash(h.content):
			changes = append(changes, hookChange{name: h.name, path: path})
		case ShippedHook(h.name, installed):
			changes = append(changes, hookChange{name: h.name, path: path, action: "update", content: h.content})
		default:
			refused = append(refused, fmt.Sprintf("the %s hook at %s is not one rlsbl installed, and rlsbl does not overwrite it. rlsbl's hook is:\n%s", h.name, path, indent(h.content, "    ")))
		}
	}
	if len(refused) > 0 {
		return nil, fmt.Errorf("%s\nDelete the hook (saferm delete --on-error abort --description \"replace with rlsbl's hook\" <path>) and run rlsbl scaffold again; a check a hook of your own needs belongs in the project's checks, which the pre-push hook runs", strings.Join(refused, "\n"))
	}
	return changes, nil
}

// indent prefixes every non-empty line of text.
func indent(text, prefix string) string {
	lines := strings.Split(strings.TrimRight(text, "\n"), "\n")
	for i, l := range lines {
		if l != "" {
			lines[i] = prefix + l
		}
	}
	return strings.Join(lines, "\n")
}

// installHooks writes the planned hooks, executable, and says what it did,
// or under --dry-run what it would do.
func installHooks(e *strictcli.Effects, changes []hookChange, dryRun bool, say func(string)) error {
	for _, c := range changes {
		if c.action == "" {
			continue
		}
		if _, err := e.Mkdir(filepath.Dir(c.path)); err != nil {
			return fmt.Errorf("creating %s: %w", filepath.Dir(c.path), err)
		}
		if _, err := e.Write(c.path, c.content, strictcli.Mode(0o755)); err != nil {
			return fmt.Errorf("writing the %s hook: %w", c.name, err)
		}
		switch {
		case dryRun && c.action == "install":
			say(fmt.Sprintf("Would install the %s hook (%s)", c.name, c.path))
		case dryRun:
			say(fmt.Sprintf("Would update the %s hook (%s), which is an earlier rlsbl version", c.name, c.path))
		case c.action == "install":
			say(fmt.Sprintf("Installed %s hook (%s)", c.name, c.path))
		default:
			say(fmt.Sprintf("Updated %s hook (%s), which was an earlier rlsbl version", c.name, c.path))
		}
	}
	return nil
}
