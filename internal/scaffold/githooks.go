// Scaffold installs two git hooks where git runs them: pre-push, which runs
// `rlsbl failing-checks --hook pre-push` for a push to a branch, and
// post-rewrite, which remaps the changelog's commit ids after an amend or a
// rebase. A hook already installed is replaced only when its content is one
// rlsbl shipped; any other content is refused, because a hook that does not
// run rlsbl's checks lets a push through unchecked.

// PrePushHook is the pre-push hook. git feeds it one line per ref pushed;
// only branch pushes (refs/heads/*) are checked, because refs/tags/* and
// refs/backups/* are written by rlsbl's release and safegit, which own them.
const PrePushHook = `#!/usr/bin/env bash
# rlsbl pre-push hook. Enforces on refs/heads/* only; refs/tags/* and
# refs/backups/* are tool-owned namespaces and exit 0.
stdin_data="$(cat)"
enforce=0
while read -r _local_ref _local_sha remote_ref _remote_sha; do
  case "$remote_ref" in
    refs/heads/*) enforce=1 ;;
  esac
done <<< "$stdin_data"
if [ "$enforce" -eq 0 ]; then
  exit 0
fi
export RLSBL_PUSH_STDIN="$stdin_data"
exec rlsbl failing-checks --hook pre-push
`

// PostRewriteHook is the post-rewrite hook: git's old and new commit ids on
// stdin, piped to the changelog remap.
const PostRewriteHook = "#!/usr/bin/env bash\nexec rlsbl changelog remap --stdin\n"

