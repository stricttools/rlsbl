// Package migration converts a repository's rlsbl records from the layout the
// Python rlsbl wrote (.rlsbl/, .rlsbl-monorepo/, and each member's .rlsbl/)
// to the .strictmetadata/ layout the Go rlsbl reads, once per repository.
//
// The migration reads the whole old layout and decides everything before it
// writes anything: every refusal (a value the new layout has no place for, a
// missing license, an uncommitted change to a path it would write or remove,
// a file of the old layout it does not recognize) is reported together, and
// a refused run writes nothing. A run that is not refused writes the new
// records, regenerates the changelogs from them, removes the old layout
// through saferm, and commits exactly the paths it wrote or removed with the
// Autogenerated trailer, leaving every other uncommitted change alone. A
// repository already converted has nothing to do, and says so.
//
// The readers of the old formats live here and nowhere else: the Go rlsbl
// reads only the new layout.
package migration

import (
	"errors"
	"fmt"
	"io/fs"
	"path"
	"sort"
	"strings"
	"time"

	"github.com/stricttools/strictcli/go/strictcli"
	"github.com/stricttools/strictspec/go/lifecycle/index"

	"github.com/stricttools/rlsbl/internal/declarations"
)

// CommitMessage is the message of the migration's commit.
const CommitMessage = "Migrate rlsbl records to the .strictmetadata layout"

// The old layout's directories.
const (
	oldDir           = ".rlsbl"
	oldWorkspaceDir  = ".rlsbl-monorepo"
	oldWorkspaceFile = oldWorkspaceDir + "/workspace.toml"
	oldConfigName    = "config.json"
)

// Request is one run of the migration.
type Request struct {
	// Root is the repository root, absolute.
	Root string
	// Licenses maps releasable names to an SPDX identifier or
	// "proprietary", read from the --licenses file; nil when none was given.
	Licenses map[string]string
	// LicensesFile names the --licenses file in messages; empty when none
	// was given.
	LicensesFile string
	// Now is the migration date: the start of every period it opens.
	Now time.Time
	// RlsblVersion is the version of the rlsbl binary running the
	// migration.
	RlsblVersion string
	// IndexPath is the machine-local confidential-name index the migration
	// updates.
	IndexPath string
}

// write is one file the migration writes.
type write struct {
	// path is repository-relative.
	path string
	// sources are the old paths it is converted from; empty for a file the
	// migration composes.
	sources []string
	// change says what the conversion did.
	change string
	data   []byte
	mode   fs.FileMode
	// ignored marks a file git ignores (run state), which the commit
	// leaves out.
	ignored bool
	// writer, when set, writes the file through the record's own writer
	// instead of data.
	writer func(e *strictcli.Effects, root string) error
}

// removal is one old-layout directory the migration removes whole.
type removal struct {
	// dir is repository-relative.
	dir string
	// files are every file under it, repository-relative.
	files []string
}

// Plan is everything one run decides before it writes anything.
type Plan struct {
	// Converted reports a repository already in the new layout: there is
	// nothing to do.
	Converted bool
	// Layout is the repository layout the migration writes.
	Layout declarations.Layout
	writes []write
	// generated are the changelogs regenerated from the converted records
	// once they are written.
	generated []string
	removals  []removal
	// notes are what the report says besides the files: values dropped,
	// ids minted.
	notes []string
	// dirty are uncommitted changes to paths the migration does not touch,
	// listed and left alone.
	dirty []string
	// index is the confidential-name index entry the run records, nil when
	// the repository is public.
	// index is the update of the repository's entry in the
	// confidential-name index.
	index *index.Update
	d     *declarations.Releasables
}

// RefusedError is a run refused before anything was written: every problem
// found, each naming what to do.
type RefusedError struct {
	Problems []string
	// Plan is what the conversions planned up to the refusals, nil when
	// the refusal came before any; a dry run prints it.
	Plan *Plan
}

func (e *RefusedError) Error() string {
	return "rlsbl migrate records refused; nothing was written:\n  - " + strings.Join(e.Problems, "\n  - ")
}

// problems collects refusals while a plan is built.
type problems struct {
	list []string
}

func (p *problems) add(format string, args ...any) {
	p.list = append(p.list, fmt.Sprintf(format, args...))
}

func (p *problems) err() *RefusedError {
	if len(p.list) == 0 {
		return nil
	}
	sorted := append([]string(nil), p.list...)
	sort.Strings(sorted)
	return &RefusedError{Problems: dedupe(sorted)}
}

func dedupe(sorted []string) []string {
	var out []string
	for i, s := range sorted {
		if i == 0 || sorted[i-1] != s {
			out = append(out, s)
		}
	}
	return out
}

// Run migrates the repository at req.Root: it builds the plan, prints it,
// and, outside a dry run, applies it and commits.
func Run(ctx *strictcli.Context, req Request) error {
	plan, err := Build(ctx.Effects(), req)
	if err != nil {
		var refused *RefusedError
		if ctx.DryRun() && errors.As(err, &refused) && refused.Plan != nil {
			ctx.Out(refused.Plan.Report(true) + "\nThe plan above stops at the refusals: a conversion they stop is not listed.")
		}
		return err
	}
	ctx.Out(plan.Report(ctx.DryRun()))
	if plan.Converted || ctx.DryRun() {
		return nil
	}
	committed, err := Apply(ctx.Effects(), req, plan)
	if err != nil {
		return err
	}
	ctx.Out(committed)
	return nil
}

// Paths are every repository-relative path the plan writes or removes, in
// order: the paths its commit may carry.
func (p *Plan) Paths() []string {
	seen := map[string]bool{}
	var out []string
	add := func(rel string) {
		if !seen[rel] {
			seen[rel] = true
			out = append(out, rel)
		}
	}
	for _, w := range p.writes {
		add(w.path)
	}
	for _, g := range p.generated {
		add(g)
	}
	for _, r := range p.removals {
		for _, f := range r.files {
			add(f)
		}
	}
	sort.Strings(out)
	return out
}

// Report is the plan as text: per file, the source, the destination, and the
// change, then the removals, the notes, and the uncommitted changes left
// alone.
func (p *Plan) Report(dryRun bool) string {
	if p.Converted {
		return "This repository is already in the .strictmetadata layout: nothing to migrate."
	}
	var b strings.Builder
	verb := "Writes"
	if dryRun {
		verb = "Would write"
	}
	fmt.Fprintf(&b, "Migrating the rlsbl records to the .strictmetadata layout (%s layout).\n", p.Layout)
	writes := append([]write(nil), p.writes...)
	sort.Slice(writes, func(i, j int) bool { return writes[i].path < writes[j].path })
	for _, w := range writes {
		from := "(new)"
		if len(w.sources) > 0 {
			from = strings.Join(w.sources, ", ")
		}
		fmt.Fprintf(&b, "%s %s <- %s: %s\n", verb, w.path, from, w.change)
	}
	for _, g := range p.generated {
		fmt.Fprintf(&b, "%s %s: regenerated from the converted changelog\n", verb, g)
	}
	remove := "Removes"
	if dryRun {
		remove = "Would remove"
	}
	for _, r := range p.removals {
		fmt.Fprintf(&b, "%s %s through saferm (%d files)\n", remove, r.dir, len(r.files))
	}
	switch {
	case p.index == nil:
	case p.index.Confidential() && len(p.index.Names) == 0:
		fmt.Fprintf(&b, "%s no confidential names: the repository is confidential with no name to protect, so its entry for %s in the confidential-name index is removed\n", verb, strings.Join(p.index.Subjects, ", "))
	case p.index.Confidential():
		fmt.Fprintf(&b, "%s the confidential-name index entry for %s: %s\n", verb, strings.Join(p.index.Subjects, ", "), strings.Join(p.index.Names, ", "))
	case len(p.index.Subjects) > 0:
		fmt.Fprintf(&b, "%s no confidential names: the repository is public, so its entry for %s in the confidential-name index is removed\n", verb, strings.Join(p.index.Subjects, ", "))
	}
	for _, n := range p.notes {
		fmt.Fprintf(&b, "Note: %s\n", n)
	}
	for _, d := range p.dirty {
		fmt.Fprintf(&b, "Left alone (uncommitted, not a path the migration touches): %s\n", d)
	}
	return strings.TrimRight(b.String(), "\n")
}

// topDirectory is the directory directly under .strictmetadata/ that rel
// lies in, the one carrying an ownership manifest; empty for a file directly
// under .strictmetadata/ or outside it.
func topDirectory(rel string) string {
	rest, ok := strings.CutPrefix(rel, declarations.MetadataDir+"/")
	if !ok {
		return ""
	}
	first, _, found := strings.Cut(rest, "/")
	if !found {
		return ""
	}
	return declarations.MetadataDir + "/" + first
}

// joinRel joins repository-relative slash paths, "." disappearing.
func joinRel(parts ...string) string {
	var kept []string
	for _, p := range parts {
		if p != "" && p != "." {
			kept = append(kept, p)
		}
	}
	if len(kept) == 0 {
		return "."
	}
	return path.Join(kept...)
}
