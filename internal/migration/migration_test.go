func TestAStandaloneProjectMigratesAndCommitsOnce(t *testing.T) {
	hygiene.Isolate(t)
	f := standalone(t)
	r := f.migrate()
	contains(t, r.Stdout, "Committed")

	d, err := declarations.Load(f.repo.Dir)
	if err != nil {
		t.Fatal(err)
	}
	if d.Layout != declarations.LayoutStandalone || len(d.Releasables) != 1 || d.Releasables[0].Name != "portal" || d.Releasables[0].TagFormat != "v{version}" {
		t.Fatalf("declarations: %+v", d)
	}
	if d.Timeouts.PushSeconds != 120 || strings.Join(d.ReleaseBranches, ",") != "main,master" {
		t.Fatalf("repository values: %+v", d)
	}
	root := d.RootMember()
	if len(root.Pipelines) != 1 || root.Pipelines[0].Artifact != declarations.ArtifactPackage {
		t.Fatalf("pipelines: %+v", root.Pipelines)
	}

	unreleased, err := changelog.ReadUnreleased(f.repo.Dir, changelog.Dir("portal"))
	if err != nil {
		t.Fatal(err)
	}
	if len(unreleased.Entries()) != 1 || !isEntryID(unreleased.Entries()[0].ID) {
		t.Fatalf("the unreleased entry: %+v", unreleased.Entries())
	}
	released, err := changelog.ReadVersion(f.repo.Dir, changelog.Dir("portal"), semver.Version{Minor: 1})
	if err != nil {
		t.Fatal(err)
	}
	if released.Entries()[0].ID != someID {
		t.Fatalf("an id the old line carried was replaced: %+v", released.Entries())
	}
	info, err := os.Stat(f.repo.Path(".strictmetadata/changelog/portal/0.1.0.jsonl"))
	if err != nil || info.Mode().Perm() != 0o444 {
		t.Fatalf("the released changelog file: %v %v", info, err)
	}
	archive := f.read(".strictmetadata/releases/portal/v0.1.0.toml")
	contains(t, archive, "format_version = 2")
	contains(t, archive, "release_commit = ")
	contains(t, archive, "[released_trees]")
	lacks(t, archive, "candidate_sha =")

	state, found, err := scaffold.ReadState(f.repo.Dir)
	if err != nil || !found {
		t.Fatalf("the scaffold state: %v %v", found, err)
	}
	if state.RlsblVersion != "0.130.0" || state.Files[".github/workflows/ci.yml"] != someHash || len(state.Files) != 1 {
		t.Fatalf("the scaffold state: %+v", state)
	}
	if f.read(".strictmetadata/.scaffold-bases/.github/workflows/ci.yml") != "name: ci\n" {
		t.Fatal("the merge base was not carried")
	}

	rec, err := lifecycle.Load(f.repo.Dir)
	if err != nil {
		t.Fatal(err)
	}
	if l, ok := rec.LicenseOn("portal", testNow); !ok || l.License != "MIT" {
		t.Fatalf("the license period: %+v %v", l, ok)
	}
	if p, ok := rec.LifecycleOn("portal", testNow); !ok || p.Status != lifecycle.StatusActive {
		t.Fatalf("the lifecycle period: %+v %v", p, ok)
	}
	names := rec.RegistryNames()
	if len(names) != 1 || names[0].Registry != "npm" || names[0].Name != "portal" {
		t.Fatalf("the registry names: %+v", names)
	}
	ids := rec.Identities()
	if len(ids) != 1 || ids[0].Facet != lifecycle.FacetReleasableName || ids[0].Value != "portal" || strings.Join(ids[0].TagPatterns, ",") != "v*" {
		t.Fatalf("the identities: %+v", ids)
	}

	contains(t, f.read("CHANGELOG.md"), "# Changelog")
	contains(t, f.read("CHANGELOG.md"), "The first feature")
	if f.exists(".rlsbl") {
		t.Fatal("the old layout is still there")
	}
	if status := f.repo.Git("status", "--porcelain"); status != "" {
		t.Fatalf("the migration left uncommitted changes:\n%s", status)
	}
	message := f.repo.Git("log", "-1", "--format=%B")
	contains(t, message, CommitMessage)
	contains(t, message, "Autogenerated: true")

	again := f.migrate()
	contains(t, again.Stdout, "already in the .strictmetadata layout")
}

func TestADryRunWritesNothing(t *testing.T) {
	hygiene.Isolate(t)
	f := standalone(t)
	before := f.repo.Git("status", "--porcelain", "--ignored")
	head := f.repo.Head()
	r := testsupport.RunCommand(t, commandOptions(true), func(ctx *strictcli.Context) error { return Run(ctx, f.request()) })
	if r.ExitCode != 0 {
		t.Fatalf("the dry run exited %d:\n%s%s", r.ExitCode, r.Stdout, r.Stderr)
	}
	contains(t, r.Stdout, "Would write .strictmetadata/releasables/releasables.toml")
	contains(t, r.Stdout, "Would remove .rlsbl through saferm")
	if f.exists(".strictmetadata") || !f.exists(".rlsbl/config.json") {
		t.Fatal("the dry run wrote or removed something")
	}
	if after := f.repo.Git("status", "--porcelain", "--ignored"); after != before || f.repo.Head() != head {
		t.Fatalf("the dry run changed the repository:\n%s\n%s", before, after)
	}
	if _, err := os.Stat(f.indexPath); err == nil {
		t.Fatal("the dry run wrote the confidential-name index")
	}
}

func TestTheCommitCarriesOnlyThePathsTheMigrationTouched(t *testing.T) {
	hygiene.Isolate(t)
	f := standalone(t)
	f.write("notes.txt", "kept\n")
	f.commit("an unrelated file")
	f.write("notes.txt", "another session's edit\n")
	f.write("draft.txt", "another session's new file\n")
	r := f.migrate()
	contains(t, r.Stdout, "Left alone (uncommitted, not a path the migration touches): notes.txt")
	committed := strings.Split(f.repo.Git("show", "--name-only", "--format=", "HEAD"), "\n")
	for _, p := range committed {
		if p == "notes.txt" || p == "draft.txt" {
			t.Fatalf("the commit carries %s:\n%s", p, strings.Join(committed, "\n"))
		}
		if !strings.HasPrefix(p, ".strictmetadata/") && !strings.HasPrefix(p, ".rlsbl/") && p != "CHANGELOG.md" {
			t.Fatalf("the commit carries %s, which the migration did not write or remove", p)
		}
	}
	sort.Strings(committed)
	for _, want := range []string{".rlsbl/config.json", ".strictmetadata/releasables/releasables.toml", "CHANGELOG.md", ".strictmetadata/lifecycle-and-license/lifecycle-and-license.toml"} {
		if i := sort.SearchStrings(committed, want); i == len(committed) || committed[i] != want {
			t.Fatalf("the commit does not carry %s:\n%s", want, strings.Join(committed, "\n"))
		}
	}
	if status := f.repo.Git("status", "--porcelain"); !strings.Contains(status, "notes.txt") || !strings.Contains(status, "draft.txt") {
		t.Fatalf("the unrelated changes were not left alone:\n%s", status)
	}
	if f.read("notes.txt") != "another session's edit\n" {
		t.Fatal("the unrelated edit was touched")
	}
}

