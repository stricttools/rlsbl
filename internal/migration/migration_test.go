func TestTransitionsSplitBetweenTheRecordsAndAClosedHistoryRetires(t *testing.T) {
	hygiene.Isolate(t)
	f := withClosedHistory(t)
	plan := f.mustPlan()
	surgery := planned(t, plan, declarations.TransitionsFile)
	contains(t, surgery, `"event":"boundary-alias"`)
	contains(t, surgery, `"releasable":"widget"`)
	lacks(t, surgery, oldKey)
	lacks(t, surgery, "identity-transition")
	lacks(t, surgery, "release-history-closed")

	if planned(t, plan, ".strictmetadata/retired-release-histories/conformance/releases/version") != "0.4.0\n" {
		t.Fatal("the retired subject's version was not moved")
	}
	contains(t, planned(t, plan, ".strictmetadata/retired-release-histories/conformance/changelog/0.4.0.jsonl"), `"format_version":2`)
	contains(t, planned(t, plan, ".strictmetadata/retired-release-histories/conformance/releases/v0.4.0.toml"), "release_commit")
	contains(t, planned(t, plan, ".strictmetadata/retired-release-histories/conformance/config.json"), `"publish_mode": "ci"`)

	rec, err := lifecycle.Parse([]byte(planned(t, plan, lifecycle.RecordFile)))
	if err != nil {
		t.Fatal(err)
	}
	if p, ok := rec.LifecycleOn("conformance", testNow); !ok || p.Status != lifecycle.StatusRetired {
		t.Fatalf("conformance: %+v %v", p, ok)
	}
	var gizmo, gadget, pending bool
	for _, id := range rec.Identities() {
		switch {
		case id.Subject == "gadget" && id.Value == "gizmo" && !id.Open():
			gizmo = true
		case id.Subject == "gadget" && id.Value == "gadget" && id.Open():
			gadget = true
		case id.Subject == "widget" && id.Value == "widget-client" && id.Pending() && id.EffectiveVersion == "0.4.0":
			pending = true
		}
	}
	if !gizmo || !gadget || !pending {
		t.Fatalf("the identities: %+v", rec.Identities())
	}
	tags := rec.UnversionedTags()
	if len(tags) != 1 || tags[0].Tag != "nightly" {
		t.Fatalf("the unversioned tags: %+v", tags)
	}
}

