func TestADryRunRetractionWritesNothing(t *testing.T) {
	hygiene.Isolate(t)
	p, _ := goPortalAt050(t)
	safegit := testsupport.FakeSafegit(t)
	gh := testsupport.FakeGH(t, authStatus, releaseExists("v0.5.0"))
	head, goMod, refs := p.Head(), p.read("go.mod"), p.originRefs()
	r := retract(t, p, true, "0.5.0")
	requireExit(t, r, 0)
	requireContains(t, r.Stdout, "Would retract v0.5.0 of portal through 0.5.1", "retract [v0.5.0, v0.5.1]", "GitHub Releases deleted: v0.5.0")
	if p.Head() != head || p.read("go.mod") != goMod || len(safegit.Calls()) != 0 {
		t.Fatal("the dry run wrote")
	}
	if _, ok := called(gh.Calls(), deleteArgs("v0.5.0")); ok {
		t.Fatal("the dry run deleted a Release")
	}
	if after := p.originRefs(); len(after) != len(refs) {
		t.Fatalf("the dry run pushed: %v", after)
	}
	if p.Git("tag", "--list", "v0.5.1") != "" {
		t.Fatal("the dry run tagged")
	}
}

