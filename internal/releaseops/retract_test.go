// retractionInfoURL is the Go module proxy's info document of portal's
// retraction version, 0.5.1, which every retraction here publishes.
const retractionInfoURL = "https://proxy.golang.org/github.com/acme/portal/@v/v0.5.1.info"

// proxyReturns is the proxy returning the retraction version.
var proxyReturns = get(retractionInfoURL, 200, `{"Version":"v0.5.1","Time":"2026-10-11T00:00:00Z"}`)

func retract(t *testing.T, p *project, dryRun bool, versions ...string) strictcli.Result {
	t.Helper()
	return retractWithProxy(t, p, dryRun, proxyReturns, versions...)
}

// retractWithProxy runs a retraction whose request to the Go module proxy is
// answered with proxy. The proxy is asked for the retraction version, which
// its pushed tag publishes, and about no other version: once by a run that
// succeeds, at most once by one that stops, never by a dry run.
func retractWithProxy(t *testing.T, p *project, dryRun bool, proxy testsupport.HTTPAnswer, versions ...string) strictcli.Result {
	t.Helper()
	req := releaseops.RetractRequest{Dir: p.Dir, Versions: versions, Reason: "Published by mistake", TermList: p.termList}
	fake := testsupport.NewFakeHTTP(t, proxy)
	r := run(t, fake, dryRun, func(ctx *strictcli.Context) error { return releaseops.Retract(ctx, req) })
	urls := fake.URLs()
	for _, u := range urls {
		if u != retractionInfoURL {
			t.Fatalf("the retraction asked for something other than the retraction version: %q", urls)
		}
	}
	if len(urls) > 1 || (r.ExitCode == 0 && !dryRun && len(urls) != 1) || (dryRun && len(urls) != 0) {
		t.Fatalf("the retraction (exit %d, dry run %v) asked the proxy %d times: %q", r.ExitCode, dryRun, len(urls), urls)
	}
	return r
}

// goPortalAt050 is the Go module portal with 0.5.0 released and pushed, and
// unreleased work committed above it.
func goPortalAt050(t *testing.T) (*project, string) {
	t.Helper()
	p := newPortal(t, "go.mod")
	release := p.release("portal", "0.5.0")
	p.CommitFile("notes.md", "unreleased work\n", "Unreleased work")
	return p, release
}

func TestRetractPushesOnlyTheRetractionTagAndRecordsEveryVersionRetracted(t *testing.T) {
	hygiene.Isolate(t)
	p, release := goPortalAt050(t)
	testsupport.FakeSafegit(t)
	gh := testsupport.FakeGH(t, authStatus, releaseExists("v0.5.0"), testsupport.GHAnswer{Args: deleteArgs("v0.5.0")})
	originMain := p.originRefs()["refs/heads/main"]
	r := retract(t, p, false, "0.5.0")
	requireExit(t, r, 0)
	requireContains(t, r.Stdout, "Retracted v0.5.0 of portal through 0.5.1", "v0.5.1")
	requireContains(t, p.read("go.mod"), "\nretract [v0.5.0, v0.5.1] // Published by mistake\n")

	// The retraction commit, then the records, both machine-made.
	subjects := p.subjects(2)
	if subjects[1] != "v0.5.1: retract v0.5.0 and v0.5.1" || subjects[0] != "Record the retraction of v0.5.0 and v0.5.1" {
		t.Fatalf("the last commits are %q", subjects)
	}
	for _, rev := range []string{"HEAD", "HEAD~1"} {
		if !strings.Contains(p.Git("log", "-1", "--format=%B", rev), "Autogenerated: true") {
			t.Errorf("%s carries no Autogenerated trailer", rev)
		}
	}
	retraction := p.Git("rev-parse", "HEAD~1")
	if !strings.Contains(p.Git("show", "--stat", "--format=", retraction), "go.mod") {
		t.Error("the retraction commit does not change go.mod")
	}

	// Only the tag is pushed, at the retraction commit; the branch is not.
	refs := p.originRefs()
	if refs["refs/tags/v0.5.1"] != retraction || p.Git("rev-parse", "v0.5.1") != retraction {
		t.Fatalf("v0.5.1 is not at the retraction commit %s here and on origin: %v", retraction, refs)
	}
	if refs["refs/heads/main"] != originMain {
		t.Fatal("the retraction pushed the branch")
	}
	if refs["refs/tags/v0.5.0"] != release {
		t.Fatal("the retracted version's tag moved")
	}

	// The record holds both versions retracted, neither a release.
	old := p.read(".strictmetadata/releases/portal/v0.5.0.toml")
	requireContains(t, old, `retracted_by = "0.5.1"`, `release_commit = "`+release+`"`)
	next := p.read(".strictmetadata/releases/portal/v0.5.1.toml")
	requireContains(t, next, `retracted_by = "0.5.1"`, `retracts = ["0.5.0"]`, `release_commit = "`+retraction+`"`, "Retracts v0.5.0 and v0.5.1: Published by mistake")
	if has, err := releaserecord.HasRelease(p.Dir, "portal"); err != nil || has {
		t.Fatalf("the record still holds a release: %v %v", has, err)
	}

	// The retracted version's GitHub Release is deleted; none is created.
	if _, ok := called(gh.Calls(), deleteArgs("v0.5.0")); !ok {
		t.Fatalf("the Release of v0.5.0 was not deleted: %+v", gh.Calls())
	}
	for _, c := range gh.Calls() {
		if len(c.Args) > 1 && c.Args[0] == "release" && c.Args[1] == "create" {
			t.Fatalf("a Release was created: %v", c.Args)
		}
	}

	// Running it again finds everything done and writes nothing.
	head := p.Head()
	requireExit(t, retract(t, p, false, "0.5.0"), 0)
	if p.Head() != head {
		t.Fatal("a second run committed")
	}
}

func TestARetractionThatStoppedIsFinishedByRunningItAgain(t *testing.T) {
	hygiene.Isolate(t)
	p, _ := goPortalAt050(t)
	testsupport.FakeSafegit(t)
	testsupport.FakeGH(t, authStatus, releaseExists("v0.5.0"), testsupport.GHAnswer{Args: deleteArgs("v0.5.0"), Stderr: "HTTP 502\n", Exit: 1})
	r := retract(t, p, false, "0.5.0")
	requireExit(t, r, 1)
	requireContains(t, r.Stderr, "deleting the GitHub Release of v0.5.0 failed", "rlsbl release retract")
	head := p.Head()
	gh := testsupport.FakeGH(t, authStatus, releaseExists("v0.5.0"), testsupport.GHAnswer{Args: deleteArgs("v0.5.0")})
	requireExit(t, retract(t, p, false, "0.5.0"), 0)
	if _, ok := called(gh.Calls(), deleteArgs("v0.5.0")); !ok {
		t.Fatal("the run that finished it did not delete the Release")
	}
	if p.Head() != head || strings.Count(p.read("go.mod"), "retract") != 1 {
		t.Fatal("the run that finished it wrote again")
	}
}

func TestARetractionIsNoSuccessUntilTheProxyReturnsTheRetractionVersion(t *testing.T) {
	hygiene.Isolate(t)
	p, _ := goPortalAt050(t)
	testsupport.FakeSafegit(t)
	gh := testsupport.FakeGH(t, authStatus, releaseExists("v0.5.0"), testsupport.GHAnswer{Args: deleteArgs("v0.5.0")})
	r := retractWithProxy(t, p, false, get(retractionInfoURL, 404, "not found: unknown revision v0.5.1\n"), "0.5.0")
	requireExit(t, r, 1)
	requireContains(t, r.Stderr, "the Go module proxy did not return github.com/acme/portal@v0.5.1", "HTTP 404", "unknown revision", "rlsbl release retract")
	if strings.Contains(r.Stdout, "Retracted") {
		t.Fatalf("a retraction the proxy did not return reported success:\n%s", r.Stdout)
	}
	if p.originRefs()["refs/tags/v0.5.1"] == "" {
		t.Fatal("the proxy was asked before the tag was pushed")
	}
	if _, ok := called(gh.Calls(), deleteArgs("v0.5.0")); ok {
		t.Fatal("the run went on past the proxy's refusal")
	}
	// Running it again asks the proxy again, and nothing else is written.
	head := p.Head()
	r = retract(t, p, false, "0.5.0")
	requireExit(t, r, 0)
	requireContains(t, r.Stdout, "Retracted v0.5.0 of portal through 0.5.1", "Go module proxy: github.com/acme/portal@v0.5.1 returned")
	if p.Head() != head {
		t.Fatal("the run that finished it committed")
	}
}

func TestARetractionWhoseRangeCoversAnUnnamedReleaseIsRefused(t *testing.T) {
	hygiene.Isolate(t)
	p := newPortal(t, "go.mod")
	p.release("portal", "0.4.0")
	p.release("portal", "0.5.0")
	testsupport.FakeSafegit(t)
	testsupport.FakeGH(t, authStatus, releaseExists("v0.4.0"), releaseExists("v0.5.0"), testsupport.GHAnswer{Args: deleteArgs("v0.4.0")}, testsupport.GHAnswer{Args: deleteArgs("v0.5.0")})
	head := p.Head()
	r := retract(t, p, false, "0.4.0")
	requireExit(t, r, 1)
	requireContains(t, r.Stderr, "retract [v0.4.0, v0.5.1]", "would also retract 0.5.0", "Nothing was changed")
	if p.Head() != head {
		t.Fatal("a refused retraction committed")
	}
	// Naming every version from 0.4.0 up, as the refusal says, retracts them.
	requireExit(t, retract(t, p, false, "0.4.0", "0.5.0"), 0)
	requireContains(t, p.read("go.mod"), "retract [v0.4.0, v0.5.1] // Published by mistake")
}

