func TestTheAttemptsLocalTagIsRefusedUntilTheBackfillRecordsIt(t *testing.T) {
	hygiene.Isolate(t)
	p := portalWithAnAttempt(t)
	p.Git("tag", "v0.4.0")
	r := abandon(t, p, false)
	requireExit(t, r, 1)
	requireContains(t, r.Stderr, "the attempt's tag v0.4.0 exists in this repository", "rlsbl release backfill --dry-run")
	// What the backfill does: record the release the tag is evidence of.
	// finalize tags the release commit itself, so the tag is taken off first.
	tagged := p.Git("rev-parse", "v0.4.0^{commit}")
	p.Git("tag", "-d", "v0.4.0")
	p.finalize("portal", "0.4.0", tagged)
	r = abandon(t, p, false)
	if strings.Contains(r.Stderr, "exists in this repository") {
		t.Fatalf("the refusal did not clear:\n%s", r.Stderr)
	}
	requireContains(t, r.Stderr, "already archived, as a release")
}

func TestTheAttemptsTagOnOriginIsRefusedNamingTheFetch(t *testing.T) {
	hygiene.Isolate(t)
	p := portalWithAnAttempt(t)
	p.Git("tag", "v0.4.0")
	p.Git("push", "-q", "origin", "v0.4.0")
	p.Git("tag", "-d", "v0.4.0")
	r := abandon(t, p, false)
	requireExit(t, r, 1)
	requireContains(t, r.Stderr, "exists on origin", "git fetch origin tag v0.4.0")
	p.Git("fetch", "-q", "origin", "tag", "v0.4.0")
	r = abandon(t, p, false)
	requireContains(t, r.Stderr, "exists in this repository")
}

