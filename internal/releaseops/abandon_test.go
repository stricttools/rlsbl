func TestADryRunAbandonWritesNothing(t *testing.T) {
	hygiene.Isolate(t)
	p := portalWithAnAttempt(t)
	safegit := testsupport.FakeSafegit(t)
	testsupport.FakeGH(t, authStatus, releaseMissing("v0.4.0"))
	r := abandon(t, p, true)
	requireExit(t, r, 0)
	requireContains(t, r.Stdout, "Would record 0.4.0", "Would delete")
	if p.exists(archive040) || !p.exists(runstate.InProgressPath("portal")) || len(safegit.Calls()) != 0 {
		t.Fatal("a dry run wrote")
	}
}

func TestARunAfterAnInterruptedAbandonFinishesIt(t *testing.T) {
	hygiene.Isolate(t)
	p := portalWithAnAttempt(t)
	testsupport.FakeSafegit(t)
	testsupport.FakeGH(t, authStatus, releaseMissing("v0.4.0"))
	requireExit(t, abandon(t, p, false), 0)
	// The earlier run stopped before deleting the state file.
	p.inProgress("portal", "0.4.0")
	head := p.Head()
	r := abandon(t, p, false)
	requireExit(t, r, 0)
	requireContains(t, r.Stdout, "completed the earlier abandon of 0.4.0")
	if p.Head() != head || p.exists(runstate.InProgressPath("portal")) {
		t.Fatal("the run did not just delete the state file")
	}
}

