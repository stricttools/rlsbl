func TestVersionFilesBehindTheLatestReleaseAreRefusedUntilTheyNameIt(t *testing.T) {
	hygiene.Isolate(t)
	p := newPortal(t, "package.json")
	p.release("portal", "0.3.0")
	p.CommitFile("package.json", packageJSON("portal", "0.2.0"), "go back")
	r := abandon(t, p, false)
	requireExit(t, r, 1)
	requireContains(t, r.Stderr, "behind the latest release, 0.3.0", "Set the version files to 0.3.0")
	p.CommitFile("package.json", packageJSON("portal", "0.3.0"), "forward again")
	r = abandon(t, p, false)
	if strings.Contains(r.Stderr, "behind the latest release") {
		t.Fatalf("the refusal did not clear:\n%s", r.Stderr)
	}
}

