func abandon(t *testing.T, p *project, dryRun bool) strictcli.Result {
	t.Helper()
	return run(t, nil, dryRun, func(ctx *strictcli.Context) error {
		return releaseops.Abandon(ctx, releaseops.AbandonRequest{Dir: p.Dir})
	})
}

// inProgress writes releasable's in-progress state for an attempt at v.
func (p *project) inProgress(releasable, v string) string {
	p.t.Helper()
	state := runstate.InProgress{
		Releasable:           releasable,
		RepresentativeMember: "root",
		Version:              v,
		Tag:                  p.tagOf(releasable, v),
		Branch:               "main",
		Bump:                 "minor",
		CommitMessage:        p.tagOf(releasable, v),
		Description:          "the attempt",
		Include:              []string{},
		Exclude:              []string{},
		PreReleaseCommit:     p.Head(),
		PinCommit:            p.Head(),
		CompletedSteps:       []string{"version-bumped"},
	}
	rel := runstate.InProgressPath(releasable)
	p.Write(rel, string(state.Render()))
	return rel
}

// portalWithAnAttempt is portal with 0.3.0 released and an attempt at 0.4.0
// that bumped the version files and stopped before it was recorded.
func portalWithAnAttempt(t *testing.T) *project {
	t.Helper()
	p := newPortal(t, "package.json")
	p.release("portal", "0.3.0")
	p.bump("portal", "0.4.0")
	p.inProgress("portal", "0.4.0")
	return p
}

const archive040 = ".strictmetadata/releases/portal/v0.4.0.toml"

func TestAbandonRecordsTheStateFilesVersionAsNeverReleased(t *testing.T) {
	hygiene.Isolate(t)
	p := portalWithAnAttempt(t)
	testsupport.FakeSafegit(t)
	testsupport.FakeGH(t, authStatus, releaseMissing("v0.4.0"))
	r := abandon(t, p, false)
	requireExit(t, r, 0)
	requireContains(t, r.Stdout, "Recorded 0.4.0 as never released", "Deleted the in-progress release state")
	requireContains(t, p.read(archive040), "never_released = true", `bump = "minor"`, "Written by `rlsbl release abandon`")
	if p.exists(runstate.InProgressPath("portal")) {
		t.Fatal("the in-progress state is still there")
	}
	if got := p.subjects(1)[0]; got != "Record 0.4.0 as never released (abandoned release attempt)" {
		t.Fatalf("the last commit is %q", got)
	}
	requireContains(t, p.Git("log", "-1", "--format=%B"), "Autogenerated: true")
	if got := p.Git("show", "--name-only", "--format=", "HEAD"); got != archive040 {
		t.Fatalf("the abandon commit carries %q", got)
	}
}

