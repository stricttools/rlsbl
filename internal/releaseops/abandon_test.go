func TestDisagreeingVersionFilesAreRefusedUntilTheyAgree(t *testing.T) {
	hygiene.Isolate(t)
	p := newPortal(t, "package.json", "pyproject.toml")
	p.release("portal", "0.3.0")
	p.Write("package.json", packageJSON("portal", "0.4.0"))
	p.Write("pyproject.toml", pyproject("portal", "0.5.0"))
	p.Commit("disagree", "package.json", "pyproject.toml")
	testsupport.FakeSafegit(t)
	testsupport.FakeGH(t, authStatus, releaseMissing("v0.4.0"))
	r := abandon(t, p, false)
	requireExit(t, r, 1)
	requireContains(t, r.Stderr, "the version files disagree", "npm (.): 0.4.0", "pypi (.): 0.5.0", "Make them agree")
	p.CommitFile("pyproject.toml", pyproject("portal", "0.4.0"), "agree")
	requireExit(t, abandon(t, p, false), 0)
}

