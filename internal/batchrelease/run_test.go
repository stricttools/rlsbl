func TestABatchReleasesItsReleasablesInDependencyOrderOnOneCandidate(t *testing.T) {
	hygiene.Isolate(t)
	gh := testsupport.FakeGH(t, answers(validationAnswers(), releaseCreation("widget@v0.2.0"), releaseCreation("gadget@v0.2.1"))...)
	repo := batchRepo(t, nil)
	start := repo.Head()
	out, err := batchCommand(t, repo, false)
	mustNotFail(t, err, out)
	widget, gadget := tagCommit(t, repo, "widget@v0.2.0"), tagCommit(t, repo, "gadget@v0.2.1")
	if widget == "" || widget != gadget {
		t.Fatalf("the two releasables are not tagged on one candidate: widget %q, gadget %q\n%s", widget, gadget, out)
	}
	if remoteRef(t, repo, "refs/tags/widget@v0.2.0") != widget || remoteRef(t, repo, "refs/tags/gadget@v0.2.1") != gadget {
		t.Errorf("origin does not hold both tags at the candidate")
	}
	// widget, which gadget depends on, is released first although gadget
	// comes first by name: its release commit is the older of the two.
	subjects := repo.Git("log", "--format=%s", start+".."+widget)
	if w, g := strings.Index(subjects, "widget: release v0.2.0"), strings.Index(subjects, "gadget: release v0.2.1"); w < 0 || g < 0 || g > w {
		t.Errorf("the release commits are not in dependency order (newest first):\n%s", subjects)
	}
	var created []string
	for _, c := range gh.Calls() {
		if len(c.Args) > 2 && c.Args[0] == "release" && c.Args[1] == "create" {
			created = append(created, c.Args[2])
		}
	}
	if strings.Join(created, ",") != "widget@v0.2.0,gadget@v0.2.1" {
		t.Errorf("the GitHub Releases were created as %v", created)
	}
	for _, archive := range []string{".strictmetadata/releases/widget/v0.2.0.toml", ".strictmetadata/releases/gadget/v0.2.1.toml"} {
		requireContains(t, read(t, repo.Path(archive)), `release_commit = "`+widget+`"`, "next release")
	}
	if read(t, repo.Path(".strictmetadata/releases/widget/version")) != "0.2.0\n" || read(t, repo.Path(".strictmetadata/releases/gadget/version")) != "0.2.1\n" {
		t.Errorf("the version files were not bumped")
	}
	// The batch release file is archived, committed, and pushed; the plan
	// and the release states are gone.
	if exists(t, repo.Path(batchFilePath)) {
		t.Errorf("the batch release file was not archived")
	}
	archives := batchArchives(t, repo)
	if len(archives) != 1 || !strings.Contains(read(t, archives[0]), "[releasables.gadget]") {
		t.Fatalf("the batch release file's archive: %v", archives)
	}
	requireContains(t, repo.Git("log", "-1", "--format=%B"), "chore: archive the batch release file as batch-", "Autogenerated: true")
	if remoteRef(t, repo, "refs/heads/main") != repo.Head() {
		t.Errorf("origin's main is not the working tree's after the archive")
	}
	if exists(t, repo.Path(runstate.BatchPlanPath)) {
		t.Errorf("the batch plan was left behind")
	}
	for _, name := range []string{"widget", "gadget"} {
		if _, found := loadState(t, repo, name); found {
			t.Errorf("the release state of %s was left behind", name)
		}
	}
	if c := changes(t, repo); c != "" {
		t.Errorf("the batch left the working tree changed:\n%s", c)
	}
	requireContains(t, out, "Batch release complete: widget, gadget")
}

func TestABatchStoppedByARedVerdictContinuesAtTheSameVersionsAfterTheFix(t *testing.T) {
	hygiene.Isolate(t)
	testsupport.FakeGH(t, answers(validationAnswers(), ciRun(42, "failure"))...)
	repo := batchRepo(t, map[string]string{".github/workflows/ci.yml": ciWorkflow})
	out, err := batchCommand(t, repo, false)
	if err == nil || !strings.Contains(err.Error(), "CI did not pass on the batch release candidate") || !strings.Contains(err.Error(), "rlsbl monorepo release run --watch") {
		t.Fatalf("a red verdict did not stop the batch naming how it continues: %v\n%s", err, out)
	}
	var candidate string
	for _, name := range []string{"widget", "gadget"} {
		state, found := loadState(t, repo, name)
		if !found || !state.Completed(release.StepCandidatePushed) || state.Completed(release.StepCIVerified) || state.FailedSteps[release.StepCIVerified] == "" {
			t.Fatalf("the stopped state of %s: %+v", name, state)
		}
		candidate = state.ReleaseCommit
	}
	if remoteRef(t, repo, "refs/heads/main") != candidate || tagCommit(t, repo, "widget@v0.2.0") != "" || tagCommit(t, repo, "gadget@v0.2.1") != "" {
		t.Fatalf("the candidate is not on origin untagged")
	}
	if !exists(t, repo.Path(runstate.BatchPlanPath)) || !exists(t, repo.Path(batchFilePath)) {
		t.Fatalf("the plan or the batch release file is gone")
	}
	// The fix forward the refusal names, recorded in widget's changelog.
	fix := repo.CommitFile("widget/fix.txt", "the fix\n", "fix the failure")
	addEntry(t, repo, "widget", false, fix)
	tip := repo.Head()
	testsupport.FakeGH(t, answers(validationAnswers(), ciRun(43, "success"), releaseCreation("widget@v0.2.0"), releaseCreation("gadget@v0.2.1"))...)
	out, err = batchCommand(t, repo, false)
	mustNotFail(t, err, out)
	if tagCommit(t, repo, "widget@v0.2.0") != tip || tagCommit(t, repo, "gadget@v0.2.1") != tip {
		t.Errorf("the releasables are not tagged on the fixed tip CI verified (%s)", tip)
	}
	requireContains(t, read(t, repo.Path(".strictmetadata/changelog/widget/0.2.0.jsonl")), fix)
	if exists(t, repo.Path(runstate.BatchPlanPath)) || exists(t, repo.Path(batchFilePath)) || len(batchArchives(t, repo)) != 1 {
		t.Errorf("the finished batch was not archived")
	}
}

func TestABatchStoppedPastTheVerdictIsRefusedUntilThatReleaseIsResumed(t *testing.T) {
	hygiene.Isolate(t)
	testsupport.FakeGH(t, answers(validationAnswers(), failingReleaseCreation("widget@v0.2.0"))...)
	repo := batchRepo(t, nil)
	out, err := batchCommand(t, repo, false)
	if err == nil || !strings.Contains(err.Error(), "Finish widget with `rlsbl release resume --watch`") {
		t.Fatalf("a failed GitHub Release did not stop the batch naming the resume: %v\n%s", err, out)
	}
	if state, found := loadState(t, repo, "widget"); !found || !state.Completed(release.StepCIVerified) || state.FailedSteps[release.StepGitHubReleaseCreated] == "" {
		t.Fatalf("widget's stopped state: %+v", state)
	}
	if state, found := loadState(t, repo, "gadget"); !found || state.Completed(release.StepCIVerified) {
		t.Fatalf("gadget's stopped state: %+v", state)
	}
	// Running the batch again would move the commit widget's verdict is
	// about: refused, naming the resume and where to run it.
	head := repo.Head()
	widgetDir, err := filepath.EvalSymlinks(repo.Path("widget"))
	if err != nil {
		t.Fatal(err)
	}
	testsupport.FakeGH(t, validationAnswers()...)
	_, err = batchCommand(t, repo, false)
	if err == nil || !strings.Contains(err.Error(), "`rlsbl release resume --watch`") || !strings.Contains(err.Error(), widgetDir) {
		t.Fatalf("a batch with a release past its verdict was not refused: %v", err)
	}
	if repo.Head() != head {
		t.Fatalf("the refused batch committed")
	}
	// The fix the refusal names: widget's release resumed from its member.
	testsupport.FakeGH(t, answers(validationAnswers(), releaseCreation("widget@v0.2.0"))...)
	out, err = resumeCommand(t, repo, repo.Path("widget"))
	mustNotFail(t, err, out)
	if _, found := loadState(t, repo, "widget"); found || tagCommit(t, repo, "widget@v0.2.0") == "" {
		t.Fatalf("the resume did not finish widget's release")
	}
	// The batch then finishes gadget and archives itself.
	testsupport.FakeGH(t, answers(validationAnswers(), releaseCreation("gadget@v0.2.1"))...)
	out, err = batchCommand(t, repo, false)
	mustNotFail(t, err, out)
	requireContains(t, out, "Skipping widget", "Batch release complete: gadget")
	if tagCommit(t, repo, "gadget@v0.2.1") == "" || remoteRef(t, repo, "refs/tags/gadget@v0.2.1") == "" {
		t.Errorf("gadget was not released")
	}
	if exists(t, repo.Path(batchFilePath)) || exists(t, repo.Path(runstate.BatchPlanPath)) {
		t.Errorf("the finished batch was not archived")
	}
}

