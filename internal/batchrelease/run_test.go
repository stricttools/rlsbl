func TestABatchReleasableWithAReleaseFileOfItsOwnIsRefusedUntilItIsDeleted(t *testing.T) {
	hygiene.Isolate(t)
	testsupport.FakeGH(t, validationAnswers()...)
	repo := batchRepo(t, nil)
	own := ".strictmetadata/releases/widget/unreleased.toml"
	repo.CommitFile(own, "format_version = 2\nbump = \"major\"\ninclude = [\"npm\"]\nexclude = []\ndescription = \"its own\"\n", "widget's own release file")
	_, err := batchCommand(t, repo, true)
	if err == nil || !strings.Contains(err.Error(), "a release file of its own") || !strings.Contains(err.Error(), "saferm delete") || !strings.Contains(err.Error(), "safegit commit") {
		t.Fatalf("a releasable with two release files was not refused: %v", err)
	}
	// The fix the refusal names: the release file deleted, the deletion
	// committed.
	repo.Git("rm", "-q", own)
	repo.Git("commit", "-q", "-m", "release widget through the batch release file")
	out, err := batchCommand(t, repo, true)
	mustNotFail(t, err, out)
}

func TestABatchReleaseFileThatNoLongerMatchesItsPlanIsRefusedUntilThePlanIsGone(t *testing.T) {
	hygiene.Isolate(t)
	testsupport.FakeGH(t, validationAnswers()...)
	repo := batchRepo(t, nil)
	plan := runstate.BatchPlan{Items: []runstate.BatchPlanItem{
		{Name: "widget", BaseVersion: "0.1.0", TargetVersion: "1.0.0", Tag: "widget@v1.0.0", Registry: "npm", Bump: "major"},
	}}
	testsupport.WriteFile(t, repo.Path(runstate.BatchPlanPath), string(runstate.RenderBatchPlan(plan)))
	_, err := batchCommand(t, repo, true)
	if err == nil || !strings.Contains(err.Error(), "does not match the plan") || !strings.Contains(err.Error(), "the plan bumps widget major, and the batch release file minor") || !strings.Contains(err.Error(), "saferm delete") {
		t.Fatalf("a batch release file not matching its plan was not refused: %v", err)
	}
	// The fix the refusal names: the plan deleted.
	if err := os.Remove(repo.Path(runstate.BatchPlanPath)); err != nil {
		t.Fatal(err)
	}
	out, err := batchCommand(t, repo, true)
	mustNotFail(t, err, out)
}

