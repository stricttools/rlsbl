// The pre-release pipeline runs in the release checkout before the
// preflight, in this order: the pre-checks hooks; the strictcli schema dump
// of every member that is a strictcli program; `selfdoc gen` and then
// `selfdoc check` in every member declaring selfdoc.json, both told the
// version being released; and the selfdoc commit, which commits what the
// selfdoc steps wrote with the Autogenerated trailer. That commit is one of
// the release's own commits, so the refuse-on-drift checkpoints never take
// it for another session's work.

// SelfdocCommitMessage is the subject of the selfdoc commit.
const SelfdocCommitMessage = "selfdoc: regenerate"

// noHelpCommand is what a strictcli without a help command answers `help
// --json` with on stderr.
const noHelpCommand = "error: unknown command 'help'"

// helpUpgrades are the last release of each strictcli implementation without
// `help --json`, and how a project on it moves past it.
var helpUpgrades = map[string][2]string{
	targets.StrictcliPython:     {"Python strictcli 0.43.0", "raise the strictcli requirement in pyproject.toml above 0.43.0 and run `uv lock --upgrade-package strictcli`"},
	targets.StrictcliGo:         {"Go strictcli v0.36.0", "run `go get github.com/stricttools/strictcli/go@latest` and `go mod tidy`"},
	targets.StrictcliTypeScript: {"TypeScript strictcli 0.42.0", "run `npm install strictcli@latest`"},
}

// SchemaDump is one member's strictcli schema dump: the member's directory
// and the program whose `help --json` is written to its SchemaDumpPath.
type SchemaDump struct {
	Member  string
	Dir     string
	Program targets.StrictcliProgram
}

// argv is the command printing the program's help document.
func (d SchemaDump) argv() ([]string, error) {
	var launcher []string
	switch d.Program.Language {
	case targets.StrictcliPython:
		launcher = []string{"uv", "run", d.Program.EntryPoint}
	case targets.StrictcliGo:
		launcher = []string{"go", "run", d.Program.EntryPoint}
	case targets.StrictcliTypeScript:
		launcher = []string{"node", d.Program.EntryPoint}
	default:
		return nil, fmt.Errorf("the member %q is a strictcli program in %q, a language rlsbl does not dump", d.Member, d.Program.Language)
	}
	return append(launcher, "help", "--json"), nil
}

// PipelineInputs are what the pre-release pipeline runs on.
type PipelineInputs struct {
	// Workspace is rooted at the release checkout (the working tree under
	// --dry-run).
	Workspace *workspace.Workspace
	// Repo is the repository at the workspace's root.
	Repo           git.Repo
	Releasable     string
	Representative string
	Version        semver.Version
	Hooks          HookContext
	// Environment is what every program of the release gets.
	Environment map[string]string
	HookTimeout time.Duration
	// ProgramTimeout bounds the schema dump and each selfdoc run.
	ProgramTimeout time.Duration
	DryRun         bool
	Log            func(string)
}

// PipelineResult is what the pre-release pipeline did.
type PipelineResult struct {
	// SelfdocCommit is the selfdoc commit, empty when the selfdoc steps wrote
	// nothing or ran under --dry-run, where nothing they would write exists.
	SelfdocCommit string
	// Dumps are the schema dumps it ran.
	Dumps []SchemaDump
	// Selfdoc are the members it ran selfdoc in, by name.
	Selfdoc []string
}

// SchemaDumps are the strictcli schema dumps of the releasable's members:
// each member whose directory strictcli detection finds a strictcli program
// in. A member that depends on strictcli while its entry point cannot be
// told is an error.
func SchemaDumps(r targets.Runner, w *workspace.Workspace, releasable string) ([]SchemaDump, error) {
	var out []SchemaDump
	for _, m := range sortedMembers(w.MembersOf(releasable)) {
		dir := w.MemberDir(m)
		program, found, err := targets.DetectStrictcli(r, dir)
		if err != nil {
			return nil, err
		}
		if found {
			out = append(out, SchemaDump{Member: m.Name, Dir: dir, Program: program})
		}
	}
	return out, nil
}

// SelfdocMembers are the members of the releasable whose directory holds
// selfdoc.json, by name.
func SelfdocMembers(w *workspace.Workspace, releasable string) ([]declarations.Member, error) {
	var out []declarations.Member
	for _, m := range sortedMembers(w.MembersOf(releasable)) {
		_, err := os.Stat(filepath.Join(w.MemberDir(m), selfdocFile))
		if errors.Is(err, fs.ErrNotExist) {
			continue
		}
		if err != nil {
			return nil, err
		}
		out = append(out, m)
	}
	return out, nil
}

func sortedMembers(members []declarations.Member) []declarations.Member {
	out := append([]declarations.Member(nil), members...)
	sort.Slice(out, func(i, j int) bool { return out[i].Name < out[j].Name })
	return out
}

// RunPipeline runs the pre-release pipeline. The schema dumps are decided
// before anything runs (strictcli detection lists a Go module's packages,
// which a preview cannot ask about once it recorded a write). Under
// --dry-run every program is recorded rather than run, and the selfdoc
// commit is not made, since nothing it would carry was written.
func RunPipeline(e *strictcli.Effects, in PipelineInputs) (PipelineResult, error) {
	log := in.Log
	if log == nil {
		log = func(string) {}
	}
	var result PipelineResult
	dumps, err := SchemaDumps(e, in.Workspace, in.Releasable)
	if err != nil {
		return result, &ValidationError{Message: err.Error()}
	}
	selfdocMembers, err := SelfdocMembers(in.Workspace, in.Releasable)
	if err != nil {
		return result, err
	}
	if len(selfdocMembers) > 0 {
		if _, err := exec.LookPath("selfdoc"); err != nil {
			var dirs []string
			for _, m := range selfdocMembers {
				dirs = append(dirs, declarations.Join(m.Path, selfdocFile))
			}
			return result, &ValidationError{Message: fmt.Sprintf("%s declares documentation that selfdoc generates and checks, and selfdoc is not on PATH; a release never ships its documentation unchecked, so install selfdoc and run the release again", strings.Join(dirs, ", "))}
		}
	}
	runs, err := HookRuns(in.Workspace, in.Releasable, in.Representative, PreChecks, in.Hooks)
	if err != nil {
		return result, err
	}
	if len(runs) > 0 {
		log(fmt.Sprintf("Running %d pre-checks hook(s)", len(runs)))
	}
	if err := RunHooks(e, runs, in.Environment, in.HookTimeout); err != nil {
		return result, err
	}
	for _, d := range dumps {
		if err := writeSchemaDump(e, d, in); err != nil {
			return result, err
		}
		result.Dumps = append(result.Dumps, d)
	}
	var before map[string]bool
	if !in.DryRun && len(selfdocMembers) > 0 {
		if before, err = changedPaths(in.Repo); err != nil {
			return result, err
		}
	}
	version := in.Version.String()
	for _, verb := range []string{"gen", "check"} {
		for _, m := range selfdocMembers {
			log(fmt.Sprintf("Running selfdoc %s in %s", verb, m.Path))
			argv := []interface{}{"selfdoc", verb, "--no-auto-commit", "--version-override", version}
			if _, err := e.Run(argv, strictcli.Cwd(in.Workspace.MemberDir(m)), strictcli.EffectEnv(in.Environment), strictcli.Stream(true), strictcli.Timeout(in.ProgramTimeout)); err != nil {
				return result, fmt.Errorf("selfdoc %s in %s failed, so the release stops before anything is committed: %w. Fix what it reports and run the release again", verb, m.Path, err)
			}
		}
	}
	for _, m := range selfdocMembers {
		result.Selfdoc = append(result.Selfdoc, m.Name)
	}
	if in.DryRun || len(selfdocMembers) == 0 {
		return result, nil
	}
	after, err := changedPaths(in.Repo)
	if err != nil {
		return result, err
	}
	var written []string
	for p := range after {
		if !before[p] {
			written = append(written, p)
		}
	}
	sort.Strings(written)
	if len(written) == 0 {
		return result, nil
	}
	committed, err := in.Repo.CommitDetached(git.CommitRequest{Message: SelfdocCommitMessage, Paths: written, Autogenerated: true})
	if err != nil || !committed {
		return result, err
	}
	if result.SelfdocCommit, err = in.Repo.Head(); err != nil {
		return result, err
	}
	log(fmt.Sprintf("Committed what selfdoc wrote (%d file(s)) as %s", len(written), short(result.SelfdocCommit)))
	return result, nil
}

// changedPaths are the repository's changed paths, rlsbl's run state left
// out.
func changedPaths(repo git.Repo) (map[string]bool, error) {
	changes, err := repo.Changes()
	if err != nil {
		return nil, err
	}
	out := map[string]bool{}
	for _, c := range changes {
		if !isRunState(c.Path) {
			out[c.Path] = true
		}
	}
	return out, nil
}

// schemaVersionLine is the top-level version member of a help document in
// strictcli's canonical encoding: two spaces of indent, so a "version" key
// nested deeper never matches.
var schemaVersionLine = regexp.MustCompile(`(?m)^  "version": "(?:[^"\\]|\\.)*"(,?)$`)

// writeSchemaDump runs the program's `help --json` and writes its stdout,
// the help document, to the member's SchemaDumpPath with the version being
// released as its version. Under --dry-run the program is recorded and
// nothing is written.
func writeSchemaDump(e *strictcli.Effects, d SchemaDump, in PipelineInputs) error {
	argv, err := d.argv()
	if err != nil {
		return err
	}
	shown := strings.Join(argv, " ")
	target := filepath.Join(d.Dir, filepath.FromSlash(targets.SchemaDumpPath))
	if in.Log != nil {
		in.Log(fmt.Sprintf("Writing the strictcli help document of %s (%s)", d.Member, shown))
	}
	args := make([]interface{}, len(argv))
	for i, a := range argv {
		args[i] = a
	}
	done, err := e.Run(args, strictcli.Cwd(d.Dir), strictcli.EffectEnv(in.Environment), strictcli.Check(false), strictcli.Timeout(in.ProgramTimeout))
	if err != nil {
		return &ValidationError{Message: fmt.Sprintf("the strictcli help document of %s could not be written: `%s` failed: %v", d.Member, shown, err)}
	}
	if in.DryRun {
		return nil
	}
	stderr := strings.TrimSpace(done.Stderr())
	if code := done.ExitCode(); code != 0 {
		if strings.Contains(stderr, noHelpCommand) {
			upgrade := helpUpgrades[d.Program.Language]
			return &ValidationError{Message: fmt.Sprintf("`%s` exited %d: %s\nThis program's strictcli predates `help --json`, the command that prints the help document the release writes to %s. %s and every earlier release have only `--dump-schema`, which rlsbl does not run. Upgrade strictcli in %s (%s), commit it, and run the release again", shown, code, stderr, target, upgrade[0], d.Dir, upgrade[1])}
		}
		detail := ""
		if stderr != "" {
			detail = ": " + stderr
		}
		return &ValidationError{Message: fmt.Sprintf("the strictcli help document of %s could not be written: `%s` exited %d%s", d.Member, shown, code, detail)}
	}
	document := done.Stdout()
	var parsed map[string]any
	if err := json.Unmarshal([]byte(document), &parsed); err != nil || parsed["schema_version"] == nil {
		shownOut := strings.TrimSpace(document)
		if len(shownOut) > 200 {
			shownOut = shownOut[:200]
		}
		if shownOut == "" {
			shownOut = "(nothing)"
		}
		return &ValidationError{Message: fmt.Sprintf("`%s` exited 0, and its stdout is not a strictcli help document (a JSON object with a schema_version): %s", shown, shownOut)}
	}
	if !strings.HasSuffix(document, "\n") {
		document += "\n"
	}
	stamped, err := stampSchemaVersion(document, in.Version, target)
	if err != nil {
		return err
	}
	return writeKeepingMode(e, target, []byte(stamped))
}

// stampSchemaVersion is the help document with its top-level version set to
// v, every other byte kept: strictcli prints the document in its own
// canonical encoding, which a decode and re-encode would not reproduce.
func stampSchemaVersion(document string, v semver.Version, target string) (string, error) {
	loc := schemaVersionLine.FindStringSubmatchIndex(document)
	if loc == nil {
		return "", &ValidationError{Message: fmt.Sprintf("the help document bound for %s has no top-level \"version\" key on a line of its own: either the program declares no version, or something other than strictcli printed the document", target)}
	}
	value, err := json.Marshal(v.String())
	if err != nil {
		return "", err
	}
	comma := document[loc[2]:loc[3]]
	return document[:loc[0]] + `  "version": ` + string(value) + comma + document[loc[1]:], nil
}

// writeKeepingMode replaces the file at path with data through a sibling
// written first and renamed, keeping the mode of the file it replaces (0644
// for a new one), creating its directory.
func writeKeepingMode(e *strictcli.Effects, path string, data []byte) error {
	mode := os.FileMode(0o644)
	if info, err := os.Stat(path); err == nil {
		mode = info.Mode().Perm()
	} else if !errors.Is(err, fs.ErrNotExist) {
		return err
	}
	if _, err := e.Mkdir(filepath.Dir(path)); err != nil {
		return err
	}
	tmp := path + ".rlsbl-writing"
	if _, err := e.Write(tmp, data, strictcli.Mode(mode)); err != nil {
		return err
	}
	_, err := e.Rename(tmp, path)
	return err
}
