func TestStatusAsksForTheTargetWhenTheMemberHasSeveral(t *testing.T) {
	hygiene.Isolate(t)
	repo := standalone(t, "none")
	repo.CommitFile("pyproject.toml", "[project]\nname = \"portal\"\nversion = \"0.4.1\"\n", "python too")
	_, err := readStatus(t, nil, release.StatusRequest{Dir: repo.Dir})
	if err == nil {
		t.Fatal("a member of two targets was reported on without naming one")
	}
	requireContains(t, err.Error(), "npm, pypi", "--target")
	st, err := readStatus(t, nil, release.StatusRequest{Dir: repo.Dir, Target: "pypi"})
	mustNotFail(t, err)
	if st.Target != "pypi" || st.Version != "0.4.1" || !slices.Contains(st.VersionFiles, "pyproject.toml") {
		t.Fatalf("status %+v", st)
	}
	if _, err := readStatus(t, nil, release.StatusRequest{Dir: repo.Dir, Target: "go"}); err == nil || !strings.Contains(err.Error(), "has no go target; its targets are npm, pypi") {
		t.Fatalf("a target the member does not have: %v", err)
	}
}

