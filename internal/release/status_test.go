func TestStatusInAWorkspaceCountsOnlyTheReleasablesCommits(t *testing.T) {
	hygiene.Isolate(t)
	repo := workspaceRepo(t)
	recordRelease(t, repo, "widget", "0.1.0", "widget@v0.1.0", "recorded")
	repo.CommitFile("widget/a.txt", "a\n", "a widget change")
	repo.CommitFile("gadget/a.txt", "a\n", "a gadget change")
	repo.CommitFile("widget/b.txt", "b\n", "another widget change")
	st, err := readStatus(t, nil, release.StatusRequest{Dir: repo.Path("widget")})
	mustNotFail(t, err)
	if !st.Workspace || st.ReleasableVersion == nil || *st.ReleasableVersion != "0.1.0" {
		t.Fatalf("status %+v", st)
	}
	if st.CommitsAhead == nil || *st.CommitsAhead != 2 || *st.NearestReleaseTag != "widget@v0.1.0" {
		t.Fatalf("ahead %+v", st)
	}
	if st.Coverage == nil || st.Coverage.Exempted != 1 {
		t.Fatalf("the archive commit is the only exempt one in widget's scope: %+v", st.Coverage)
	}
}

