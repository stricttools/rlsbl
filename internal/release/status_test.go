func readStatus(t *testing.T, fake *testsupport.FakeHTTP, req release.StatusRequest) (release.Status, error) {
	t.Helper()
	var st release.Status
	err := run(t, fake, func(e *strictcli.Effects) error {
		var err error
		st, err = release.ReadStatus(e, req)
		return err
	})
	return st, err
}

// released is portal released at 0.4.0, followed by a change the changelog
// covers, an autogenerated commit, and the changelog entry's own commit.
func released(t *testing.T, publishMode string) (*testsupport.Repo, string) {
	t.Helper()
	repo := standalone(t, publishMode)
	recordRelease(t, repo, "portal", "0.4.0", "v0.4.0", "recorded")
	change := repo.CommitFile("b.txt", "b\n", "a change")
	repo.CommitFile("c.txt", "c\n", "regenerate\n\nAutogenerated: true")
	addEntry(t, repo, "portal", change)
	return repo, change
}

func TestStatusReportsTheProjectItsReleaseAndItsCoverage(t *testing.T) {
	hygiene.Isolate(t)
	repo, _ := released(t, "none")
	repo.Write(".github/workflows/ci-npm.yml", "name: ci\n")
	repo.Write(".github/workflows/publish.yml", "name: publish\n")
	repo.Commit("workflows", ".github/workflows/ci-npm.yml", ".github/workflows/publish.yml")
	st, err := readStatus(t, nil, release.StatusRequest{Dir: repo.Dir})
	mustNotFail(t, err)
	if st.Member != "root" || st.Releasable == nil || *st.Releasable != "portal" || st.Workspace {
		t.Fatalf("selection %+v", st)
	}
	if st.Target != "npm" || st.Name != "portal" || st.Version != "0.4.0" || !slices.Equal(st.VersionFiles, []string{"package.json"}) {
		t.Fatalf("package %+v", st)
	}
	if st.Branch == nil || *st.Branch != "main" || !st.Clean || st.ReleasableVersion != nil {
		t.Fatalf("checkout %+v", st)
	}
	if st.LatestRelease == nil || *st.LatestRelease != "0.4.0" || st.LatestReleaseInCheckout == nil || !*st.LatestReleaseInCheckout || *st.LatestReleaseState != "recorded" || st.LatestReleaseLabel != "0.4.0" {
		t.Fatalf("latest %+v", st)
	}
	if st.ChangelogHasVersion == nil || !*st.ChangelogHasVersion {
		t.Fatalf("the released changelog file of 0.4.0 was not found: %+v", st)
	}
	// After the release: the archive commit, the change, the autogenerated
	// commit, the changelog commit, and the workflows commit, which needs an
	// entry the changelog does not give it.
	if st.Coverage == nil || *st.Coverage != (release.Coverage{Covered: 1, Total: 2, Exempted: 3}) {
		t.Fatalf("coverage %+v", st.Coverage)
	}
	if st.CommitsAhead == nil || *st.CommitsAhead != 2 || st.NearestReleaseTag == nil || *st.NearestReleaseTag != "v0.4.0" {
		t.Fatalf("ahead %+v", st)
	}
	if !slices.Equal(st.CI, []string{"ci-npm.yml"}) || !st.Publish {
		t.Fatalf("workflows %v, publish %v", st.CI, st.Publish)
	}
	if st.RegistryVersion != nil || st.Drift != nil {
		t.Fatalf("a registry field without --registry: %+v", st)
	}
}

