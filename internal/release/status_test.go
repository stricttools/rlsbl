const npmDocument = `{"name":"portal","dist-tags":{"latest":"0.3.0"},"versions":{"0.2.0":{},"0.3.0":{}}}`

func TestStatusRegistryReadsOnlyThePackageListing(t *testing.T) {
	hygiene.Isolate(t)
	repo := standalone(t, "ci")
	fake := testsupport.NewFakeHTTP(t, testsupport.HTTPAnswer{Method: "GET", URL: "https://registry.npmjs.org/portal", Status: 200, Body: npmDocument})
	st, err := readStatus(t, fake, release.StatusRequest{Dir: repo.Dir, Registry: true})
	mustNotFail(t, err)
	if st.RegistryVersion == nil || *st.RegistryVersion != "0.3.0" || st.Drift == nil || *st.Drift != release.DriftAhead {
		t.Fatalf("registry %+v", st)
	}
	if urls := fake.URLs(); !slices.Equal(urls, []string{"https://registry.npmjs.org/portal"}) {
		t.Fatalf("requests %v: only the package document may be asked for", urls)
	}
}

func TestStatusRegistryDrifts(t *testing.T) {
	hygiene.Isolate(t)
	repo := standalone(t, "ci")
	for _, c := range []struct {
		status int
		body   string
		drift  string
	}{
		{200, `{"dist-tags":{"latest":"0.4.0"},"versions":{"0.4.0":{}}}`, release.DriftSame},
		{200, `{"dist-tags":{"latest":"0.5.0"},"versions":{"0.5.0":{}}}`, release.DriftBehind},
		{404, `{"error":"Not found"}`, release.DriftUnpublished},
	} {
		fake := testsupport.NewFakeHTTP(t, testsupport.HTTPAnswer{Method: "GET", URL: "https://registry.npmjs.org/portal", Status: c.status, Body: c.body})
		st, err := readStatus(t, fake, release.StatusRequest{Dir: repo.Dir, Registry: true})
		mustNotFail(t, err)
		if st.Drift == nil || *st.Drift != c.drift {
			t.Errorf("HTTP %d %s: drift %v, want %s", c.status, c.body, st.Drift, c.drift)
		}
	}
}

