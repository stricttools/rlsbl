func TestStatusNamesTheFatesOfTheLatestRelease(t *testing.T) {
	hygiene.Isolate(t)
	repo := standalone(t, "none")
	recordRelease(t, repo, "portal", "0.4.0", "v0.4.0", "recorded")
	recordRelease(t, repo, "portal", "0.5.0", "", "never-released")
	st, err := readStatus(t, nil, release.StatusRequest{Dir: repo.Dir})
	mustNotFail(t, err)
	if st.LatestRelease == nil || *st.LatestRelease != "0.4.0" || !slices.Equal(st.NeverReleasedVersions, []string{"0.5.0"}) {
		t.Fatalf("latest %+v", st)
	}
	requireContains(t, st.LatestReleaseLabel, "0.4.0", "0.5.0 archived but never released")

	repo = standalone(t, "none")
	recordRelease(t, repo, "portal", "0.4.0", "", "unrecoverable")
	st, err = readStatus(t, nil, release.StatusRequest{Dir: repo.Dir})
	mustNotFail(t, err)
	if st.LatestReleaseState == nil || *st.LatestReleaseState != "unrecoverable" || st.LatestReleaseInCheckout != nil || !strings.Contains(st.LatestReleaseLabel, "commit not recoverable") {
		t.Fatalf("latest %+v", st)
	}
}

