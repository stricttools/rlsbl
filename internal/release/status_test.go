func TestStatusRegistryAsksTheGoProxyForTheModulesList(t *testing.T) {
	hygiene.Isolate(t)
	repo := testsupport.NewRepo(t)
	repo.Write(declarationsPath, strings.Replace(standaloneDeclarations, "%s", "ci", 1))
	repo.Write("go.mod", "module github.com/acme/Portal\n\ngo 1.26\n")
	repo.Write("VERSION", "0.4.0\n")
	repo.Commit("the project", declarationsPath, "go.mod", "VERSION")
	fake := testsupport.NewFakeHTTP(t, testsupport.HTTPAnswer{Method: "GET", URL: "https://proxy.golang.org/github.com/acme/!portal/@v/list", Status: 200, Body: "v0.3.0\nv0.4.0\n"})
	st, err := readStatus(t, fake, release.StatusRequest{Dir: repo.Dir, Registry: true})
	mustNotFail(t, err)
	if st.Name != "Portal" || *st.RegistryVersion != "0.4.0" || *st.Drift != release.DriftSame {
		t.Fatalf("status %+v", st)
	}
	if urls := fake.URLs(); !slices.Equal(urls, []string{"https://proxy.golang.org/github.com/acme/!portal/@v/list"}) {
		t.Fatalf("requests %v", urls)
	}
}
