package testsupport

import (
	"fmt"
	"go/ast"
	"go/parser"
	"go/token"
	"os"
	"path/filepath"
	"strings"
	"testing"

	tomledit "github.com/stricttools/go-toml-edit"
	"github.com/stricttools/testisolation/go/hygiene"
)

// bannedWord is the word no Go file of rlsbl may carry, assembled so this
// file does not carry it either. Name the thing instead: a type, a class, or
// the word that says what it is.
var bannedWord = "k" + "ind"

// bannedWordFindings names every place a listed Go file carries the banned
// word, case-insensitively: its file name, an identifier, a comment, or a
// literal.
func bannedWordFindings(t *testing.T, root string, files []string) []string {
	t.Helper()
	has := func(s string) bool { return strings.Contains(strings.ToLower(s), bannedWord) }
	fset := token.NewFileSet()
	var findings []string
	for _, rel := range files {
		if has(rel) {
			findings = append(findings, fmt.Sprintf("%s: the file name", rel))
		}
		f, err := parser.ParseFile(fset, filepath.Join(root, filepath.FromSlash(rel)), nil, parser.ParseComments|parser.SkipObjectResolution)
		if err != nil {
			t.Fatalf("parsing %s: %v", rel, err)
		}
		// A generated file (one carrying the standard "Code generated ... DO NOT
		// EDIT." header) is written by a generator rlsbl does not own, so its
		// spelling is not rlsbl's to choose.
		if ast.IsGenerated(f) {
			continue
		}
		at := func(pos token.Pos) string {
			return fmt.Sprintf("%s:%d", rel, fset.Position(pos).Line)
		}
		ast.Inspect(f, func(n ast.Node) bool {
			switch n := n.(type) {
			case *ast.Ident:
				if has(n.Name) {
					findings = append(findings, fmt.Sprintf("%s: identifier %s", at(n.Pos()), n.Name))
				}
			case *ast.BasicLit:
				if has(n.Value) {
					findings = append(findings, fmt.Sprintf("%s: literal %s", at(n.Pos()), n.Value))
				}
			}
			return true
		})
		for _, group := range f.Comments {
			for _, c := range group.List {
				if has(c.Text) {
					findings = append(findings, fmt.Sprintf("%s: comment", at(c.Pos())))
				}
			}
		}
	}
	return findings
}

func TestNoGoFileCarriesTheBannedWord(t *testing.T) {
	hygiene.Isolate(t)
	root := ModuleRoot(t)
	if findings := bannedWordFindings(t, root, GoFiles(t, root)); len(findings) > 0 {
		t.Fatalf("the word %q is banned from rlsbl's Go files (name the thing: a type, a class, or the word that says what it is):\n  %s", bannedWord, strings.Join(findings, "\n  "))
	}
}

func TestTheBannedWordGuardFindsEveryPlace(t *testing.T) {
	hygiene.Isolate(t)
	root := t.TempDir()
	word := strings.ToUpper(bannedWord[:1]) + bannedWord[1:]
	WriteFile(t, filepath.Join(root, "clean.go"), "package a\n\n// Type names what it is.\nvar Type = \"plain\"\n")
	WriteFile(t, filepath.Join(root, "dirty.go"), "package a\n\n// The "+bannedWord+" of thing.\nvar "+word+" = \"a "+bannedWord+"\"\n")
	WriteFile(t, filepath.Join(root, bannedWord+".go"), "package a\n")
	WriteFile(t, filepath.Join(root, "generated.go"), "// Code generated by a generator. DO NOT EDIT.\n\npackage a\n\nvar "+word+" = 1\n")
	got := bannedWordFindings(t, root, []string{"clean.go", "dirty.go", bannedWord + ".go", "generated.go"})
	want := []string{
		"dirty.go:4: identifier " + word,
		"dirty.go:4: literal \"a " + bannedWord + "\"",
		"dirty.go:3: comment",
		bannedWord + ".go: the file name",
	}
	if strings.Join(got, "\n") != strings.Join(want, "\n") {
		t.Fatalf("findings = %q, want %q", got, want)
	}
}

// schemaKeywords are the words of strictspec's schema language that carry
// the banned word; they are strictspec's to spell, and a text file's other
// uses of the word are rlsbl's.
var schemaKeywords = []string{"node-" + bannedWord + "-union", "datetime_" + bannedWord}

// textFindings names every line of a listed text file carrying the banned
// word outside strictspec's keywords, case-insensitively.
func textFindings(t *testing.T, root string, files []string) []string {
	t.Helper()
	var findings []string
	for _, rel := range files {
		data, err := os.ReadFile(filepath.Join(root, filepath.FromSlash(rel)))
		if err != nil {
			t.Fatal(err)
		}
		for i, line := range strings.Split(string(data), "\n") {
			line = strings.ToLower(line)
			for _, k := range schemaKeywords {
				line = strings.ReplaceAll(line, k, "")
			}
			if strings.Contains(line, bannedWord) {
				findings = append(findings, fmt.Sprintf("%s:%d", rel, i+1))
			}
		}
	}
	return findings
}

// rlsblTextFiles are the text files rlsbl writes for its Go implementation:
// the documentation pages and the schemas of the Go validators strictspec
// generates.
func rlsblTextFiles(t *testing.T, root string) []string {
	t.Helper()
	files, err := filepath.Glob(filepath.Join(root, ".strictmetadata", "docs", "*.md"))
	if err != nil {
		t.Fatal(err)
	}
	var out []string
	for _, f := range files {
		rel, _ := filepath.Rel(root, f)
		out = append(out, filepath.ToSlash(rel))
	}
	data, err := os.ReadFile(filepath.Join(root, "strictspec.toml"))
	if err != nil {
		t.Fatal(err)
	}
	manifest, err := tomledit.Unmarshal[struct {
		FormatVersion int `toml:"format_version"`
		Schemas       []struct {
			Path    string `toml:"path"`
			Targets []struct {
				Lang    string `toml:"lang"`
				Output  string `toml:"output"`
				Package string `toml:"package"`
			} `toml:"targets"`
		} `toml:"schemas"`
	}](data)
	if err != nil {
		t.Fatalf("strictspec.toml: %v", err)
	}
	for _, s := range manifest.Schemas {
		for _, target := range s.Targets {
			if target.Lang == "go" {
				out = append(out, s.Path)
				break
			}
		}
	}
	return out
}

func TestNoTextFileOfTheGoImplementationCarriesTheBannedWord(t *testing.T) {
	hygiene.Isolate(t)
	root := ModuleRoot(t)
	if findings := textFindings(t, root, rlsblTextFiles(t, root)); len(findings) > 0 {
		t.Fatalf("the word %q is banned from rlsbl's documentation pages and Go validator schemas, outside strictspec's own keywords (name the thing instead):\n  %s", bannedWord, strings.Join(findings, "\n  "))
	}
}

func TestTheBannedWordGuardReadsTextFilesPastTheSchemaKeywords(t *testing.T) {
	hygiene.Isolate(t)
	root := t.TempDir()
	WriteFile(t, filepath.Join(root, "a.schema.toml"), "type = \"node-"+bannedWord+"-union\"\ndatetime_"+bannedWord+" = \"offset\"\n# one "+strings.ToUpper(bannedWord)+" of union\n")
	if got := textFindings(t, root, []string{"a.schema.toml"}); strings.Join(got, ",") != "a.schema.toml:3" {
		t.Fatalf("findings = %q", got)
	}
}
