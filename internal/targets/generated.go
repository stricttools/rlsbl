// RenderMatrix is the support matrix as committed: indented JSON with a
// trailing newline, the same bytes on every run.
func RenderMatrix() ([]byte, error) {
	var b bytes.Buffer
	enc := json.NewEncoder(&b)
	enc.SetEscapeHTML(false)
	enc.SetIndent("", "  ")
	if err := enc.Encode(BuildMatrix()); err != nil {
		return nil, err
	}
	return b.Bytes(), nil
}

// privatePathsSource is this package's private-path rules, the text the CI
// program carries.
//
//go:embed privatepaths.go
var privatePathsSource string

// privatePathsCheckSource is the CI program's own part: reading the built
// artifacts and refusing what the rules match.
//
//go:embed privatepathscheck.go.in
var privatePathsCheckSource string

// generatedHeader opens the generated program.
const generatedHeader = "// Code generated by internal/targets/gen from internal/targets/privatepaths.go and internal/targets/privatepathscheck.go.in; DO NOT EDIT.\n\n"

// splitGoSource splits one Go file's text into what precedes its package
// clause, the import paths of its one parenthesized import block (quoted, as
// written), and everything after that block.
func splitGoSource(name, src, pkg string) (preamble string, imports []string, body string, err error) {
	clause := "package " + pkg + "\n"
	i := strings.Index(src, clause)
	if i < 0 || (i > 0 && src[i-1] != '\n') {
		return "", nil, "", fmt.Errorf("%s has no line %q", name, strings.TrimSpace(clause))
	}
	preamble = src[:i]
	rest := strings.TrimLeft(src[i+len(clause):], "\n")
	block, after, ok := strings.Cut(rest, "\n)\n")
	lines, ok2 := strings.CutPrefix(block, "import (\n")
	if !ok || !ok2 {
		return "", nil, "", fmt.Errorf("%s does not follow its package clause with one parenthesized import block", name)
	}
	for _, line := range strings.Split(lines, "\n") {
		if line = strings.TrimSpace(line); line != "" {
			imports = append(imports, line)
		}
	}
	return preamble, imports, strings.TrimLeft(after, "\n"), nil
}

// RenderPrivatePathsProgram is the standalone program the pypi CI workflow
// runs over a built upload: the CI part and this package's rule file
// joined into one package main, gofmt-formatted.
func RenderPrivatePathsProgram() ([]byte, error) {
	rulesPreamble, rulesImports, rulesBody, err := splitGoSource("internal/targets/privatepaths.go", privatePathsSource, "targets")
	if err != nil {
		return nil, err
	}
	if rulesPreamble != "" {
		return nil, fmt.Errorf("internal/targets/privatepaths.go has text before its package clause, which the generated program cannot carry")
	}
	preamble, imports, body, err := splitGoSource("internal/targets/privatepathscheck.go.in", privatePathsCheckSource, "main")
	if err != nil {
		return nil, err
	}
	seen := map[string]bool{}
	var all []string
	for _, imp := range append(imports, rulesImports...) {
		if !seen[imp] {
			seen[imp] = true
			all = append(all, imp)
		}
	}
	sort.Strings(all)
	var b strings.Builder
	b.WriteString(generatedHeader)
	b.WriteString(preamble)
	b.WriteString("package main\n\nimport (\n")
	for _, imp := range all {
		b.WriteString("\t" + imp + "\n")
	}
	b.WriteString(")\n\n")
	b.WriteString(body)
	b.WriteString("\n")
	b.WriteString(rulesBody)
	return format.Source([]byte(b.String()))
}
