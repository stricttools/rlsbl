// gitAt runs git in dir with the author and committer dates (and, when
// identity is given, the author and committer) set, returning its trimmed
// stdout.
func gitAt(t *testing.T, dir string, env []string, args ...string) string {
	t.Helper()
	cmd := exec.Command("git", args...)
	cmd.Dir = dir
	cmd.Env = append(os.Environ(), env...)
	var out, errOut bytes.Buffer
	cmd.Stdout, cmd.Stderr = &out, &errOut
	if err := cmd.Run(); err != nil {
		t.Fatalf("git %s: %v\n%s", strings.Join(args, " "), err, errOut.String())
	}
	return strings.TrimSpace(out.String())
}

// commitOn writes files and commits every change with both dates on date.
func commitOn(t *testing.T, repo *testsupport.Repo, date string, files map[string]string, message string) string {
	t.Helper()
	for rel, content := range files {
		repo.Write(rel, content)
	}
	repo.Git("add", "-A")
	when := date + "T10:00:00+00:00"
	gitAt(t, repo.Dir, []string{"GIT_AUTHOR_DATE=" + when, "GIT_COMMITTER_DATE=" + when}, "commit", "-q", "-m", message)
	return repo.Head()
}

// commitTree writes a commit carrying tree, parents, and the author and
// committer (dates included) of like, with message, as safegit's squash
// writes one.
func commitTree(t *testing.T, repo *testsupport.Repo, tree string, parents []string, like, message string) string {
	t.Helper()
	fields := strings.Split(repo.Git("log", "-1", "--format=%an%x00%ae%x00%aI%x00%cn%x00%ce%x00%cI", like), "\x00")
	env := []string{
		"GIT_AUTHOR_NAME=" + fields[0], "GIT_AUTHOR_EMAIL=" + fields[1], "GIT_AUTHOR_DATE=" + fields[2],
		"GIT_COMMITTER_NAME=" + fields[3], "GIT_COMMITTER_EMAIL=" + fields[4], "GIT_COMMITTER_DATE=" + fields[5],
	}
	args := []string{"commit-tree", tree, "-m", message}
	for _, p := range parents {
		args = append(args, "-p", p)
	}
	return gitAt(t, repo.Dir, env, args...)
}

func treeOf(repo *testsupport.Repo, commit string) string {
	return repo.Git("rev-parse", commit+"^{tree}")
}

// fakeSafegit is a safegit for one test: `--version` prints the version,
// `commit` commits with git as safegit would, and each squash runs the next
// answer's script and prints its stdout with its exit status, in order.
// Every invocation is recorded.
type fakeSafegit struct {
	t   *testing.T
	dir string
	n   int
}

const fakeSafegitScript = `#!/bin/sh
here="${0%/*}"
printf '%s\n' "$*" >> "$here/calls.txt"
if [ "$1" = --version ]; then
	echo "safegit 0.31.0"
	exit 0
fi
if [ "$1" = --approve-consequential ] && [ "$2" = scrub ]; then
	n=$(($(cat "$here/count.txt") + 1))
	echo "$n" > "$here/count.txt"
	if [ ! -f "$here/out-$n.txt" ]; then
		echo "fake safegit: no answer for squash $n" >&2
		exit 97
	fi
	sh "$here/script-$n.sh" >&2 || exit 1
	cat "$here/out-$n.txt"
	exit "$(cat "$here/exit-$n.txt")"
fi
if [ "$1" != commit ]; then
	echo "fake safegit: unexpected $*" >&2
	exit 97
fi
shift
trailer=""
message=""
while [ $# -gt 0 ]; do
	case "$1" in
	--trailer) trailer="$2"; shift 2 ;;
	-m) message="$2"; shift 2 ;;
	--) shift; break ;;
	*) echo "fake safegit: unexpected argument $1" >&2; exit 97 ;;
	esac
done
git add -A -- "$@" || exit 1
if [ -n "$trailer" ]; then
	exec git commit -q --trailer "$trailer" -m "$message"
fi
exec git commit -q -m "$message"
`

func newFakeSafegit(t *testing.T) *fakeSafegit {
	t.Helper()
	dir := t.TempDir()
	if err := os.WriteFile(filepath.Join(dir, "safegit"), []byte(fakeSafegitScript), 0o755); err != nil {
		t.Fatal(err)
	}
	s := &fakeSafegit{t: t, dir: dir}
	s.write("count.txt", "0\n")
	t.Setenv("PATH", dir+string(os.PathListSeparator)+os.Getenv("PATH"))
	return s
}

func (s *fakeSafegit) write(name, content string) {
	s.t.Helper()
	if err := os.WriteFile(filepath.Join(s.dir, name), []byte(content), 0o644); err != nil {
		s.t.Fatal(err)
	}
}

// Squash queues the next squash's answer.
func (s *fakeSafegit) Squash(script, stdout string, exit int) {
	s.t.Helper()
	s.n++
	s.write(fmt.Sprintf("script-%d.sh", s.n), script)
	s.write(fmt.Sprintf("out-%d.txt", s.n), stdout)
	s.write(fmt.Sprintf("exit-%d.txt", s.n), fmt.Sprintf("%d\n", exit))
}

// Squashes are the squash invocations, in order.
func (s *fakeSafegit) Squashes() []string {
	s.t.Helper()
	data, err := os.ReadFile(filepath.Join(s.dir, "calls.txt"))
	if os.IsNotExist(err) {
		return nil
	}
	if err != nil {
		s.t.Fatal(err)
	}
	var out []string
	for _, c := range strings.Split(strings.TrimRight(string(data), "\n"), "\n") {
		if strings.HasPrefix(c, "--approve-consequential scrub squash") {
			out = append(out, c)
		}
	}
	return out
}

