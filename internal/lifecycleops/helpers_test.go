// lastCommit is HEAD's subject and its Autogenerated trailer's value.
func (f *fixture) lastCommit(t *testing.T) (subject, autogenerated string) {
	t.Helper()
	out := f.repo.Git("log", "-1", "--format=%s%x00%(trailers:key=Autogenerated,valueonly)")
	subject, autogenerated, _ = strings.Cut(out, "\x00")
	return subject, strings.TrimSpace(autogenerated)
}

