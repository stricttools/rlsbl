// Package lifecycleops is rlsbl's `transition` command group: the commands
// that write the lifecycle-and-license record
// (.strictmetadata/lifecycle-and-license/lifecycle-and-license.toml, owned
// by strictspec and read through its lifecycle library), `transition show`,
// which prints the record and every rule's verdict, `transition classify`,
// which makes a releasable proprietary, `transition declassify`, which takes
// a repository public, and `transition init-minimal-record`, for a
// repository rlsbl does not manage.
//
// A command that opens a period closes the subject's period in effect on the
// command's date first. A command that changes the record validates the
// whole record against the repository's declarations, writes it through the
// effects handle, and commits it with the Autogenerated trailer, together
// with whatever else the command changes (declassify's repaired release
// files, for one).
package lifecycleops

import (
	"fmt"
	"os"
	"path/filepath"
	"strings"
	"time"

	"github.com/stricttools/strictcli/go/strictcli"
	"github.com/stricttools/strictspec/go/confidential"
	"github.com/stricttools/strictspec/go/lifecycle"

	"github.com/stricttools/rlsbl/internal/git"
	"github.com/stricttools/rlsbl/internal/workflows"
	"github.com/stricttools/rlsbl/internal/workspace"
)

// origin is the remote every push goes to.
const origin = "origin"

// Invocation is one run of a `transition` command.
type Invocation struct {
	E      *strictcli.Effects
	DryRun bool
	Say    func(string)
	// Now is the command's date: every period it closes ends there and
	// every period it opens starts there.
	Now func() time.Time
	// TermList is where the confidential-term list is
	// (confidential.ConfiguredLocation in the binary), which what a command
	// publishes is scanned against.
	TermList confidential.Location
	// RouterInputs are what a workspace's routers are regenerated with, for
	// the workspace given: retiring a releasable regenerates them without
	// it.
	RouterInputs func(*workspace.Workspace) (workflows.SyncInputs, error)
}

// managed is a repository rlsbl manages, as a command reads it.
type managed struct {
	root   string
	repo   git.Repo
	ws     *workspace.Workspace
	record *lifecycle.Record
}

// openManaged reads the repository holding the absolute directory dir: its
// declarations, which every record-writing command validates the record
// against, and its record.
func (inv Invocation) openManaged(dir string) (managed, error) {
	ws, err := workspace.Discover(dir)
	if err != nil {
		return managed{}, err
	}
	repo, err := git.Open(inv.E, ws.Root)
	if err != nil {
		return managed{}, err
	}
	rec, err := lifecycle.Load(ws.Root)
	if err != nil {
		return managed{}, err
	}
	return managed{root: ws.Root, repo: repo, ws: ws, record: rec}, nil
}

// requireReleasable refuses a subject the declarations declare no
// releasable of: licenses are declared per releasable.
func (m managed) requireReleasable(subject string) error {
	if _, ok := m.ws.Declarations.Releasable(subject); ok {
		return nil
	}
	var names []string
	for _, r := range m.ws.Releasables() {
		names = append(names, r.Name)
	}
	return fmt.Errorf("%q is not a releasable the declarations declare; the releasables are %s", subject, strings.Join(names, ", "))
}

// recordWriter is the lifecycle library's file writer backed by the effects
// handle, so a dry run records the record's writes instead of making them.
type recordWriter struct {
	e *strictcli.Effects
}

func (w recordWriter) WriteFile(path string, data []byte) error {
	_, err := w.e.Write(path, data)
	return err
}

func (w recordWriter) MkdirAll(path string) error {
	_, err := w.e.Mkdir(path)
	return err
}

// recordPaths are the files a record write commits.
var recordPaths = []string{lifecycle.RecordFile, lifecycle.ManifestFile}

// report says what a command did, or under --dry-run what it would do.
func (inv Invocation) report(done, would string) {
	if inv.DryRun {
		inv.Say(would)
		return
	}
	inv.Say(done)
}

// outcome is what a command that changes the record says once the record
// is written: done, or would under --dry-run.
type outcome struct{ done, would string }

// save validates the whole record against the declared subjects on the
// command's date, writes it, says the outcome,
// and commits the record alone with the Autogenerated trailer. Nothing is
// said before a refusal.
func (inv Invocation) save(m managed, rec *lifecycle.Record, on time.Time, message string, said outcome) error {
	if err := rec.Validate(on, m.ws.Declarations.SubjectNames()); err != nil {
		return fmt.Errorf("the record would not be valid, so nothing was written: %w", err)
	}
	return inv.write(m.root, m.repo, rec, on, message, said)
}

// write writes a validated record, says the outcome, and commits it.
func (inv Invocation) write(root string, repo git.Repo, rec *lifecycle.Record, on time.Time, message string, said outcome) error {
	if err := rec.Write(recordWriter{inv.E}, root); err != nil {
		return err
	}
	if said.done != "" {
		inv.report(said.done, said.would)
	}
	return inv.commit(repo, message, recordPaths)
}

// commit commits paths with the Autogenerated trailer, skipped under
// --dry-run. A commit that fails leaves the files written, and the error
// names the commit that records them.
func (inv Invocation) commit(repo git.Repo, message string, paths []string) error {
	if inv.DryRun {
		inv.Say("Would commit " + strings.Join(paths, ", ") + ": " + message)
		return nil
	}
	if _, err := repo.Commit(git.CommitRequest{Message: message, Paths: paths, Autogenerated: true, RequireChange: true}); err != nil {
		return fmt.Errorf("the record is written but not committed: %w\nOnce the cause is fixed, commit it: safegit commit --trailer '%s: true' -m %s -- %s", err, git.AutogeneratedTrailer, shellQuote(message), strings.Join(presentPaths(repo.Dir(), paths), " "))
	}
	inv.Say("Committed " + strings.Join(paths, ", "))
	return nil
}

func presentPaths(root string, paths []string) []string {
	var out []string
	for _, p := range paths {
		if _, err := os.Lstat(filepath.Join(root, filepath.FromSlash(p))); err == nil {
			out = append(out, p)
		}
	}
	return out
}

// shellQuote is s as one single-quoted shell word.
func shellQuote(s string) string {
	return "'" + strings.ReplaceAll(s, "'", `'"'"'`) + "'"
}

// day renders a date the way the record writes it.
func day(t time.Time) string { return t.Format(time.DateOnly) }
