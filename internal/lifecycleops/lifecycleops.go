// Package lifecycleops is rlsbl's `transition` command group: the commands
// that write the lifecycle-and-license record
// (.strictmetadata/lifecycle-and-license/lifecycle-and-license.toml, owned
// by strictspec and read through its lifecycle library), `transition show`,
// which prints the record and every rule's verdict, `transition classify`,
// which makes a releasable proprietary, `transition declassify`, which takes
// a repository public, and `transition init-minimal-record`, for a
// repository rlsbl does not manage.
//
// Every command that changes the record closes the period in effect on the
// command's date and opens the new one, validates the whole record against
// the repository's declarations, writes it through the effects handle, keeps
// the machine-local confidential-name index in step with it (the repository's
// names while it is confidential, no entry while it is public), and commits
// the record alone with the Autogenerated trailer.
package lifecycleops

import (
	"errors"
	"fmt"
	"os"
	"path"
	"path/filepath"
	"strings"
	"time"

	"github.com/stricttools/strictcli/go/strictcli"
	"github.com/stricttools/strictspec/go/lifecycle"
	"github.com/stricttools/strictspec/go/lifecycle/index"

	"github.com/stricttools/rlsbl/internal/git"
	"github.com/stricttools/rlsbl/internal/workspace"
)

// origin is the remote the index keys a repository by and every push goes
// to.
const origin = "origin"

// Invocation is one run of a `transition` command.
type Invocation struct {
	E      *strictcli.Effects
	DryRun bool
	Say    func(string)
	// Now is the command's date: every period it closes ends there and
	// every period it opens starts there.
	Now func() time.Time
	// IndexPath is the confidential-name index (index.DefaultPath in the
	// binary).
	IndexPath string
}

// managed is a repository rlsbl manages, as a command reads it.
type managed struct {
	root   string
	repo   git.Repo
	ws     *workspace.Workspace
	record *lifecycle.Record
}

// openManaged reads the repository holding the absolute directory dir: its
// declarations, which every record-writing command validates the record
// against, and its record.
func (inv Invocation) openManaged(dir string) (managed, error) {
	ws, err := workspace.Discover(dir)
	if err != nil {
		return managed{}, err
	}
	repo, err := git.Open(inv.E, ws.Root)
	if err != nil {
		return managed{}, err
	}
	rec, err := lifecycle.Load(ws.Root)
	if err != nil {
		return managed{}, err
	}
	return managed{root: ws.Root, repo: repo, ws: ws, record: rec}, nil
}

// requireReleasable refuses a subject the declarations declare no
// releasable of: licenses are declared per releasable.
func (m managed) requireReleasable(subject string) error {
	if _, ok := m.ws.Declarations.Releasable(subject); ok {
		return nil
	}
	var names []string
	for _, r := range m.ws.Releasables() {
		names = append(names, r.Name)
	}
	return fmt.Errorf("%q is not a releasable the declarations declare; the releasables are %s", subject, strings.Join(names, ", "))
}

// recordWriter is the lifecycle library's file writer backed by the effects
// handle, so a dry run records the record's and the index's writes instead
// of making them.
type recordWriter struct {
	e *strictcli.Effects
}

func (w recordWriter) WriteFile(path string, data []byte) error {
	_, err := w.e.Write(path, data)
	return err
}

func (w recordWriter) MkdirAll(path string) error {
	_, err := w.e.Mkdir(path)
	return err
}

// indexUpdate is the change to the confidential-name index a record
// implies, decided before anything is written and applied after the record
// is.
type indexUpdate struct {
	idx    *index.Index
	origin string
	// names is empty when the repository is public and its entry is
	// removed.
	names []string
}

// planIndex decides the index update for the record as it will be written.
// A confidential repository without an origin remote is refused: the index
// keys its names by the origin, so they could not be recorded. A public one
// without an origin has no entry to remove.
func (inv Invocation) planIndex(repo git.Repo, rec *lifecycle.Record, on time.Time) (*indexUpdate, error) {
	configured, err := repo.RemoteConfigured(origin)
	if err != nil {
		return nil, err
	}
	confidential := rec.Confidential(on)
	if !configured {
		if confidential {
			return nil, fmt.Errorf("the repository is confidential, and the confidential-name index records a confidential repository's names under its origin remote, which this repository lacks; nothing was written. Add it (`git remote add origin <url>`) and run this again")
		}
		return nil, nil
	}
	url, err := repo.RemoteURL(origin)
	if err != nil {
		return nil, err
	}
	normalized, err := index.NormalizeOrigin(url)
	if err != nil {
		return nil, err
	}
	if inv.IndexPath == "" {
		return nil, errors.New("no confidential-name index path was given to the command")
	}
	idx, err := index.Load(inv.IndexPath)
	if err != nil {
		return nil, err
	}
	u := &indexUpdate{idx: idx, origin: url}
	if confidential {
		if u.names, err = rec.ConfidentialNames(on, path.Base(normalized)); err != nil {
			return nil, err
		}
	}
	return u, nil
}

// apply writes the index update through the effects handle.
func (u *indexUpdate) apply(e *strictcli.Effects) error {
	if u == nil {
		return nil
	}
	if len(u.names) > 0 {
		return u.idx.Upsert(recordWriter{e}, u.origin, u.names)
	}
	return u.idx.Remove(recordWriter{e}, u.origin)
}

// RefreshIndex brings the confidential-name index entry of the repository
// at root in line with its record as it stands on the date of on: upserted
// under its origin while the record makes the repository confidential,
// removed while it is public. It is rlsbl's part of the index rule, owed by
// every mutating command that loads declarations; the writes go through
// the effects handle. A confidential repository without an origin remote
// is refused, as planIndex refuses it.
func RefreshIndex(e *strictcli.Effects, root, indexPath string, on time.Time) error {
	repo, err := git.Open(e, root)
	if err != nil {
		return err
	}
	rec, err := lifecycle.Load(root)
	if err != nil {
		return err
	}
	u, err := Invocation{E: e, IndexPath: indexPath}.planIndex(repo, rec, on)
	if err != nil {
		return err
	}
	return u.apply(e)
}

// recordPaths are the files a record write commits.
var recordPaths = []string{lifecycle.RecordFile, lifecycle.ManifestFile}

// report says what a command did, or under --dry-run what it would do.
func (inv Invocation) report(done, would string) {
	if inv.DryRun {
		inv.Say(would)
		return
	}
	inv.Say(done)
}

// save validates the whole record against the declared subjects on the
// command's date, writes it, brings the index in step, and commits the
// record alone with the Autogenerated trailer.
func (inv Invocation) save(m managed, rec *lifecycle.Record, on time.Time, message string) error {
	if err := rec.Validate(on, m.ws.Declarations.SubjectNames()); err != nil {
		return fmt.Errorf("the record would not be valid, so nothing was written: %w", err)
	}
	return inv.write(m.root, m.repo, rec, on, message)
}

// write writes a validated record, applies the index update it implies,
// and commits it.
func (inv Invocation) write(root string, repo git.Repo, rec *lifecycle.Record, on time.Time, message string) error {
	update, err := inv.planIndex(repo, rec, on)
	if err != nil {
		return err
	}
	if err := rec.Write(recordWriter{inv.E}, root); err != nil {
		return err
	}
	if err := update.apply(inv.E); err != nil {
		return err
	}
	return inv.commit(repo, message, recordPaths)
}

// commit commits paths with the Autogenerated trailer, skipped under
// --dry-run. A commit that fails leaves the files written, and the error
// names the commit that records them.
func (inv Invocation) commit(repo git.Repo, message string, paths []string) error {
	if inv.DryRun {
		inv.Say("Would commit " + strings.Join(paths, ", ") + ": " + message)
		return nil
	}
	if _, err := repo.Commit(git.CommitRequest{Message: message, Paths: paths, Autogenerated: true, RequireChange: true}); err != nil {
		return fmt.Errorf("the record is written but not committed: %w\nOnce the cause is fixed, commit it: safegit commit --trailer '%s: true' -m %s -- %s", err, git.AutogeneratedTrailer, shellQuote(message), strings.Join(presentPaths(repo.Dir(), paths), " "))
	}
	inv.Say("Committed " + strings.Join(paths, ", "))
	return nil
}

func presentPaths(root string, paths []string) []string {
	var out []string
	for _, p := range paths {
		if _, err := os.Lstat(filepath.Join(root, filepath.FromSlash(p))); err == nil {
			out = append(out, p)
		}
	}
	return out
}

// shellQuote is s as one single-quoted shell word.
func shellQuote(s string) string {
	return "'" + strings.ReplaceAll(s, "'", `'"'"'`) + "'"
}

// day renders a date the way the record writes it.
func day(t time.Time) string { return t.Format(time.DateOnly) }
