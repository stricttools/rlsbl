// mitSince is a record licensing portal MIT and keeping it active since
// the start of the year.
const mitSince = `format_version = 1

[[lifecycle]]
subject = "portal"
status = "active"
from = 2026-01-01
reason = "first release"

[[licenses]]
subject = "portal"
license = "MIT"
from = 2026-01-01
reason = "first release"
`

func TestLifecycleClosesThePeriodAndOpensTheNewOne(t *testing.T) {
	hygiene.Isolate(t)
	f := newFixture(t, mitSince)
	testsupport.FakeSafegit(t)
	r := f.run(t, false, func(inv lifecycleops.Invocation, dir string) error {
		return inv.Lifecycle(lifecycleops.PeriodRequest{Dir: dir, Subject: "portal", Value: "on-hold", Reason: "paused"})
	})
	requireExit(t, r, 0)
	rec, err := lifecycle.Parse([]byte(f.record(t)))
	if err != nil {
		t.Fatal(err)
	}
	periods := rec.Lifecycle()
	if len(periods) != 2 || periods[0].Until != time.Date(2026, 6, 1, 0, 0, 0, 0, time.UTC) || periods[1].Status != lifecycle.StatusOnHold || !periods[1].Open() {
		t.Fatalf("periods %+v", periods)
	}
	if subject, trailer := f.lastCommit(t); subject != "transition: portal is on-hold" || trailer != "true" {
		t.Errorf("commit %q, Autogenerated %q", subject, trailer)
	}
	f.clean(t)

	r = f.run(t, false, func(inv lifecycleops.Invocation, dir string) error {
		return inv.Lifecycle(lifecycleops.PeriodRequest{Dir: dir, Subject: "portal", Value: "on-hold", Reason: "again"})
	})
	requireExit(t, r, 1)
	requireContains(t, r.Stderr, "already on-hold")
	r = f.run(t, false, func(inv lifecycleops.Invocation, dir string) error {
		return inv.Lifecycle(lifecycleops.PeriodRequest{Dir: dir, Subject: "nobody", Value: "active", Reason: "typo"})
	})
	requireExit(t, r, 1)
	requireContains(t, r.Stderr, `"nobody" is neither`)
}

func TestADryRunWritesNoRecordAndNoIndex(t *testing.T) {
	hygiene.Isolate(t)
	f := newFixture(t, mitSince)
	before := f.record(t)
	head := f.repo.Head()
	r := f.run(t, true, func(inv lifecycleops.Invocation, dir string) error {
		return inv.Lifecycle(lifecycleops.PeriodRequest{Dir: dir, Subject: "portal", Value: "retired", Reason: "done"})
	})
	requireExit(t, r, 0)
	requireContains(t, r.Stdout, "Would commit")
	// What the dry run says names what it would record, never a state it
	// did not bring about.
	requireContains(t, r.Stdout, "Would record portal as retired from")
	if strings.Contains(r.Stdout, "portal is retired from") {
		t.Fatalf("a dry run reports the period as recorded:\n%s", r.Stdout)
	}
	if f.record(t) != before || f.repo.Head() != head {
		t.Fatal("a dry run wrote the record or committed")
	}
	r = f.run(t, true, func(inv lifecycleops.Invocation, dir string) error {
		return inv.UnversionedTag(dir, "nightly", "a marker")
	})
	requireExit(t, r, 0)
	requireContains(t, r.Stdout, "Would record nightly as a tag that releases no version")
}

