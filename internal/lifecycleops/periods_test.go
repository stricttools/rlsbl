func TestIdentityRecordsCurrentAndDeadIdentities(t *testing.T) {
	hygiene.Isolate(t)
	f := newFixture(t, mitSince)
	testsupport.FakeSafegit(t)
	identity := func(req lifecycleops.IdentityRequest) error {
		req.Dir = f.repo.Dir
		r := f.run(t, false, func(inv lifecycleops.Invocation, _ string) error { return inv.Identity(req) })
		if r.ExitCode != 0 {
			return &exitError{r.Stderr}
		}
		return nil
	}
	if err := identity(lifecycleops.IdentityRequest{Subject: "portal", Facet: lifecycle.FacetPackageName, Value: "portal", Registry: "npm", TagPatterns: []string{"v*"}, Reason: "first name"}); err != nil {
		t.Fatal(err)
	}
	if err := identity(lifecycleops.IdentityRequest{Subject: "portal", Facet: lifecycle.FacetPackageName, Value: "portal-client", Registry: "npm", TagPatterns: []string{"v*"}, Reason: "renamed"}); err != nil {
		t.Fatal(err)
	}
	err := identity(lifecycleops.IdentityRequest{Subject: "gizmo", Facet: lifecycle.FacetGoModulePath, Value: "example.com/gizmo", Until: time.Date(2025, 6, 1, 0, 0, 0, 0, time.UTC), Reason: "dead"})
	if err == nil || !strings.Contains(err.Error(), "pass --from with it") {
		t.Fatalf("until without from: %v", err)
	}
	if err := identity(lifecycleops.IdentityRequest{Subject: "gizmo", Facet: lifecycle.FacetGoModulePath, Value: "example.com/gizmo", TagPatterns: []string{"gizmo/v*"},
		From: time.Date(2024, 1, 1, 0, 0, 0, 0, time.UTC), Until: time.Date(2025, 6, 1, 0, 0, 0, 0, time.UTC), Reason: "dead"}); err != nil {
		t.Fatal(err)
	}
	rec, perr := lifecycle.Parse([]byte(f.record(t)))
	if perr != nil {
		t.Fatal(perr)
	}
	ids := rec.Identities()
	if len(ids) != 3 || !ids[0].Until.Equal(time.Date(2026, 6, 1, 0, 0, 0, 0, time.UTC)) || !ids[1].Open() || ids[2].Subject != "gizmo" || ids[2].Open() {
		t.Fatalf("identities %+v", ids)
	}
}

type exitError struct{ stderr string }

func (e *exitError) Error() string { return e.stderr }

func TestUnversionedTagIsRecordedOnce(t *testing.T) {
	hygiene.Isolate(t)
	f := newFixture(t, mitSince)
	testsupport.FakeSafegit(t)
	tag := func() int {
		return f.run(t, false, func(inv lifecycleops.Invocation, dir string) error {
			return inv.UnversionedTag(dir, "nightly", "a moving marker")
		}).ExitCode
	}
	if code := tag(); code != 0 {
		t.Fatalf("exit %d", code)
	}
	requireContains(t, f.record(t), `tag = "nightly"`, "recorded = 2026-06-01")
	if code := tag(); code != 1 {
		t.Fatalf("a second declaration exited %d", code)
	}
}

func TestInitMinimalRecordWritesTheRecordAndRefusesManagedRepositories(t *testing.T) {
	hygiene.Isolate(t)
	testsupport.FakeSafegit(t)
	repo := testsupport.NewRepo(t)
	repo.CommitFile("README.md", "readme\n", "start")
	f := &fixture{repo: repo, index: t.TempDir() + "/index.toml"}
	initRecord := func() (int, string) {
		r := f.run(t, false, func(inv lifecycleops.Invocation, dir string) error { return inv.InitMinimalRecord(dir) })
		return r.ExitCode, r.Stderr
	}
	if code, stderr := initRecord(); code != 0 {
		t.Fatalf("exit %d: %s", code, stderr)
	}
	if got := f.record(t); got != "format_version = 1\n" {
		t.Fatalf("the record is %q", got)
	}
	if subject, trailer := f.lastCommit(t); !strings.Contains(subject, "minimal lifecycle-and-license record") || trailer != "true" {
		t.Errorf("commit %q, Autogenerated %q", subject, trailer)
	}
	if out := repo.Git("show", "--name-only", "--format=", "HEAD"); !strings.Contains(out, lifecycle.ManifestFile) || !strings.Contains(out, lifecycle.RecordFile) {
		t.Errorf("the commit carries %s", out)
	}
	if code, stderr := initRecord(); code != 1 || !strings.Contains(stderr, "already exists") {
		t.Fatalf("a second run: exit %d: %s", code, stderr)
	}

	managedRepo := newFixture(t, "")
	if r := managedRepo.run(t, false, func(inv lifecycleops.Invocation, dir string) error { return inv.InitMinimalRecord(dir) }); r.ExitCode != 1 || !strings.Contains(r.Stderr, "rlsbl manages this repository") {
		t.Fatalf("a managed repository: exit %d: %s", r.ExitCode, r.Stderr)
	}
	old := testsupport.NewRepo(t)
	old.CommitFile(".rlsbl/config.json", "{}\n", "old layout")
	g := &fixture{repo: old, index: t.TempDir() + "/index.toml"}
	if r := g.run(t, false, func(inv lifecycleops.Invocation, dir string) error { return inv.InitMinimalRecord(dir) }); r.ExitCode != 1 || !strings.Contains(r.Stderr, ".rlsbl/ of the old layout") {
		t.Fatalf("an old layout: exit %d: %s", r.ExitCode, r.Stderr)
	}
	if _, err := os.Stat(old.Path(lifecycle.RecordFile)); !os.IsNotExist(err) {
		t.Fatal("a refused run wrote the record")
	}
}

func TestShowJudgesEveryRule(t *testing.T) {
	hygiene.Isolate(t)
	record := "format_version = 1\ncodenames = [\"moonbeam\"]\n\n[[licenses]]\nsubject = \"portal\"\nlicense = \"proprietary\"\nfrom = 2026-01-01\nreason = \"server\"\n\n[[lifecycle]]\nsubject = \"portal\"\nstatus = \"on-hold\"\nfrom = 2026-01-01\nreason = \"paused\"\n"
	f := newFixture(t, record)
	f.repo.Git("remote", "add", "origin", "https://github.com/acme/portal.git")
	testsupport.FakeGH(t, ghVisibility("public"))
	var report lifecycleops.Report
	r := f.run(t, false, func(inv lifecycleops.Invocation, dir string) error {
		var err error
		report, err = inv.Show(dir)
		return err
	})
	requireExit(t, r, 0)
	if !report.Present || !report.Confidential || len(report.Codenames) != 1 || len(report.Problems) != 0 {
		t.Fatalf("report %+v", report)
	}
	verdicts := map[string]string{}
	for _, v := range report.Verdicts {
		verdicts[v.Rule+"/"+v.Subject] = v.Verdict
	}
	for key, want := range map[string]string{
		"proprietary-requires-private/":            lifecycleops.VerdictRefuses,
		"proprietary-refuses-public-output/portal": lifecycleops.VerdictRefuses,
		"private-repository-publishing/":           lifecycleops.VerdictRefuses,
		"lifecycle-allows-release/portal":          lifecycleops.VerdictRefuses,
		"confidential-names/":                      lifecycleops.VerdictHolds,
		"proprietary-history-is-squashed/":         lifecycleops.VerdictHolds,
		"identity-owns-its-tags/":                  lifecycleops.VerdictNotApplicable,
		"registry-names-are-held/":                 lifecycleops.VerdictHolds,
		"closed-periods-are-final/":                lifecycleops.VerdictHolds,
	} {
		if verdicts[key] != want {
			t.Errorf("%s: %q, want %q (all: %v)", key, verdicts[key], want, verdicts)
		}
	}
}
