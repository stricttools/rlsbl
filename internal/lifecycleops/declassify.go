func mergePaths(a, b []string) []string {
	out := append([]string(nil), a...)
	for _, p := range b {
		if !slices.Contains(out, p) {
			out = append(out, p)
		}
	}
	return out
}

// finishDeclassify runs the steps after the squashes, skipping the
// completed ones, and removes the declassify result once every one is
// done.
func (inv Invocation) finishDeclassify(m managed, s *declassifyState) error {
	client, slug, err := inv.gitHubRepository(m)
	if err != nil {
		return err
	}
	timeout, err := historyrewrite.PushTimeout(m.ws.Declarations, 0, false)
	if err != nil {
		return err
	}
	steps := []struct {
		name string
		run  func() error
	}{
		{stepRecords, func() error { return inv.repairRecords(m, s) }},
		{stepCommitted, func() error { return inv.commitDeclassification(m, s) }},
		{stepBranch, func() error {
			ref := "refs/heads/" + s.Branch
			return historyrewrite.PushWithLease(m.repo, ref, s.RemoteRefs[ref], s.Commit, timeout)
		}},
		{stepTags, func() error {
			for _, t := range s.Tags {
				if !strings.HasPrefix(t.Refname, "refs/tags/") {
					return fmt.Errorf("the squash's tag list names %q, which is not a tag ref; nothing further was pushed", t.Refname)
				}
				if err := historyrewrite.PushWithLease(m.repo, t.Refname, s.RemoteRefs[t.Refname], t.NewSHA, timeout); err != nil {
					return err
				}
			}
			return nil
		}},
		{stepReleases, func() error {
			if len(s.Tags) == 0 {
				return nil
			}
			rec, err := lifecycle.Load(m.root)
			if err != nil {
				return err
			}
			scanner, err := publishrules.LoadScanner(m.root, inv.IndexPath, inv.Now())
			if err != nil {
				return err
			}
			written, err := historyrewrite.RewriteReleases(historyrewrite.ReleaseRepair{Repo: m.repo, Workspace: m.ws, Record: rec, GitHub: client, Repository: slug, Scanner: scanner, Rewrites: s.Rewrites, Say: inv.Say}, s.Tags)
			s.ReleasesWritten = written
			return err
		}},
		{stepPublic, func() error {
			if err := client.SetVisibility(slug, github.Public); err != nil {
				return err
			}
			inv.Say(slug.String() + " is public.")
			return nil
		}},
	}
	for _, step := range steps {
		if s.done(step.name) {
			continue
		}
		if err := step.run(); err != nil {
			return fmt.Errorf("%w\nThe declassification stopped before its %s step; %s is kept, so running the same command again resumes from there", err, step.name, runstate.DeclassifyResultPath)
		}
		s.CompletedSteps = append(s.CompletedSteps, step.name)
		if err := inv.saveState(m.root, s); err != nil {
			return err
		}
	}
	if err := runstate.ClearDeclassifyResult(inv.E, m.root); err != nil {
		return err
	}
	inv.Say(fmt.Sprintf("Declassified: %d period(s) squashed, %d commit(s) rewritten, %d tag(s) pushed, %d GitHub Release(s) written, and %s made public.", len(s.Ranges), len(s.Rewrites), len(s.Tags), s.ReleasesWritten, slug))
	inv.Say(servedReport(s.Served, slug))
	return nil
}

// servedReport names the commits of the proprietary periods GitHub still
// serves by their ids after the force-push, which only GitHub support can
// purge.
func servedReport(served []string, slug github.Repository) string {
	if len(served) == 0 {
		return "origin held no commit of a proprietary period, so GitHub serves none of them by its id."
	}
	return fmt.Sprintf("GitHub still serves these %d commit(s) of the proprietary periods by their ids after the force-push, and only GitHub support can purge them: the owner asks GitHub support to remove them from %s now, at the declassification.\n  %s", len(served), slug, strings.Join(served, "\n  "))
}

// servedProprietaryCommits are the commits of the ranges, oldest first, that
// origin holds before the declassification rewrites anything: the ones
// reachable from a ref origin holds. GitHub keeps serving a commit it
// received by its id after a force-push takes every ref off it. A ref origin
// holds at a commit this repository lacks is refused, since what it holds
// could not be told.
func servedProprietaryCommits(repo git.Repo, history []git.FirstParentCommit, ranges []squashRange, remote map[string]string) ([]string, error) {
	if len(ranges) == 0 {
		return nil, nil
	}
	var tips []string
	seen := map[string]bool{}
	for _, ref := range sortedKeys(remote) {
		sha := remote[ref]
		if seen[sha] {
			continue
		}
		seen[sha] = true
		has, err := repo.HasObject(sha)
		if err != nil {
			return nil, err
		}
		if !has {
			return nil, fmt.Errorf("origin's %s is at %s, which this repository does not have, so which commits of the proprietary periods GitHub keeps serving after the force-push cannot be listed; nothing was rewritten. Fetch it (`git fetch origin`) and run this again", ref, sha)
		}
		tips = append(tips, sha)
	}
	if len(tips) == 0 {
		return nil, nil
	}
	reachable, err := repo.Commits(tips, nil)
	if err != nil {
		return nil, err
	}
	held := map[string]bool{}
	for _, c := range reachable {
		held[c] = true
	}
	var served []string
	for _, r := range ranges {
		inRange := false
		for _, c := range history {
			if c.SHA == r.First {
				inRange = true
			}
			if inRange && held[c.SHA] {
				served = append(served, c.SHA)
			}
			if c.SHA == r.Last {
				break
			}
		}
	}
	return served, nil
}

// repairRecords repairs what the squashes renamed and writes the record of
// the repository going public.
func (inv Invocation) repairRecords(m managed, s *declassifyState) error {
	on, err := s.date()
	if err != nil {
		return err
	}
	started, err := time.Parse(time.RFC3339, s.StartedAt)
	if err != nil {
		return fmt.Errorf("the declassify result's started_at %q is not an RFC 3339 time: %w", s.StartedAt, err)
	}
	var paths []string
	if len(s.Rewrites) > 0 {
		report, err := changelog.Remap(inv.E, m.root, s.Rewrites)
		if err != nil {
			return err
		}
		for _, f := range report.Files {
			inv.Say(fmt.Sprintf("Remapped %d commit id(s) in %s.", f.CommitsRemapped, f.Path))
			paths = append(paths, f.Path)
		}
		dropped, err := inv.dropFoldedReleases(m, s)
		if err != nil {
			return err
		}
		paths = append(paths, dropped...)
		remaps, files, err := releaserecord.RepairReleaseCommits(inv.E, m.repo, s.Rewrites, "rlsbl transition declassify to "+s.NewHead, releaserecord.ContentChangeRefuse, inv.Now())
		if err != nil {
			return err
		}
		for _, r := range remaps {
			inv.Say(fmt.Sprintf("Moved the release commit of %s %s: %s -> %s.", r.Dir, r.Version, r.OldCommit, r.NewCommit))
		}
		paths = append(paths, files...)
	}
	rec, err := lifecycle.Load(m.root)
	if err != nil {
		return err
	}
	for _, subject := range sortedKeys(s.Licenses) {
		license := s.Licenses[subject]
		current, ok := rec.LicenseOn(subject, on)
		if ok && current.License == license {
			continue
		}
		if err := closeOpen(rec, lifecycle.TableLicenses, subject, on); err != nil {
			return err
		}
		if err := rec.OpenPeriod(lifecycle.TableLicenses, subject, license, on, s.Reason); err != nil {
			return err
		}
	}
	if err := rec.ClearConfidentialTerms(); err != nil {
		return err
	}
	if rec.Confidential(on) {
		return fmt.Errorf("the record is still confidential on %s after the proprietary licenses closed; nothing was committed. Check %s", day(on), lifecycle.RecordFile)
	}
	if err := rec.Validate(on, m.ws.Declarations.SubjectNames()); err != nil {
		return fmt.Errorf("the declassified record would not be valid, so nothing was committed: %w", err)
	}
	if s.ArchivePath == "" {
		tags := make([]releaserecord.ArchivedTag, len(s.Tags))
		for i, t := range s.Tags {
			tags[i] = releaserecord.ArchivedTag{Refname: t.Refname, OldSHA: t.OldSHA, NewSHA: t.NewSHA, Annotated: t.Annotated}
		}
		rel, err := releaserecord.WriteRewriteArchive(inv.E, m.root, started, releaserecord.RewriteArchive{
			Operation:        releaserecord.OperationDeclassify,
			Mode:             "squash",
			Reason:           s.Reason,
			OldHead:          s.OldHead,
			NewHead:          s.NewHead,
			CommitsRewritten: s.CommitsRewritten,
			Rewrites:         s.Rewrites,
			Tags:             tags,
			SquashCommits:    s.SquashCommits,
		})
		if err != nil {
			return err
		}
		s.ArchivePath = rel
	}
	update, err := inv.planIndex(m.repo, rec, on)
	if err != nil {
		return err
	}
	if err := rec.Write(recordWriter{inv.E}, m.root); err != nil {
		return err
	}
	if err := update.apply(inv.E); err != nil {
		return err
	}
	s.Paths = mergePaths(mergePaths(mergePaths(s.Paths, paths), recordPaths), append([]string{s.ArchivePath}, recordManifests...))
	return nil
}

// dropFoldedReleases makes unrecoverable the archive of every version
// whose release commit a squash folded into a commit carrying another
// tree: the released tree is gone from the history. A release commit that
// was its period's last commit keeps its tree in the squash commit, and
// moves there with the other release commits.
func (inv Invocation) dropFoldedReleases(m managed, s *declassifyState) ([]string, error) {
	targets, err := releaserecord.RemapTargets(m.root)
	if err != nil {
		return nil, err
	}
	folded := map[string]bool{}
	for _, c := range s.Folded {
		folded[c] = true
	}
	var paths []string
	for _, t := range targets {
		planned, err := releaserecord.PlanRemap(m.repo, t.Dir, s.Rewrites, releaserecord.ContentChangeRecord)
		if err != nil {
			return nil, err
		}
		for _, p := range planned {
			if !folded[p.OldCommit] || len(p.Changed) == 0 {
				continue
			}
			changed, err := releaserecord.DropReleaseCommit(inv.E, m.root, t.Dir, p.Version)
			if err != nil {
				return nil, err
			}
			if changed {
				inv.Say(fmt.Sprintf("%s %s shipped from %s, which a squash folded into %s, whose tree is another: its released tree is gone from the history, so %s now records it unrecoverable.", t.Subject, p.Version, p.OldCommit, p.NewCommit, p.Path))
				paths = append(paths, p.Path)
			}
		}
	}
	return paths, nil
}

// recordDirs are the directories the declassification's repairs write
// into. safegit squashes only a clean working tree, so what changed in them
// since is the declassification's own, a repair an earlier run stopped
// part-way through included.
var recordDirs = []string{
	declarations.ChangelogRoot,
	declarations.ReleasesRoot,
	declarations.RetiredHistoriesRoot,
	path.Dir(declarations.TransitionsFile),
	declarations.HistoryRewritesDir,
	lifecycle.RecordDir,
}

// commitDeclassification commits every record the declassification wrote,
// with the Autogenerated trailer and a trailer naming the rewrite's heads.
func (inv Invocation) commitDeclassification(m managed, s *declassifyState) error {
	changed, err := m.repo.ChangedPaths(recordDirs, git.UntrackedAll)
	if err != nil {
		return err
	}
	paths := mergePaths(s.Paths, changed)
	message := fmt.Sprintf("declassify: %s\n\nDeclassify-remap: %s..%s", s.Reason, s.OldHead, s.NewHead)
	if _, err := m.repo.Commit(git.CommitRequest{Message: message, Paths: paths, Autogenerated: true, RequireChange: true}); err != nil {
		return fmt.Errorf("the declassification's records could not be committed (%w); nothing was pushed", err)
	}
	head, err := m.repo.Head()
	if err != nil {
		return err
	}
	s.Commit = head
	inv.Say("Committed the declassification's records as " + head + ".")
	return nil
}
