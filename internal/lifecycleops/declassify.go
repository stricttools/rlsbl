// SquashMessage is the whole message of every squash commit a
// declassification writes: a fixed text, so it names no confidential term,
// carrying the Autogenerated trailer, since rlsbl wrote the commit and no
// changelog entry describes it.
const SquashMessage = "Squash the history of a proprietary period\n\n" +
	"The commits of one proprietary period, folded into one commit when the repository was made public.\n\n" +
	git.AutogeneratedTrailer + ": true"

// The declassification's steps after its squashes, in order. Each completed
// step is saved in the declassify result, so a declassification that stops
// is finished by running the same command again, from the step that
// stopped it.
const (
	stepRecords   = "records-repaired"
	stepCommitted = "committed"
	stepBranch    = "branch-pushed"
	stepTags      = "tags-pushed"
	stepReleases  = "releases-updated"
	stepPublic    = "made-public"
)

var declassifySteps = []string{stepRecords, stepCommitted, stepBranch, stepTags, stepReleases, stepPublic}

// safegitSquashTimeout bounds one squash.
const safegitSquashTimeout = 10 * time.Minute

// pruneCommand removes the objects a rewrite left unreachable.
const pruneCommand = "git reflog expire --expire=now --all && git gc --prune=now"

// DeclassifyRequest is one `transition declassify`.
type DeclassifyRequest struct {
	// Dir is the working directory, absolute.
	Dir string
	// Licenses maps every releasable whose license is proprietary to the
	// license it takes when the repository goes public.
	Licenses map[string]string
	Reason   string
}

// declassifyState is the declassify result: the plan, what the squashes
// rewrote, and which steps completed. It is run state, never committed.
type declassifyState struct {
	Licenses map[string]string `json:"licenses"`
	Reason   string            `json:"reason"`
	// Date is the command's date, on which the proprietary periods close.
	Date      string `json:"date"`
	StartedAt string `json:"started_at"`
	Branch    string `json:"branch"`
	// RemoteRefs is origin's refs as read before the first squash: the
	// lease of every push.
	RemoteRefs map[string]string `json:"remote_refs"`
	// Ranges are the planned squashes, oldest first; they are run newest
	// first, so the commits of an older range keep their ids until its
	// squash runs.
	Ranges []squashRange `json:"ranges"`
	// Served are the commits of the ranges origin held before the first
	// squash, oldest first: GitHub keeps serving them by their ids after
	// the force-push, until GitHub support purges them.
	Served   []string `json:"served"`
	Squashed int      `json:"squashed"`
	OldHead  string   `json:"old_head"`
	NewHead  string   `json:"new_head"`
	// Rewrites maps every original commit the squashes rewrote to the
	// commit it ended as.
	Rewrites         map[string]string           `json:"rewrites"`
	Folded           []string                    `json:"folded"`
	SquashCommits    []string                    `json:"squash_commits"`
	Tags             []historyrewrite.TagRewrite `json:"tags"`
	CommitsRewritten int                         `json:"commits_rewritten"`
	// CleanupFailed marks a squash after which safegit could not prune the
	// folded commits; the next run requires them gone.
	CleanupFailed   bool     `json:"cleanup_failed"`
	CompletedSteps  []string `json:"completed_steps"`
	Paths           []string `json:"paths"`
	ArchivePath     string   `json:"archive_path"`
	Commit          string   `json:"commit"`
	ReleasesWritten int      `json:"releases_written"`
}

func (s *declassifyState) done(step string) bool { return slices.Contains(s.CompletedSteps, step) }

func (s *declassifyState) date() (time.Time, error) {
	t, err := time.Parse(time.DateOnly, s.Date)
	if err != nil {
		return time.Time{}, fmt.Errorf("the declassify result's date %q is not a date: %w", s.Date, err)
	}
	return t, nil
}

func loadDeclassifyState(root string) (*declassifyState, bool, error) {
	data, found, err := runstate.LoadDeclassifyResult(root)
	if err != nil || !found {
		return nil, false, err
	}
	dec := json.NewDecoder(bytes.NewReader(data))
	dec.DisallowUnknownFields()
	var s declassifyState
	if err := dec.Decode(&s); err != nil {
		return nil, false, fmt.Errorf("%s cannot be read (%v); it is the state of a declassification in progress, written by rlsbl", runstate.DeclassifyResultPath, err)
	}
	return &s, true, nil
}

func (inv Invocation) saveState(root string, s *declassifyState) error {
	data, err := json.MarshalIndent(s, "", "  ")
	if err != nil {
		return err
	}
	return runstate.SaveDeclassifyResult(inv.E, root, append(data, '\n'))
}

// licenseFlags spells a request's licenses as the command line takes them.
func licenseFlags(licenses map[string]string) string {
	names := make([]string, 0, len(licenses))
	for name := range licenses {
		names = append(names, name)
	}
	sort.Strings(names)
	parts := make([]string, len(names))
	for i, name := range names {
		parts[i] = "--license " + name + "=" + licenses[name]
	}
	return strings.Join(parts, " ")
}

func sameLicenses(a, b map[string]string) bool {
	if len(a) != len(b) {
		return false
	}
	for k, v := range a {
		if b[k] != v {
			return false
		}
	}
	return true
}

// Declassify takes a confidential repository public, in this order: each
// proprietary period's commits on the release branch's first-parent history
// are squashed into one commit (SquashMessage) through safegit's squash,
// newest period first, keeping the public history before and after each;
// the records the rewrite renamed are repaired as a scrub repairs them (the
// changelog's commit ids, the archives' release commits, with an archive
// whose release commit was folded into a commit of another tree made
// unrecoverable); the proprietary license periods close and the licenses
// --license names open; the codenames, distinctive terms, and public-client
// declarations are removed;
// the repository's confidential-name index entry is removed; a history-
// rewrite archive records the run; everything is committed; the branch and
// the moved tags are force-pushed with leases taken before the first
// squash; each moved tag's GitHub Release is rewritten from the record; and
// the GitHub repository is made public. A declassification that stops is
// finished by running the same command again.
func (inv Invocation) Declassify(req DeclassifyRequest) (err error) {
	m, err := inv.openManaged(req.Dir)
	if err != nil {
		return err
	}
	state, resuming, err := loadDeclassifyState(m.root)
	if err != nil {
		return err
	}
	if resuming {
		if !sameLicenses(state.Licenses, req.Licenses) || state.Reason != req.Reason {
			return fmt.Errorf("%s holds a declassification started with `%s --reason %s`; run `rlsbl transition declassify` with those arguments to finish it", runstate.DeclassifyResultPath, licenseFlags(state.Licenses), shellQuote(state.Reason))
		}
		if inv.DryRun {
			inv.Say(fmt.Sprintf("A declassification is in progress (%s). Without --dry-run this command finishes it, from: %s.", runstate.DeclassifyResultPath, strings.Join(remaining(state), ", ")))
			return nil
		}
	} else {
		if state, err = inv.beginDeclassify(m, req); err != nil || state == nil {
			return err
		}
	}

	lock, err := runstate.Acquire(inv.E, m.root, runstate.AcquireOptions{Wait: runstate.WaitForHolder, OnWait: func(path string) {
		inv.Say(fmt.Sprintf("Another rlsbl process holds %s; waiting for it to finish before rewriting.", path))
	}})
	if err != nil {
		return err
	}
	defer func() {
		if rerr := lock.Release(); rerr != nil && err == nil {
			err = rerr
		}
	}()

	if resuming {
		inv.Say("Resuming the declassification saved in " + runstate.DeclassifyResultPath + ".")
		if err := inv.requireSameHistory(m, state); err != nil {
			return err
		}
	}
	for state.Squashed < len(state.Ranges) {
		if err := inv.squash(m, state); err != nil {
			return err
		}
	}
	if err := inv.requireCleanup(m, state); err != nil {
		return err
	}
	return inv.finishDeclassify(m, state)
}

// remaining lists what a saved declassification has left.
func remaining(s *declassifyState) []string {
	var left []string
	if n := len(s.Ranges) - s.Squashed; n > 0 {
		left = append(left, fmt.Sprintf("%d squash(es)", n))
	}
	for _, step := range declassifySteps {
		if !s.done(step) {
			left = append(left, step)
		}
	}
	return left
}

// requireSameHistory refuses to finish a saved declassification when HEAD
// is not where it left HEAD: its squashes' new head, or its commit on top.
func (inv Invocation) requireSameHistory(m managed, s *declassifyState) error {
	head, err := m.repo.Head()
	if err != nil {
		return err
	}
	want := s.NewHead
	if s.done(stepCommitted) {
		want = s.Commit
	}
	if head != want {
		return fmt.Errorf("%s holds a declassification that left HEAD at %s, but HEAD is %s; check out the branch it rewrote (%s) at that commit and run it again. If that declassification was finished or given up some other way, remove %s first", runstate.DeclassifyResultPath, want, head, s.Branch, runstate.DeclassifyResultPath)
	}
	return nil
}

// proprietarySubjects are the subjects whose license on the date of on is
// proprietary, sorted.
func proprietarySubjects(rec *lifecycle.Record, on time.Time) []string {
	var out []string
	for _, l := range rec.Licenses() {
		if l.Proprietary() && l.Contains(on) && !slices.Contains(out, l.Subject) {
			out = append(out, l.Subject)
		}
	}
	sort.Strings(out)
	return out
}

// beginDeclassify makes every check before anything is written, plans the
// squashes, and saves the state the run goes on from. Under --dry-run it
// prints the plan and returns no state.
func (inv Invocation) beginDeclassify(m managed, req DeclassifyRequest) (*declassifyState, error) {
	on := inv.Now()
	rec := m.record
	proprietary := proprietarySubjects(rec, on)
	if len(proprietary) == 0 {
		return nil, fmt.Errorf("no releasable's license is proprietary on %s, so the repository is public already and there is nothing to declassify", day(on))
	}
	for _, subject := range sortedKeys(req.Licenses) {
		if !slices.Contains(proprietary, subject) {
			return nil, fmt.Errorf("--license names %q, whose license on %s is not proprietary; name the proprietary releasables and no other: %s", subject, day(on), strings.Join(proprietary, ", "))
		}
		license := req.Licenses[subject]
		if license == "" || strings.ContainsAny(license, " \t\n") || license == lifecycle.ProprietaryLicense {
			return nil, fmt.Errorf("--license %s=%s does not name the public license %s takes; name an SPDX identifier (MIT, Apache-2.0, ...)", subject, license, subject)
		}
	}
	for _, subject := range proprietary {
		if _, ok := req.Licenses[subject]; !ok {
			return nil, fmt.Errorf("--license names no license for %q, whose license is proprietary; every proprietary releasable takes a license when the repository goes public: --license %s=<SPDX identifier>", subject, subject)
		}
	}
	if names, err := runstate.InProgressReleasables(m.root); err != nil {
		return nil, err
	} else if len(names) > 0 {
		return nil, fmt.Errorf("a release of %s is stopped mid-flight, and the declassification rewrites the history its state records; finish it with `"+runstate.ResumeInvocation+"` or give it up with `rlsbl release abandon`, then run this again", strings.Join(names, ", "))
	}
	if _, found, err := runstate.LoadScrubResult(m.root); err != nil {
		return nil, err
	} else if found {
		return nil, fmt.Errorf("a scrub is in progress (%s); finish it by running the same `rlsbl release scrub` again, then run this", runstate.ScrubResultPath)
	}
	branch, err := m.repo.CurrentBranch()
	if err != nil {
		return nil, err
	}
	if !slices.Contains(m.ws.Declarations.ReleaseBranches, branch) {
		return nil, fmt.Errorf("the declassification force-pushes the branch it rewrites, and %s is not a release branch (release_branches in %s: %s); check out a release branch and run it there", branch, declarations.ReleasablesFile, strings.Join(m.ws.Declarations.ReleaseBranches, ", "))
	}
	configured, err := m.repo.RemoteConfigured(origin)
	if err != nil {
		return nil, err
	}
	if !configured {
		return nil, errors.New("the declassification pushes the rewritten history to origin, and this repository has no origin remote; add it (`git remote add origin <url>`) and run this again")
	}
	url, err := m.repo.RemoteURL(origin)
	if err != nil {
		return nil, err
	}
	repoNames, err := index.RepositoryNames(m.root, url)
	if err != nil {
		return nil, err
	}
	client, slug, err := inv.gitHubRepository(m)
	if err != nil {
		return nil, err
	}
	if err := client.CheckAuth(); err != nil {
		return nil, err
	}
	terms, err := rec.ConfidentialNames(on, repoNames...)
	if err != nil {
		return nil, err
	}
	if matches := index.ScanTerms(SquashMessage, terms); len(matches) > 0 {
		return nil, fmt.Errorf("the squash commits' fixed message names the confidential term %q (line %d), which the history would publish; nothing was rewritten. Remove %q from the record's codenames or distinctive terms, if it is one, or report this", matches[0].Term, matches[0].Line, matches[0].Term)
	}
	removed := append(rec.Codenames(), rec.DistinctiveTerms()...)
	if matches := index.ScanTerms(req.Reason, removed); len(matches) > 0 {
		return nil, fmt.Errorf("--reason names %q, a codename or distinctive term the declassification removes from the record so it is never published, and the reason is published (the record, the rewrite's archive, and the commit carry it); nothing was rewritten. Word the reason without it", matches[0].Term)
	}
	history, err := m.repo.FirstParentHistory("HEAD")
	if err != nil {
		return nil, err
	}
	ranges, err := declassifySquashPlan(history, rec.ProprietaryPeriods())
	if err != nil {
		return nil, err
	}
	if err := requireSafegit(inv.E); err != nil {
		return nil, err
	}
	head, err := m.repo.Head()
	if err != nil {
		return nil, err
	}
	for _, r := range ranges {
		inv.Say(fmt.Sprintf("Squash %s: %d commit(s), %s through %s, into one commit.", r.describe(), r.Count, r.First, r.Last))
	}
	if len(ranges) == 0 {
		inv.Say("No commit of the release branch falls in a proprietary period; there is nothing to squash.")
	}
	if inv.DryRun {
		inv.Say(fmt.Sprintf("Then close the proprietary licenses on %s and open %s, remove the codenames, distinctive terms, public-client declarations, and the index entry, commit, force-push %s and the moved tags, rewrite their GitHub Releases, and make %s public. Nothing was written.", day(on), licenseFlags(req.Licenses), branch, slug))
		return nil, nil
	}
	remote, err := m.repo.RemoteRefsPeeled(origin)
	if err != nil {
		return nil, fmt.Errorf("origin's refs cannot be read (%v): the declassification force-pushes the rewritten history, so origin must answer before the history is rewritten", err)
	}
	served, err := servedProprietaryCommits(m.repo, history, ranges, remote)
	if err != nil {
		return nil, err
	}
	state := &declassifyState{
		Licenses:   req.Licenses,
		Reason:     req.Reason,
		Date:       day(on),
		StartedAt:  on.UTC().Format(time.RFC3339),
		Branch:     branch,
		RemoteRefs: remote,
		Ranges:     ranges,
		Served:     served,
		OldHead:    head,
		NewHead:    head,
		Rewrites:   map[string]string{},
	}
	if err := inv.saveState(m.root, state); err != nil {
		return nil, err
	}
	if err := release.RemoveCheckout(m.repo, inv.Say); err != nil {
		return nil, err
	}
	return state, nil
}

func sortedKeys[V any](m map[string]V) []string {
	keys := make([]string, 0, len(m))
	for k := range m {
		keys = append(keys, k)
	}
	sort.Strings(keys)
	return keys
}

var releaseVersion = regexp.MustCompile(`(\d+)\.(\d+)\.(\d+)`)

// requireSafegit refuses a safegit that is missing or older than the
// release whose squash the declassification runs.
func requireSafegit(e *strictcli.Effects) error {
	install := fmt.Sprintf("`rlsbl transition declassify` squashes history through `safegit scrub squash` of safegit %s or newer; install that safegit and run this again", historyrewrite.SafegitMinimum)
	done, err := e.Run([]interface{}{"safegit", "--version"}, strictcli.Check(false), strictcli.Timeout(15*time.Second))
	if err != nil {
		return fmt.Errorf("safegit could not be run (%v): %s", err, install)
	}
	if done.ExitCode() != 0 {
		return fmt.Errorf("`safegit --version` exited %d (%s): %s", done.ExitCode(), strings.TrimSpace(done.Stderr()), install)
	}
	fields := strings.Fields(strings.TrimSpace(done.Stdout()))
	var m []string
	if len(fields) > 0 {
		m = releaseVersion.FindStringSubmatch(fields[len(fields)-1])
	}
	if m == nil {
		return fmt.Errorf("the safegit version cannot be read from %q: %s", strings.TrimSpace(done.Stdout()), install)
	}
	found, err := semver.Parse(m[1] + "." + m[2] + "." + m[3])
	if err != nil {
		return fmt.Errorf("the safegit version cannot be read from %q (%v): %s", strings.TrimSpace(done.Stdout()), err, install)
	}
	if semver.Compare(found, historyrewrite.SafegitMinimum) < 0 {
		return fmt.Errorf("safegit %s is installed, and %s", found, install)
	}
	return nil
}

// squashPayload is what the declassification reads of safegit's squash
// payload; every other member is safegit's own.
type squashPayload struct {
	Squashed         []string                    `json:"squashed"`
	SquashCommit     string                      `json:"squash_commit"`
	Rewrites         map[string]string           `json:"rewrites"`
	Tags             []historyrewrite.TagRewrite `json:"tags"`
	CommitsRewritten *int                        `json:"commits_rewritten"`
	NewHead          string                      `json:"new_head"`
	CleanupOK        *bool                       `json:"cleanup_ok"`
	CleanupErrors    []string                    `json:"cleanup_errors"`
}

// parseSquashDocument reads safegit's --json stdout: strictcli's
// machine-mode document at historyrewrite.SafegitInterfaceVersion, whose payload is the
// squash's.
func parseSquashDocument(stdout string) (*squashPayload, error) {
	need := fmt.Sprintf("the declassification needs safegit %s or newer, whose --json prints strictcli's machine-mode document at interface_version %d", historyrewrite.SafegitMinimum, historyrewrite.SafegitInterfaceVersion)
	var doc struct {
		InterfaceVersion *int            `json:"interface_version"`
		Payload          json.RawMessage `json:"payload"`
	}
	if err := json.Unmarshal([]byte(strings.TrimSpace(stdout)), &doc); err != nil {
		return nil, fmt.Errorf("safegit --json printed something that is not one JSON document (%v); %s", err, need)
	}
	if doc.InterfaceVersion == nil || *doc.InterfaceVersion != historyrewrite.SafegitInterfaceVersion {
		return nil, fmt.Errorf("safegit printed no machine-mode document at interface_version %d; %s", historyrewrite.SafegitInterfaceVersion, need)
	}
	if len(doc.Payload) == 0 || string(doc.Payload) == "null" {
		return nil, fmt.Errorf("safegit's squash printed no payload; %s", need)
	}
	var p squashPayload
	if err := json.Unmarshal(doc.Payload, &p); err != nil {
		return nil, fmt.Errorf("safegit's squash payload cannot be read: %v", err)
	}
	return &p, nil
}

// squash runs the next squash, newest range first, and folds what it
// rewrote into the state.
func (inv Invocation) squash(m managed, s *declassifyState) error {
	r := s.Ranges[len(s.Ranges)-1-s.Squashed]
	args := []interface{}{"safegit", "--approve-consequential", "scrub", "squash", "--json", "--first", r.First, "--last", r.Last, "--message", SquashMessage, "--reason", "declassify: " + s.Reason}
	done, err := inv.E.Run(args, strictcli.Cwd(m.root), strictcli.Check(false), strictcli.Timeout(safegitSquashTimeout))
	if err != nil {
		return fmt.Errorf("safegit scrub squash could not be run: %w", err)
	}
	payload, perr := parseSquashDocument(done.Stdout())
	if done.ExitCode() != 0 {
		report := strings.TrimSpace(done.Stderr())
		head, herr := m.repo.Head()
		if perr == nil && payload.SquashCommit != "" && herr == nil && head == payload.NewHead {
			fold(s, payload)
			if err := inv.saveState(m.root, s); err != nil {
				return err
			}
			return fmt.Errorf("safegit squashed %s, then failed (exit %d):\n%s\nThe squash is saved in %s; fix what safegit reports, then run the same command again", r.describe(), done.ExitCode(), report, runstate.DeclassifyResultPath)
		}
		return fmt.Errorf("safegit could not squash %s (exit %d):\n%s\nNothing of this squash was rewritten; %s keeps what earlier squashes did, so running the same command again goes on from here", r.describe(), done.ExitCode(), report, runstate.DeclassifyResultPath)
	}
	if perr != nil {
		return perr
	}
	fold(s, payload)
	if err := inv.saveState(m.root, s); err != nil {
		return err
	}
	inv.Say(fmt.Sprintf("Squashed %d commit(s) of %s into %s.", len(payload.Squashed), r.describe(), payload.SquashCommit))
	return nil
}

// fold composes one squash's rewrite into the state: each original commit
// maps to where it ends, a tag keeps its original old_sha with its final
// new_sha, and an earlier squash commit the later squash rewrote is
// followed.
func fold(s *declassifyState, p *squashPayload) {
	written := map[string]bool{}
	for old, mid := range s.Rewrites {
		written[mid] = true
		if final, ok := p.Rewrites[mid]; ok {
			s.Rewrites[old] = final
		}
	}
	for old, next := range p.Rewrites {
		if _, ok := s.Rewrites[old]; !ok && !written[old] {
			s.Rewrites[old] = next
		}
	}
	for i, c := range s.SquashCommits {
		if next, ok := p.Rewrites[c]; ok {
			s.SquashCommits[i] = next
		}
	}
	s.SquashCommits = append(s.SquashCommits, p.SquashCommit)
	s.Folded = append(s.Folded, p.Squashed...)
	for _, t := range p.Tags {
		i := slices.IndexFunc(s.Tags, func(x historyrewrite.TagRewrite) bool { return x.Refname == t.Refname })
		if i >= 0 {
			s.Tags[i].NewSHA = t.NewSHA
		} else {
			s.Tags = append(s.Tags, t)
		}
	}
	if p.CommitsRewritten != nil {
		s.CommitsRewritten += *p.CommitsRewritten
	}
	s.NewHead = p.NewHead
	if p.CleanupOK != nil && !*p.CleanupOK {
		s.CleanupFailed = true
	}
	s.Squashed++
}

// requireCleanup refuses to go on while a folded commit safegit could not
// prune still exists: the next steps publish the rewritten history, and
// the folded commits are what the declassification exists to remove.
func (inv Invocation) requireCleanup(m managed, s *declassifyState) error {
	if !s.CleanupFailed {
		return nil
	}
	for _, sha := range s.Folded {
		has, err := m.repo.HasObject(sha)
		if err != nil {
			return err
		}
		if has {
			return fmt.Errorf("safegit could not prune the commits its squash folded, and %s still exists here; complete the prune (`%s`) and run the same command again", sha, pruneCommand)
		}
	}
	s.CleanupFailed = false
	return inv.saveState(m.root, s)
}

