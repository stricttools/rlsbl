// clientRecord makes portal proprietary, with a codename and an npm name
// recorded for it.
const clientRecord = `format_version = 1
codenames = ["moonbeam"]

[[licenses]]
subject = "portal"
license = "proprietary"
from = 2026-01-01
reason = "server"

[[registry_names]]
registry = "npm"
name = "portal-client"
subject = "portal"
recorded_since = 2026-01-01
` + portalName

func TestPublicClientTakesTheRegistryAndRepositoryNamesOutOfTheIndex(t *testing.T) {
	hygiene.Isolate(t)
	f := newFixture(t, clientRecord)
	f.repo.Git("remote", "add", "origin", "https://github.com/acme/portal-checkout.git")
	testsupport.FakeSafegit(t)
	testsupport.FakeGH(t, ghVisibility("private"))
	f.refreshIndex(t)
	requireContains(t, f.indexText(t), `"portal-client"`, `"portal-checkout"`, `"moonbeam"`)

	r := f.run(t, false, func(inv lifecycleops.Invocation, dir string) error {
		return inv.PublicClient(dir, "portal", "a thin public client is planned")
	})
	requireExit(t, r, 0)
	requireContains(t, f.record(t), "[[public_clients]]\nsubject = \"portal\"\nreason = \"a thin public client is planned\"\ndeclared = 2026-06-01")
	if subject, trailer := f.lastCommit(t); subject != "transition: portal has a public client" || trailer != "true" {
		t.Errorf("commit %q, Autogenerated %q", subject, trailer)
	}
	f.clean(t)
	text := f.indexText(t)
	requireContains(t, text, `names = ["moonbeam"]`)
	if strings.Contains(text, "portal-client") || strings.Contains(text, "portal-checkout") {
		t.Fatalf("the index keeps a name the public client releases:\n%s", text)
	}
	if v := f.confidentialNamesVerdict(t); v.Verdict != lifecycleops.VerdictHolds {
		t.Fatalf("show after the declaration: %+v", v)
	}
	var report lifecycleops.Report
	requireExit(t, f.run(t, false, func(inv lifecycleops.Invocation, dir string) error {
		var err error
		report, err = inv.Show(dir)
		return err
	}), 0)
	if len(report.PublicClients) != 1 || report.PublicClients[0] != (lifecycleops.ReportPublicClient{Subject: "portal", Reason: "a thin public client is planned", Declared: "2026-06-01"}) {
		t.Fatalf("show's public clients %+v", report.PublicClients)
	}

	r = f.run(t, false, func(inv lifecycleops.Invocation, dir string) error {
		return inv.PublicClient(dir, "portal", "again")
	})
	requireExit(t, r, 1)
	requireContains(t, r.Stderr, `"portal" already has a public client (declared 2026-06-01)`)
}

func TestPublicClientRefusesAnUnknownSubjectAndAPublicRepository(t *testing.T) {
	hygiene.Isolate(t)
	f := newFixture(t, clientRecord)
	testsupport.FakeSafegit(t)
	r := f.run(t, false, func(inv lifecycleops.Invocation, dir string) error {
		return inv.PublicClient(dir, "gizmo", "a client")
	})
	requireExit(t, r, 1)
	requireContains(t, r.Stderr, `"gizmo" is not a subject`)

	public := newFixture(t, mitSince)
	r = public.run(t, false, func(inv lifecycleops.Invocation, dir string) error {
		return inv.PublicClient(dir, "portal", "a client")
	})
	requireExit(t, r, 1)
	requireContains(t, r.Stderr, "the repository is public", "rlsbl transition classify")
	if strings.Contains(public.record(t), "public_clients") {
		t.Fatal("a refused declaration wrote the record")
	}
}

func TestPublicClientDryRunWritesNothing(t *testing.T) {
	hygiene.Isolate(t)
	f := newFixture(t, clientRecord)
	before := f.record(t)
	r := f.run(t, true, func(inv lifecycleops.Invocation, dir string) error {
		return inv.PublicClient(dir, "portal", "a client")
	})
	requireExit(t, r, 0)
	requireContains(t, r.Stdout, "Would record that portal has a public client")
	if f.record(t) != before || f.indexText(t) != "" {
		t.Fatal("a dry run wrote the record or the index")
	}
}

// A public client that leaves a confidential repository no name to protect
// removes its index entry, and show still judges it confidential.
func TestShowHoldsForAConfidentialRepositoryWithNoNameLeftToProtect(t *testing.T) {
	hygiene.Isolate(t)
	f := newFixture(t, strings.Replace(clientRecord, "codenames = [\"moonbeam\"]\n", "", 1))
	testsupport.FakeSafegit(t)
	testsupport.FakeGH(t, ghVisibility("private"))
	requireExit(t, f.run(t, false, func(inv lifecycleops.Invocation, dir string) error {
		return inv.PublicClient(dir, "portal", "a thin public client is planned")
	}), 0)
	if text := f.indexText(t); strings.Contains(text, "portal") {
		t.Fatalf("the index keeps an entry with no names:\n%s", text)
	}
	v := f.confidentialNamesVerdict(t)
	if v.Verdict != lifecycleops.VerdictHolds || !strings.Contains(v.Detail, "confidential") || strings.Contains(v.Detail, "is public") {
		t.Fatalf("show for a confidential repository with no names: %+v", v)
	}
}
