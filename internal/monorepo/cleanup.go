package monorepo

import (
	"errors"
	"strings"

	"github.com/stricttools/strictcli/go/strictcli"

	"github.com/stricttools/rlsbl/internal/git"
	"github.com/stricttools/rlsbl/internal/runstate"
	"github.com/stricttools/rlsbl/internal/saferm"
	"github.com/stricttools/rlsbl/internal/workspace"
)

// CleanupCommitMessage is the message of the commit `monorepo cleanup`
// makes.
const CleanupCommitMessage = "monorepo: remove old-layout release state residue"

// Cleanup is what `monorepo cleanup` removed, and the residue it keeps.
type Cleanup struct {
	Removed []ResidueEntry `json:"removed"`
	// Kept is residue cleanup never removes: the release state of a subject
	// no releasable is declared as, which records what it released.
	Kept []ResidueEntry `json:"kept"`
	// Committed is whether the removals were committed.
	Committed bool `json:"committed"`
	// DryRun is whether the removals were previewed and not made.
	DryRun bool `json:"dry_run"`
}

// ResidueEntry is one residue path and why nothing reads it.
type ResidueEntry struct {
	Path      string `json:"path"`
	Directory bool   `json:"directory"`
	Reason    string `json:"reason"`
}

// RunCleanup removes, through saferm, every residue the workspace's residue
// detection says cleanup removes, and with autoCommit commits the removal of
// what git tracked, with the Autogenerated trailer. Under dryRun the
// removals are recorded and not made, and nothing is committed.
func RunCleanup(e *strictcli.Effects, repo git.Repo, ws *workspace.Workspace, autoCommit, dryRun bool) (_ Cleanup, err error) {
	// The removals and their commit change the repository's release state,
	// which a release beside them would commit or read half-removed.
	lock, err := runstate.Acquire(e, ws.Root, runstate.AcquireOptions{DryRun: dryRun, Wait: runstate.RefuseWhenHeld})
	if err != nil {
		return Cleanup{}, err
	}
	defer func() { err = errors.Join(err, lock.Release()) }()
	tracked, err := repo.TrackedFiles()
	if err != nil {
		return Cleanup{}, err
	}
	residue, err := ws.DetectResidue(tracked)
	if err != nil {
		return Cleanup{}, err
	}
	out := Cleanup{Removed: []ResidueEntry{}, Kept: []ResidueEntry{}, DryRun: dryRun}
	var paths []string
	for _, r := range residue {
		entry := ResidueEntry{Path: r.Path, Directory: r.Directory, Reason: r.Reason}
		if !r.CleanupRemoves {
			out.Kept = append(out.Kept, entry)
			continue
		}
		out.Removed = append(out.Removed, entry)
		paths = append(paths, r.Path)
	}
	if len(paths) == 0 {
		return out, nil
	}
	// git's account of the tracked files under each path is read before the
	// removal, so the commit names the deletions and nothing else.
	var trackedUnder []string
	for _, p := range paths {
		for _, f := range tracked {
			if f == p || strings.HasPrefix(f, p+"/") {
				trackedUnder = append(trackedUnder, f)
			}
		}
	}
	for _, r := range out.Removed {
		if err := saferm.Delete(e, ws.Root, saferm.Request{
			Path:        r.Path,
			Description: "removing old-layout release state residue: " + r.Reason,
			Recursive:   r.Directory,
			SkipMissing: true,
		}); err != nil {
			return Cleanup{}, err
		}
	}
	if !autoCommit || dryRun || len(trackedUnder) == 0 {
		return out, nil
	}
	committed, err := repo.Commit(git.CommitRequest{Message: CleanupCommitMessage, Paths: trackedUnder, Autogenerated: true})
	if err != nil {
		return Cleanup{}, err
	}
	out.Committed = committed
	return out, nil
}
