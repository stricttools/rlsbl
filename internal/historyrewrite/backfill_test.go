func TestAnUnexplainedTagRefusesTheApplyUntilResolved(t *testing.T) {
	hygiene.Isolate(t)
	f := newUnarchived(t, true, "v0.1.0")
	f.repo.Git("tag", "nightly", f.A)
	newSafegit(t, "0.31.0")
	noRelease(t)

	// The preview shows the whole plan, the blocker first, and exits 1.
	r := backfill(t, f.repo.Dir, "", true)
	requireExit(t, r, 1)
	if i, j := strings.Index(r.Stdout, "tag nightly"), strings.Index(r.Stdout, "portal 0.1.0"); i < 0 || j < 0 || i > j {
		t.Fatalf("the unexplained tag is not listed before the versions:\n%s", r.Stdout)
	}
	r = backfill(t, f.repo.Dir, "", false)
	requireExit(t, r, 1)
	requireStderr(t, r, "refusing to backfill", "shipped_as = \"nightly\"", "rlsbl transition unversioned-tag --tag nightly", "git tag -d nightly")
	if exists(f.repo, archivePath) {
		t.Fatal("the refused apply wrote an archive")
	}

	// Recording it outside the version model clears the refusal.
	f.repo.Write(".strictmetadata/lifecycle-and-license/lifecycle-and-license.toml", "format_version = 1\n\n[[unversioned_tags]]\ntag = \"nightly\"\nreason = \"a moving marker\"\nrecorded = 2026-01-01\n")
	requireExit(t, backfill(t, f.repo.Dir, "", true), 0)
	if err := os.Remove(f.repo.Path(".strictmetadata/lifecycle-and-license/lifecycle-and-license.toml")); err != nil {
		t.Fatal(err)
	}

	// Deleting it clears the refusal too.
	f.repo.Git("tag", "-d", "nightly")
	requireExit(t, backfill(t, f.repo.Dir, "", true), 0)
}

func TestAnOldSpellingIsExplainedOnceItsArchiveRecordsShippedAs(t *testing.T) {
	hygiene.Isolate(t)
	f := newUnarchived(t, false, "the changelog")
	f.repo.Git("tag", "portal-0.1.0", f.R)
	newSafegit(t, "0.31.0")
	gh(t)
	r := backfill(t, f.repo.Dir, "", true)
	requireExit(t, r, 1)
	requireStderr(t, r, "portal-0.1.0", "shipped_as = \"portal-0.1.0\"")

	// The archive recording the spelling the version shipped under adopts the
	// tag's commit.
	f.repo.Write(archivePath, "format_version = 2\nbump = \"minor\"\ninclude = [\"npm\"]\nexclude = []\ndescription = \"The first release\"\nshipped_as = \"portal-0.1.0\"\n")
	portal := []string{"release", "view", "portal-0.1.0", "--repo", "acme/portal", "--json", "tagName", "--jq", ".tagName"}
	gh(t, testsupport.GHAnswer{Args: portal, Stderr: "release not found", Exit: 1})
	r = backfill(t, f.repo.Dir, "", false)
	requireExit(t, r, 0)
	if a := readArchive(t, f.repo, "0.1.0"); a.ReleaseCommit.Commit != f.R || a.ShippedAs != "portal-0.1.0" {
		t.Fatalf("the archive holds %+v", a)
	}
}

func TestReviewedDescriptionsComeFirst(t *testing.T) {
	hygiene.Isolate(t)
	f := newUnarchived(t, true, "v0.1.0")
	newSafegit(t, "0.31.0")
	noRelease(t)
	overrides := f.repo.Path("experiments/overrides.toml")
	testsupport.WriteFile(t, overrides, "[versions.\"0.1.0\"]\ndescription = \"The first release, reviewed.\"\ncontext = \"Why it was made.\"\n")
	requireExit(t, backfill(t, f.repo.Dir, overrides, false), 0)
	a := readArchive(t, f.repo, "0.1.0")
	if a.Description != "The first release, reviewed." || a.Context != "Why it was made." {
		t.Fatalf("the archive holds %q and %q", a.Description, a.Context)
	}
	r := backfill(t, f.repo.Dir, overrides, false)
	requireExit(t, r, 0)
	if !strings.Contains(r.Stdout, "Nothing to do") {
		t.Fatalf("a second run with the same file was not settled:\n%s", r.Stdout)
	}
}

