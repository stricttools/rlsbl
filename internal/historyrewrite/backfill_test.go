	f.repo.Git("stash", "push", "-q")
	r := backfill(t, f.repo.Dir, "", true)
	requireExit(t, r, 0)
	if !strings.Contains(r.Stdout, "stash") {
		t.Fatalf("the preview does not report the stash:\n%s", r.Stdout)
	}
