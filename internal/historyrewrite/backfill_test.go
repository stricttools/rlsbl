// unarchived is portal with 0.1.0 released (its changelog file committed
// in R, tagged v0.1.0 when tagged is true) and no archive.
type unarchived struct {
	repo *testsupport.Repo
	A, R string
}

func newUnarchived(t *testing.T, tagged bool, releaseMessage string) *unarchived {
	t.Helper()
	repo := testsupport.NewRepo(t)
	base := map[string]string{declarationsPath: portalDeclarations, "package.json": packageJSON("0.1.0"), "notes.txt": "notes\n"}
	for _, m := range manifests {
		base[m] = "owner = \"rlsbl\"\n"
	}
	a := commitAll(t, repo, base, "the project")
	r := commitAll(t, repo, map[string]string{changelogFilePath: entryLine(1, a)}, releaseMessage)
	if tagged {
		repo.Git("tag", "v0.1.0", r)
	}
	return &unarchived{repo: repo, A: a, R: r}
}

func backfill(t *testing.T, dir, overrides string, dryRun bool) strictcli.Result {
	t.Helper()
	return run(t, dryRun, func(ctx *strictcli.Context) error {
		return historyrewrite.Backfill(ctx, dir, historyrewrite.BackfillRequest{Overrides: overrides, AutoCommit: true})
	})
}

// noRelease answers that v0.1.0 carries no GitHub Release.
func noRelease(t *testing.T) *testsupport.GH {
	t.Helper()
	return gh(t, testsupport.GHAnswer{Args: ghExists, Stderr: "release not found", Exit: 1})
}

func readArchive(t *testing.T, repo *testsupport.Repo, v string) releaserecord.Archive {
	t.Helper()
	version, err := semver.Parse(v)
	if err != nil {
		t.Fatal(err)
	}
	a, err := releaserecord.ReadArchive(repo.Dir, releaserecord.ArchiveDir("portal"), version)
	if err != nil {
		t.Fatal(err)
	}
	return a
}

func TestAReleasedVersionWithNoArchiveIsMaterializedFromItsTag(t *testing.T) {
	hygiene.Isolate(t)
	f := newUnarchived(t, true, "v0.1.0")
	newSafegit(t, "0.31.0")
	noRelease(t)

	r := backfill(t, f.repo.Dir, "", true)
	requireExit(t, r, 0)
	if !strings.Contains(r.Stdout, "materialize") || exists(f.repo, archivePath) {
		t.Fatalf("the dry run did not plan the archive, or wrote it:\n%s", r.Stdout)
	}

	r = backfill(t, f.repo.Dir, "", false)
	requireExit(t, r, 0)
	a := readArchive(t, f.repo, "0.1.0")
	if a.Fate != releaserecord.FateRecorded || a.ReleaseCommit.Commit != f.R || a.ReleaseCommit.Trees["."] != f.repo.Git("rev-parse", f.R+"^{tree}") {
		t.Fatalf("the archive records %+v", a)
	}
	if a.Bump != semver.Minor || !strings.HasPrefix(a.Description, "Reconstructed from this version's commit subjects") {
		t.Fatalf("the archive's reconstructed fields are %q and %q", a.Bump, a.Description)
	}
	text := readFile(t, f.repo, archivePath)
	if !strings.Contains(text, "Materialized by `rlsbl release backfill`") || !strings.Contains(text, "came from: commit-subjects:") {
		t.Fatalf("the archive does not say it was materialized and where its description came from:\n%s", text)
	}
	if !strings.Contains(f.repo.Git("log", "-1", "--format=%B"), "Autogenerated: true") {
		t.Fatal("the archive was not committed with the Autogenerated trailer")
	}
	r = backfill(t, f.repo.Dir, "", false)
	requireExit(t, r, 0)
	if !strings.Contains(r.Stdout, "Nothing to do") {
		t.Fatalf("a second run was not settled:\n%s", r.Stdout)
	}
}

func TestAnArchiveWithBlankFieldsIsCompletedNamingEachSource(t *testing.T) {
	hygiene.Isolate(t)
	f := newUnarchived(t, true, "v0.1.0")
	tree := f.repo.Git("rev-parse", f.R+"^{tree}")
	f.repo.Write(archivePath, "format_version = 2\nbump = \"\"\ninclude = [\"npm\"]\nexclude = []\ndescription = \"\"\nrelease_commit = \""+f.R+"\"\n\n[released_trees]\n\".\" = \""+tree+"\"\n")
	f.repo.Git("add", "-A")
	f.repo.Git("commit", "-q", "-m", "an archive nobody filled in")
	newSafegit(t, "0.31.0")
	gh(t, testsupport.GHAnswer{Args: ghExists, Stdout: "v0.1.0"},
		testsupport.GHAnswer{Args: ghBody, Stdout: "## What changed\n\nThe notes are fixed.\n\n**Full Changelog**: https://github.com/acme/portal/commits/v0.1.0"})

	requireExit(t, backfill(t, f.repo.Dir, "", false), 0)
	a := readArchive(t, f.repo, "0.1.0")
	if a.Bump != semver.Minor || a.Description != "The notes are fixed." || a.ReleaseCommit.Commit != f.R {
		t.Fatalf("the completed archive holds %+v", a)
	}
	text := readFile(t, f.repo, archivePath)
	for _, want := range []string{"bump reconstructed by `rlsbl release backfill` from version arithmetic against 0.0.0", "description reconstructed by `rlsbl release backfill` from github-release:v0.1.0"} {
		if !strings.Contains(text, want) {
			t.Fatalf("the archive lacks %q:\n%s", want, text)
		}
	}
	r := backfill(t, f.repo.Dir, "", false)
	requireExit(t, r, 0)
	if !strings.Contains(r.Stdout, "Nothing to do") {
		t.Fatalf("a second run was not settled:\n%s", r.Stdout)
	}
}

func TestANeverReleasedArchiveIsLeftAsItIs(t *testing.T) {
	hygiene.Isolate(t)
	f := newUnarchived(t, false, "the changelog")
	content := "format_version = 2\nbump = \"minor\"\ninclude = []\nexclude = []\ndescription = \"An attempt\"\nnever_released = true\n"
	f.repo.Write(archivePath, content)
	f.repo.Git("add", "-A")
	f.repo.Git("commit", "-q", "-m", "declare the fate")
	newSafegit(t, "0.31.0")
	gh(t)
	r := backfill(t, f.repo.Dir, "", true)
	requireExit(t, r, 0)
	if !strings.Contains(r.Stdout, "never_released = true") || !strings.Contains(r.Stdout, "0 archive(s) would be written") {
		t.Fatalf("the settled fate was not reported:\n%s", r.Stdout)
	}
	r = backfill(t, f.repo.Dir, "", false)
	requireExit(t, r, 0)
	if !strings.Contains(r.Stdout, "Nothing to do") {
		t.Fatalf("an apply had something to do:\n%s", r.Stdout)
	}
	if readFile(t, f.repo, archivePath) != content {
		t.Fatal("the never-released archive was rewritten")
	}
}

