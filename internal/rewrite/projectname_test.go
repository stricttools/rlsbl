func TestRefusalsNameTheirFixAndTheFixClearsThem(t *testing.T) {
	hygiene.Isolate(t)
	repo := portalProject(t)
	refused := func(from, to string, wants ...string) {
		t.Helper()
		_, err := renameProject(t, repo, true, from, to)
		if err == nil {
			t.Fatalf("%s -> %s was not refused", from, to)
		}
		requireContains(t, err.Error(), wants...)
	}
	cleared := func(from, to string) {
		t.Helper()
		if _, err := renameProject(t, repo, true, from, to); err != nil {
			t.Fatalf("the fix did not clear the refusal: %v", err)
		}
	}

	refused("portal", "portal", "the same name")
	refused("portal", "_gateway", "is not a valid package name", "npm: an npm package name cannot start with an underscore")
	refused("gizmo", "gateway", `--from 'gizmo' does not match`, `package.json (package.json "name") declares "portal"`, "Run again with --from portal.")
	cleared("portal", "gateway")

	repo.Write("scratch.txt", "work in progress\n")
	refused("portal", "gateway", "uncommitted changes", "scratch.txt", "Commit them")
	repo.Commit("commit the work", "scratch.txt")
	cleared("portal", "gateway")

	repo.Git("rm", "-q", releaseFileRel)
	repo.Git("commit", "-q", "-m", "drop the release file")
	refused("portal", "gateway", "rlsbl release init")
	repo.CommitFile(releaseFileRel, nextRelease, "restore the release file")
	cleared("portal", "gateway")

	repo.CommitFile("go.mod", "module github.com/acme/portal-server\n\ngo 1.26\n", "a module path not ending in the name")
	refused("portal", "gateway", "whose last element 'portal-server' is not --from 'portal'", "rlsbl rewrite go-module-path --from-module github.com/acme/portal-server")
}

