func TestAnUnrecoverableLatestReleaseRefusesOnlyAGoTarget(t *testing.T) {
	hygiene.Isolate(t)
	repo := portalProject(t)
	release(t, repo, "unrecoverable")
	_, err := renameProject(t, repo, true, "portal", "gateway")
	if err == nil || !strings.Contains(err.Error(), "the latest release, 0.1.0, is marked unrecoverable") {
		t.Fatalf("%v", err)
	}
	repo.Git("rm", "-q", "go.mod", "main.go", "VERSION")
	repo.Git("commit", "-q", "-m", "no Go target")
	res, err := renameProject(t, repo, true, "portal", "gateway")
	if err != nil {
		t.Fatalf("%v\n%s", err, res.Stderr)
	}
	requireContains(t, res.Stdout, "effective 0.2.0")
}

func TestTheModeOfARenamedManifestIsKept(t *testing.T) {
	hygiene.Isolate(t)
	repo := portalProject(t)
	if err := os.Chmod(filepath.Join(repo.Dir, "package.json"), 0o600); err != nil {
		t.Fatal(err)
	}
	if _, err := renameProject(t, repo, false, "portal", "gateway"); err != nil {
		t.Fatal(err)
	}
	if info, err := os.Stat(filepath.Join(repo.Dir, "package.json")); err != nil || info.Mode().Perm() != 0o600 {
		t.Errorf("%v, %v", info.Mode(), err)
	}
}
