func TestARunAfterACrashBetweenTheCommitsRecordsWhatIsLeft(t *testing.T) {
	hygiene.Isolate(t)
	repo := portalProject(t)
	release(t, repo, "recorded")
	repo.Write("package.json", strings.Replace(read(t, repo.Path("package.json")), `"portal",`, `"gateway",`, 1))
	repo.Write("go.mod", "module github.com/acme/gateway\n\ngo 1.26\n")
	repo.Write("main.go", strings.Replace(read(t, repo.Path("main.go")), "acme/portal", "acme/gateway", 1))
	repo.Commit(rewrite.RenameCommitMessage("portal", "gateway"), "package.json", "go.mod", "main.go")
	renameCommit := repo.Head()
	res, err := renameProject(t, repo, false, "portal", "gateway")
	if err != nil {
		t.Fatalf("%v\n%s", err, res.Stderr)
	}
	if len(pendingOf(t, repo.Dir)) != 2 {
		t.Errorf("%+v", pendingOf(t, repo.Dir))
	}
	requireContains(t, res.Stdout, "--commits "+renameCommit[:12])
}

func TestAPendingIdentityOfAnotherValueRefusesUntilItIsRemoved(t *testing.T) {
	hygiene.Isolate(t)
	repo := portalProject(t)
	other := "format_version = 1\n\n[[identities]]\nsubject = \"portal\"\nfacet = \"package-name\"\nvalue = \"portal-next\"\nregistry = \"npm\"\ntag_patterns = [\"v*\"]\neffective_version = \"0.1.0\"\nreason = \"an earlier plan\"\n"
	repo.Write(lifecycle.ManifestFile, "owner = \"strictspec\"\n")
	repo.Write(lifecycle.RecordFile, other)
	repo.Commit("an earlier pending identity", lifecycle.ManifestFile, lifecycle.RecordFile)
	_, err := renameProject(t, repo, true, "portal", "gateway")
	if err == nil || !strings.Contains(err.Error(), `a pending package-name identity of portal, "portal-next" effective 0.1.0`) || !strings.Contains(err.Error(), "Delete that [[identities]] entry") {
		t.Fatalf("%v", err)
	}
	repo.CommitFile(lifecycle.RecordFile, "format_version = 1\n", "remove the earlier pending identity")
	if _, err := renameProject(t, repo, true, "portal", "gateway"); err != nil {
		t.Fatalf("the named fix did not clear the refusal: %v", err)
	}
}

